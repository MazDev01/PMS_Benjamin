// ── ปิดเซสชัน: ถอดทางลัดก่อน แล้วค่อยลบโฟลเดอร์ (บอสสั่ง 22 ต.ค. 69 · ทางเดียวที่ใช้ลบโฟลเดอร์เซสชัน) ─────────────────────
//
// เหตุ 22 ต.ค. 69: ลบโฟลเดอร์แยกที่มีทางลัด (junction) node_modules ไปโฟลเดอร์หลัก ด้วย git worktree remove --force
//   → คำสั่งลบเดินตามทางลัดเข้าไปลบของจริง node_modules + packages/shared ของโฟลเดอร์หลักหาย 214 ไฟล์
// ใช้ (จากโฟลเดอร์หลัก): npm run session:close -- <ชื่อ>            งานต้อง merge เข้าแล้ว และไม่มีไฟล์ค้าง
//                        npm run session:close -- <ชื่อ> --ทิ้งงาน  ทิ้งงานที่ยังไม่ merge (ตั้งใจเท่านั้น)
// ขั้น: ตรวจ → ถอดทางลัดทุกตัว (ถอดแค่ลิงก์ ไม่ลบปลายทาง) → ตรวจซ้ำว่าไม่เหลือ (เหลือ = หยุด ไม่ลบ) → ลบโฟลเดอร์ → ลบ branch → คืนช่องพอร์ต
import { rmSync } from "node:fs";
import path from "node:path";
import { เป็นโฟลเดอร์หลัก } from "./lib/session.mjs";
import { gitใน, ชื่อถูกแบบ, อ่านทะเบียน, เขียนทะเบียน, ล็อกทะเบียน, หาทางลัด, ถอดทางลัดทั้งหมด, มีอยู่ } from "./lib/sessions.mjs";

const cwd = process.cwd();
const git = gitใน(cwd);
const ชื่อ = process.argv.slice(2).find(x => !x.startsWith("--")) ?? "";
const ทิ้งงาน = process.argv.includes("--ทิ้งงาน");
const ตาย = (m) => { console.error(`⛔ ${m}`); process.exit(1); };

if (!ชื่อถูกแบบ(ชื่อ)) ตาย("ใช้: npm run session:close -- <ชื่อ> [--ทิ้งงาน]");
if (!เป็นโฟลเดอร์หลัก(cwd)) ตาย("ปิดเซสชันได้จากโฟลเดอร์หลัก (เซสชันรวมงาน) เท่านั้น");

const ล็อก = ล็อกทะเบียน(`session:close ${ชื่อ}`);
try {
  const ทะเบียน = อ่านทะเบียน(cwd);
  const s = ทะเบียน[ชื่อ];
  if (!s) ตาย(`ไม่มีเซสชัน ${ชื่อ} ในทะเบียน`);
  const โฟลเดอร์ = path.resolve(s.โฟลเดอร์);

  if (มีอยู่(โฟลเดอร์) && !ทิ้งงาน) {
    const ค้าง = gitใน(โฟลเดอร์)("status", "--porcelain");
    if (ค้าง) ตาย(`เซสชัน ${ชื่อ} มีไฟล์ที่ยังไม่ commit — commit หรือใส่ --ทิ้งงาน ถ้าตั้งใจทิ้ง\n${ค้าง.split("\n").slice(0, 10).join("\n")}`);
    try { git("merge-base", "--is-ancestor", s.branch, "HEAD"); }
    catch { ตาย(`งานใน ${s.branch} ยังไม่ได้ merge เข้าโฟลเดอร์หลัก — merge ก่อน (npm run session:merge -- ${ชื่อ}) หรือใส่ --ทิ้งงาน ถ้าตั้งใจทิ้ง`); }
  }

  if (มีอยู่(โฟลเดอร์)) {
    const ทั้งหมด = หาทางลัด(โฟลเดอร์);
    const ถอดไม่ได้ = ถอดทางลัดทั้งหมด(โฟลเดอร์);
    const เหลือ = หาทางลัด(โฟลเดอร์);
    if (ถอดไม่ได้.length || เหลือ.length) {
      ตาย(`ถอดทางลัดไม่หมด ${เหลือ.length} ตัว — ไม่ลบโฟลเดอร์ (ลบตอนนี้อาจเดินตามทางลัดไปลบของที่อื่น)\n${[...ถอดไม่ได้, ...เหลือ.map(x => `${x.ที่} → ${x.ไป}`)].slice(0, 10).join("\n")}`);
    }
    console.log(`▶ ถอดทางลัด ${ทั้งหมด.length} ตัวแล้ว (ถอดแค่ลิงก์ ปลายทางไม่ถูกแตะ) · ไม่เหลือทางลัด`);
    try { git("worktree", "remove", "--force", โฟลเดอร์); } catch { /* ลบไม่หมด (ชื่อไฟล์ยาว) — ลบที่เหลือด้านล่าง */ }
    if (มีอยู่(โฟลเดอร์)) rmSync(โฟลเดอร์, { recursive: true, force: true, maxRetries: 3 });
    git("worktree", "prune");
    if (มีอยู่(โฟลเดอร์)) ตาย(`ลบโฟลเดอร์ ${โฟลเดอร์} ไม่หมด — ไม่มีทางลัดเหลือแล้ว ลบด้วยมือได้อย่างปลอดภัย`);
  }
  try { git("branch", ทิ้งงาน ? "-D" : "-d", s.branch); } catch (e) { console.error(`⚠️ ลบ branch ${s.branch} ไม่ได้: ${String(e.stderr ?? e.message).trim()}`); }
  delete ทะเบียน[ชื่อ];
  เขียนทะเบียน(cwd, ทะเบียน);
  console.log(`✓ ปิดเซสชัน ${ชื่อ} แล้ว — ลบโฟลเดอร์ ${โฟลเดอร์.replaceAll("\\", "/")} · branch ${s.branch} · คืนช่องพอร์ต ${s.ช่อง}`);
} finally {
  ล็อก.release();
}
