// ── คำสั่งรายการรอรอบตรวจเต็ม (บอสสั่ง 5 พ.ย. 69 · scripts/lib/roundQueue.mjs) ─────────────────────────────────────────
//   npm run round:add   -- --งาน "<ข้อความ>" --เซสชัน <ชื่อ> [--ทดสอบผ่าน] [--ใบ <เลข>]...
//                                                                            เพิ่มงานที่แก้แล้ว (รันข้อทดสอบของส่วนที่แก้แล้ว = --ทดสอบผ่าน · เพิ่มใบปรับฐาน = --ใบ 0277 ต่อใบ)
//   npm run round:pass  -- --รหัส <id>                                       ตั้งว่าทดสอบส่วนตัวผ่านภายหลัง
//   npm run round:list                                                       ข้อมูลพร้อมใช้ในกล่องคำถามถึงบอส
//   npm run round:close -- --บอสตอบ "<เวลาที่บอสตอบ ตรวจเลย>" [--ตัด <id>]... [--เร่งด่วน]
//                                                                            ปิดรอบ (เฉพาะคนรวมงาน · หลังบอสตอบ "ตรวจเลย" เท่านั้น)
//   npm run round:cancel -- --เหตุ "<ข้อความ>"                                ยกเลิกรอบที่ปิดแล้วยังไม่ผ่าน (ชุดงานเปลี่ยน → ถามบอสใหม่)
//   ห้ามเซสชันรันรอบตรวจเต็มเอง — test:prodbuild รอบเต็มเริ่มได้เฉพาะรอบที่ปิดแล้ว (ไม่มีทางข้าม)
import { เพิ่มงาน, ตั้งผ่าน, สรุปรายการ, ปิดรอบ, ยกเลิกรอบ } from "./lib/roundQueue.mjs";

const [คำสั่ง, ...ส่วน] = process.argv.slice(2);
const ค่า = (ชื่อ) => { const i = ส่วน.indexOf(`--${ชื่อ}`); return i >= 0 && i + 1 < ส่วน.length && !ส่วน[i + 1].startsWith("--") ? ส่วน[i + 1] : undefined; };
const ทุกค่า = (ชื่อ) => ส่วน.flatMap((x, i) => x === `--${ชื่อ}` && ส่วน[i + 1] && !ส่วน[i + 1].startsWith("--") ? [ส่วน[i + 1]] : []);
const มี = (ชื่อ) => ส่วน.includes(`--${ชื่อ}`);

try {
  if (คำสั่ง === "add") {
    const r = เพิ่มงาน({ งาน: ค่า("งาน"), เซสชัน: ค่า("เซสชัน"), ทดสอบผ่าน: มี("ทดสอบผ่าน"), ใบ: ทุกค่า("ใบ").flatMap(x => x.split(",")).map(x => x.trim()).filter(Boolean) });
    console.log(`✓ เพิ่มเข้ารายการรอรอบแล้ว: ${r.งาน} · เซสชัน ${r.เซสชัน}${r.ใบ ? ` · ใบ ${r.ใบ.join(", ")}` : ""} · ${r.ทดสอบผ่าน ? "ทดสอบส่วนตัวผ่าน" : "ยังไม่ผ่านทดสอบส่วนตัว (ตั้งภายหลัง: npm run round:pass -- --รหัส " + r.id + ")"} · รหัส ${r.id}`);
  } else if (คำสั่ง === "pass") {
    const r = ตั้งผ่าน(ค่า("รหัส"));
    console.log(`✓ ทดสอบส่วนตัวผ่าน: ${r.งาน} · รหัส ${r.id}`);
  } else if (คำสั่ง === "list") {
    console.log(สรุปรายการ());
  } else if (คำสั่ง === "close") {
    const r = ปิดรอบ({ บอสตอบ: ค่า("บอสตอบ"), ตัด: ทุกค่า("ตัด"), เร่งด่วน: มี("เร่งด่วน") });
    console.log(`✓ ปิดรอบ ${r.รอบ}${r.เร่งด่วน ? " (เร่งด่วน)" : ""} · บอสตอบ ${r.บอสตอบ} · ${r.งาน.length} งาน · ใบ ${r.ใบ.join(", ") || "ไม่มี"}${r.ตัดออก.length ? ` · ตัดออก ${r.ตัดออก.length}` : ""} · ลายนิ้วมือ ${r.ลายนิ้วมือ.slice(0, 12)}`);
    console.log("  ต่อไป: npm run test:prodbuild (รอบเต็ม) — เพิ่มงานเข้ารายการหลังปิดรอบ = รอบเต็มไม่ยอมเริ่ม");
  } else if (คำสั่ง === "cancel") {
    const r = ยกเลิกรอบ(ค่า("เหตุ"));
    console.log(`✓ ยกเลิกรอบ ${r.รอบ} (${r.เหตุยกเลิก}) — ถามบอสใหม่แล้วปิดรอบใหม่`);
  } else {
    console.error("ใช้: npm run round:add | round:pass | round:list | round:close | round:cancel (ดูหัวไฟล์ scripts/round.mjs)");
    process.exit(2);
  }
} catch (e) {
  console.error(`⛔ ${e.message}`);
  process.exit(2);
}
