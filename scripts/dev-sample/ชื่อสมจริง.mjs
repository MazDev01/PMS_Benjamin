// คอลัมน์ข้อความ/jsonb ของ public (ไม่รวม audit_log)
const คอลัมน์ทั้งหมด = `select x.table_name, x.column_name, x.data_type from information_schema.columns x
  join information_schema.tables t on t.table_schema = x.table_schema and t.table_name = x.table_name and t.table_type = 'BASE TABLE'
  where x.table_schema = 'public' and x.data_type in ('text', 'jsonb', 'character varying') and x.table_name <> 'audit_log'`;

/** SQL แทนคู่ [เดิม, ใหม่] ทุกคอลัมน์ (กรองแถวที่มีคำเดิมอย่างน้อย 1 คำด้วย regex รวม) ในธุรกรรมเดียว · ตัวดักปิด (replica) */
function sqlแทน(คู่) {
  const ค่า = คู่.map(([a, b]) => `(${q(a)}, ${q(b)})`).join(", ");
  // regex รวมของคำเดิมทั้งชุด (escape อักขระพิเศษ) — แถวที่ไม่มีคำไหนเลยไม่แตะ
  const รวม = คู่.map(([a]) => a.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).sort((a, b) => b.length - a.length).join("|");
  return `begin;
    set local session_replication_role = replica;
    create temp table คู่ชื่อ (เดิม text, ใหม่ text) on commit drop;
    insert into คู่ชื่อ values ${ค่า};
    create function pg_temp.แทนชื่อ(t text) returns text language plpgsql as $f$
      declare r record; begin
        for r in select เดิม, ใหม่ from คู่ชื่อ where position(เดิม in t) > 0 order by length(เดิม) desc loop t := replace(t, r.เดิม, r.ใหม่); end loop;
        return t; end $f$;
    do $$ declare r record; begin
      for r in ${คอลัมน์ทั้งหมด} loop
        execute format('update public.%I set %I = pg_temp.แทนชื่อ(%I::text)::%s where %I::text ~ %L',
          r.table_name, r.column_name, r.column_name, r.data_type, r.column_name, ${q(รวม)});
      end loop;
    end $$;
    commit;`;
}

