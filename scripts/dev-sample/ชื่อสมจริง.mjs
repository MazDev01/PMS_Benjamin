  if ((x = m(/^ลูกค้าทดสอบ (.+)$/))) return ชื่อหจก(`ตั้งต้น:${x[1]}`);
  if ((x = m(/^ผู้ติดต่อทดสอบ (.+)$/))) return ผู้ติดต่อสมจริง(`ตั้งต้น:${x[1]}`);
  if (เดิม === "ที่อยู่ทดสอบ สำนักงานใหญ่") return "99/9 ถ.พัฒนาการ เขตสวนหลวง กรุงเทพมหานคร";
  if ((x = m(/^ที่อยู่ทดสอบ (.+)$/))) return ที่อยู่สั้น(x[1]);
  if ((x = m(/^โครงการทดสอบ (.+)$/))) return เลือก(งานโครงการ, `งาน:${x[1]}`);
  if ((x = m(/^บันทึกนัดหมายทดสอบ (.+)$/))) return เลือก(บันทึกนัด, `นัด:${x[1]}`);
  if ((x = m(/^บันทึกทดสอบ (.+)$/))) return เลือก(บันทึกลีด, `บันทึก:${x[1]}`);
  if ((x = m(/^รายงานทดสอบ (.+)$/))) return เลือก(รายงาน, `รายงาน:${x[1]}`);
  if ((x = m(/^หมายเหตุทดสอบ (.+)$/))) return เลือก(หมายเหตุใบ, `หมายเหตุ:${x[1]}`);
