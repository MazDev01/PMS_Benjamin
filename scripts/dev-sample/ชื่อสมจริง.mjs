export async function สร้าง(ctx) {
  // คำเดิมทุกคำจากทุกคอลัมน์ (ทีละคอลัมน์ที่มี "ทดสอบ")
  const ดิบ = ctx.sql(`do $$ declare r record; begin
      create temp table คำพบ (คำ text) on commit preserve rows;
      for r in ${คอลัมน์ทั้งหมด} loop
        execute format('insert into คำพบ select (regexp_matches(%I::text, %L, ''g''))[1] from public.%I where %I::text like ''%%ทดสอบ%%''',
          r.column_name, ${q(รูปคำเดิม)}, r.table_name, r.column_name);
      end loop; end $$;
    select coalesce(json_agg(distinct คำ), '[]') from คำพบ;`);
  const คำเดิม = อ่านJSON(ดิบ);
  const เดิมพนักงาน = คำเดิม.filter(k => k.startsWith("พนักงานขายทดสอบ ")).sort();
  if (เดิมพนักงาน.length > พนักงาน.length) throw new Error(`ชื่อพนักงานขายไม่พอ (${เดิมพนักงาน.length} คน)`);
  const ลำดับพนักงาน = new Map(เดิมพนักงาน.map((n, i) => [n, i]));
  const คู่ = คำเดิม.map(k => [k, คำใหม่(k, ลำดับพนักงาน)]).filter(([, v]) => v);
  if (!คู่.length) { console.log("✓ ชื่อสมจริง: ไม่มีคำเดิมให้แทน"); return; }
  writeFileSync(ไฟล์คู่(ctx), JSON.stringify(คู่, null, 1));
  ctx.sql(sqlแทน(คู่));
  const นับ = (p) => คู่.filter(([k]) => k.startsWith(p)).length;
  console.log(`✓ ชื่อสมจริง: แทน ${คู่.length} คำ (ดีลเลอร์ ${นับ("ดีลเลอร์ทดสอบ")} · พนักงานขาย ${นับ("พนักงานขายทดสอบ")} · ลูกค้า ${นับ("ลูกค้าทดสอบ")}`
    + ` · ผู้ติดต่อ ${นับ("ผู้ติดต่อทดสอบ")} · ที่อยู่ ${นับ("ที่อยู่ทดสอบ")} · งาน ${นับ("โครงการทดสอบ")} · บันทึก/รายงาน/หมายเหตุ ${นับ("บันทึก") + นับ("รายงาน") + นับ("หมายเหตุ")})`
    + ` · ทุกตาราง ยกเว้นบันทึกการใช้งาน · คู่คำ ${ไฟล์คู่(ctx)}`);
}

