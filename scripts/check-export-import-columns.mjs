// ── ตรวจ: ไฟล์ที่ "ส่งออก" ต้องนำกลับเข้าระบบได้ครบทุกช่อง ────────────────────────
//
// กับดักจริง (บอสแจ้ง 9 ก.ย. 69): หน้าลูกค้าของดีลเลอร์มีทั้งปุ่มส่งออกและปุ่มนำเข้าลูกค้าเดิม
//   แต่คอลัมน์ของสองฝั่งไม่ตรงกัน — ส่งออกไม่มี อีเมล · ที่อยู่ · แม่แบบ · เป็นลูกค้าเมื่อ
//   ใครส่งออกไปแก้ใน Excel แล้วนำเข้ากลับ ช่องพวกนั้นกลายเป็นว่างทันที โดยไม่มีข้อความเตือนอะไรเลย
//   (ตัวนำเข้าจับคู่คอลัมน์ตาม "ชื่อหัวตาราง" — ไม่เจอหัวไหนก็เติมค่าว่างให้เงียบ ๆ)
//
// กติกา: ทุกคอลัมน์ในเทมเพลตนำเข้า (CSV_HEADERS) ต้องมีอยู่ในหัวตารางของ ExportMenu หน้าเดียวกัน
//   คอลัมน์สรุปที่ระบบคำนวณเอง (ยอดขายรวม ฯลฯ) จะมีเกินมาได้ ตัวนำเข้าไม่สนใจอยู่แล้ว
import { readFileSync } from "node:fs";

const ไฟล์ = "apps/dealer/app/(app)/customers/page.tsx";
const เทมเพลต = "packages/shared/lib/customerImportTemplate.ts";
const src = readFileSync(ไฟล์, "utf8");
// CSV_HEADERS ย้ายไปอยู่โมดูลกลางแล้ว (หน้าจอ import มาใช้) — อ่านจากที่นั่นเป็นหลัก
const srcHeaders = readFileSync(เทมเพลต, "utf8");

const อ่านรายการ = (หลัง, เนื้อไฟล์ = src) => {
  const i = เนื้อไฟล์.indexOf(หลัง);
  if (i < 0) return null;
  const เปิด = เนื้อไฟล์.indexOf("[", i);
  const ปิด = เนื้อไฟล์.indexOf("]", เปิด);
  if (เปิด < 0 || ปิด < 0) return null;
  return [...เนื้อไฟล์.slice(เปิด, ปิด).matchAll(/"([^"]+)"/g)].map(m => m[1]);
};

const อ่านดิบ = (หลัง) => {
  const i = src.indexOf(หลัง);
  if (i < 0) return "";
  const เปิด = src.indexOf("[", i);
  const ปิด = src.indexOf("]", เปิด);
  return เปิด < 0 || ปิด < 0 ? "" : src.slice(เปิด, ปิด);
};

const นำเข้า = อ่านรายการ("export const CSV_HEADERS", srcHeaders);
// หัวตารางส่งออกเขียนเป็น [...CSV_HEADERS, "คอลัมน์สรุป"] ได้ — นับว่ามีครบทุกช่องของเทมเพลตนำเข้า
const ส่งออกดิบ = อ่านดิบ("<ExportMenu");
const ส่งออก = /\.\.\.\s*CSV_HEADERS/.test(ส่งออกดิบ)
  ? [...(นำเข้า ?? []), ...(อ่านรายการ("<ExportMenu") ?? [])]
  : อ่านรายการ("<ExportMenu");

if (!นำเข้า || !ส่งออก) {
  console.error(`❌ อ่านรายการคอลัมน์จาก ${ไฟล์} ไม่ได้ — โครงสร้างไฟล์เปลี่ยนไป ต้องแก้ตัวตรวจนี้ด้วย`);
  process.exit(1);
}

const ขาด = นำเข้า.filter(h => !ส่งออก.includes(h));
if (ขาด.length) {
  console.error(`❌ คอลัมน์ที่นำเข้าได้ แต่ไม่มีในไฟล์ส่งออก: ${ขาด.join(" · ")}`);
  console.error(`   แก้ที่ ${ไฟล์} → หัวตารางของ <ExportMenu> ต้องมีครบทุกช่องของ CSV_HEADERS`);
  console.error("   ไม่งั้นคนส่งออกไปแก้แล้วนำเข้ากลับ ข้อมูลช่องพวกนี้จะหายเงียบ ๆ");
  process.exit(1);
}
console.log(`ช่องที่ส่งออกแล้วนำเข้ากลับไม่ได้: 0 (ตรวจ ${นำเข้า.length} ช่อง)`);
