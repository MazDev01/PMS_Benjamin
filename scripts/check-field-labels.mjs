// ทำไม: ช่องเดียวกันเคยชื่อไม่เหมือนกันในแต่ละหน้า ("บริษัท" / "บริษัท / ชื่อลูกค้า" · "ผู้ติดต่อ" / "ชื่อ-สกุล"
//   · "โทรศัพท์" / "เบอร์โทรศัพท์" · "แหล่งที่มา" / "ช่องทางที่มา" · "หมายเหตุ" / "สเปก / รายละเอียดงาน") — ผู้ใช้ไม่แน่ใจว่าเป็นข้อมูลเดียวกัน
//   ทางที่ถูก: ใช้ ช่อง / กลุ่มช่อง / ตัวอย่างช่อง / ป้ายบังคับ จาก packages/shared/lib/fieldLabels.ts
// ตก เมื่อเจอ (ไม่นับคำอธิบายในโค้ด · ไม่นับข้อทดสอบ):
//   1) ทุกไฟล์ใน apps/ · packages/ (ยกเว้นไฟล์กลาง): ข้อความตรงตัวของชื่อช่องที่เฉพาะเจาะจง — "จังหวัดหน้างาน" · "งานที่ต้องการ"
//      · "พื้นที่ (ตร.ม.)" · "สเปก / รายละเอียดงาน" · "ช่องทางที่มา" · "ชื่อบริษัท / ชื่อลูกค้า" · "งานที่ขอราคา" (± " *")
//   2) ไฟล์ฟอร์มข้อมูลลูกค้า/งาน (รายชื่อข้างล่าง): ข้อความตรงตัวของชื่อช่องทั่วไปและชื่อเก่า — บริษัท · ผู้ติดต่อ · โทรศัพท์ · อีเมล
//      · ที่อยู่ · จังหวัด · ขั้นตอน · ผู้รับผิดชอบ · แหล่งที่มา · ชื่อโครงการ · หมายเหตุ · ชื่อ-สกุล · เบอร์โทรศัพท์ (± " *")
//   "ข้อความตรงตัว" = สตริงทั้งก้อน ("…" '…' `…`) หรือข้อความใน JSX ระหว่างแท็ก (>…<) — คำที่อยู่ในประโยคอื่นไม่นับ
// ใช้: node scripts/check-field-labels.mjs   (อยู่ใน npm run checks)
import { readFileSync } from "node:fs";
import path from "node:path";
import { ไฟล์ที่gitเก็บ } from "./lib/gitFiles.mjs";

const ไฟล์กลาง = "packages/shared/lib/fieldLabels.ts";
const ไฟล์ฟอร์ม = new Set([
  "apps/dealer/app/(app)/leads/page.tsx",
  "apps/dealer/app/(app)/customers/page.tsx",
  "packages/shared/components/ui/QuoteRequestPanel.tsx",
  "packages/shared/components/hq/HqQuoteEditor.tsx",
  "packages/shared/lib/customerImportTemplate.ts",
]);
const เฉพาะ = ["จังหวัดหน้างาน", "งานที่ต้องการ", "พื้นที่ (ตร.ม.)", "สเปก / รายละเอียดงาน", "ช่องทางที่มา", "ชื่อบริษัท / ชื่อลูกค้า", "บริษัท / ชื่อลูกค้า", "งานที่ขอราคา"];
const ทั่วไป = ["บริษัท", "ผู้ติดต่อ", "โทรศัพท์", "อีเมล", "ที่อยู่", "จังหวัด", "ขั้นตอน", "ผู้รับผิดชอบ", "แหล่งที่มา", "ชื่อโครงการ", "หมายเหตุ", "ชื่อ-สกุล", "เบอร์โทรศัพท์"];
const หนี = s => s.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
const รูป = คำ => new RegExp(`(["'\`])\\s*(${คำ.map(หนี).join("|")})(\\s*\\*)?\\s*\\1|>\\s*(${คำ.map(หนี).join("|")})(\\s*\\*)?\\s*<`, "g");
const รูปเฉพาะ = รูป(เฉพาะ), รูปทั่วไป = รูป(ทั่วไป);

// ตัดคำอธิบายออก (คงเลขบรรทัด) — คำอธิบายเล่าชื่อเก่าได้
function ตัดคำอธิบาย(ข้อความ) {
  return ข้อความ
    .replace(/\/\*[\s\S]*?\*\//g, m => m.replace(/[^\n]/g, " "))
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, m => m.replace(/[^\n]/g, " "))
    .split("\n").map(บ => บ.replace(/(^|[^:"'`])\/\/.*$/, "$1")).join("\n");
}

const เจอ = [];
for (const p of ไฟล์ที่gitเก็บ(["apps", "packages"], { ext: /\.(ts|tsx)$/ })) {
  const ทาง = p.replace(/\\/g, "/");
  if (/node_modules|\/\.next|\/dist\//.test(ทาง) || ทาง === ไฟล์กลาง) continue;
  const เดิม = readFileSync(p, "utf8").replace(/\r\n/g, "\n");
  const โค้ด = ตัดคำอธิบาย(เดิม);
  const บรรทัด = เดิม.split("\n");
  const ตรวจ = (re, เหตุ) => {
    for (const m of โค้ด.matchAll(re)) {
      // คีย์ของไฟล์กลาง (ป้ายบังคับ("จังหวัด") · รับ("บริษัท") · ช่อง["…"]) สะกดเหมือนชื่อช่องโดยบังเอิญ — ไม่ใช่ป้ายที่เขียนเอง
      if (/(ป้ายบังคับ|รับ)\(\s*$|ช่อง\[\s*$/.test(โค้ด.slice(Math.max(0, m.index - 20), m.index))) continue;
      const ที่ = โค้ด.slice(0, m.index).split("\n").length;
      เจอ.push(`${ทาง}:${ที่}  "${(m[2] ?? m[4]).trim()}" ${เหตุ}\n      ${(บรรทัด[ที่ - 1] ?? "").trim().slice(0, 110)}`);
    }
  };
  ตรวจ(รูปเฉพาะ, "— ใช้ ช่อง.* จาก lib/fieldLabels.ts");
  if (ไฟล์ฟอร์ม.has(ทาง)) ตรวจ(รูปทั่วไป, "— ไฟล์ฟอร์มข้อมูลลูกค้า/งาน ต้องใช้ชื่อช่องจาก lib/fieldLabels.ts");
}

if (เจอ.length) {
  console.error(`❌ check-field-labels: เขียนชื่อช่องข้อมูลลูกค้า/งานเอง ${เจอ.length} จุด (ต้องใช้ไฟล์กลาง ${ไฟล์กลาง})`);
  for (const x of เจอ) console.error(`  ${x}`);
  process.exit(1);
}
console.log(`check-field-labels: ผ่าน — ชื่อช่องข้อมูลลูกค้า/งานมาจาก ${ไฟล์กลาง} ที่เดียว`);
