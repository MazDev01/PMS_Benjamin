// ── ตัวกันเลขใบปรับฐาน: ลำดับใบ + ใบของรอบตรวจ (บอสสั่ง 5 พ.ย. 69) ───────────────────────────────────────────────────
//
// กติกา (คำบอส):
//   ก. ใบในเครื่องที่ยังไม่อยู่บนฐานจริง แต่เลขน้อยกว่าใบล่าสุดบนฐาน = ข้ามลำดับ → ต้อง supabase db push --include-all (ห้าม)
//      → db:push และรอบตรวจเต็มปฏิเสธ พร้อมเหตุผลภาษาไทย
//   ข. ใบใหม่ (ยังไม่อยู่บนฐาน) ต้องอยู่ในรายการใบของรอบ: round:add --ใบ <เลข> (หลายใบได้) → ปิดรอบจดรายการใบของรอบ
//      · รอบตรวจเต็มปฏิเสธถ้าใบใหม่ในเครื่องไม่ตรงกับรายการใบของรอบ (เกินหรือขาด)
//      · db:push ปฏิเสธถ้าใบที่จะลงไม่อยู่ในรายการใบของรอบที่ผ่านแล้วล่าสุด
// รายชื่อใบบนฐานจริง: db:push จดทุกครั้งที่อ่านรายชื่อใบจากฐานจริงได้ (--dry-run ก็จด · ลงสำเร็จ = ใบในเครื่องทั้งหมด)
//   → <ที่เก็บรอบ>/prod-migrations.json · รอบตรวจเต็มเทียบกับไฟล์นี้ ไม่ต่อฐานจริงเอง
// ข้อทดสอบ: tests/tools/migration-order.test.mjs
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ที่เก็บรอบ } from "./roundQueue.mjs";

export const ไฟล์ใบบนฐาน = () => path.join(ที่เก็บรอบ(), "prod-migrations.json");
export const เลขใบ = (f) => String(f).slice(0, 4);
const เลขถูก = (x) => /^\d{4}$/.test(String(x));
/** ชื่อไฟล์ใบในโฟลเดอร์ (NNNN_ชื่อ.sql) เรียงตามเลข */
export const ใบในโฟลเดอร์ = (dir) => readdirSync(dir).filter(n => /^\d{4}_.*\.sql$/.test(n)).sort();

/** จดรายชื่อใบที่อยู่บนฐานจริง (ชื่อไฟล์) — เรียกจาก db:push หลังอ่านรายชื่อจากฐานจริงได้ */
export function จดใบบนฐาน(ใบ, ที่มา) {
  const ไฟล์ = ไฟล์ใบบนฐาน();
  mkdirSync(path.dirname(ไฟล์), { recursive: true });
  const ค่า = { คำอธิบาย: "รายชื่อใบปรับฐานที่อยู่บนฐานจริง — เขียนโดย db:push:prod เท่านั้น ห้ามแก้มือ (รอบตรวจเต็มเทียบกับไฟล์นี้)",
    บันทึกเมื่อ: new Date().toISOString(), ที่มา, ใบ: [...new Set(ใบ)].sort() };
  const ชั่วคราว = `${ไฟล์}.${process.pid}.tmp`;
  writeFileSync(ชั่วคราว, JSON.stringify(ค่า, null, 2) + "\n");
  renameSync(ชั่วคราว, ไฟล์);
  return ค่า;
}
export function อ่านใบบนฐาน() {
  try { const x = JSON.parse(readFileSync(ไฟล์ใบบนฐาน(), "utf8")); return Array.isArray(x?.ใบ) ? x : null; } catch { return null; }
}

/** ใบใหม่ที่เลขน้อยกว่าใบล่าสุดบนฐาน (ข้อ ก) */
export function ใบข้ามลำดับ(ใหม่, บนฐาน) {
  const สูงสุด = บนฐาน.map(เลขใบ).sort().at(-1);
  return สูงสุด ? ใหม่.filter(f => เลขใบ(f) < สูงสุด) : [];
}
const ข้อความข้ามลำดับ = (ข้าม, บนฐาน) =>
  `ใบ ${ข้าม.map(เลขใบ).join(", ")} ยังไม่อยู่บนฐานจริง แต่เลขน้อยกว่าใบล่าสุดบนฐาน (${บนฐาน.map(เลขใบ).sort().at(-1)}) — ลงต่อไม่ได้ (ต้อง --include-all ซึ่งห้ามใช้) · เปลี่ยนเลขใบเป็นเลขถัดไปด้วย npm run migration:new แล้วย้ายเนื้อใบไปไฟล์ใหม่`;

/** รายการใบของงานชุดหนึ่ง (รวมทุกงาน · ไม่ซ้ำ · เรียง) */
export const ใบของงาน = (งาน) => [...new Set(งาน.flatMap(x => x.ใบ ?? []))].sort();
export function ตรวจรายการใบ(ใบ) {
  const ผิด = (ใบ ?? []).filter(x => !เลขถูก(x));
  if (ผิด.length) throw new Error(`เลขใบต้องเป็นตัวเลข 4 หลัก (เช่น --ใบ 0277) — ได้ ${ผิด.join(", ")}`);
  return [...new Set(ใบ ?? [])].sort();
}

/** ก่อนรอบตรวจเต็ม: ใบใหม่ในเครื่อง (ไม่อยู่ในรายชื่อบนฐานที่จดไว้) ต้องไม่ข้ามลำดับ และตรงกับรายการใบของรอบ → { ได้, เหตุ? , ใหม่ } */
export function ตรวจใบก่อนรอบเต็ม({ รอบ, dir = process.env.PMS_MIGRATIONS_DIR ?? "supabase/migrations", บนฐาน = อ่านใบบนฐาน() }) {
  if (!บนฐาน) return { ได้: false, เหตุ: `ยังไม่มีรายชื่อใบบนฐานจริงที่จดไว้ (${ไฟล์ใบบนฐาน()}) — คนรวมงานสั่ง npm run db:push:prod -- --yes-prod --dry-run หนึ่งครั้ง (อ่านรายชื่อใบอย่างเดียว ไม่ลงใบ) ให้จดก่อน` };
  const มี = new Set(บนฐาน.ใบ);
  const ใหม่ = ใบในโฟลเดอร์(dir).filter(f => !มี.has(f));
  const ข้าม = ใบข้ามลำดับ(ใหม่, บนฐาน.ใบ);
  if (ข้าม.length) return { ได้: false, เหตุ: ข้อความข้ามลำดับ(ข้าม, บนฐาน.ใบ), ใหม่ };
  const ของรอบ = new Set(รอบ?.ใบ ?? []), ในเครื่อง = new Set(ใหม่.map(เลขใบ));
  const เกิน = [...ในเครื่อง].filter(x => !ของรอบ.has(x)), ขาด = [...ของรอบ].filter(x => !ในเครื่อง.has(x));
  if (เกิน.length || ขาด.length) {
    return { ได้: false, ใหม่, เหตุ: `ใบใหม่ในเครื่องไม่ตรงกับรายการใบของรอบ ${รอบ?.รอบ ?? ""} (รอบ: ${[...ของรอบ].join(", ") || "ไม่มีใบ"} · ในเครื่อง: ${[...ในเครื่อง].join(", ") || "ไม่มีใบ"})`
      + `${เกิน.length ? ` · เกิน: ใบ ${เกิน.join(", ")} ไม่อยู่ในรอบ (เพิ่มงานด้วย round:add -- --ใบ <เลข> แล้วถามบอสปิดรอบใหม่ หรือเอาใบออกจากก้อนนี้)` : ""}`
      + `${ขาด.length ? ` · ขาด: ใบ ${ขาด.join(", ")} อยู่ในรอบแต่ไม่มีในเครื่อง (ยังไม่ merge ใบเข้าก้อน หรือจดเลขผิด)` : ""}` };
  }
  return { ได้: true, ใหม่ };
}

/** ก่อน db:push ลงใบ: ไม่ข้ามลำดับ + ทุกใบที่จะลงอยู่ในรายการใบของรอบที่ผ่านแล้วล่าสุด → { ได้, เหตุ? } */
export function ตรวจใบก่อนลงฐาน({ ที่จะลง, ในเครื่อง, รอบผ่าน }) {
  const ลง = new Set(ที่จะลง);
  const บนฐาน = ในเครื่อง.filter(f => !ลง.has(f));
  const ข้าม = ใบข้ามลำดับ(ที่จะลง, บนฐาน);
  if (ข้าม.length) return { ได้: false, เหตุ: ข้อความข้ามลำดับ(ข้าม, บนฐาน) };
  if (!รอบผ่าน) return { ได้: false, เหตุ: "ไม่มีรอบตรวจเต็มที่ผ่านแล้ว — ใบที่จะลงต้องอยู่ในรายการใบของรอบที่ผ่านแล้วล่าสุด" };
  const ของรอบ = new Set(รอบผ่าน.ใบ ?? []);
  const นอกรอบ = ที่จะลง.filter(f => !ของรอบ.has(เลขใบ(f)));
  if (นอกรอบ.length) return { ได้: false, เหตุ: `ใบ ${นอกรอบ.map(เลขใบ).join(", ")} ไม่อยู่ในรายการใบของรอบที่ผ่านแล้วล่าสุด (${รอบผ่าน.รอบ} · ใบของรอบ: ${[...ของรอบ].join(", ") || "ไม่มีใบ"}) — ลงได้เฉพาะใบของรอบที่ผ่านแล้ว` };
  return { ได้: true };
}

/** รอบตรวจเต็มที่ผ่านแล้วล่าสุด (จาก <ที่เก็บรอบ>/rounds/*.json) */
export function รอบผ่านล่าสุด() {
  const ที่ = path.join(ที่เก็บรอบ(), "rounds");
  if (!existsSync(ที่)) return null;
  const ผ่าน = readdirSync(ที่).filter(n => n.endsWith(".json")).map(n => { try { return JSON.parse(readFileSync(path.join(ที่, n), "utf8")); } catch { return null; } })
    .filter(x => x?.สถานะ === "ผ่านแล้ว" && x.ผ่านเมื่อ);
  return ผ่าน.sort((a, b) => String(a.ผ่านเมื่อ).localeCompare(String(b.ผ่านเมื่อ))).at(-1) ?? null;
}
