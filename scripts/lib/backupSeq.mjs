// ── ตัวนับเลข (sequence) ของซ้อมกู้: เทียบฐานที่กู้กับค่าที่อยู่ในไฟล์สำรองเอง (บอสอนุมัติ 28 ต.ค. 69) ──────────────────────
// เหตุ: 28 ต.ค. 69 ซ้อมกู้ตก — งานสแกนการแจ้งเตือน (cron */15) รันตกระหว่าง dump กับอ่านตัวนับต้นทาง กินตัวนับ 240 โดยไม่เพิ่มแถว
//   เดิมเทียบกับฐานจริงที่ยังทำงาน (อ่านหลัง dump) → ต่างทั้งที่ไฟล์สำรองกู้ได้ครบ
// เกณฑ์เท่าเดิม: ตัวนับทุกตัวต้องตรงทุกตัว · ตัวนับที่ฐานจริงมีแต่ไฟล์สำรองไม่มี = ไม่ผ่าน
//   · ค่าในไฟล์สำรองมากกว่าฐานจริงที่อ่านทีหลัง = ไม่ผ่าน (ตัวนับย้อนไม่ได้ — ไฟล์ผิดที่มา)
// ข้อทดสอบ: tests/tools/db-push-prod-guard.test.mjs ข้อ I–J

/** ค่าตัวนับจากคำสั่ง setval ในไฟล์ dump → { "schema.name": "ค่า" | null } (null = ยังไม่เคยใช้ · is_called false เหมือน pg_sequences) */
export function ตัวนับในไฟล์สำรอง(sql) {
  const ค่า = {};
  for (const m of sql.matchAll(/pg_catalog\.setval\('"?([^".']+)"?\."?([^".']+)"?', (\d+), (true|false)\)/g))
    ค่า[`${m[1]}.${m[2]}`] = m[4] === "true" ? m[3] : null;
  return ค่า;
}

/** คืนรายการปัญหา (ว่าง = ตรงครบ) */
export function เทียบตัวนับ({ ในชุด, ต้นทาง = {}, กู้ได้ = {} }) {
  const ชื่อ = [...new Set([...Object.keys(ต้นทาง), ...Object.keys(ในชุด)])].sort();
  const ปัญหา = [];
  for (const k of ชื่อ) {
    if (!(k in ในชุด)) { ปัญหา.push(`ตัวนับเลข ${k}: ฐานจริงมี (${ต้นทาง[k]}) แต่ไม่มีในไฟล์สำรอง`); continue; }
    if (String(ในชุด[k]) !== String(กู้ได้[k] ?? null)) ปัญหา.push(`ตัวนับเลข ${k}: ในไฟล์สำรอง ${ในชุด[k]} · กู้ได้ ${กู้ได้[k] ?? "ไม่มี"}`);
    if (ในชุด[k] !== null && ต้นทาง[k] != null && Number(ในชุด[k]) > Number(ต้นทาง[k]))
      ปัญหา.push(`ตัวนับเลข ${k}: ในไฟล์สำรอง ${ในชุด[k]} มากกว่าฐานจริงที่อ่านทีหลัง ${ต้นทาง[k]} (ตัวนับย้อนไม่ได้)`);
  }
  return ปัญหา;
}
