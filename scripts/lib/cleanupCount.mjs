// ── ตรวจผลขั้นนับก่อนลบของการล้างข้อมูลทดสอบเว็บจริง (tests/prod-live/run.mjs cleanup · บอสสั่ง 5 พ.ย. 69) ─────────────────
//   เหตุ: บอสรันล้างจากหน้าจอคน ขึ้น "บันทึกการใช้งานทดสอบลบ 0" แต่ฐานจดลบจริง 54 แถว → ด่าน "ปนแถวจริง" ก็อาจอ่านได้ 0 แบบเดียวกัน
//   กติกา: ผลนับต้องเป็นแถวเดียว มีครบทุกคอลัมน์ที่คำสั่งนับให้ (ชื่อไทยตรงตัว) และทุกค่าเป็นจำนวนเต็มไม่ติดลบ · เห็นทุกแถว = true
//     · บันทึกการใช้งานทั้งตาราง (จะลบ + เหลือ) ต้องมากกว่า 0 — ฐานจริงมีบันทึกเสมอ ได้ 0 ทั้งคู่ = อ่านผิด/มองไม่เห็น ไม่ใช่ "ไม่มีอะไรให้ลบ"
//   ไม่ผ่าน = โยนข้อผิดพลาดบอกเหตุ (ผู้เรียกต้องหยุดก่อนลบ) — ห้ามเดาค่าที่อ่านไม่ได้เป็น 0
// ข้อทดสอบ: tests/tools/supabase-cli-rows.test.mjs (ข้อ 5)

export const คอลัมน์นับ = ["เห็นทุกแถว", "จะลบ", "เหลือ", "ปนแถวจริง"];

const เลข = (ชื่อ, v) => {
  if (typeof v === "number" && Number.isInteger(v) && v >= 0) return v;
  if (typeof v === "string" && /^\d+$/.test(v.trim())) return Number(v.trim());   // count(*) เป็น bigint — บางรูปแบบผลส่งเป็นข้อความตัวเลข
  throw new Error(`ผลนับคอลัมน์ "${ชื่อ}" ไม่ใช่จำนวนเต็ม (ได้ ${JSON.stringify(v)})`);
};

/** ผลขั้นนับ (แถวจาก แถวจากผลCLI) → { จะลบ, เหลือ, ปนแถวจริง } · อ่านไม่ได้/ผิดรูป/มองไม่เห็นทุกแถว = โยนข้อผิดพลาด */
export function ตรวจผลนับ(แถว) {
  if (!Array.isArray(แถว) || แถว.length !== 1) throw new Error(`ผลนับต้องได้ 1 แถว (ได้ ${Array.isArray(แถว) ? แถว.length : typeof แถว} แถว)`);
  const r = แถว[0];
  if (!r || typeof r !== "object") throw new Error("ผลนับไม่ใช่แถวข้อมูล");
  const ขาด = คอลัมน์นับ.filter(k => !(k in r));
  if (ขาด.length) throw new Error(`ผลนับไม่มีคอลัมน์ ${ขาด.join(" · ")} (ได้คอลัมน์: ${Object.keys(r).join(" · ") || "ไม่มี"}) — ชื่อคอลัมน์อาจถูกแปลง`);
  if (r.เห็นทุกแถว !== true) throw new Error(`บัญชีที่ CLI ใช้มองไม่เห็นทุกแถว (เห็นทุกแถว = ${JSON.stringify(r.เห็นทุกแถว)})`);
  const จะลบ = เลข("จะลบ", r.จะลบ), เหลือ = เลข("เหลือ", r.เหลือ), ปน = เลข("ปนแถวจริง", r.ปนแถวจริง);
  if (จะลบ + เหลือ === 0) throw new Error("ผลนับบันทึกการใช้งานทั้งตารางได้ 0 — ฐานจริงต้องมีบันทึกเสมอ (อ่านผิดหรือมองไม่เห็น)");
  if (ปน > จะลบ) throw new Error(`ผลนับขัดกันเอง: ปนแถวจริง ${ปน} มากกว่าจะลบ ${จะลบ}`);
  return { จะลบ, เหลือ, ปนแถวจริง: ปน };
}
