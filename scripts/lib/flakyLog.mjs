// กติกา: ข้อไหนไม่นิ่งครบ 3 ครั้งโดยยังไม่มีบรรทัด "ต้นเหตุ" → รอบตรวจเต็มรายงาน "ต้องหาต้นเหตุ" และไม่บันทึกผลผ่าน = ขึ้นเว็บไม่ได้
//   ไฟล์นี้ไม่นับในลายนิ้วมือโค้ด (scripts/lib/commitGate.mjs) — เพิ่มบรรทัดต้นเหตุแล้วรันรอบตรวจใหม่ ไม่ต้องแก้โค้ด
// ข้อทดสอบ: tests/tools/flaky-log.test.mjs
import { appendFileSync, existsSync, readFileSync } from "node:fs";
import path from "node:path";

export const ไฟล์บันทึกไม่นิ่ง = "tests/flaky-log.txt";
export const เกณฑ์ = 3;
const หัวไฟล์ = `# ข้อทดสอบไม่นิ่ง (ตกแล้วผ่านตอนรันซ้ำ) — รอบตรวจเต็มเขียนบรรทัด "ไม่นิ่ง" เอง · คนเขียนบรรทัด "ต้นเหตุ" เมื่อหาต้นเหตุได้
# ครบ ${เกณฑ์} ครั้งโดยไม่มีต้นเหตุ = รอบตรวจเต็มไม่ผ่าน (scripts/lib/flakyLog.mjs · บอสสั่ง 26 ต.ค. 69)
# รูปแบบ:  ไม่นิ่ง | YYYY-MM-DD | รอบ | ไฟล์ › ชื่อข้อ      ต้นเหตุ | YYYY-MM-DD | ไฟล์ › ชื่อข้อ | ข้อความ
`;

// รหัสขั้นนำหน้าชื่อข้อ ([D3] [H9x] · ตัวตรวจ check-flow-step-tests · 28 ต.ค. 69) ไม่นับในตัวระบุ — ติดรหัสภายหลังแล้วประวัติไม่นิ่งของข้อเดิมไม่หลุด
const ตัดรหัสขั้น = (ชื่อ) => String(ชื่อ).trim().replace(/^(\[[DH]\d+[a-z]?\]\s*)+/, "");
export const ตัวระบุ = (ไฟล์, ชื่อ) => `${String(ไฟล์).replaceAll("\\", "/").split("/").pop()} › ${ตัดรหัสขั้น(ชื่อ)}`;

/** ข้อที่ไม่นิ่งจากรายงาน JSON ของ playwright (สถานะ flaky = ตกครั้งแรก ผ่านตอนรันซ้ำ) */
export function ข้อไม่นิ่งจากรายงาน(ไฟล์รายงาน) {
  const ผล = [];
  for (const f of ไฟล์รายงาน) {
    let r; try { r = JSON.parse(readFileSync(f, "utf8")); } catch { continue; }
    const เดิน = (s) => {
      for (const x of s.suites ?? []) เดิน(x);
      for (const sp of s.specs ?? []) for (const t of sp.tests ?? []) if (t.status === "flaky") ผล.push(ตัวระบุ(sp.file, sp.title));
    };
    เดิน(r);
  }
  return [...new Set(ผล)];
}

const อ่าน = (cwd) => {
  const f = path.join(cwd, ไฟล์บันทึกไม่นิ่ง);
  return existsSync(f) ? readFileSync(f, "utf8").split(/\r?\n/).filter(l => l && !l.startsWith("#")) : [];
};

/** ต่อท้ายบรรทัด "ไม่นิ่ง" ของรอบนี้ */
export function บันทึกไม่นิ่ง(รายการ, { รอบ, วันที่ = new Date(Date.now() + 7 * 3_600_000).toISOString().slice(0, 10), cwd = process.cwd() } = {}) {
  if (!รายการ.length) return;
  const f = path.join(cwd, ไฟล์บันทึกไม่นิ่ง);
  if (!existsSync(f)) appendFileSync(f, หัวไฟล์);
  appendFileSync(f, รายการ.map(k => `ไม่นิ่ง | ${วันที่} | ${รอบ} | ${k}`).join("\n") + "\n");
}

/** สรุปต่อข้อ: { ครั้ง, ต้นเหตุ[], วันที่[] } */
export function สรุป(cwd = process.cwd()) {
  const ต่อข้อ = new Map();
  // บรรทัดที่คนเขียน (ต้นเหตุ) อาจพิมพ์ชื่อข้อพร้อมรหัสขั้น — ตัดออกแบบเดียวกับ ตัวระบุ() ให้นับเป็นข้อเดียวกัน
  const ปกติ = (k) => { const i = k.indexOf(" › "); return i < 0 ? k : `${k.slice(0, i)} › ${ตัดรหัสขั้น(k.slice(i + 3))}`; };
  const ของ = (k0) => { const k = ปกติ(k0); if (!ต่อข้อ.has(k)) ต่อข้อ.set(k, { ครั้ง: 0, ต้นเหตุ: [], วันที่: [] }); return ต่อข้อ.get(k); };
  for (const l of อ่าน(cwd)) {
    const ช่อง = l.split(" | ").map(x => x.trim());
    if (ช่อง[0] === "ไม่นิ่ง" && ช่อง.length >= 4) { const x = ของ(ช่อง.slice(3).join(" | ")); x.ครั้ง++; x.วันที่.push(ช่อง[1]); }
    else if (ช่อง[0] === "ต้นเหตุ" && ช่อง.length >= 4 && ช่อง[3]) ของ(ช่อง[2]).ต้นเหตุ.push(ช่อง.slice(3).join(" | "));
  }
  return ต่อข้อ;
}

/** ข้อที่ต้องหาต้นเหตุ (ครบเกณฑ์ ไม่มีต้นเหตุ) */
export function ต้องหาต้นเหตุ(cwd = process.cwd()) {
  return [...สรุป(cwd)].filter(([, x]) => x.ครั้ง >= เกณฑ์ && !x.ต้นเหตุ.length).map(([k, x]) => ({ ข้อ: k, ...x }));
}

/** ท้ายรอบตรวจเต็ม (scripts/test-prodbuild.mjs): จดข้อไม่นิ่งของรอบนี้ แล้วตัดสิน · คืน true = รอบนี้ต้องไม่ผ่าน */
export function ตรวจไม่นิ่งท้ายรอบ(ไฟล์รายงาน, { รอบ, วันที่, cwd = process.cwd(), log = console.log, err = console.error } = {}) {
  const ไม่นิ่ง = ข้อไม่นิ่งจากรายงาน(ไฟล์รายงาน);
  บันทึกไม่นิ่ง(ไม่นิ่ง, { รอบ, วันที่, cwd });
  if (ไม่นิ่ง.length) {
    const นับ = สรุป(cwd);
    log(`▶ ข้อไม่นิ่งรอบนี้ ${ไม่นิ่ง.length} ข้อ → ${ไฟล์บันทึกไม่นิ่ง} (commit ไฟล์นี้พร้อมงาน)`);
    for (const k of ไม่นิ่ง) log(`   ${k} · ครั้งที่ ${นับ.get(k)?.ครั้ง ?? 1}${นับ.get(k)?.ต้นเหตุ.length ? " · มีต้นเหตุแล้ว" : ""}`);
  }
  const ค้าง = ต้องหาต้นเหตุ(cwd);
  if (!ค้าง.length) return false;
  err(`⛔ ต้องหาต้นเหตุ — ข้อไม่นิ่งครบ ${เกณฑ์} ครั้งโดยยังไม่มีบันทึกต้นเหตุ ${ค้าง.length} ข้อ · รอบนี้ไม่ผ่าน (ขึ้นเว็บไม่ได้)`);
  for (const x of ค้าง) err(`   ${x.ข้อ} · ${x.ครั้ง} ครั้ง (${x.วันที่.join(", ")})`);
  err(`   หาต้นเหตุแล้วเพิ่มบรรทัด "ต้นเหตุ | วันที่ | <ข้อ> | <ต้นเหตุ/ที่แก้>" ใน ${ไฟล์บันทึกไม่นิ่ง} แล้วรันรอบตรวจใหม่ · ห้ามแก้ด้วยการเพิ่มเวลารอ`);
  return true;
}
