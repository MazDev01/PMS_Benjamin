/** ตรวจรายการข้อความ → จุดที่เจอคำห้าม */
export function หาคำห้าม(ไฟล์, ข้อความ) {
  const เจอ = [];
  for (const { text, line } of ข้อความ)
    for (const k of คำห้าม)
      if ((k.แบบ ? new RegExp(k.แบบ, "u").test(text) : text.includes(k.ห้าม)) && !ยกเว้น.some(y => y.ไฟล์ === ไฟล์ && y.คำ === k.ห้าม))
        เจอ.push({ ไฟล์, line, ห้าม: k.ห้าม, ใช้: k.ใช้, text });
  return เจอ;
}
