// ── รอบตรวจเต็มที่มีข้อทดสอบไม่นิ่ง = ไม่นับว่าผ่านจนกว่าบอสรับทราบ (บอสสั่ง 11 พ.ย. 69) ─────────────────────────────────
//
// เหตุ: รอบตรวจเต็มนับ "ตกครั้งแรก ผ่านตอนรันซ้ำ" เป็นผ่าน (แค่ตัวเลข flaky 1) — บอสไม่เห็นชื่อข้อ · ข้อไม่นิ่งหลุดขึ้นเว็บโดยไม่มีใครรับรู้
// กติกา:
//   ① ทุกตัวรัน (ทดสอบส่วนตัว · รอบตรวจเต็ม · รันซ้ำไฟล์ที่ตกท้ายรอบ) ขึ้นชื่อข้อไม่นิ่งท้ายผลชัด ๆ ทุกครั้ง (พิมพ์สรุปไม่นิ่ง)
//   ② รอบตรวจเต็มผ่าน (ตก 0) แต่มีข้อไม่นิ่ง → บันทึกผลแบบ "รอรับทราบ" (gate-passed-code.txt บรรทัดมีคำว่า รอรับทราบ ·
//      gate-passed-migrations.json มีช่อง รอรับทราบ) → session:merge / pre-push / Vercel / db:push:prod ปฏิเสธจนกว่าบอสรับทราบ
//   ③ ทางรับทราบ: npm run round:ack -- --รอบ <ป้ายรอบ> (scripts/round-ack.mjs) — บอสรันเองในหน้าต่างคำสั่ง พิมพ์ป้ายรอบยืนยัน
//      AI รันไม่ได้ (เจอตัวแปร CLAUDECODE/AI_AGENT หรือไม่ใช่หน้าต่างคำสั่งจริง = ปฏิเสธ) · บันทึกเวลา + ชื่อข้อที่รับทราบ
//   ไฟล์ supabase/gate-flaky-ack.txt (commit พร้อมงาน · ไม่นับในลายนิ้วมือโค้ด · merge=union) บรรทัดละเหตุการณ์:
//     รอรับทราบ | <ป้ายรอบ> | <เวลา> | <sha> | <ข้อ> ; <ข้อ>     ← รอบตรวจเต็มเขียน
//     รับทราบ   | <ป้ายรอบ> | <เวลา> | <ผู้รับทราบ> | <ข้อ> ; <ข้อ>  ← round:ack เขียน (บอส)
//   ข้อไม่นิ่งยังจด tests/flaky-log.txt + เข้ารายการรอบหน้าเหมือนเดิม (scripts/lib/flakyLog.mjs)
// ข้อทดสอบ: tests/tools/flaky-ack.test.mjs
import { appendFileSync, existsSync, readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { ข้อไม่นิ่งจากรายงาน } from "./flakyLog.mjs";

export const ไฟล์รับทราบ = "supabase/gate-flaky-ack.txt";
export const คำรอรับทราบ = "รอรับทราบ";
const หัวไฟล์ = "# รอบตรวจเต็มที่มีข้อไม่นิ่ง — รอบตรวจเขียน \"รอรับทราบ\" · บอสรัน npm run round:ack เขียน \"รับทราบ\" (scripts/lib/flakyAck.mjs) ห้ามแก้มือ\n";
const เวลาไทย = () => new Date(Date.now() + 7 * 3_600_000).toISOString().slice(0, 19).replace("T", " ");

/** บรรทัดของไฟล์รับทราบ (จากเนื้อไฟล์) → [{ ชนิด, ป้าย, เวลา, ช่อง4, ข้อ[] }] */
export function แยกบรรทัด(เนื้อ) {
  return String(เนื้อ ?? "").split(/\r?\n/).filter(l => l && !l.startsWith("#")).map(l => {
    const ช่อง = l.split(" | ").map(x => x.trim());
    return { ชนิด: ช่อง[0], ป้าย: ช่อง[1] ?? "", เวลา: ช่อง[2] ?? "", ช่อง4: ช่อง[3] ?? "", ข้อ: (ช่อง.slice(4).join(" | ") || "").split(" ; ").filter(Boolean) };
  });
}
const อ่านไฟล์ = (cwd) => { const f = path.join(cwd, ไฟล์รับทราบ); return existsSync(f) ? readFileSync(f, "utf8") : ""; };

/** รอบตรวจเต็มผ่านแต่มีข้อไม่นิ่ง → จด "รอรับทราบ" */
export function จดรอรับทราบ({ ป้าย, sha, ข้อ, cwd = process.cwd() }) {
  const f = path.join(cwd, ไฟล์รับทราบ);
  if (!existsSync(f)) appendFileSync(f, หัวไฟล์);
  appendFileSync(f, `${คำรอรับทราบ} | ${ป้าย} | ${เวลาไทย()} | ${sha.slice(0, 12)} | ${ข้อ.join(" ; ")}\n`);
}

/** สถานะการรับทราบของรอบ จากเนื้อไฟล์ · { รอ: [{ป้าย, sha, ข้อ}], รับทราบแล้ว: Set<ป้าย> } */
export function สถานะ(เนื้อ) {
  const บรรทัด = แยกบรรทัด(เนื้อ);
  const รับ = new Set(บรรทัด.filter(b => b.ชนิด === "รับทราบ").map(b => b.ป้าย));
  const รอ = บรรทัด.filter(b => b.ชนิด === คำรอรับทราบ && !รับ.has(b.ป้าย)).map(b => ({ ป้าย: b.ป้าย, sha: b.ช่อง4, ข้อ: b.ข้อ }));
  return { รอ, รับทราบแล้ว: รับ };
}
export const สถานะในเครื่อง = (cwd = process.cwd()) => สถานะ(อ่านไฟล์(cwd));
/** สถานะจากไฟล์ใน commit (ตรวจแบบ Vercel/pre-push — ไม่พึ่งไฟล์ในเครื่อง) */
export function สถานะในcommit(sha, cwd = process.cwd()) {
  let เนื้อ = "";
  try { เนื้อ = execFileSync("git", ["show", `${sha}:${ไฟล์รับทราบ}`], { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }); } catch { /* ยังไม่มีไฟล์ */ }
  return สถานะ(เนื้อ);
}

/** บอสรับทราบรอบ (เรียกจาก scripts/round-ack.mjs เท่านั้น) · คืนข้อที่รับทราบ */
export function จดรับทราบ({ ป้าย, ผู้รับทราบ = "บอส", cwd = process.cwd() }) {
  const ค้าง = สถานะในเครื่อง(cwd).รอ.find(x => x.ป้าย === ป้าย);
  if (!ค้าง) throw new Error(`ไม่มีรอบ "${ป้าย}" ที่รอรับทราบ`);
  appendFileSync(path.join(cwd, ไฟล์รับทราบ), `รับทราบ | ${ป้าย} | ${เวลาไทย()} | ${ผู้รับทราบ} | ${ค้าง.ข้อ.join(" ; ")}\n`);
  return ค้าง;
}

/** ข้อความเหตุผลเมื่อยังรอรับทราบ (ใช้ทั้ง session:merge / pre-push / Vercel / db:push) */
export const เหตุรอรับทราบ = (ป้าย, ข้อ = []) =>
  `รอบตรวจ ${ป้าย} ผ่านแต่มีข้อทดสอบไม่นิ่ง ${ข้อ.length} ข้อ — ยังไม่นับว่าผ่าน รอบอสรับทราบ (บอสรันเอง: npm run round:ack -- --รอบ ${ป้าย}) แล้ว commit ${ไฟล์รับทราบ}`
  + (ข้อ.length ? `\n   ${ข้อ.join("\n   ")}` : "");

/** ขึ้นท้ายผลทุกตัวรัน: ชื่อข้อที่ตกครั้งแรกแล้วผ่านตอนรันซ้ำ (ไม่ใช่แค่ตัวเลข) */
export function พิมพ์สรุปไม่นิ่ง(ข้อ, { log = console.log, รอบเต็ม = false } = {}) {
  if (!ข้อ.length) { log("▶ ข้อทดสอบไม่นิ่ง (ตกครั้งแรก ผ่านตอนรันซ้ำ): ไม่มี"); return; }
  log(`\n⚠️ ข้อทดสอบไม่นิ่ง ${ข้อ.length} ข้อ (ตกครั้งแรก ผ่านตอนรันซ้ำ — ไม่นับว่าผ่าน${รอบเต็ม ? " · รอบตรวจนี้รอบอสรับทราบ" : " · รายงานชื่อ + เข้ารายการรอบหน้า"}):`);
  ข้อ.forEach((k, i) => log(`   ${i + 1}. ${k}`));
}

/** ข้อไม่นิ่งของรอบ = สถานะ flaky ในรายงาน playwright + ข้อที่ตกในรอบหลักแล้วผ่านตอนรันซ้ำทั้งไฟล์ (gateRerun) */
export const ข้อไม่นิ่งของรอบ = (ไฟล์รายงาน, เพิ่ม = []) => [...new Set([...ข้อไม่นิ่งจากรายงาน(ไฟล์รายงาน), ...เพิ่ม])];
