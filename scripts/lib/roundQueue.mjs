// กติกา (คำบอส):
//   · ไม่มีตัดรอบอัตโนมัติ · ระหว่างวันแต่ละเซสชันแก้แล้วรันแค่ข้อทดสอบของส่วนที่ตัวเองแก้ แล้วเพิ่มงานเข้ารายการรอรอบ (round:add)
//   · ห้ามเซสชันรันรอบตรวจเต็มเอง — ก่อนรอบเต็มทุกครั้ง คนรวมงานถามบอสด้วยกล่องคำถาม (ข้อมูลจาก round:list)
//     ตัวเลือก "ตรวจเลย" / "รอเพิ่มงานก่อน" · ไม่ตอบ = ไม่ตรวจ · บอสตอบ "ตรวจเลย" → round:close -- --บอสตอบ "<เวลา>"
