//   · ข้อยกเว้น: บั๊กเว็บจริงที่ทำข้อมูลเสีย = ถามบอสทันที ไม่รอรวมรอบ — ยังปิดรอบด้วยคำสั่งเดียวกัน ใส่ --เร่งด่วน
// ไฟล์ (จุดกลางนอก repo — ทุกโฟลเดอร์เซสชันเห็นตรงกัน แบบทะเบียนเซสชัน):
//   <ที่> = PMS_ROUND_DIR (ข้อทดสอบชี้ที่อื่น · ย้ายที่เก็บเท่านั้น ไม่ได้ปิดตัวกัน) หรือ C:/.claude/pms-round
//   <ที่>/queue.json     รายการรอรอบ { งาน: [{ id, งาน, เซสชัน, ทดสอบผ่าน, เวลาเพิ่ม, ผ่านเมื่อ? }] }
//   <ที่>/round.json     รอบที่ปิดล่าสุด { รอบ, สถานะ: "ปิดแล้ว"|"กำลังตรวจ"|"ผ่านแล้ว", บอสตอบ, เร่งด่วน, ปิดเมื่อ, งาน[], ตัดออก[], ลายนิ้วมือ, ... }
//   <ที่>/rounds/<รอบ>.json  สำเนาของทุกรอบที่ปิด (ประวัติ · ไม่ลบ)
// ข้อทดสอบ: tests/tools/round-queue.test.mjs
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { ตัวล็อก } from "./fileLock.mjs";

export const ที่เก็บรอบ = () => process.env.PMS_ROUND_DIR
  || (process.platform === "win32" ? "C:/.claude/pms-round" : path.join(os.homedir(), ".pms-round"));
const ไฟล์ = (ชื่อ) => path.join(ที่เก็บรอบ(), ชื่อ);
const อ่าน = (ชื่อ, ว่าง) => { try { return JSON.parse(readFileSync(ไฟล์(ชื่อ), "utf8")); } catch { return ว่าง; } };
const เขียน = (ชื่อ, ค่า) => {
  mkdirSync(path.dirname(ไฟล์(ชื่อ)), { recursive: true });
  const ชั่วคราว = `${ไฟล์(ชื่อ)}.${process.pid}.tmp`;
  writeFileSync(ชั่วคราว, JSON.stringify(ค่า, null, 2) + "\n");
  renameSync(ชั่วคราว, ไฟล์(ชื่อ));   // แทนที่ทั้งไฟล์ทีเดียว — คนอ่านพร้อมกันไม่เห็นไฟล์ครึ่ง ๆ
};
/** ทำงานเขียนภายใต้ล็อกของที่เก็บรอบ — สองเซสชันเพิ่มงานพร้อมกันไม่ทับกัน */
function ใต้ล็อก(งาน, fn) {
  mkdirSync(ที่เก็บรอบ(), { recursive: true });
  const ล็อก = ตัวล็อก({ path: ไฟล์(".lock"), envHeld: "PMS_ROUND_LOCK_HELD", เรื่อง: "แก้รายการรอรอบตรวจ" })(งาน, { รอ: 30_000 });
  try { return fn(); } finally { ล็อก.release(); }
}

export const อ่านรายการ = () => อ่าน("queue.json", { งาน: [] }).งาน ?? [];
export const อ่านรอบ = () => อ่าน("round.json", null);
const เวลาไทย = (iso) => iso ? new Date(iso).toLocaleString("th-TH", { timeZone: "Asia/Bangkok", hour12: false }) : "—";

/** ลายนิ้วมือของงานชุดหนึ่ง — เปลี่ยนเมื่อมีงานเพิ่ม/หาย/แก้ข้อความ/สถานะทดสอบเปลี่ยน · ไม่ขึ้นกับลำดับในไฟล์ */
export const ลายนิ้วมือ = (งาน) => createHash("sha256").update(JSON.stringify(
  [...งาน].map(x => [x.id, x.งาน, x.เซสชัน, !!x.ทดสอบผ่าน]).sort((a, b) => String(a[0]).localeCompare(String(b[0]))))).digest("hex");

/** เพิ่มงานเข้ารายการรอรอบ → คืนแถวที่เพิ่ม */
export function เพิ่มงาน({ งาน, เซสชัน, ทดสอบผ่าน = false }) {
  if (!String(งาน ?? "").trim()) throw new Error("ต้องระบุงาน (--งาน \"<ข้อความ>\")");
  if (!String(เซสชัน ?? "").trim()) throw new Error("ต้องระบุเซสชัน (--เซสชัน <ชื่อ>)");
  return ใต้ล็อก(`เพิ่มงาน ${งาน}`, () => {
    const รายการ = อ่านรายการ();
    const id = `r${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`;
    const แถว = { id, งาน: String(งาน).trim(), เซสชัน: String(เซสชัน).trim(), ทดสอบผ่าน: !!ทดสอบผ่าน, เวลาเพิ่ม: new Date().toISOString(),
      ...(ทดสอบผ่าน ? { ผ่านเมื่อ: new Date().toISOString() } : {}) };
    เขียน("queue.json", { งาน: [...รายการ, แถว] });
    return แถว;
  });
}

/** ตั้งสถานะ "ทดสอบส่วนตัวผ่าน" ของงานที่มีอยู่ */
export function ตั้งผ่าน(id) {
  return ใต้ล็อก(`ตั้งผ่าน ${id}`, () => {
    const รายการ = อ่านรายการ();
    const แถว = รายการ.find(x => x.id === id);
    if (!แถว) throw new Error(`ไม่มีงานรหัส ${id} ในรายการรอรอบ (ดู npm run round:list)`);
    แถว.ทดสอบผ่าน = true; แถว.ผ่านเมื่อ = new Date().toISOString();
    เขียน("queue.json", { งาน: รายการ });
    return แถว;
  });
}

/** ข้อความพร้อมใช้ในกล่องคำถามถึงบอส (round:list) */
export function สรุปรายการ() {
  const รายการ = อ่านรายการ(), รอบ = อ่านรอบ();
  const บรรทัด = รายการ.map((x, i) => `${i + 1}. ${x.งาน} — เซสชัน ${x.เซสชัน} · ${x.ทดสอบผ่าน ? "ทดสอบส่วนตัวผ่าน" : "ยังไม่ผ่านทดสอบส่วนตัว"} · เพิ่ม ${เวลาไทย(x.เวลาเพิ่ม)} · รหัส ${x.id}`);
  const ยังไม่ผ่าน = รายการ.filter(x => !x.ทดสอบผ่าน);
  return [
    `รายการรอรอบตรวจเต็ม ${รายการ.length} งาน (ทดสอบส่วนตัวผ่าน ${รายการ.length - ยังไม่ผ่าน.length} · ยังไม่ผ่าน ${ยังไม่ผ่าน.length})`,
    ...(บรรทัด.length ? บรรทัด : ["(ยังไม่มีงานในรายการ)"]),
    ...(ยังไม่ผ่าน.length ? [`งานที่ยังไม่เสร็จ (ปิดรอบไม่ได้จนกว่าจะผ่าน หรือตัดออกด้วย --ตัด <รหัส>): ${ยังไม่ผ่าน.map(x => x.id).join(" · ")}`] : []),
    `ลายนิ้วมือรายการ: ${ลายนิ้วมือ(รายการ).slice(0, 12)}`,
    `รอบล่าสุด: ${รอบ ? `${รอบ.รอบ} · ${รอบ.สถานะ} · บอสตอบ ${รอบ.บอสตอบ}${รอบ.เร่งด่วน ? " · เร่งด่วน" : ""}` : "ยังไม่เคยปิดรอบ"}`,
    "กล่องคำถามถึงบอส: แสดงรายการงานข้างบน · งานที่ยังไม่เสร็จ · ต้อง db:push ไหม · ตรวจเสร็จราวกี่โมง · ตัวเลือก \"ตรวจเลย\" / \"รอเพิ่มงานก่อน\" (ไม่ตอบ = ไม่ตรวจ)",
  ].join("\n");
}

/** ปิดรอบตามคำตอบ "ตรวจเลย" ของบอส → สำเนารายการ + ลายนิ้วมือ + เวลาที่บอสตอบ */
export function ปิดรอบ({ บอสตอบ, ตัด = [], เร่งด่วน = false }) {
  if (!String(บอสตอบ ?? "").trim()) throw new Error("ต้องระบุเวลาที่บอสตอบ \"ตรวจเลย\" (--บอสตอบ \"<เวลา>\") — ยังไม่ได้ถามบอส = ห้ามปิดรอบ");
  return ใต้ล็อก("ปิดรอบ", () => {
    const รายการ = อ่านรายการ();
    const ไม่มี = ตัด.filter(id => !รายการ.some(x => x.id === id));
    if (ไม่มี.length) throw new Error(`ตัดออกไม่ได้ — ไม่มีงานรหัส ${ไม่มี.join(", ")} ในรายการ`);
    const ในรอบ = รายการ.filter(x => !ตัด.includes(x.id));
    if (!ในรอบ.length) throw new Error("ไม่มีงานในรอบ — เพิ่มงานด้วย npm run round:add ก่อน");
    const ยังไม่ผ่าน = ในรอบ.filter(x => !x.ทดสอบผ่าน);
    if (ยังไม่ผ่าน.length) throw new Error(`ปิดรอบไม่ได้ — งานที่ทดสอบส่วนตัวยังไม่ผ่าน: ${ยังไม่ผ่าน.map(x => `${x.id} (${x.งาน} · ${x.เซสชัน})`).join(" · ")} — ตั้งผ่านด้วย round:pass หรือตัดออกจากรอบด้วย --ตัด <รหัส>`);
    const เดิม = อ่านรอบ();
    if (เดิม && เดิม.สถานะ !== "ผ่านแล้ว" && เดิม.สถานะ !== "ยกเลิก") throw new Error(`รอบ ${เดิม.รอบ} ปิดไว้แล้วยังไม่ผ่าน (${เดิม.สถานะ}) — รันรอบเต็มของรอบนั้นให้จบก่อน · เปลี่ยนชุดงาน = ยกเลิกรอบเดิมด้วย round:cancel แล้วถามบอสใหม่`);
    const ปิดเมื่อ = new Date().toISOString();
    const รอบ = { รอบ: `รอบ-${ปิดเมื่อ.replace(/[-:.TZ]/g, "").slice(0, 14)}`, สถานะ: "ปิดแล้ว", บอสตอบ: String(บอสตอบ).trim(), เร่งด่วน: !!เร่งด่วน, ปิดเมื่อ,
      งาน: ในรอบ, ตัดออก: ตัด, ลายนิ้วมือ: ลายนิ้วมือ(ในรอบ) };
    เขียน("round.json", รอบ);
    เขียน(path.join("rounds", `${รอบ.รอบ}.json`), รอบ);
    return รอบ;
  });
}

/** ยกเลิกรอบที่ปิดไว้แต่ยังไม่ผ่าน (บอสเปลี่ยนใจ / ชุดงานเปลี่ยน) — ต้องถามบอสแล้วปิดรอบใหม่ */
export function ยกเลิกรอบ(เหตุ) {
  if (!String(เหตุ ?? "").trim()) throw new Error("ต้องระบุเหตุที่ยกเลิกรอบ (--เหตุ \"<ข้อความ>\")");
  return ใต้ล็อก("ยกเลิกรอบ", () => {
    const รอบ = อ่านรอบ();
    if (!รอบ || รอบ.สถานะ === "ผ่านแล้ว" || รอบ.สถานะ === "ยกเลิก") throw new Error("ไม่มีรอบที่ปิดไว้และยังไม่ผ่าน");
    const ยกเลิก = { ...รอบ, สถานะ: "ยกเลิก", ยกเลิกเมื่อ: new Date().toISOString(), เหตุยกเลิก: String(เหตุ).trim() };
    เขียน(path.join("rounds", `${รอบ.รอบ}.json`), ยกเลิก);
    เขียน("round.json", ยกเลิก);
    return ยกเลิก;
  });
}

/**
 * ตรวจก่อนเริ่มรอบตรวจเต็ม (test:prodbuild ไม่ระบุไฟล์ · รวม PMS_GATE_FULL=1 และโหมดรันต่อ)
 * → { ได้: true, รอบ } หรือ { ได้: false, เหตุ } (ภาษาไทย บอกทางแก้)
 *   รันต่อเฉพาะไฟล์ที่ตก = รอบเดิม (สถานะ "กำลังตรวจ") → ได้ ตราบที่รายการยังเท่าตอนปิด
 */
export function ตรวจก่อนรอบเต็ม() {
  const รอบ = อ่านรอบ();
  const ถามบอส = "คนรวมงานถามบอสด้วยกล่องคำถาม (ข้อมูลจาก npm run round:list) → บอสตอบ \"ตรวจเลย\" → npm run round:close -- --บอสตอบ \"<เวลา>\"";
  if (!รอบ || รอบ.สถานะ === "ผ่านแล้ว" || รอบ.สถานะ === "ยกเลิก")
    return { ได้: false, เหตุ: `ยังไม่ปิดรอบ${รอบ ? ` (รอบล่าสุด ${รอบ.รอบ} ${รอบ.สถานะ === "ผ่านแล้ว" ? "ผ่านและใช้ไปแล้ว — ใช้ซ้ำไม่ได้" : "ยกเลิกแล้ว"})` : ""} — รอบตรวจเต็มต้องได้คำอนุมัติของบอสก่อน: ${ถามบอส}` };
  const ตอนนี้ = อ่านรายการ().filter(x => !(รอบ.ตัดออก ?? []).includes(x.id));
  if (ลายนิ้วมือ(ตอนนี้) !== รอบ.ลายนิ้วมือ) {
    const ใน = new Set(รอบ.งาน.map(x => x.id)), เพิ่ม = ตอนนี้.filter(x => !ใน.has(x.id)), หาย = รอบ.งาน.filter(x => !ตอนนี้.some(y => y.id === x.id));
    return { ได้: false, เหตุ: `รายการรอรอบเปลี่ยนหลังบอสอนุมัติรอบ ${รอบ.รอบ}${เพิ่ม.length ? ` · เพิ่ม: ${เพิ่ม.map(x => x.งาน).join(" · ")}` : ""}${หาย.length ? ` · หาย: ${หาย.map(x => x.งาน).join(" · ")}` : ""}${!เพิ่ม.length && !หาย.length ? " · งานในรอบถูกแก้" : ""} — บอสอนุมัติชุดงานเดิม: ยกเลิกรอบ (round:cancel) แล้ว${ถามบอส}` };
  }
  return { ได้: true, รอบ };
}

/** รอบเต็มเริ่ม (ผ่านตัวตรวจแล้ว) → สถานะ "กำลังตรวจ" · รันต่อจากรอบที่ตกใช้รอบเดิม */
export function เริ่มรอบ(sha) {
  return ใต้ล็อก("เริ่มรอบตรวจเต็ม", () => {
    const รอบ = อ่านรอบ();
    if (!รอบ) return null;
    const ใหม่ = { ...รอบ, สถานะ: "กำลังตรวจ", รัน: [...(รอบ.รัน ?? []), { sha, เริ่ม: new Date().toISOString() }] };
    เขียน("round.json", ใหม่);
    return ใหม่;
  });
}

/** รอบเต็มผ่าน → รอบนั้นปิดจบ (ใช้ซ้ำไม่ได้) · งานของรอบออกจากรายการรอรอบ (งานที่ตัดออกยังรอรอบหน้า) */
export function จบรอบ({ sha, ป้าย }) {
  return ใต้ล็อก("จบรอบตรวจเต็ม", () => {
    const รอบ = อ่านรอบ();
    if (!รอบ) return null;
    const จบ = { ...รอบ, สถานะ: "ผ่านแล้ว", ผ่านเมื่อ: new Date().toISOString(), ผ่านที่: sha, ป้าย };
    เขียน("round.json", จบ);
    เขียน(path.join("rounds", `${รอบ.รอบ}.json`), จบ);
    const ใน = new Set(รอบ.งาน.map(x => x.id));
    เขียน("queue.json", { งาน: อ่านรายการ().filter(x => !ใน.has(x.id)) });
    return จบ;
  });
}

