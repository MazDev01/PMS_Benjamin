"use client";

// ─── #5 แนวโน้มใบเสนอราคา ─────────────────────────────────────────────────────
// เดินตามแถบกรองช่วงเวลาแล้ว (บอสสั่ง 25 ส.ค. 69 "เอาทุกกราฟใน hq")
//   ช่วงยาว (ปีนี้) → รายเดือน · ช่วงสั้น (วันนี้/7 วัน/เดือนนี้) → รายวัน
// ผู้เรียกเป็นคนตัดช่องมาให้แล้ว การ์ดนี้แค่วาด — ป้ายหน่วยจึงรับมาเป็น prop
import { GroupedBarChart } from "@pms/shared/components/ui/Charts";

// trend = 12 ช่องย้อนหลัง (bar=ใบทั้งหมด · line=ตอบรับ) คำนวณมาแล้ว (DB byMonth หรือ client) — M9 Phase 2
export function QuotationTrendChart({ trend, หน่วยเวลา = "รายเดือน" }: {
  trend: { months: string[]; bar: number[]; line: number[] };
  /** "รายเดือน" หรือ "รายวัน" — ต้องตรงกับช่องที่ผู้เรียกตัดมา ไม่งั้นหัวการ์ดโกหก */
  หน่วยเวลา?: string;
}) {
  return (
    // ไม่ตรึงความสูงด้วย .chart-* — การ์ดนี้เป็น SVG ที่ยืดตามความกว้าง
    // ถ้าตรึงแล้วให้เลื่อน = กราฟเส้นโดนตัดครึ่ง (อ่านไม่ได้) ต้องคุมที่สัดส่วน viewBox แทน
    //
    // ⚠️ ระยะห่างด้านล่างต้องเท่ากับช่องไฟของแถวการ์ดถัดไป (.hq-dealer-charts margin-bottom = 24px)
    //   เดิมเป็น 0 → การ์ดแถวถัดไปชนขอบล่างพอดี พอเอาเมาส์ชี้แล้วการ์ดยกตัวขึ้นตามเอฟเฟกต์ hover
    //   ขอบของมันจะพาดทับหัวข้อ "แนวโน้มใบเสนอราคารายเดือน" (ผู้ใช้แจ้ง 14 ส.ค. 69)
    <div className="card" style={{ marginBottom: 24 }}>
      <div className="card-header">
        <div>
          <div className="card-title">แนวโน้มใบเสนอราคา{หน่วยเวลา}</div>
        </div>
        {/* คำอธิบายกำกับใต้หัวข้อถูกเอาออกทั้งระบบ (บอสสั่ง 27 ส.ค. 69) */}
      </div>
      <div className="card-body" style={{ paddingTop: 6 }}>
        {/* vw ต้องใกล้ความกว้างการ์ดจริง ไม่งั้น SVG ถูกสเกลทั้งใบ (ตัวอักษร/เส้นใหญ่ผิดส่วน และการ์ดสูงเกิน)
            การ์ดนี้กินเต็มแถว ≈ 1,130px — เดิมส่ง 560 (ค่าสมัยยังอยู่ในกริด 2 คอลัมน์)
            SVG เลยถูกขยาย 2 เท่า สูง 564px แทนที่จะเป็น 280px */}
        {/* ── แท่งคู่: ใบที่สร้าง (น้ำเงิน) เทียบ ตอบรับ (เขียว) — บอสสั่ง 21 ส.ค. 69 ──────
            เดิมเป็น "แท่ง + เส้น" ซึ่งอ่านยากเมื่อยอดตอบรับน้อย: เส้นเขียวไปแนบเส้นศูนย์
            จนแยกไม่ออกว่าเดือนไหนมีกี่ใบ · แท่งคู่เทียบสองค่าตรง ๆ แบบเดียวกับกราฟ
            "วิเคราะห์ประสิทธิภาพการปิดการขายของดีลเลอร์" ที่บอสอ้างอิง
            ⚠️ สองชุดนี้ห้ามซ้อนกัน (stacked) — ตอบรับเป็นสับเซตของใบที่สร้าง ยอดรวมจะไม่มีความหมาย */}
        <GroupedBarChart
          months={trend.months}
          vw={1130}
          height={280}
          fmt={v => `${Math.round(v)}`}
          series={[
            { name: "ใบเสนอราคาที่สร้าง", color: "#003366", data: trend.bar },
            { name: "ตอบรับ", color: "#059669", data: trend.line },
          ]}
        />
      </div>
    </div>
  );
}
