"use client";
// ── ตารางรายการกลาง: จำนวน/หน่วยคนละคอลัมน์ · หัวคอลัมน์ชิดแนวเดียวกับข้อมูล (บอสสั่ง 30 ต.ค. 69) ─────────────────────────────
//   ทุกตารางที่มีจำนวน/หน่วยใช้ตัวนี้ตัวเดียว: กล่องใบ HQ ฝั่งดีลเลอร์ · ตาราง BOQ ของ HQ · ใบลูกค้า (แผงลีด · แผงดูใบ · ฟอร์มบวก %)
//   · ราคาประเมินวัสดุตอนขอราคา · แม่แบบวัสดุ · หน้าใบเสนอราคา HQ · หน้าลูกค้าดีลเลอร์ — ใบพิมพ์ A4 ใช้ชนิดคอลัมน์ชุดเดียวกัน
//   สร้างบนตารางมาตรฐานของระบบ (.table-wrap · table-layout: fixed · ความกว้างคุมที่ <colgroup>) — ระยะขอบช่อง/หัวคอลัมน์เดียวกับตารางอื่น
//   แนวชิดมาจากชนิดคอลัมน์ (lib/lineItemColumns.ts) ใส่ทั้ง <th> และ <td> → หัวตรงแนวข้อมูลเสมอ · ช่องกรอกในช่องตัวเลขชิดขวาตาม
import type { CSSProperties, HTMLAttributes, ReactNode, Ref } from "react";
import { คลาสของชนิด, type ชนิดคอลัมน์ } from "@pms/shared/lib/lineItemColumns";

export type คอลัมน์รายการ<T> = {
  /** ชื่อคอลัมน์ (data-col บนหัวและช่อง — ข้อทดสอบใช้จับคู่หัวกับข้อมูล) */
  key: string;
  หัว: ReactNode;
  ชนิด: ชนิดคอลัมน์;
  /** ความกว้างใน colgroup (px หรือ %) — ตารางแบบตายตัว: ทุกคอลัมน์ควรกำหนด */
  กว้าง?: number | string;
  ค่า: (แถว: T, i: number) => ReactNode;
  /** สไตล์เพิ่มของช่องข้อมูล (สี/น้ำหนัก) — แนวชิดมาจากชนิดเสมอ ห้ามใส่ textAlign ที่นี่ */
  สไตล์?: (แถว: T, i: number) => CSSProperties | undefined;
  /** ข้อความเต็มเมื่อชี้ (ช่องที่ยาวถูกตัดด้วย …) */
  ชี้?: (แถว: T, i: number) => string | undefined;
  /** ช่องนี้ห้ามตัดเนื้อหา (ช่องกรอก · คำเตือนใต้ชื่อ) */
  แสดงเกิน?: boolean;
};

export function ตารางรายการ<T>({ ป้าย, แถว, คอลัมน์: คอลัมน์ของผู้เรียก, ลำดับ = true, ท้าย, ว่าง = "ยังไม่มีรายการ", แน่น = false, กว้างขั้นต่ำ, กรอบ, คุณสมบัติแถว, อ้างอิง }: {
  /** aria-label ของตาราง */
  ป้าย: string;
  แถว: T[];
  คอลัมน์: คอลัมน์รายการ<T>[];
  /** คอลัมน์ "ลำดับ" นำหน้า (ค่าตั้งต้น: มี — ตารางรายการสินค้าทุกตาราง · บอสสั่ง 30 ต.ค. 69) · ตารางที่ไม่ใช่รายการ (แม่แบบวัสดุ) ปิดได้
   *  ท้ายตารางของผู้เรียกต้องนับคอลัมน์นี้ใน colSpan ด้วย */
  ลำดับ?: boolean;
  /** แถวท้ายตาราง (<tr>…) — ผู้เรียกจัดเอง (ยอดรวม · ต่อ ตร.ม.) · ช่องตัวเลขใส่ className="num" */
  ท้าย?: ReactNode;
  ว่าง?: ReactNode;
  /** ช่องแคบ (.table-wrap.dense) — กล่องในแผง/ฟอร์ม */
  แน่น?: boolean;
  /** ความกว้างขั้นต่ำของตาราง — จอแคบเลื่อนในกรอบตาราง ไม่ดันหน้า */
  กว้างขั้นต่ำ?: number;
  /** สไตล์ของกรอบนอก (ขอบ/มุมโค้ง) */
  กรอบ?: CSSProperties;
  คุณสมบัติแถว?: (แถว: T, i: number) => HTMLAttributes<HTMLTableRowElement> & Record<`data-${string}`, string | undefined>;
  อ้างอิง?: Ref<HTMLTableElement>;
}) {
  const คอลัมน์: คอลัมน์รายการ<T>[] = ลำดับ
    ? [{ key: "no", หัว: "ลำดับ", ชนิด: "ลำดับ", กว้าง: แน่น ? 56 : 68, ค่า: (_r, i) => i + 1 }, ...คอลัมน์ของผู้เรียก]   // ตารางปกติขอบช่องกว้างกว่า (1rem) — 56px ตัดหัว "ลำดับ"
    : คอลัมน์ของผู้เรียก;
  // ชื่อรายการ (ข้อความ) ยาวตัดบรรทัดได้ · ตัวเลขไม่ตัดบรรทัด · ช่องกรอก/คำเตือนไม่ถูกตัด
  const คลาสช่อง = (c: คอลัมน์รายการ<T>) =>
    [คลาสของชนิด(c.ชนิด), c.แสดงเกิน ? "ovf-visible wrap" : c.ชนิด === "ข้อความ" ? "li-wrap" : ""].filter(Boolean).join(" ") || undefined;
  return (
    <div className={`table-wrap table-scroll${แน่น ? " dense" : ""}`} data-line-items style={กรอบ}>
      <table ref={อ้างอิง} aria-label={ป้าย} style={กว้างขั้นต่ำ ? { minWidth: กว้างขั้นต่ำ } : undefined}>
        <colgroup>{คอลัมน์.map(c => <col key={c.key} style={c.กว้าง != null ? { width: c.กว้าง } : undefined} />)}</colgroup>
        <thead>
          <tr>{คอลัมน์.map(c => <th key={c.key} data-col={c.key} className={คลาสของชนิด(c.ชนิด) || undefined}>{c.หัว}</th>)}</tr>
        </thead>
        <tbody>
          {แถว.length === 0 && <tr><td colSpan={คอลัมน์.length} className="empty-row">{ว่าง}</td></tr>}
          {แถว.map((r, i) => (
            <tr key={i} {...คุณสมบัติแถว?.(r, i)}>
              {คอลัมน์.map(c => (
                <td key={c.key} data-col={c.key} title={c.ชี้?.(r, i)} style={c.สไตล์?.(r, i)} className={คลาสช่อง(c)}>{c.ค่า(r, i)}</td>
              ))}
            </tr>
          ))}
        </tbody>
        {ท้าย && <tfoot>{ท้าย}</tfoot>}
      </table>
    </div>
  );
}
