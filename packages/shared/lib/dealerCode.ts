//   เดิมสองฝั่งเติมค่าที่ขาดไปคนละแบบ
//     ฝั่งดีลเลอร์  LocalAdapter.scopeByDealer  ใช้ `?? DEFAULT_DEALER_CODE`  → ไม่มีรหัส = CNX
//     ฝั่งสำนักงานใหญ่  หน้ารวมยอด            ใช้ `?? ""`                   → ไม่มีรหัส = ตกหาย
//   เรคคอร์ดเดียวกันจึงถูกนับที่หนึ่งแต่หายจากอีกที่หนึ่ง → ยอดสองฝั่งไม่ตรงกันแบบหาสาเหตุยาก
//
// กติกา: ไม่มีรหัส / เป็นค่าว่าง = ของสาขาตั้งต้น (สาขาแรกของระบบ)
//   เพราะเรคคอร์ดรุ่นแรกสุดถูกสร้างก่อนที่ระบบจะมีหลายสาขา จึงไม่มีคอลัมน์นี้ติดมา
//   ⚠️ ห้ามเขียน `dealerCode ?? ""` ตรง ๆ ในจุดที่เอาไปกรอง/จัดกลุ่ม/รวมยอดอีก
//      (มีตัวดักใน npm run checks คอยจับไว้แล้ว)
import { DEFAULT_DEALER_CODE } from "./mock";

export function dealerCodeOf(rec: { dealerCode?: string | null } | null | undefined): string {
  const code = String(rec?.dealerCode ?? "").trim();
  return code || DEFAULT_DEALER_CODE;
}
