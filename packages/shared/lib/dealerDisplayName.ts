// ── ชื่อแสดงของดีลเลอร์ (ตรรกะล้วน · ตัวกลางตัวเดียว · บอสสั่ง 6 พ.ย. 69) — ชื่อซ้ำ = "ชื่อ (รหัส)" เฉพาะคู่ที่ซ้ำ · ฐานใช้กติกาเดียวกัน (_dealer_display_name ใบ 0281)
const คีย์ชื่อ = (s: string) => s.trim().toLowerCase();

/** ตัวแปลงรหัส → ชื่อแสดง จากรายชื่อดีลเลอร์ทั้งเครือ · ไม่รู้จักรหัส = ชื่อสำรองที่ส่งมา หรือรหัส (ไม่เดาชื่อ) */
export function สร้างชื่อแสดง(รายชื่อ: readonly { code: string; name: string }[]): (code: string | null | undefined, สำรอง?: string | null) => string {
  const นับ = new Map<string, number>();
  for (const d of รายชื่อ) if (d.name?.trim()) นับ.set(คีย์ชื่อ(d.name), (นับ.get(คีย์ชื่อ(d.name)) ?? 0) + 1);
  const ชื่อ = new Map(รายชื่อ.map(d => [d.code, d.name?.trim() || ""]));
  return (code, สำรอง) => {
    if (!code) return สำรอง?.trim() || "—";
    const n = ชื่อ.get(code) || สำรอง?.trim() || "";
    if (!n) return code;
    return (นับ.get(คีย์ชื่อ(n)) ?? 0) > 1 ? `${n} (${code})` : n;
  };
}


/** แปลงรหัสดีลเลอร์ในข้อความบันทึก (target ของบันทึกการใช้งาน) เป็นชื่อแสดง ตอนแสดงผลเท่านั้น (บอสตอบ 6 พ.ย. 69 · ฐานเก็บรหัสเหมือนเดิม)
 *  แปลงเฉพาะรหัสที่ยืนเดี่ยว (คั่นด้วยต้น/ท้ายข้อความ · ช่องว่าง · "·" · วงเล็บ · จุลภาค · ทวิภาค) และมีในทะเบียนดีลเลอร์
 *  ไม่แตะรหัสในเลขเอกสาร (RQ-… · Q-RYG-… · RYG-00012 — มีขีด/ตัวอักษร/ตัวเลขติด) · ไม่แปลงแถว HQ (คำว่า HQ ในข้อความ เช่น "ใบ HQ") */
export function แทนรหัสด้วยชื่อ(ข้อความ: string, รหัสที่รู้จัก: Iterable<string>, ชื่อของ: (code: string) => string): string {
  const รหัส = [...new Set(รหัสที่รู้จัก)].filter(c => c && c !== "HQ" && /^[A-Z0-9]{2,6}$/.test(c)).sort((a, b) => b.length - a.length);
  if (!ข้อความ || !รหัส.length) return ข้อความ;
  const แบบ = new RegExp(`(^|[\\s·(,:/])(${รหัส.join("|")})(?=$|[\\s·),:/])`, "g");
  return ข้อความ.replace(new RegExp(`รหัส (${รหัส.join("|")})(?=$|[\\s·),:/])`, "g"), (_m, c: string) => ชื่อของ(c))   // "รหัส RYG" → ชื่อ (ประวัติผู้สนใจ)
    .replace(แบบ, (_m, หน้า: string, c: string) => หน้า + ชื่อของ(c));
}

/** ชื่อบทบาท HQ เดิมในบันทึก "เปลี่ยนบทบาทผู้ใช้" (อีเมล: เดิม → ใหม่ · ใบ 0240) = "สำนักงานใหญ่" ตอนแสดง (HQ บทบาทเดียว · ใบ 0282 · แถวในฐานไม่แก้)
 *  แปลงเฉพาะตำแหน่งชื่อบทบาท (หลัง ": " หรือ "→ " และก่อน " →"/ท้ายข้อความ) — ชื่อคน/ข้อความอื่นที่มีคำเดียวกันไม่ถูกแตะ */
export function แปลงบทบาทเดิมในบันทึก(ข้อความ: string): string {
  return (ข้อความ ?? "").replace(/(: |→ )(ผู้ดูแลระบบ|ผู้บริหารสำนักงานใหญ่|เจ้าหน้าที่สำนักงานใหญ่)(?= →|$)/g, (_m, หน้า: string) => `${หน้า}สำนักงานใหญ่`);
}
