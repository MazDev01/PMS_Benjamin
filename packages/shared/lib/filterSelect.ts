//   บอสสั่ง 11 พ.ย. 69: เลิกใช้ <select> ของเบราว์เซอร์ในแถบตัวกรอง → ตัวกลางทำเอง ตัวเดียวทุกที่
//   กางลงข้างล่างเสมอ · สูงไม่เกินที่ว่างใต้ช่อง · ช่องค้นหาเมื่อเกิน 8 ตัวเลือก · ลูกศร/Enter/Esc · คลิกข้างนอกปิด · เป้ากด ≥ 30px
//   ข้อทดสอบหน่วย: tests/unit/filterSelect.test.ts

export type ตัวเลือก = { v: string; l: string; /** จำนวนของตัวเลือก (ถ้ามี) — ออกเป็น data-count ให้ข้อทดสอบเทียบกับฐาน */ n?: number };

/** มีช่องค้นหาเมื่อรายการ (รวมตัวเลือก "ทั้งหมด") เกิน 8 */
export const ต้องมีช่องค้น = (จำนวน: number) => จำนวน > 8;

/** ตัดวรรณยุกต์/ช่องว่าง/ตัวพิมพ์ เพื่อค้นแบบหลวม ๆ */
const ปกติ = (s: string) => s.normalize("NFC").toLowerCase().replace(/\s+/g, "");

/** กรองตามคำค้น (ค้นในข้อความที่แสดง) — คำค้นว่าง = ทั้งหมด · ตัวเลือก "ทั้งหมด" (ค่า all) อยู่บนสุดเสมอ */
export function กรองตัวเลือก(รายการ: ตัวเลือก[], คำค้น: string, all?: string): ตัวเลือก[] {
  const q = ปกติ(คำค้น);
  if (!q) return รายการ;
  return รายการ.filter(o => o.v === all || ปกติ(o.l).includes(q));
}

/** ตำแหน่งที่ไฮไลต์หลังกดปุ่ม (ไม่วนรอบ · -1 = ยังไม่ไฮไลต์) */
export function ขยับไฮไลต์(ตอนนี้: number, ปุ่ม: string, จำนวน: number): number {
  if (จำนวน <= 0) return -1;
  if (ปุ่ม === "ArrowDown") return Math.min(จำนวน - 1, ตอนนี้ + 1);
  if (ปุ่ม === "ArrowUp") return Math.max(0, ตอนนี้ < 0 ? 0 : ตอนนี้ - 1);
  if (ปุ่ม === "Home") return 0;
  if (ปุ่ม === "End") return จำนวน - 1;
  return ตอนนี้;
}

/** ตำแหน่ง/ความสูงของรายการ: กางลงใต้ช่องเสมอ · สูงไม่เกินที่ว่างใต้ช่อง (เว้นขอบ 8px) และไม่เกินเพดาน
 *  · ที่ว่างน้อยกว่าขั้นต่ำ = ใช้ขั้นต่ำ (ยังอยู่ใต้ช่อง หน้าเลื่อนลงดูได้) — ไม่พลิกขึ้นบนแบบ <select> */
/** ต้องเลื่อนหน้าก่อนกางไหม (13 พ.ย. 69): รายการตรึงกับจอและตามช่องเมื่อหน้าเลื่อน — ช่องอยู่ติดขอบล่าง = รายการตกนอกจอ
 *  เลื่อนหน้าดูก็ไม่เห็น (เจอที่ลูกค้าเป้าหมายทั้งเครือ ช่องขั้นตอนท้ายแถบตัวกรอง) → ที่ว่างใต้ช่องน้อยกว่าที่ต้องใช้ = เลื่อนช่องขึ้นก่อนแล้วค่อยกางลง
 *  ต้องใช้ = ความสูงตามจำนวนตัวเลือก (แถวละ 34 + ขอบ 16 + ช่องค้นหา 44) ไม่เกินเพดาน · คืน true = ต้องเลื่อน */
export function ต้องเลื่อนก่อนกาง(ช่องล่าง: number, จอสูง: number, จำนวน: number, มีช่องค้น: boolean, เพดาน = 320) {
  const ต้องใช้ = Math.min(เพดาน, จำนวน * 34 + 16 + (มีช่องค้น ? 44 : 0));
  return จอสูง - ช่องล่าง - 8 < ต้องใช้;
}

export function ตำแหน่งรายการ(ช่อง: { left: number; bottom: number; width: number }, จอ: { w: number; h: number }, เพดาน = 320, ขั้นต่ำ = 120) {
  const ว่างล่าง = จอ.h - ช่อง.bottom - 8;
  const สูง = Math.max(ขั้นต่ำ, Math.min(เพดาน, ว่างล่าง));
  const กว้าง = Math.max(ช่อง.width, 180);
  const ซ้าย = Math.max(8, Math.min(ช่อง.left, จอ.w - กว้าง - 8));
  return { top: ช่อง.bottom + 4, left: ซ้าย, maxHeight: สูง, minWidth: กว้าง };
}
