//   อัตราปิดการขาย = ลูกค้าเป้าหมายที่ปิดการขายสำเร็จ ÷ (ปิดสำเร็จ + ปิดไม่สำเร็จ) × 100 · ปัดเป็นจำนวนเต็ม
//   นับจาก "ลีด" ไม่ใช่จาก "ใบ" · ยังไม่มีลีดที่ปิด = null (หน้าจอขึ้น "—" ห้ามขึ้น 0%)
//   อัตราอื่น (ตอบรับต่อใบที่ส่ง · ใบ HQ ที่ปิดได้ · ผู้สนใจตอบรับใบค่าแฟรนไชส์) ห้ามใช้ชื่อ "อัตราปิดการขาย"
//   เขียนไว้ใน docs/FLOW.html #win-rate · ข้อทดสอบ tests/unit/winRate.test.ts
export const ชื่ออัตราปิดการขาย = "อัตราปิดการขาย";
export const คำอธิบายอัตราปิดการขาย = "ลูกค้าเป้าหมายปิดสำเร็จ ÷ (ปิดสำเร็จ + ปิดไม่สำเร็จ)";

export function อัตราปิดการขาย(ปิดสำเร็จ: number, ปิดไม่สำเร็จ: number): number | null {
  const ปิดแล้ว = ปิดสำเร็จ + ปิดไม่สำเร็จ;
  return ปิดแล้ว > 0 ? Math.round((ปิดสำเร็จ / ปิดแล้ว) * 100) : null;
}

/** นับจากรายการลีด (สถานะ PAID / CANCELLED) — ใช้ฝั่งที่มีรายการลีดในมือ */
export function อัตราปิดการขายจากลีด(leads: { status: string }[]): number | null {
  let ได้ = 0, เสีย = 0;
  for (const l of leads) { if (l.status === "PAID") ได้++; else if (l.status === "CANCELLED") เสีย++; }
  return อัตราปิดการขาย(ได้, เสีย);
}
