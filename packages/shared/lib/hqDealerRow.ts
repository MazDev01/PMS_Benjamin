//   แถวนี้มีไว้เป็นเจ้าของลูกค้าเป้าหมายที่สำนักงานใหญ่ถือก่อนโอนให้ดีลเลอร์ (ใบ 0197) · ฐานกันลบ/ปิดใช้งาน (ใบ 0222)
//   หน้าเว็บ: ซ่อนจากรายชื่อดีลเลอร์ และไม่นับในตัวเลขดีลเลอร์ทุกที่ (ทะเบียน · แดชบอร์ด · ภาพรวมยอดขาย · เป้ารวม · ตัวกรอง · ค้นหา)
//   ยกเลิกคำสั่งเดิม "ตรึงแถว HQ ไว้บนสุด" (7 ก.ย. 69)
//   ข้อทดสอบ: tests/scenario/flow-b-hq-dealers.spec.ts
export const HQ_DEALER_CODE = "HQ";

/** ใช้กรองรายชื่อดีลเลอร์ก่อนแสดง/นับ — `dealers.filter(ไม่ใช่แถวHQ)` */
export const ไม่ใช่แถวHQ = (d: { code?: string | null }): boolean => (d.code ?? "") !== HQ_DEALER_CODE;
