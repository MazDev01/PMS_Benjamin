// ── แถว "HQ" ในทะเบียนดีลเลอร์ = สำนักงานใหญ่ ไม่ใช่ดีลเลอร์ (บอสตัดสิน 19 ต.ค. 69 · รอบ 2 ช่วง ข) ──────────────────────
//   แถวนี้มีไว้เป็นเจ้าของลูกค้าเป้าหมายที่สำนักงานใหญ่ถือก่อนโอนให้ดีลเลอร์ (ใบ 0197) · ฐานกันลบ/ปิดใช้งาน (ใบ 0222)
//   หน้าเว็บ: ซ่อนจากรายชื่อดีลเลอร์ และไม่นับในตัวเลขดีลเลอร์ทุกที่ (ทะเบียน · แดชบอร์ด · ภาพรวมยอดขาย · เป้ารวม · ตัวกรอง · ค้นหา)
//   ยกเลิกคำสั่งเดิม "ตรึงแถว HQ ไว้บนสุด" (7 ก.ย. 69)
//   ข้อทดสอบ: tests/scenario/flow-b-hq-dealers.spec.ts
export const HQ_DEALER_CODE = "HQ";

/** ใช้กรองรายชื่อดีลเลอร์ก่อนแสดง/นับ — `dealers.filter(ไม่ใช่แถวHQ)` */
export const ไม่ใช่แถวHQ = (d: { code?: string | null }): boolean => (d.code ?? "") !== HQ_DEALER_CODE;

// ── HQD "สำนักงานใหญ่ (ขายตรง)" (บอสสั่ง 18 พ.ย. 69 · ใบ 0287) ─────────────────────────────────────────────────────
//   ดีลเลอร์ที่สำนักงานใหญ่ใช้ขายตรง (เข้าฝั่งดีลเลอร์ได้) · ยอดนับในยอดรวมทั้งเครือ แต่ไม่นับเป็นดีลเลอร์:
//   ไม่อยู่ในทะเบียน/จำนวนดีลเลอร์ · ไม่ติดอันดับ · ไม่มีเป้า (ไม่อยู่ในตารางตั้งเป้า) · ไม่มีจังหวัด/ภาค · ไม่ผูกผู้สนใจ
//   ยังเลือกเป็นตัวกรอง/ค้นหาได้ (ดูยอดขายตรง) · ฐานคิดตัวเลขเอง (hq_dashboard · kpi_cards · _network_target)
export const HQ_DIRECT_CODE = "HQD";
/** นับเป็นดีลเลอร์ (ทะเบียน · จำนวน · ตั้งเป้า · ผูกผู้สนใจ) — ไม่ใช่แถว HQ และไม่ใช่ HQD */
export const นับเป็นดีลเลอร์ = (d: { code?: string | null }): boolean => ไม่ใช่แถวHQ(d) && (d.code ?? "") !== HQ_DIRECT_CODE;
