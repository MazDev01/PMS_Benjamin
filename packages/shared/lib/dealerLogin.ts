// บัญชีดีลเลอร์เข้าระบบด้วยอีเมล "<รหัสสาขาตัวเล็ก>@dealer.benjaminpebsteel.com" — โดเมนย่อยของบริษัทเอง
//   เดิมเป็นโดเมนที่ยังไม่มีใครจด: ใครจดได้ + Send Email Hook ถูกปิด = รับลิงก์รีเซ็ตรหัสของทุกสาขาได้
//   ย้ายบัญชีเดิมด้วย scripts/migrate-dealer-login-domain.mjs · ตัวตรวจ scripts/check-no-old-login-domain.mjs
// ดีลเลอร์พิมพ์แค่รหัสสาขาในหน้าเข้าระบบ — ระบบเติมโดเมนให้ (พิมพ์อีเมลเต็มก็ยังได้ เช่นบัญชีที่ย้ายไปอีเมลของตัวเองแล้ว)
// ⚠️ อีเมลนี้ไม่มีกล่องจดหมายจริง ห้ามใช้เป็นผู้รับอีเมลใด ๆ (อีเมลติดต่อ = profiles.contact_email ที่ยืนยันแล้วเท่านั้น)

export const DEALER_LOGIN_DOMAIN = "dealer.benjaminpebsteel.com";

/** อีเมลเข้าระบบของสาขา (บัญชีที่ระบบสร้างให้) */
export const อีเมลเข้าระบบของสาขา = (code: string): string => `${code.trim().toLowerCase()}@${DEALER_LOGIN_DOMAIN}`;

/** สิ่งที่ดีลเลอร์พิมพ์ในช่องเข้าระบบ → อีเมลที่ใช้ล็อกอิน
 *  ตัดช่องว่างหัวท้าย · ไม่มี @ = รหัสสาขา (ไม่สนตัวพิมพ์เล็กใหญ่) · มี @ = อีเมลเต็ม ใช้ตามนั้น */
export function ชื่อผู้ใช้เป็นอีเมล(พิมพ์: string): string {
  const v = พิมพ์.trim();
  if (!v) return "";
  return v.includes("@") ? v.toLowerCase() : อีเมลเข้าระบบของสาขา(v);
}

/** อีเมลนี้เป็นอีเมลเข้าระบบของดีลเลอร์ (ไม่มีกล่องจดหมายจริง) หรือไม่ */
export const เป็นอีเมลเข้าระบบดีลเลอร์ = (email: string): boolean => email.trim().toLowerCase().endsWith(`@${DEALER_LOGIN_DOMAIN}`);
