// กฎ (บอสสั่ง 21 ส.ค. 69): ใบที่ "ส่งให้ลูกค้าไปแล้ว" พอแก้เนื้อหา = ขึ้นฉบับใหม่
//   ใบร่างยังไม่ถึงมือลูกค้า แก้กี่รอบก็ยังเป็นฉบับเดิม
//   ใบที่ส่งไปแล้ว ลูกค้าถือกระดาษฉบับเก่าอยู่ในมือ — ต้องมีเลขฉบับให้อ้างอิงตรงกันเวลาคุยกัน
//
// ⚠️ ทำไมต้องอยู่ไฟล์เดียว (แก้ 28 ส.ค. 69 · จากผลตรวจระบบ):
//   ก่อนหน้านี้กติกานี้ถูกเขียนไว้ 2 ที่ที่ไม่คุยกัน แล้วพลาดคนละแบบ
//     1) ในแผงใบเสนอราคาของหน้าลูกค้าเป้าหมาย → หน้า /quotations ของดีลเลอร์ไม่มีกติกานี้เลย
//        แก้ใบที่ส่งไปแล้วจากหน้านั้น เลขฉบับค้างที่ V1 ตลอด
//     2) ในเส้นทาง PUT /api/v1/quotations (ทำงานเฉพาะโหมด api) → ระบบที่ใช้อยู่จริงเป็นโหมด
//        supabase (หน้าเว็บยิงเข้าฐานข้อมูลตรง) กติกาที่ฝั่งนั้นจึงไม่เคยถูกเรียกเลย
//        และในโหมด api มันขึ้นฉบับใหม่แม้แต่ตอน "กดปฏิเสธ" หรือ "ส่งอีกครั้ง" ซึ่งไม่ได้แก้เนื้อหา
//        (ยิงพิสูจน์แล้ว: ส่งใบ V1 → กดปฏิเสธ → กลายเป็น V2 ทั้งที่ไม่มีใครแก้อะไร)
//
//   ตอนนี้ย้ายมาอยู่ที่ SalesContext.updateQuotation ซึ่งเป็นทางผ่านทางเดียวของทุกหน้า
//   และทำงานเหมือนกันทั้งสามโหมด (local / supabase / api)
import type { QuotationMock } from "./mock";

/** ช่องที่ "ปรากฏบนกระดาษที่ลูกค้าถืออยู่" — เปลี่ยนช่องพวกนี้ = คนละฉบับกัน
 *
 *  ⚠️ ห้ามใส่ status / date / lostReason:
 *     ส่งอีกครั้ง · กดปฏิเสธ · ปิดการขาย ล้วนไม่ได้แก้เนื้อหาใบ ไม่ใช่ฉบับใหม่ */
const ช่องที่เป็นเนื้อหาใบ = [
  "project", "buildingType", "area", "totalValue", "materialCost",
  "items", "expiry", "note", "vatPercent", "province", "customer",
] as const;

const เลขฉบับ = (v: string | undefined) => Number(String(v ?? "V1").replace(/[^0-9]/g, "")) || 1;

/** รายการ BOQ เทียบกันทั้งก้อน — เทียบทีละช่องจะพลาดตอนลบ/สลับลำดับรายการ */
const boq = (q: QuotationMock) => JSON.stringify(q.lineItems ?? []);

/** เนื้อหาใบเปลี่ยนไปจริงไหม (ไม่นับสถานะ/วันที่ส่ง) */
export function เนื้อหาใบเปลี่ยน(ก่อน: QuotationMock, หลัง: QuotationMock): boolean {
  if (boq(ก่อน) !== boq(หลัง)) return true;
  return ช่องที่เป็นเนื้อหาใบ.some(k => (ก่อน[k] ?? "") !== (หลัง[k] ?? ""));
}

/**
 * เลขฉบับที่ควรบันทึกสำหรับการแก้ครั้งนี้
 *   • ยังไม่เคยมีใบเดิม (สร้างใหม่) → ใช้ค่าที่ส่งมา หรือ V1
 *   • ใบร่าง → คงเลขเดิม แก้กี่รอบก็ยังฉบับเดิม
 *   • ส่งให้ลูกค้าแล้ว + เนื้อหาเปลี่ยน → +1
 *   • ส่งให้ลูกค้าแล้ว + เนื้อหาเท่าเดิม (เปลี่ยนแค่สถานะ) → คงเลขเดิม
 */
export function ฉบับถัดไป(ก่อน: QuotationMock | undefined, หลัง: QuotationMock): string {
  if (!ก่อน) return หลัง.revision ?? "V1";
  const เดิม = `V${เลขฉบับ(ก่อน.revision)}`;
  if (ก่อน.status === "draft") return เดิม;
  return เนื้อหาใบเปลี่ยน(ก่อน, หลัง) ? `V${เลขฉบับ(ก่อน.revision) + 1}` : เดิม;
}

/** การแก้ครั้งนี้จะทำให้ขึ้นฉบับใหม่ไหม — หน้าจอเอาไปเลือกข้อความแจ้งผู้ใช้ */
export function จะขึ้นฉบับใหม่(ก่อน: QuotationMock | undefined, หลัง: QuotationMock): boolean {
  if (!ก่อน) return false;
  return ฉบับถัดไป(ก่อน, หลัง) !== `V${เลขฉบับ(ก่อน.revision)}`;
}

/** ป้ายฉบับที่แสดงบนจอ — ฐานเก็บปนกันสองแบบ: ใบเดิม 104 ใบเป็น "1"/"2" · ใบใหม่เป็น "V1"
 *  แสดงเป็น "V1"/"V2" เสมอทุกแถว (บอสสั่ง 28 ต.ค. 69) · แปลงตอนแสดงเท่านั้น ไม่แก้ข้อมูลในฐาน */
export const ป้ายฉบับ = (v: string | undefined | null): string => `V${เลขฉบับ(v ?? undefined)}`;
