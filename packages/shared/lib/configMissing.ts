export const ข้อความตั้งค่าไม่ครบ = "ระบบยังตั้งค่าไม่ครบ — แจ้งสำนักงานใหญ่ให้ตั้งค่าก่อนแล้วลองใหม่";

/** จดชื่อตัวแปรที่ขาดลงบันทึกฝั่งระบบ แล้วคืนข้อความที่ผู้ใช้เห็น */
export function ตั้งค่าไม่ครบ(ตัวแปร: string, ที่: string): string {
  console.error(`[ตั้งค่าไม่ครบ] ${ที่}: ยังไม่ได้ตั้ง ${ตัวแปร}`);
  return ข้อความตั้งค่าไม่ครบ;
}
