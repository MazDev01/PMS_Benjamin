/** พื้นที่รับผิดชอบแบบ "ทั่วประเทศ" — ใช้กับสำนักงานใหญ่ที่ดูแลทุกภาคทุกจังหวัด (บอสสั่ง 7 ก.ย. 69)
 *  เก็บเป็นค่าในช่อง region/province เหมือนภาค/จังหวัดปกติ จะได้ไม่ต้องเพิ่มคอลัมน์ใหม่ทั้งระบบ
 *  ⚠️ ไม่ได้อยู่ใน REGIONS — ตัวกรอง "ภาค" ตามหน้าต่าง ๆ จึงไม่มีตัวเลือกนี้โผล่ขึ้นมาปนกับภาคจริง */
export const ALL_REGIONS = "ทุกภาค";
export const ALL_PROVINCES = "ทุกจังหวัด";

// ── ชื่อภาคที่แสดงบนหน้าจอ — รายการกลางชุดเดียวทุกหน้า HQ (บอสสั่ง 30 ต.ค. 69) ──────────────────────────────────────────
//   เดิมแต่ละหน้าแสดงเอง: หน้าลูกค้า "อีสาน/ใต้" (ค่าดิบในฐาน) · หน้าใบเสนอราคา "ภาคตะวันออกเฉียงเหนือ/ภาคใต้"
//   ค่าในฐาน (dealer.region) ยังเป็นชื่อสั้นตาม REGIONS — แสดงผ่าน ชื่อภาค() เสมอ · ตัวตรวจ scripts/check-region-labels.mjs
//   ตัวกรองภาคใช้ป้าย "ทุกภูมิภาค" ทุกหน้า (ป้ายทุกภูมิภาค) · ค่า "ทุกภาค" (ALL_REGIONS) เป็นค่าข้อมูลของแถว HQ แสดงเป็น "ทั่วประเทศ"
const ชื่อเต็มของภาค: Record<Region, string> = {
  เหนือ: "ภาคเหนือ", อีสาน: "ภาคตะวันออกเฉียงเหนือ", กลาง: "ภาคกลาง", ตะวันออก: "ภาคตะวันออก", ตะวันตก: "ภาคตะวันตก", ใต้: "ภาคใต้",
};
/** ค่าภาคในฐานที่สะกดต่าง → ภาคมาตรฐาน: "ตะวันออกเฉียงเหนือ"/"ภาคอีสาน"/"ภาคใต้" … (ข้อมูลตั้งต้น KKN NMA UBN เก็บ "ตะวันออกเฉียงเหนือ")
 *  ไม่รู้จัก = null · ใช้ทั้งแสดงผลและตัวกรอง (ภาคเดียวกันไม่แยกเป็น 2 ตัวเลือก) */
export function ภาคมาตรฐาน(r: string | null | undefined): Region | null {
  const v = (r ?? "").trim().replace(/^ภาค/, "");
  if (v === "ตะวันออกเฉียงเหนือ") return "อีสาน";
  return (REGIONS as readonly string[]).includes(v) ? (v as Region) : null;
}
/** ชื่อภาคสำหรับแสดง: "อีสาน"/"ตะวันออกเฉียงเหนือ" → "ภาคตะวันออกเฉียงเหนือ" · "ทุกภาค" → "ทั่วประเทศ" · ว่าง → "—" · ค่าอื่น (เช่น "ไม่ระบุ") แสดงตามเดิม */
export function ชื่อภาค(r: string | null | undefined): string {
  const v = (r ?? "").trim();
  if (!v) return "—";
  if (v === ALL_REGIONS) return "ทั่วประเทศ";
  const ม = ภาคมาตรฐาน(v);
  return ม ? ชื่อเต็มของภาค[ม] : v;
}
/** ป้ายตัวเลือก "ทั้งหมด" ของตัวกรองภาค — ทุกหน้าใช้คำนี้ */
export const ป้ายทุกภูมิภาค = "ทุกภูมิภาค";

/** ภาคของจังหวัด · จังหวัดที่ไม่รู้จัก = null (หน้าแสดง "—") */
export const regionOf = (province: string): Region | null => REGION_OF[(province ?? "").trim()] ?? null;

/** จังหวัดทั้งหมดในภาคนั้น (เรียงตามที่ประกาศไว้ข้างบน) — ใช้ทำกล่องเลือกจังหวัดที่ผูกกับภาค
 *  "ทุกภาค" = ได้จังหวัดทั้งประเทศ (เรียงตามภาค) เพื่อให้สำนักงานใหญ่เลือกจังหวัดไหนก็ได้ */
export const provincesOfRegion = (region: string): string[] => {
  const r = (region ?? "").trim();
  if (r === ALL_REGIONS) return REGIONS.flatMap(x => PROVINCES_OF[x] ?? []);
  return PROVINCES_OF[r] ?? [];
};

/** จังหวัดมาตรฐาน 77 จังหวัด (ตรงกับ th_provinces ในฐาน) — ใช้ตรวจว่าชื่อจังหวัดเป็นชื่อมาตรฐาน */
const จังหวัดมาตรฐาน = provincesOfRegion(ALL_REGIONS);
/** ชื่อนี้อยู่ในรายชื่อ 77 จังหวัดไหม (ชื่อย่อ เช่น "กทม" / "กรุงเทพฯ" = ไม่ใช่) — ฐานตรวจซ้ำอีกชั้น (ใบ 0196 · 0259) */
export const เป็นจังหวัดมาตรฐาน = (p: string | null | undefined): boolean => จังหวัดมาตรฐาน.includes((p ?? "").trim());

/** ตัวคำนวณล้วนของ useMyProvinces (useMyProvinces.ts) — แยกไว้ให้เทสย่อยเรียกได้ */
export function จังหวัดให้เลือก(dealers: { code: string; region?: string | null; province?: string | null }[], code: string, current?: string): string[] {
  const mine = dealers.find(d => d.code === code);
  const inRegion = provincesOfRegion(mine?.region ?? "");
  // ยังไม่รู้ภาคของสาขา (ทะเบียนดีลเลอร์ยังโหลดไม่เสร็จ) = ยังไม่มีตัวเลือก — ห้ามเดารายชื่อสำรอง (15 ต.ค. 69 · trace ข้อทดสอบที่ไม่นิ่ง)
  //   เดิมรายชื่อสำรองมี "กรุงเทพฯ"/"อื่นๆ" (ฐานปฏิเสธ · ใบ 0196) แล้วเปลี่ยนเป็น 77 จังหวัด ก็ยังเลือกจังหวัดของสาขาอื่นได้
  //   (ฐานปฏิเสธ lead_outside_territory — หนึ่งจังหวัด หนึ่งดีลเลอร์) · ช่องเลือกโชว์ "ยังไม่ระบุ" จนกว่าจะรู้ภาค
  const ฐาน = inRegion;
  const พ่วง: string[] = [];
  // จังหวัดที่ตั้งของสาขาต้องอยู่ในลิสต์เสมอ (บางสาขาตั้งอยู่คนละภาคกับที่รับผิดชอบ)
  //   ยกเว้น "ทุกจังหวัด" ของสำนักงานใหญ่ — เป็นคำบอกขอบเขต ไม่ใช่ชื่อจังหวัดที่เลือกลงเอกสารได้
  //   และยกเว้นชื่อที่ไม่ใช่ชื่อมาตรฐาน (เช่นชื่อย่อ "กรุงเทพฯ") — ฐานไม่รับ · ชื่อมาตรฐานอยู่ในรายการภาคอยู่แล้ว
  if (inRegion.length && mine?.province && mine.province !== ALL_PROVINCES && จังหวัดมาตรฐาน.includes(mine.province) && !ฐาน.includes(mine.province)) พ่วง.push(mine.province);
  if (current && !ฐาน.includes(current) && !พ่วง.includes(current)) พ่วง.push(current);
  return พ่วง.length ? [...พ่วง, ...ฐาน] : ฐาน;
}
