// ── ข้อความผิดพลาดของฐานที่ยังใช้คำเก่า → แปลเป็นคำปัจจุบันตอนแสดง (ไม่มีใบปรับฐาน) ─────────────────────────────────────
//   บอสสั่ง 13 พ.ย. 69 (งาน A · คนรวมงานเลือกแบบ ข): ฟังก์ชันฐาน quotations_version_guard (ใบ 0285) ยังส่งข้อความที่มีคำห้าม
//   ของสถานะใบที่มีฉบับใหม่แล้ว 2 ข้อ — แอปแปลด้วยรหัสนำหน้า (quote_superseded · quote_superseded_manual) ให้ใช้คำ "ฉบับเก่า"
//   จุดที่ใช้: DbError (ทุกข้อผิดพลาดของทั้งสองตัวต่อฐาน · โหมดผ่านเซิร์ฟเวอร์ด้วย) + friendlyError (ข้อผิดพลาดที่ไม่ใช่ DbError)
//   คงรหัสนำหน้าไว้ (โค้ดแยกเคสด้วยรหัสได้เหมือนเดิม · friendlyError ตัดรหัสออกก่อนขึ้นจอ)
//   ⚠️ ลบตัวแปลนี้ในรอบที่มีใบปรับฐานถัดไป (แก้ข้อความในฐานแทน) — คิวใน docs/FLOW.html (กฎ card-words-nov13) · supabase/tests/ui_terms_db.sql
//   ข้อทดสอบ: tests/unit/dbMessages.test.ts
const ตัวแปล: { รหัส: string; แปล: (เดิม: string) => string }[] = [
  { รหัส: "quote_superseded_manual", แปล: () => "ใบจะเป็นฉบับเก่าเองเมื่อส่งฉบับใหม่ให้ลูกค้า — ตั้งเองไม่ได้" },
  { รหัส: "quote_superseded", แปล: เดิม => {
    const เลข = /ใบ\s+(\S+)\s/.exec(เดิม)?.[1];
    return `${เลข ? `ใบ ${เลข}` : "ใบนี้"} เป็นฉบับเก่าแล้ว (มีฉบับใหม่ส่งให้ลูกค้า) อ่านได้อย่างเดียว — ตอบรับ/ปฏิเสธที่ฉบับล่าสุด`;
  } },
];

/** ข้อความจากฐาน → ข้อความที่ใช้คำปัจจุบัน (ไม่ตรงรหัสใด = คืนเดิม) */
export function แปลข้อความฐาน(ข้อความ: string): string {
  const ตรง = /^([a-z_]+):\s*/.exec(ข้อความ);
  if (!ตรง) return ข้อความ;
  const ตัว = ตัวแปล.find(x => x.รหัส === ตรง[1]);
  return ตัว ? `${ตัว.รหัส}: ${ตัว.แปล(ข้อความ.slice(ตรง[0].length))}` : ข้อความ;
}
