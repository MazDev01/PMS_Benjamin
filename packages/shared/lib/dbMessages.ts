/** ข้อความจากฐาน → ข้อความที่ใช้คำปัจจุบัน (คงรหัสนำหน้า · ไม่ตรงรหัสใด = แปลวลีอย่างเดียว) */
export function แปลข้อความฐาน(ข้อความ: string): string {
  const ตรง = /^([a-z_]+):\s*/.exec(ข้อความ);
  if (!ตรง) return คำปัจจุบันจากฐาน(ข้อความ);
  const ตัว = ตัวแปล.find(x => x.รหัส === ตรง[1]);
  return `${ตรง[1]}: ${ตัว ? ตัว.แปล(ข้อความ.slice(ตรง[0].length)) : คำปัจจุบันจากฐาน(ข้อความ.slice(ตรง[0].length))}`;
}

