/** วลีเก่าที่ฐานเขียน → คำปัจจุบัน + รหัสสถานะอังกฤษในประโยค → ชื่อไทย (แสดงผลเท่านั้น · ไม่แก้ค่าในฐาน) */
export function คำปัจจุบันจากฐาน(ข้อความ: string): string {
  let s = String(ข้อความ ?? "");
  for (const [re, แทน] of วลี) s = s.replace(re, แทน);
  return s.replace(/(สถานะ |จาก |เป็น |ขั้นปัจจุบัน |· สถานะ )([A-Za-z_]+)(?=[\s)·,]|$)/g, (m, หน้า: string, รหัส: string) => ชื่อสถานะจากรหัส[รหัส] ? `${หน้า}${ชื่อสถานะจากรหัส[รหัส]}` : m);
}

/** ประวัติผู้สนใจ (dealer_prospects_log) — ผู้สนใจของ HQ ไม่ใช่ "ลูกค้าเป้าหมาย" (บอส 22 ต.ค. 69) · ใช้เฉพาะจอผู้สนใจ */
export function คำปัจจุบันประวัติผู้สนใจ(ข้อความ: string): string {
  return คำปัจจุบันจากฐาน(String(ข้อความ ?? "").replace(/^เพิ่มลูกค้าเป้าหมาย/, "เพิ่มผู้สนใจ").replace(/(ใบค่าแฟรนไชส์ \S+) ถูกปฏิเสธ/g, "$1 ผู้สนใจปฏิเสธ").replace(/^ถูกปฏิเสธ$/, "ปฏิเสธแล้ว"));
}
