type Cell = string | number;

// ── ความปลอดภัยของไฟล์ที่ส่งออก ─────────────────────────────────────────────────
//
// ข้อมูลในตารางมาจากสิ่งที่ผู้ใช้พิมพ์เอง (ชื่อบริษัท · ชื่อผู้ติดต่อ · หมายเหตุ) จึงเชื่อไม่ได้
// เดิม esc() แค่แปลงเป็นข้อความเฉย ๆ ไม่ได้ป้องกันอะไรเลย เปิดช่องไว้ 2 ทาง
// (ผลตรวจสอบระบบรอบ 2 · ระดับสูง):
//
//   1) ส่งออก PDF/Excel — ค่าถูกยัดลง HTML ตรง ๆ ชื่อบริษัทอย่าง `<img src=x onerror=...>`
//      จะทำงานทันทีที่หน้าต่างพิมพ์เปิดขึ้น และหน้าต่างนั้นเป็น origin เดียวกับระบบ HQ
//      = ดีลเลอร์คนหนึ่งฝังสคริปต์ไว้ในชื่อลูกค้า แล้วรอให้ผู้ดูแลกดส่งออก
//
//   2) ส่งออก CSV — Excel ตีความค่าที่ขึ้นต้นด้วย = + - @ ว่าเป็น "สูตร" ไม่ใช่ข้อความ
//      สูตรอย่าง =WEBSERVICE(...) ดึงข้อมูลในไฟล์ส่งออกไปยังเซิร์ฟเวอร์ภายนอกได้ตอนเปิดไฟล์
export function escHtml(c: Cell): string {
  return String(c ?? "")
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

/** ค่าที่ปลอดภัยสำหรับช่องใน CSV — ขึ้นต้นด้วยอักขระสูตร ให้เติม ' นำหน้าเพื่อบังคับเป็นข้อความ
 *  (แนวทางเดียวกับที่ OWASP แนะนำสำหรับ CSV injection) */
export function escCsvCell(c: Cell): string {
  const raw = String(c ?? "");
  const risky = /^[=+\-@\t\r]/.test(raw);
  return `"${(risky ? `'${raw}` : raw).replace(/"/g, '""')}"`;
}
