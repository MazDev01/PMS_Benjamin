//   ขอราคา HQ → ได้ใบ HQ ลากไม่ได้ (HQ เป็นคนส่งราคา · L1) · ได้ใบ HQ → เสนอราคาลูกค้า = ฟอร์มทำใบจากใบ HQ
//   เสนอราคาลูกค้า → ปิดสำเร็จ = ลูกค้าตอบรับที่ใบ (L2) · ใบยังเป็นร่าง = ฟอร์มส่งใบก่อนแล้วยืนยันตอบรับ (บอสตอบ 9 พ.ย. 69)
//   ส่งใบภายในขั้นเสนอราคาลูกค้า = ปุ่ม "ส่งให้ลูกค้า" ในกล่องขั้นต่อไป · ปิดแล้วลากออกไม่ได้ (L5)
import type { ทางย้าย } from "../components/ui/StageBoard";
import { ชื่อขั้น, จำนวนขั้น, ขั้นเปิดอยู่, ขั้นปิดสำเร็จ, ขั้นปิดไม่สำเร็จ, type เลขขั้น } from "./leadStage";

export function ทางย้ายลีด(n: เลขขั้น): ทางย้าย<string>[] {
  if (!ขั้นเปิดอยู่(n)) return [];
  const ทาง: ทางย้าย<string>[] = [];
  if (n < จำนวนขั้น) ทาง.push({ ไป: String(n + 1), ป้าย: ชื่อขั้น((n + 1) as เลขขั้น),
    ไม่ได้เพราะ: n === 2 ? "ลากเองไม่ได้ — รอ HQ ส่งราคา ระบบย้ายให้เมื่อได้ใบ HQ" : null });
  else ทาง.push({ ไป: String(ขั้นปิดสำเร็จ), ป้าย: `${ชื่อขั้น(ขั้นปิดสำเร็จ)} — ลูกค้าตอบรับใบ` });
  ทาง.push({ ไป: String(ขั้นปิดไม่สำเร็จ), ป้าย: `${ชื่อขั้น(ขั้นปิดไม่สำเร็จ)} — ระบุเหตุผล` });
  return ทาง;
}
/** ปลายทางบนบอร์ด → คำสั่งของกล่องขั้นต่อไป */
export const คำสั่งของปลายทาง = (ไป: string): "ถัดไป" | "ปิดสำเร็จ" | "ปิดไม่สำเร็จ" =>
  (ไป === String(ขั้นปิดไม่สำเร็จ) ? "ปิดไม่สำเร็จ" : ไป === String(ขั้นปิดสำเร็จ) ? "ปิดสำเร็จ" : "ถัดไป");
