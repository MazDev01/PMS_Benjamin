//   ลากได้ทีละ 1 ขั้นไปข้างหน้า + ปิดไม่สำเร็จ · ทำงานจริงผ่านกล่องขั้นต่อไปในแผงลีด (ทางเดียวกับปุ่ม · LeadNextStep คำสั่ง)
//   ขอราคา HQ → ได้ใบ HQ ลากไม่ได้ (HQ เป็นคนส่งราคา · L1) · รอลูกค้าตอบ → ปิดสำเร็จ = ลูกค้าตอบรับที่ใบ (L2) · ปิดแล้วลากออกไม่ได้ (L5)
import type { ทางย้าย } from "../components/ui/StageBoard";
import { ชื่อขั้น, type เลขขั้น } from "./leadStage";

export function ทางย้ายลีด(n: เลขขั้น): ทางย้าย<string>[] {
  if (n >= 6) return [];
  const ทาง: ทางย้าย<string>[] = [];
  if (n < 5) ทาง.push({ ไป: String(n + 1), ป้าย: ชื่อขั้น((n + 1) as เลขขั้น),
    ไม่ได้เพราะ: n === 2 ? "ลากเองไม่ได้ — รอ HQ ส่งราคา ระบบย้ายให้เมื่อได้ใบ HQ" : null });
  else ทาง.push({ ไป: "6", ป้าย: `${ชื่อขั้น(6)} — ลูกค้าตอบรับใบ` });
  ทาง.push({ ไป: "7", ป้าย: `${ชื่อขั้น(7)} — ระบุเหตุผล` });
  return ทาง;
}
/** ปลายทางบนบอร์ด → คำสั่งของกล่องขั้นต่อไป */
export const คำสั่งของปลายทาง = (ไป: string): "ถัดไป" | "ปิดสำเร็จ" | "ปิดไม่สำเร็จ" => (ไป === "7" ? "ปิดไม่สำเร็จ" : ไป === "6" ? "ปิดสำเร็จ" : "ถัดไป");
