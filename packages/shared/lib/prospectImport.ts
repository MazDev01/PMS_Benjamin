// ── เบอร์ ─────────────────────────────────────────────────────────────────────────────────────────────
/** เบอร์ไทยในข้อความ (มือถือ 0X 10 หลัก · บ้าน 02/0XX 9 หลัก · +66) — เว้นวรรค/ขีดได้ */
const แบบเบอร์ = /(?:\+?66[\s-]?|0)(?:\d[\s-]?){8,9}\d?/g;
/** ทำเบอร์เป็นรูปแบบเดียว 0XX-XXX-XXXX (มือถือ) / 0X-XXX-XXXX (บ้าน) · ไม่ใช่เบอร์ = "" */
export function จัดเบอร์(ข้อความ: string | null | undefined): string {
  let d = String(ข้อความ ?? "").replace(/\D/g, "");
  if (d.startsWith("66") && d.length >= 11) d = "0" + d.slice(2);
  if (d.length === 10 && d.startsWith("0")) return `${d.slice(0, 3)}-${d.slice(3, 6)}-${d.slice(6)}`;
  if (d.length === 9 && d.startsWith("0")) return `${d.slice(0, 2)}-${d.slice(2, 5)}-${d.slice(5)}`;
  return "";
}
/** แยกเบอร์ออกจากข้อความ — คืนเบอร์ที่จัดรูปแล้ว + ข้อความที่เหลือ */
export function แยกเบอร์(ข้อความ: string | null | undefined): { เบอร์: string[]; เหลือ: string } {
  const s = String(ข้อความ ?? "");
  const เบอร์: string[] = [];
  const เหลือ = s.replace(แบบเบอร์, m => { const f = จัดเบอร์(m); if (f) { เบอร์.push(f); return " "; } return m; });
  return { เบอร์, เหลือ: เหลือ.replace(/\s+/g, " ").trim() };
}

