  if (จังหวัดทั้งหมด.includes(k)) return { จังหวัด: k, เป๊ะ: true };
  if (ชื่อเรียกจังหวัด[k]) return { จังหวัด: ชื่อเรียกจังหวัด[k], เป๊ะ: false };
  if (k.length >= 3) { const ขึ้นต้น = จังหวัดทั้งหมด.filter(p => p.startsWith(k)); if (ขึ้นต้น.length === 1) return { จังหวัด: ขึ้นต้น[0], เป๊ะ: false }; }
