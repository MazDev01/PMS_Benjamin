// ── หัวข้อของกราฟ/ตารางในหน้าเจาะลึก HQ (บอสสั่ง 3 พ.ย. 69 "ใส่หัวข้อให้ตารางและกราฟ") ─────────────────────────────────
// ทุกกราฟและทุกตารางมีหัวข้อ 2 บรรทัด: ชื่อ (เป็นอะไร · แยกตามอะไร · ระดับไหน) + คำอธิบายสั้น (ช่วงไหน · อ่าน/กดอย่างไร)
//   ใช้ที่ /hq/leads · /hq/quotations · /hq/customers (DrillEngine) และ /hq/pipeline — หัวข้อเปลี่ยนตามแท็บมิติและระดับที่เลือก
// ข้อทดสอบ: tests/unit/drillTitles.test.ts · tests/scenario/drill-titles.spec.ts
import { ชื่อภาค } from "./provinces";

export type มิติ = "dealer" | "region" | "prov" | "month";
export const ชื่อมิติ: Record<มิติ, string> = { dealer: "ดีลเลอร์", region: "ภูมิภาค", prov: "จังหวัด", month: "รายเดือน" };

/** ระดับที่เลือก (แถบระดับ ทั้งเครือ › ภูมิภาค › จังหวัด › ดีลเลอร์) */
export type ระดับหัวข้อ = { ภาค: string | null; จังหวัด: string | null; ดีลเลอร์: string | null; ชื่อดีลเลอร์?: string };

const เดือนย่อ = ["ม.ค.", "ก.พ.", "มี.ค.", "เม.ย.", "พ.ค.", "มิ.ย.", "ก.ค.", "ส.ค.", "ก.ย.", "ต.ค.", "พ.ย.", "ธ.ค."];
/** "2026-10-01" → "1 ต.ค. 2569" · อ่านไม่ออก = "—" */
export function วันที่ไทย(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso ?? "");
  if (!m) return "—";
  return `${Number(m[3])} ${เดือนย่อ[Number(m[2]) - 1]} ${Number(m[1]) + 543}`;
}
/** ช่วงเวลาที่เลือก — "ช่วง 1 ต.ค. 2569 – 31 ต.ค. 2569" */
export const ป้ายช่วง = (ช่วง: { start: string; end: string }) => `ช่วง ${วันที่ไทย(ช่วง.start)} – ${วันที่ไทย(ช่วง.end)}`;

/** ระดับที่เลือกเป็นคำ — "ทั้งเครือ" · "ภาคเหนือ" · "จังหวัดเชียงใหม่" · "ดีลเลอร์ CNX เชียงใหม่สตีล" */
export function ป้ายระดับ(r: ระดับหัวข้อ): string {
  if (r.ดีลเลอร์) return `ดีลเลอร์ ${r.ดีลเลอร์}${r.ชื่อดีลเลอร์ ? ` ${r.ชื่อดีลเลอร์}` : ""}`;
  if (r.จังหวัด) return `จังหวัด${r.จังหวัด}`;
  if (r.ภาค) return ชื่อภาค(r.ภาค);
  return "ทั้งเครือ";
}

/** ชื่อหัวข้อ: "<เรื่อง>แยกตาม<มิติ> · <ระดับ>" · แท็บรายเดือน/ระดับดีลเลอร์ = "<เรื่อง>รายเดือน · <ระดับ>" */
export function ชื่อหัวข้อ(เรื่อง: string, dim: มิติ, r: ระดับหัวข้อ): string {
  const ม = r.ดีลเลอร์ || dim === "month" ? "รายเดือน" : `แยกตาม${ชื่อมิติ[dim]}`;
  return `${เรื่อง}${ม} · ${ป้ายระดับ(r)}`;
}

/** คำอธิบายบรรทัดที่สอง: ช่วง · ส่วนเพิ่มของแต่ละกล่อง (อ่าน/กดอย่างไร) — ช่วง = null สำหรับตัวเลข "ตอนนี้" ที่ไม่ขึ้นกับช่วง */
export function คำอธิบายหัวข้อ(ช่วง: { start: string; end: string } | null, ...ส่วน: (string | false | null | undefined)[]): string {
  return [ช่วง ? ป้ายช่วง(ช่วง) : "ณ ตอนนี้ (ไม่ขึ้นกับช่วงเวลา)", ...ส่วน.filter((x): x is string => !!x)].join(" · ");
}

/** คำแนะนำการกดแถวตามแท็บ/ระดับ — ระดับดีลเลอร์ (รายเดือนของดีลเลอร์เดียว) ไม่มีที่ให้เจาะต่อ */
export function คำแนะนำกดแถว(dim: มิติ, r: ระดับหัวข้อ): string | null {
  if (r.ดีลเลอร์) return null;
  return dim === "month" ? "กดแถวเพื่อดูรายดีลเลอร์ของเดือนนั้น" : "กดแถวเพื่อเจาะลึก";
}
