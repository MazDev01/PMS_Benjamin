// ── ชื่อผู้ทำงานที่ระบบติ๊กให้เอง (รายการงานของลูกค้าเป้าหมาย · ช่อง doneBy) ──────────────────────────────────────────────
//   บอสเลือก 12 พ.ย. 69: "อัปเดตอัตโนมัติ" → "ระบบทำให้" (งานเปลี่ยนคำทับศัพท์ · ผ่านคนรวมงาน)
//   แถวใหม่บันทึก "ระบบทำให้" (หน้าเว็บ + ฟังก์ชันในฐาน ใบปรับฐานเดียวกับงานเปลี่ยนคำ)
//   แถวเก่าในฐานยังเก็บ "อัปเดตอัตโนมัติ" — ห้ามแก้แถวเก่า (บอสยืนยัน 12 พ.ย. 69) → แปลงตอนแสดงด้วย ชื่อผู้ทำ() ตัวนี้ตัวเดียว
//   ข้อทดสอบ: tests/unit/systemActor.test.ts · tests/scenario/system-actor-display.spec.ts
export const ผู้ทำโดยระบบ = "ระบบทำให้";

/** ชื่อเดิมที่ระบบเคยบันทึก (แถวเก่า) — แสดงเป็นชื่อปัจจุบัน */
const ชื่อเดิมของระบบ = new Set(["อัปเดตอัตโนมัติ"]);

/** ชื่อผู้ทำสำหรับแสดงบนจอ/ไฟล์ส่งออก — ชื่อเดิมของระบบ → "ระบบทำให้" · ชื่อคนคงเดิม */
export function ชื่อผู้ทำ(ค่า: string | null | undefined): string {
  const t = (ค่า ?? "").trim();
  return ชื่อเดิมของระบบ.has(t) ? ผู้ทำโดยระบบ : (ค่า ?? "");
}
