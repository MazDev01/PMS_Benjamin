//   คู่กับคลาส .table-wrap.fit (globals.css: ช่องแน่น · หัวคอลัมน์ขึ้นบรรทัดได้) — ความกว้างคอลัมน์ยังคุมที่ <colgroup> ตามกติกาตารางแบบตายตัว
//   คอลัมน์ที่ทั้งตารางไม่มีค่า (แสดง "—" ทุกแถว) ซ่อนเอง · ยังไม่มีแถว (กำลังโหลด/ไม่พบ) = แสดงครบ ไม่เดาว่าว่าง
//   คอลัมน์ชื่อ (บอสสั่งรอบ 2 วันเดียวกัน): กว้างพอดีชื่อที่ยาวที่สุดในตาราง ไม่เกิน 25% ของตาราง (ยาวกว่านั้นตัดบรรทัด)
//     → <col style={{ width: กว้างชื่อ }} /> · คอลัมน์ตัวเลขไม่ระบุความกว้าง = ตารางแบบตายตัวเกลี่ยที่เหลือให้เท่ากันเต็มความกว้าง (ไม่มีช่องว่างกองที่เดียว)
//   ข้อทดสอบ: tests/unit/tableFit.test.ts · tests/scenario/hq-tables-fit.spec.ts

/** ค่าว่างที่หน้าจอแสดงเป็น "—" */
export const ว่าง = (v: unknown) => v == null || v === "" || v === "—" || (typeof v === "number" && Number.isNaN(v));

/** คงเฉพาะคอลัมน์ที่มีค่าอย่างน้อย 1 แถว — ไม่มีแถว = คืนทุกคอลัมน์ · คอลัมน์ใน ห้ามซ่อน แสดงเสมอ */
export function ซ่อนคอลัมน์ว่าง<C, R>(คอลัมน์: readonly C[], แถว: readonly R[], ค่า: (c: C, r: R) => unknown, ห้ามซ่อน: (c: C) => boolean = () => false): C[] {
  if (!แถว.length) return [...คอลัมน์];
  return คอลัมน์.filter(c => ห้ามซ่อน(c) || แถว.some(r => !ว่าง(ค่า(c, r))));
}

/** ขนาดตัวอักษรของตารางพอดีจอ (บอสสั่ง 6 พ.ย. 69 รอบ 3: ใหญ่ขึ้น ใช้ที่ว่างที่เหลือ · ยังพอดีจอ 1366) — ต้องตรงกับ .table-wrap.fit ใน globals.css */
export const ขนาดตัวอักษรตาราง = "0.84rem", ขนาดบรรทัดย่อย = "0.72rem";

/** ความกว้างคอลัมน์ชื่อ (px ของ <col>): ชื่อ/บรรทัดย่อยที่ยาวที่สุด + ช่องว่างในช่อง · ไม่เกิน 25% ของความกว้างตาราง · ไม่ต่ำกว่าขั้นต่ำ
 *  เบราว์เซอร์ไม่รับ min()/calc() ที่ความกว้างของ <col> (ตกเป็นเกลี่ยเท่ากันทุกคอลัมน์ · เจอ 6 พ.ย. 69) → คิดเพดานเป็นพิกเซลจากความกว้างตารางจริง
 *  วัด = ฟังก์ชันวัดความกว้างข้อความเป็น px (หน้าเว็บใช้ วัดข้อความ() · ข้อทดสอบหน่วยส่งตัววัดปลอม) · ยังวัดไม่ได้ (ฝั่งเซิร์ฟเวอร์) = ขั้นต่ำ
 *  กว้างตาราง = ความกว้างตารางจริง (px) · ยังไม่รู้ = ไม่จำกัดเพดาน */
export function กว้างคอลัมน์ชื่อ(ชื่อ: readonly string[], วัด: ((s: string) => number) | null, กว้างตาราง: number | null, ตั้ง: { ช่องว่าง?: number; ขั้นต่ำ?: number; เพดาน?: number } = {}): number {
  const { ช่องว่าง = 22, ขั้นต่ำ = 96, เพดาน = 0.25 } = ตั้ง;
  const ยาวสุด = วัด && ชื่อ.length ? Math.max(...ชื่อ.map(s => วัด(s ?? ""))) : 0;
  const px = Math.max(ขั้นต่ำ, Math.ceil(ยาวสุด + ช่องว่าง));
  return กว้างตาราง && กว้างตาราง > 0 ? Math.min(px, Math.floor(กว้างตาราง * เพดาน)) : px;
}

const ผืนตามแบบ = new Map<string, CanvasRenderingContext2D | null>();
/** วัดความกว้างข้อความ (px) ด้วยแบบอักษรของหน้า — ฝั่งเซิร์ฟเวอร์ = null */
export function วัดข้อความ(แบบอักษร = `600 ${ขนาดตัวอักษรตาราง}`): ((s: string) => number) | null {
  if (typeof document === "undefined") return null;
  if (!ผืนตามแบบ.has(แบบอักษร)) ผืนตามแบบ.set(แบบอักษร, document.createElement("canvas").getContext("2d"));
  const ผืน = ผืนตามแบบ.get(แบบอักษร);
  if (!ผืน) return null;
  const ขนาดราก = parseFloat(getComputedStyle(document.documentElement).fontSize) || 16;
  const ตระกูล = getComputedStyle(document.body).fontFamily || "sans-serif";
  ผืน.font = `${แบบอักษร.replace(/([\d.]+)rem/, (_m, n) => `${Number(n) * ขนาดราก}px`)} ${ตระกูล}`;
  const c = ผืน;
  return (s: string) => c.measureText(s).width;
}
