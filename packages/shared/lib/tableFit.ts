/** ค่าว่างที่หน้าจอแสดงเป็น "—" */
export const ว่าง = (v: unknown) => v == null || v === "" || v === "—" || (typeof v === "number" && Number.isNaN(v));

/** คงเฉพาะคอลัมน์ที่มีค่าอย่างน้อย 1 แถว — ไม่มีแถว = คืนทุกคอลัมน์ · คอลัมน์ใน ห้ามซ่อน แสดงเสมอ */
export function ซ่อนคอลัมน์ว่าง<C, R>(คอลัมน์: readonly C[], แถว: readonly R[], ค่า: (c: C, r: R) => unknown, ห้ามซ่อน: (c: C) => boolean = () => false): C[] {
  if (!แถว.length) return [...คอลัมน์];
  return คอลัมน์.filter(c => ห้ามซ่อน(c) || แถว.some(r => !ว่าง(ค่า(c, r))));
}
