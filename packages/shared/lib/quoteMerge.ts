// ── รับแถวใบเสนอราคาเข้ารายการบนจอ (ข่าวอัปเดตสด / ผลตอบกลับของการเขียน) — ใบ 0238 · บอสสั่ง 22 ต.ค. 69 ─────────────
//
// บั๊กจริง (trace รอบตรวจเต็มรอบ 4): ข่าวอัปเดตสดของแถวเก่า (ตอนกดทำฉบับใหม่) มาถึงหลังบันทึก % แล้ว → ทับของใหม่บนจอ
//   → ปุ่มส่งหยิบใบจากจอไปส่งทั้งแถว → ลูกค้าได้ยอดเก่า · ต้นเหตุ: รับข่าวแล้วทับทันทีโดยไม่ดูว่าเก่ากว่าหรือไม่
// กติกา: แถวที่ updatedAt (ฐานใส่เองทุกครั้งที่แก้) "เก่ากว่าหรือเท่ากับ" แถวที่มีอยู่บนจอ = ทิ้ง
//   เท่ากัน = ไม่ใช่ของใหม่ (ฐานขยับเวลาขึ้นทุกครั้งที่แก้ · 0238) — ข่าวซ้ำของแถวเดิมไม่ต้องวาดใหม่
//   แถวที่ไม่มีเวลา (ข้อมูลตัวอย่าง/ฐานก่อน 0238) = รับตามเดิม เพราะเทียบไม่ได้
import type { QuotationMock } from "./mock";

/** เวลาเป็น "ไมโครวินาที" — ฐานเก็บละเอียดถึงไมโครวินาที (ตัวดัก 0238 ขยับทีละ 1 µs ได้) แต่ Date.parse ละเอียดแค่มิลลิวินาที
 *  ถ้าเทียบด้วย Date.parse ตรง ๆ แถวที่ใหม่กว่าในมิลลิวินาทีเดียวกันจะถูกนับว่า "เท่ากัน" แล้วถูกทิ้งผิด */
const เวลา = (v: string | undefined) => {
  if (!v) return null;
  const m = v.match(/^(.*T\d{2}:\d{2}:\d{2})(?:\.(\d+))?(.*)$/);
  const ฐาน = Date.parse(m ? `${m[1]}${m[3]}` : v);
  if (!Number.isFinite(ฐาน)) return null;
  const เศษ = m?.[2] ? Number(m[2].slice(0, 6).padEnd(6, "0")) : 0;
  return ฐาน * 1000 + เศษ;
};

/** แถวนี้ใหม่กว่าของที่มีอยู่จริงไหม (ไม่มีของเดิม / เทียบเวลาไม่ได้ = ถือว่าใหม่) */
export function ใหม่กว่า(มีอยู่: Pick<QuotationMock, "updatedAt"> | undefined, เข้ามา: Pick<QuotationMock, "updatedAt">): boolean {
  if (!มีอยู่) return true;
  const ก = เวลา(มีอยู่.updatedAt), ข = เวลา(เข้ามา.updatedAt);
  if (ก == null || ข == null) return true;
  return ข > ก;
}

/** ใส่แถวเข้ารายการ: ใหม่กว่า = แทนที่ · ไม่มีในรายการ = เพิ่มบนสุด · เก่ากว่าหรือเท่ากับ = คืนรายการเดิม (อ้างอิงเดิม — React ไม่วาดใหม่) */
export function รับแถวใบ(รายการ: QuotationMock[], แถว: QuotationMock): QuotationMock[] {
  const i = รายการ.findIndex(q => q.id === แถว.id);
  if (i < 0) return [แถว, ...รายการ];
  if (!ใหม่กว่า(รายการ[i], แถว)) return รายการ;
  return รายการ.map((q, j) => (j === i ? แถว : q));
}
