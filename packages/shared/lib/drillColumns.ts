// ── คอลัมน์ที่ระดับเจาะลึกบอกอยู่แล้ว = ซ่อน (บอสสั่ง 9 พ.ย. 69 · ตัวกลางของ 4 หน้าเจาะลึก) ──────────────────────────────
//   เจาะถึงดีลเลอร์รายเดียว → ไม่มีคอลัมน์ "ดีลเลอร์" (หัวตารางบอกชื่อแล้ว) · ระดับทั้งเครือ/ภาค/จังหวัด คงไว้
//   ภูมิภาค / จังหวัด (รวมบรรทัดเล็กใต้ชื่อ): ทุกแถวเป็นค่าเดียวกับระดับที่เจาะอยู่ = ซ่อน · มีแถวที่ต่าง (เช่น จังหวัดหน้างานคนละจังหวัด) = คงไว้
//   ไฟล์ส่งออกไม่ใช้ตัวนี้ (คงคอลัมน์ครบเหมือนเดิม)
import { ภาคมาตรฐาน, ชื่อภาค } from "./provinces";

export type ระดับเจาะ = { ภาค?: string | null; จังหวัด?: string | null; ดีลเลอร์?: string | null };
export type คอลัมน์ซ่อน = { ดีลเลอร์: boolean; ภาค: boolean; จังหวัด: boolean };

const เท่าระดับ = <R,>(แถว: readonly R[], ค่า: ((r: R) => string | null | undefined) | undefined, ระดับ: string | null | undefined, ปรับ: (v: string) => string = v => v) =>
  !!ระดับ && !!ค่า && แถว.length > 0 && แถว.every(r => ปรับ(String(ค่า(r) ?? "").trim()) === ปรับ(String(ระดับ).trim()));

/** คอลัมน์ไหนซ้ำกับระดับที่เจาะอยู่ — ค่า = ตัวอ่านภูมิภาค/จังหวัดของแถว (ไม่ส่ง = ไม่มีคอลัมน์นั้น) */
export function ซ่อนตามระดับ<R>(ระดับ: ระดับเจาะ, แถว: readonly R[], ค่า: { ภาค?: (r: R) => string | null | undefined; จังหวัด?: (r: R) => string | null | undefined } = {}): คอลัมน์ซ่อน {
  return {
    ดีลเลอร์: !!ระดับ.ดีลเลอร์,
    ภาค: เท่าระดับ(แถว, ค่า.ภาค, ระดับ.ภาค, v => ภาคมาตรฐาน(v) ?? v),
    จังหวัด: เท่าระดับ(แถว, ค่า.จังหวัด, ระดับ.จังหวัด),
  };
}

/** บรรทัดเล็กใต้ชื่อดีลเลอร์ "ภูมิภาค · จังหวัด" — ตัดส่วนที่ระดับบอกอยู่แล้ว (เจาะภาค = เหลือจังหวัด · เจาะจังหวัด = ไม่มีบรรทัด) */
export function บรรทัดใต้ชื่อดีลเลอร์(r: { region?: string | null; province?: string | null }, ระดับ: ระดับเจาะ): string {
  const ภาค = ระดับ.ภาค || ระดับ.จังหวัด ? "" : (r.region ? ชื่อภาค(r.region) : "ไม่ระบุภูมิภาค");
  const จังหวัด = ระดับ.จังหวัด ? "" : (r.province || "ไม่ระบุจังหวัด");
  return [ภาค, จังหวัด].filter(Boolean).join(" · ");
}
