// เจอ: กล่องใบ HQ ในแผงลีดดีลเลอร์ขึ้น "38ตัน" "2,240ตร.ม." และหัวคอลัมน์ไม่ตรงกับข้อมูล
//   ต้นเหตุ: ตารางรายการแต่ละที่เขียนเอง บางที่ใช้ className="table" ซึ่งไม่มีสไตล์ → หัวจัดกึ่งกลาง (ค่าตั้งต้นเบราว์เซอร์) · ช่องแทบไม่มีระยะ
//     จำนวนชิดขวาติดกับหน่วยที่ชิดซ้าย · ใบพิมพ์ A4 รวมจำนวน+หน่วยเป็นช่องเดียว
// กติกา: จำนวน = ชิดขวา มีคั่นหลักพัน · หน่วย = ชิดซ้าย (คอลัมน์ถัดจากจำนวน) · หัวคอลัมน์ชิดแนวเดียวกับข้อมูลของคอลัมน์นั้นเสมอ
//   คอมโพเนนต์ <ตารางรายการ> (components/ui/LineItemsTable.tsx · สร้างบนตารางมาตรฐาน .table-wrap) กับใบพิมพ์ (quotationPrint.ts)
//   อ่านชนิดจากที่นี่ที่เดียว · ข้อทดสอบ: tests/scenario/qty-unit-columns.spec.ts (ตรวจตำแหน่งข้อความหัว/ช่องบนจอจริง)

export type ชนิดคอลัมน์ = "ลำดับ" | "ข้อความ" | "จำนวน" | "หน่วย" | "เงิน" | "ร้อยละ" | "ปุ่ม";

/** แนวชิดของแต่ละชนิด — ใช้ทั้งหัวคอลัมน์และข้อมูล (หัวตรงแนวข้อมูลเสมอ) */
export const แนวของชนิด: Record<ชนิดคอลัมน์, "left" | "right" | "center"> = {
  ลำดับ: "right", ข้อความ: "left", จำนวน: "right", หน่วย: "left", เงิน: "right", ร้อยละ: "right", ปุ่ม: "center",
};

/** จำนวน: คั่นหลักพัน ทศนิยมไม่เกิน 2 ตำแหน่ง (38 · 2,240 · 12.5) · ไม่ใช่ตัวเลข = "—" */
export function จัดรูปจำนวน(n: unknown): string {
  const v = Number(n);
  return n == null || n === "" || !Number.isFinite(v) ? "—" : v.toLocaleString("en-US", { maximumFractionDigits: 2 });
}
/** หน่วย: ว่าง = "—" */
export const จัดรูปหน่วย = (u: unknown) => String(u ?? "").trim() || "—";

/** คลาสของหัว/ช่องตามชนิด — ชุดเดียวกับตารางมาตรฐาน (.table-wrap th.num/td.num ชิดขวา ตัวเลขกว้างเท่ากัน) ทั้งหน้าเว็บและใบพิมพ์ */
export const คลาสของชนิด = (ช: ชนิดคอลัมน์) => ({ left: "", right: "num", center: "li-center" })[แนวของชนิด[ช]];
