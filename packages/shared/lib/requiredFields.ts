//   * สีแดงเฉพาะช่องที่บังคับจริง (ป้ายช่อง · components/ui/FieldLabel.tsx) · กดบันทึกตอนช่องบังคับว่าง = ไม่บันทึก
//   กรอบแดง + ข้อความใต้ช่อง + เลื่อนไปช่องแรกที่ขาด (useช่องบังคับ) · ฐานกันอีกชั้นทุกช่องที่ฐานบังคับ
//   กติกา "-": ช่องข้อความบังคับที่อาจไม่มีข้อมูลจริง (เช่น เงื่อนไขใบค่าแฟรนไชส์) ใส่ "-" = ตั้งใจไม่มี ผ่าน · ว่าง/เว้นวรรคล้วน = ไม่ผ่าน
//   ตรรกะล้วน (ไม่พึ่ง React) — หน้าจอ · เซิร์ฟเวอร์ · ข้อทดสอบใช้ชุดเดียวกัน

/** ค่าที่นับว่า "ยังไม่ได้กรอก" — null/undefined/ข้อความว่างหรือเว้นวรรคล้วน · ตัวเลข NaN · รายการว่าง (ตัวเลข 0 = กรอกแล้ว) */
export function ว่างอยู่(v: unknown): boolean {
  if (v == null) return true;
  if (typeof v === "string") return v.trim() === "";
  if (typeof v === "number") return Number.isNaN(v);
  if (Array.isArray(v)) return v.length === 0;
  return false;
}
/** ค่า "-" (ตั้งใจไม่มี) — ยอมรับเฉพาะช่องที่ใช้กติกา "-" */
export const เป็นขีดตั้งใจไม่มี = (v: unknown) => typeof v === "string" && v.trim() === "-";

export type ช่องบังคับ = {
  /** คีย์ของช่อง (ใช้ผูกกรอบแดง/เลื่อนไปช่อง) */
  key: string;
  /** ชื่อช่องที่ผู้ใช้เห็น (ไม่มี *) */
  label: string;
  value: unknown;
  /** ข้อความเพิ่มใต้ช่อง (ไม่ส่ง = "ต้องกรอก<ชื่อช่อง>") */
  ข้อความ?: string;
};
export type ผลตรวจช่อง = Record<string, string>;
/** ตรวจช่องบังคับทั้งชุด → { key: ข้อความใต้ช่อง } ของช่องที่ขาด (ตามลำดับที่ส่งมา = ลำดับบนฟอร์ม) · ว่าง = ผ่าน */
export function ตรวจช่องบังคับ(ช่อง: ช่องบังคับ[]): ผลตรวจช่อง {
  const ผล: ผลตรวจช่อง = {};
  for (const c of ช่อง) if (ว่างอยู่(c.value)) ผล[c.key] = c.ข้อความ ?? `ต้องกรอก${c.label}`;
  return ผล;
}
/** ข้อความสรุปบรรทัดเดียว (แถบผิดพลาดของฟอร์ม) */
export const สรุปช่องที่ขาด = (ช่อง: ช่องบังคับ[], ผล: ผลตรวจช่อง) =>
  Object.keys(ผล).length ? `กรอกให้ครบก่อนบันทึก: ${ช่อง.filter(c => ผล[c.key]).map(c => c.label).join(" · ")}` : "";
/** ข้อความใต้ช่องของช่องที่ใช้กติกา "-" */
export const ข้อความช่องขีด = (label: string) => `ต้องกรอก${label} — ไม่มีให้ใส่ "-"`;
