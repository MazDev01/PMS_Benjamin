//
// กติกา (docs/FLOW.html ตาราง "สถานะ ↔ ขั้น"):
//   ขั้น 1 ข้อมูลลูกค้า   = ติดต่อแล้ว / รวบรวมความต้องการ
//   ขั้น 2 ขอราคา HQ     = รอราคา HQ
//   ขั้น 3 ได้ใบ HQ      = ได้ราคา HQ (ยังไม่มีใบร่างให้ลูกค้า)
//   ขั้น 4 ทำใบให้ลูกค้า = ได้ราคา HQ + มีใบร่าง
//   ขั้น 5 รอลูกค้าตอบ   = เสนอราคา / ติดตามผล / เจรจาต่อรอง
//   ปิดสำเร็จ = ผ่านครบ 5 ขั้น · ปิดไม่สำเร็จ = ติ๊กเฉพาะขั้นที่ทำจริง (ดูจากประวัติคำขอ/ใบ ไม่ใช่สถานะ)
// แถบขั้นไฮไลต์ "ขั้นที่อยู่ตอนนี้" ไม่ใช่ขั้นที่ต้องทำต่อ
// ⛔ ห้ามเขียนตาราง สถานะ→ขั้น หรือรายชื่อขั้นซ้ำที่อื่น — scripts/check-lead-stage-map.mjs (รอบตรวจเต็ม) ตกทันที
// ข้อทดสอบ: tests/unit/leadStage.test.ts
import type { LeadStatus, QuotationStatus } from "./mock";
import type { QuoteRequestStatus } from "./quoteRequests";

/** ชื่อขั้นชุดเดียวที่ใช้ทุกที่ (แผงลีดดีลเลอร์ · หน้ารายละเอียดดีลเลอร์ของ HQ) */
export const ชื่อขั้นการขาย = ["ข้อมูลลูกค้า", "ขอราคา HQ", "ได้ใบ HQ", "ทำใบให้ลูกค้า", "รอลูกค้าตอบ"] as const;
export type ขั้นการขาย = 1 | 2 | 3 | 4 | 5;
export type ผลขั้น = { kind: "open"; step: ขั้นการขาย } | { kind: "won" } | { kind: "lost" };

/** ขั้นที่ลีดอยู่ตอนนี้ — มีใบร่าง = ใบลูกค้าของดีลนี้ที่ยังเป็นร่าง (ใช้แยกขั้น 3 กับ 4 ตอนได้ราคา HQ) */
export function ขั้นของลีด(status: LeadStatus, มีใบร่าง: boolean): ผลขั้น {
  switch (status) {
    case "WAITING": case "BULLET": return { kind: "open", step: 1 };
    case "HQ_PRICING": return { kind: "open", step: 2 };
    case "HQ_QUOTED": return { kind: "open", step: มีใบร่าง ? 4 : 3 };
    case "QUOTED": case "FOLLOWUP": case "NEGO": return { kind: "open", step: 5 };
    case "PAID": return { kind: "won" };
    case "CANCELLED": return { kind: "lost" };
  }
}

/** ประวัติของดีล — ใช้ติ๊กขั้นของลีดที่ปิดไม่สำเร็จ (ติ๊กเฉพาะขั้นที่เคยทำจริง) */
export type ประวัติดีล = {
  /** สถานะคำขอราคาทุกใบของลีดนี้ (ใหม่ → เก่า ลำดับไม่สำคัญ) */
  คำขอ: QuoteRequestStatus[];
  /** สถานะใบลูกค้าทุกใบของดีลนี้ */
  ใบลูกค้า: QuotationStatus[];
};
// คำขอที่ HQ ส่งใบแล้ว: ส่งใบแล้ว · ปิด (won/lost หลังได้ใบ) · ขอแก้ราคาแล้ว — ยกเลิกได้เฉพาะก่อน HQ ส่งใบ จึงไม่นับ
const ได้ใบHQ = (s: QuoteRequestStatus) => s === "quoted" || s === "won" || s === "lost" || s === "superseded";
// ใบลูกค้าที่ถึงมือลูกค้าแล้ว — หมดอายุแยกไม่ได้ว่าเคยส่งหรือยัง (ใบร่างก็หมดอายุตามใบ HQ ได้) จึงไม่นับ
const ส่งถึงลูกค้า = (s: QuotationStatus) => s === "sent_to_client" || s === "won" || s === "lost" || s === "superseded";

export type สภาพขั้น = "ผ่าน" | "ตอนนี้" | "ยังไม่ถึง" | "ไม่ได้ทำ";

/** สภาพของทั้ง 5 ขั้นบนแถบ (index 0 = ขั้น 1) */
export function สภาพแถบขั้น(status: LeadStatus, มีใบร่าง: boolean, ประวัติ: ประวัติดีล): สภาพขั้น[] {
  const ผล = ขั้นของลีด(status, มีใบร่าง);
  if (ผล.kind === "won") return ["ผ่าน", "ผ่าน", "ผ่าน", "ผ่าน", "ผ่าน"];
  if (ผล.kind === "open") return [1, 2, 3, 4, 5].map(n => n < ผล.step ? "ผ่าน" : n === ผล.step ? "ตอนนี้" : "ยังไม่ถึง");
  const ทำแล้ว = [
    true,                                   // ขั้น 1 มีลีด = มีข้อมูลลูกค้าแล้ว
    ประวัติ.คำขอ.length > 0,                // ขั้น 2 เคยขอราคา HQ
    ประวัติ.คำขอ.some(ได้ใบHQ),            // ขั้น 3 HQ เคยส่งใบ
    ประวัติ.ใบลูกค้า.length > 0,            // ขั้น 4 เคยทำใบให้ลูกค้า
    ประวัติ.ใบลูกค้า.some(ส่งถึงลูกค้า),    // ขั้น 5 เคยส่งใบถึงลูกค้า
  ];
  return ทำแล้ว.map(x => x ? "ผ่าน" : "ไม่ได้ทำ");
}
