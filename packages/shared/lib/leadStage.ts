// ── สถานะลีด → ขั้นการขาย 4 ขั้น — ตัวแปลงกลางตัวเดียวของทั้งสองแอป (รอบ 4 · บอสสั่ง 21 ต.ค. 69 · ยุบเหลือ 4 ขั้น 9 พ.ย. 69) ─────
//
// กติกา (docs/FLOW.html ตาราง "สถานะ ↔ ขั้น"):
//   ขั้น 1 ข้อมูลลูกค้า   = ติดต่อแล้ว / รวบรวมความต้องการ
//   ขั้น 2 ขอราคา HQ     = รอราคา HQ
//   ขั้น 3 ได้ใบ HQ      = ได้ราคา HQ (ยังไม่มีใบร่างให้ลูกค้า)
//   ขั้น 4 เสนอราคาลูกค้า = ได้ราคา HQ + มีใบร่าง (ทำใบแล้ว ยังไม่ส่ง) · เสนอราคา (ส่งให้ลูกค้าแล้ว)
//     บอสสั่ง 9 พ.ย. 69: ยุบ "ทำใบให้ลูกค้า" + "รอลูกค้าตอบ" เป็นขั้นเดียว — ป้ายย่อย ป้ายย่อยขั้น() ยังบอกว่าทำใบแล้ว/ส่งแล้ว
//   ปิดสำเร็จ = ผ่านครบ 4 ขั้น · ปิดไม่สำเร็จ = ติ๊กเฉพาะขั้นที่ทำจริง (ดูจากประวัติคำขอ/ใบ ไม่ใช่สถานะ)
// แถบขั้นไฮไลต์ "ขั้นที่อยู่ตอนนี้" ไม่ใช่ขั้นที่ต้องทำต่อ
// ⛔ ห้ามเขียนตาราง สถานะ→ขั้น หรือรายชื่อขั้นซ้ำที่อื่น — scripts/check-lead-stage-map.mjs (รอบตรวจเต็ม) ตกทันที
// ข้อทดสอบ: tests/unit/leadStage.test.ts
import type { LeadStatus, QuotationStatus } from "./mock";
import type { QuoteRequestStatus } from "./quoteRequests";

/** ชื่อขั้นชุดเดียวที่ใช้ทุกที่ (แผงลีดดีลเลอร์ · หน้ารายละเอียดดีลเลอร์ของ HQ) */
export const ชื่อขั้นการขาย = ["ข้อมูลลูกค้า", "ขอราคา HQ", "ได้ใบ HQ", "เสนอราคาลูกค้า"] as const;
/** จำนวนขั้นที่เปิดอยู่ (แถบในแผงลีด · แถบความคืบหน้าในตาราง) */
export const จำนวนขั้น = ชื่อขั้นการขาย.length;
export type ขั้นการขาย = 1 | 2 | 3 | 4;
export type ผลขั้น = { kind: "open"; step: ขั้นการขาย } | { kind: "won" } | { kind: "lost" };

/** ชื่อขั้นเดิมก่อนยุบ (บันทึกเก่า/audit เก็บชื่อนี้ไว้ ห้ามแก้) → แปลงเป็นชื่อปัจจุบันตอนแสดงผล */
const ชื่อขั้นเดิม: Record<string, string> = { "ทำใบให้ลูกค้า": "เสนอราคาลูกค้า", "รอลูกค้าตอบ": "เสนอราคาลูกค้า" };
/** แปลงชื่อขั้นเดิมในข้อความเก่า (ประวัติ · บันทึกการใช้งาน) เป็นชื่อขั้นปัจจุบัน — ใช้ตอนแสดงผลเท่านั้น */
export function แปลงชื่อขั้นเดิม(ข้อความ: string): string {
  return ข้อความ.replace(/ทำใบให้ลูกค้า|รอลูกค้าตอบ/g, m => ชื่อขั้นเดิม[m] ?? m);
}

/** ขั้นที่ลีดอยู่ตอนนี้ — มีใบร่าง = ใบลูกค้าของดีลนี้ที่ยังเป็นร่าง (ใช้แยกขั้น 3 กับ 4 ตอนได้ราคา HQ) */
export function ขั้นของลีด(status: LeadStatus, มีใบร่าง: boolean): ผลขั้น {
  switch (status) {
    case "WAITING": case "BULLET": return { kind: "open", step: 1 };
    case "HQ_PRICING": return { kind: "open", step: 2 };
    case "HQ_QUOTED": return { kind: "open", step: มีใบร่าง ? 4 : 3 };
    case "QUOTED": return { kind: "open", step: 4 };
    case "PAID": return { kind: "won" };
    case "CANCELLED": return { kind: "lost" };
  }
}

/** ป้ายย่อยของขั้น "เสนอราคาลูกค้า" — บอกว่าทำใบแล้วยังไม่ส่ง หรือส่งให้ลูกค้าแล้ว (ขั้นอื่น = null) */
export function ป้ายย่อยขั้น(status: LeadStatus, มีใบร่าง: boolean): "ทำใบแล้ว (ยังไม่ส่ง)" | "ส่งให้ลูกค้าแล้ว" | null {
  if (status === "QUOTED") return "ส่งให้ลูกค้าแล้ว";
  if (status === "HQ_QUOTED" && มีใบร่าง) return "ทำใบแล้ว (ยังไม่ส่ง)";
  return null;
}

/** ประวัติของดีล — ใช้ติ๊กขั้นของลีดที่ปิดไม่สำเร็จ (ติ๊กเฉพาะขั้นที่เคยทำจริง) */
export type ประวัติดีล = {
  /** สถานะคำขอราคาทุกใบของลีดนี้ (ใหม่ → เก่า ลำดับไม่สำคัญ) */
  คำขอ: QuoteRequestStatus[];
  /** สถานะใบลูกค้าทุกใบของดีลนี้ */
  ใบลูกค้า: QuotationStatus[];
};
// คำขอที่ HQ ส่งใบแล้ว: ส่งใบแล้ว · ปิด (won/lost หลังได้ใบ) · ขอแก้ราคาแล้ว — ยกเลิกได้เฉพาะก่อน HQ ส่งใบ จึงไม่นับ
const ได้ใบHQ = (s: QuoteRequestStatus) => s === "quoted" || s === "won" || s === "lost" || s === "superseded";

export type สภาพขั้น = "ผ่าน" | "ตอนนี้" | "ยังไม่ถึง" | "ไม่ได้ทำ";

/** สภาพของทั้ง 4 ขั้นบนแถบ (index 0 = ขั้น 1) */
export function สภาพแถบขั้น(status: LeadStatus, มีใบร่าง: boolean, ประวัติ: ประวัติดีล): สภาพขั้น[] {
  const ผล = ขั้นของลีด(status, มีใบร่าง);
  const ขั้น = ชื่อขั้นการขาย.map((_, i) => i + 1);
  if (ผล.kind === "won") return ขั้น.map(() => "ผ่าน");
  if (ผล.kind === "open") return ขั้น.map(n => n < ผล.step ? "ผ่าน" : n === ผล.step ? "ตอนนี้" : "ยังไม่ถึง");
  const ทำแล้ว = [
    true,                                   // ขั้น 1 มีลีด = มีข้อมูลลูกค้าแล้ว
    ประวัติ.คำขอ.length > 0,                // ขั้น 2 เคยขอราคา HQ
    ประวัติ.คำขอ.some(ได้ใบHQ),            // ขั้น 3 HQ เคยส่งใบ
    ประวัติ.ใบลูกค้า.length > 0,            // ขั้น 4 เคยทำใบให้ลูกค้า (ส่งแล้วหรือยังไม่ส่ง)
  ];
  return ทำแล้ว.map(x => x ? "ผ่าน" : "ไม่ได้ทำ");
}

// ── ป้ายขั้นในตาราง/บอร์ด/ตัวกรอง/ส่งออก (บอสสั่ง 27 ต.ค. 69) ─────────────────────────────────────────────────────
//   ทุกที่ที่แสดงขั้นของลีดใช้ชื่อชุดนี้ชุดเดียว — ห้ามแสดงชื่อสถานะภายใน (รอราคา HQ · เสนอราคา ฯลฯ) แทนชื่อขั้น
//   เลขขั้น 1–4 = เปิดอยู่ · 6 = ปิดสำเร็จ · 7 = ปิดไม่สำเร็จ (ใช้เรียง/กรอง · ฐานคิดเลขเดียวกันที่ lead_stage_no ใบ 0251/0284)
//     เลข 5 ว่างตั้งแต่ยุบขั้น (9 พ.ย. 69) — คงเลขปิดสำเร็จ/ไม่สำเร็จเดิม ลิงก์ ?stage= และ API ไม่เปลี่ยนความหมาย
//   สีเดียวกับแถบในแผงลีด (LeadNextStep): ขั้นที่อยู่ตอนนี้ = อำพัน · ปิดสำเร็จ = เขียว · ปิดไม่สำเร็จ = แดง
export type เลขขั้น = 1 | 2 | 3 | 4 | 6 | 7;
export const เลขขั้นทั้งหมด: readonly เลขขั้น[] = [1, 2, 3, 4, 6, 7];
/** เลขขั้นที่ยังเปิดอยู่ (ก่อนปิด) */
export const เลขขั้นเปิด: readonly เลขขั้น[] = [1, 2, 3, 4];
export const ขั้นปิดสำเร็จ = 6 as const;
export const ขั้นปิดไม่สำเร็จ = 7 as const;
/** เลขขั้นนี้ยังเปิดอยู่ไหม (1–4) */
export const ขั้นเปิดอยู่ = (n: number) => n >= 1 && n <= จำนวนขั้น;
export const สีแถบขั้น = { ผ่าน: "#003366", ตอนนี้: "#d97706", ตอนนี้ตัวอักษร: "#b45309", ยังไม่ถึง: "#e5e7eb" } as const;

export function เลขขั้นจากผล(ผล: ผลขั้น): เลขขั้น {
  return ผล.kind === "won" ? 6 : ผล.kind === "lost" ? 7 : ผล.step;
}
export function เลขขั้นของลีด(status: LeadStatus, มีใบร่าง: boolean): เลขขั้น {
  return เลขขั้นจากผล(ขั้นของลีด(status, มีใบร่าง));
}
/** ชื่อขั้นที่แสดง: "ข้อมูลลูกค้า" … "เสนอราคาลูกค้า" · "ปิดสำเร็จ" · "ปิดไม่สำเร็จ"
 *  ไม่มีเลขลำดับนำหน้า (บอสสั่ง 28 ต.ค. 69) — ลำดับดูจากแถบความคืบหน้า · ใช้ทุกที่ที่แสดงขั้น (ตาราง · บอร์ด · แถบในแผงลีด · หน้า HQ)
 *  เลขที่ไม่ใช่ขั้น (เช่น 5 จากลิงก์/ข้อมูลเก่า) = ชื่อขั้นสุดท้าย "เสนอราคาลูกค้า" */
export function ชื่อขั้น(n: เลขขั้น): string {
  return n === 6 ? "ปิดสำเร็จ" : n === 7 ? "ปิดไม่สำเร็จ" : ชื่อขั้นการขาย[Math.min(n, จำนวนขั้น) - 1];
}
/** สีป้ายของขั้น — ชุดเดียวกับแถบในแผงลีด */
export function สีขั้น(n: เลขขั้น): { bg: string; text: string; bar: string } {
  if (n === 6) return { bg: "#e5faf0", text: "#059669", bar: "#059669" };
  if (n === 7) return { bg: "#fee2e2", text: "#dc2626", bar: "#dc2626" };
  return { bg: "#fef3c7", text: สีแถบขั้น.ตอนนี้ตัวอักษร, bar: สีแถบขั้น.ตอนนี้ };
}
/** สีกราฟรายขั้น (โดนัท/แท่ง ต้องแยกสีกันได้ · ป้ายในตาราง/บอร์ดใช้ สีขั้น() ชุดเดียวกับแถบ) */
export const สีกราฟขั้น: Record<เลขขั้น, string> = { 1: "#64748b", 2: "#7c3aed", 3: "#0891b2", 4: "#d97706", 6: "#059669", 7: "#dc2626" };
/** ตัวเลือกตัวกรองขั้น (เรียงตามเลขขั้น) */
export const ตัวเลือกขั้น = เลขขั้นทั้งหมด.map(n => ({ v: String(n), l: ชื่อขั้น(n) }));
