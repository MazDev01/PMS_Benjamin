// ── ความคืบหน้าของลีดในตาราง (ดีลเลอร์ + ลีดทั้งเครือ HQ · บอสสั่ง 28 ต.ค. 69) ─────────────────────────────────────
//   5 ขั้นของ leadStage.ts ขั้นละ 20% · ปิดสำเร็จ = 100% · ปิดไม่สำเร็จ = สีแดงตามขั้นไกลสุดที่เคยไปถึง
//   ขั้นของลีดที่เปิดอยู่มาจาก stageNo ที่ฐานคิด (แถวของ HQ · ใบ 0251) หรือ เลขขั้นของลีด (ตัวเดียวกับป้ายขั้น/แถบในแผงลีด) · ขั้นที่ไปถึงของลีดที่ปิดไม่สำเร็จ = leads.reached_step
//   ที่ฐานคิดจากคำขอ/ใบ เงื่อนไขเดียวกับ สภาพแถบขั้น ในแผงลีด (ใบ 0258)
import { เลขขั้นของลีด, type เลขขั้น } from "./leadStage";
import type { LeadRow } from "./mock";

export type ความคืบหน้า = { ขั้น: number; เปอร์เซ็นต์: number; ปิดไม่สำเร็จ: boolean };

type ลีดที่วัด = Pick<LeadRow, "status" | "reachedStep" | "stageNo">;
/** เลขขั้น 1–7 ของแถว — ฐานคิดให้แล้ว (HQ) ใช้ค่านั้น ไม่งั้นคิดจากสถานะ + ใบร่าง */
export const เลขขั้นแถวลีด = (l: ลีดที่วัด, มีใบร่าง: boolean): เลขขั้น => (l.stageNo as เลขขั้น | undefined) ?? เลขขั้นของลีด(l.status, มีใบร่าง);

export function ความคืบหน้าลีด(l: ลีดที่วัด, มีใบร่าง: boolean): ความคืบหน้า {
  const n = เลขขั้นแถวลีด(l, มีใบร่าง);
  const ขั้น = n === 6 ? 5 : n === 7 ? Math.min(5, Math.max(1, l.reachedStep ?? 1)) : n;
  return { ขั้น, เปอร์เซ็นต์: ขั้น * 20, ปิดไม่สำเร็จ: n === 7 };
}
