// ── กติการหัสผ่านชุดเดียวทั้งระบบ (ตรวจที่เซิร์ฟเวอร์ทุกทางที่ตั้งรหัสผ่านได้) ─────────────
//
// ใช้กับ: สร้างดีลเลอร์จากลูกค้าเป้าหมาย · HQ แก้บัญชีดีลเลอร์ · ดีลเลอร์แก้เอง/ส่งคำขอ · อนุมัติคำขอ
//         ผู้ดูแลตั้งรหัสให้ผู้ใช้ HQ · เก็บสำเนารหัสของผู้ใช้ HQ
// เดิมแต่ละทางตรวจไม่เหมือนกัน (บางทางแค่ยาว ≥ 8 · บางทาง ≥ 6 · บางทางตัดช่องว่างทิ้งเงียบ ๆ)
//   → ยิง API ตรงด้วยรหัสที่มีช่องว่างได้ แล้วเจ้าของบัญชีเข้าระบบไม่ได้ เพราะหน้าเข้าสู่ระบบตัดช่องว่างทิ้ง
//
// ไฟล์นี้เป็นตรรกะล้วน — หน้าจอใช้บอกล่วงหน้าได้ แต่ด่านจริงอยู่ที่เซิร์ฟเวอร์เสมอ
export const รหัสผ่านยาวอย่างน้อย = 8;
/** ระบบยืนยันตัวตนใช้แค่ 72 ไบต์แรก — ยาวกว่านั้นส่วนเกินไม่มีผล (รหัสสองอันที่ต่างกันแค่ท้ายจะเข้าได้ทั้งคู่) */
export const รหัสผ่านยาวไม่เกินไบต์ = 72;

/** คืนข้อความที่ผู้ใช้อ่านเข้าใจ หรือ null ถ้าใช้ได้ */
export function ตรวจรหัสผ่านใหม่(password: string): string | null {
  if (password.length < รหัสผ่านยาวอย่างน้อย) return `รหัสผ่านต้องยาวอย่างน้อย ${รหัสผ่านยาวอย่างน้อย} ตัวอักษร`;
  if (/\s/.test(password)) return "รหัสผ่านห้ามมีช่องว่าง — หน้าเข้าสู่ระบบตัดช่องว่างทิ้ง ตั้งไว้แล้วจะเข้าระบบไม่ได้";
  if (new TextEncoder().encode(password).length > รหัสผ่านยาวไม่เกินไบต์) return "รหัสผ่านยาวเกินไป — ใช้ไม่เกิน 72 ตัวอักษรภาษาอังกฤษ";
  return null;
}
