// เหลือ 4 ตัว (บอสสั่ง 3 พ.ย. 69 · ทับชุด 16 ก.ค./28 ส.ค. 69): 1 เดือน · 3 เดือน · 1 ปี (ค่าเริ่มต้น) · กำหนดเอง
//   ย้อนหลังจากวันนี้ถึงวันนี้ · ย้อนเดือนแล้ววันไม่มีในเดือนนั้น = ปัดเป็นวันสุดท้ายของเดือน (31 มี.ค. ย้อน 1 เดือน = 28/29 ก.พ.)
//   เอาออก: ทุกช่วงเวลา · วันนี้ · 7 วันล่าสุด · เดือนนี้ · ปีนี้ — อย่าใส่กลับโดยไม่ถาม
//   ค่าที่จำไว้ในเครื่องเป็นตัวเลือกที่เอาออก = กลับค่าเริ่มต้น 1 ปี (ดู FilterProvider)
export type TimePreset = "m1" | "m3" | "y1" | "custom";

export const TIME_PRESETS: { key: TimePreset; label: string }[] = [
  { key: "m1",     label: "1 เดือน" },
  { key: "m3",     label: "3 เดือน" },
  { key: "y1",     label: "1 ปี" },
  { key: "custom", label: "กำหนดเอง" },
];

/** วันที่ย้อนหลัง n เดือนจาก d — วันไม่มีในเดือนปลายทาง = วันสุดท้ายของเดือนนั้น (ไม่ล้นไปเดือนถัดไป) */
export function ย้อนเดือน(d: Date, n: number): Date {
  const เป้า = new Date(d.getFullYear(), d.getMonth() - n, 1);
  const วันสุดท้าย = new Date(เป้า.getFullYear(), เป้า.getMonth() + 1, 0).getDate();
  return new Date(เป้า.getFullYear(), เป้า.getMonth(), Math.min(d.getDate(), วันสุดท้าย));
}

