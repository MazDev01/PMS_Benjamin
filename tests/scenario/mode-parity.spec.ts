import { test, expect } from "@playwright/test";
import { open, settle } from "./helpers";
import { appEnv, skipReason, SUPABASE_URL } from "./supabaseEnv";

// ── ด่านกัน "ทดสอบคนละโหมดกับเว็บจริง" ────────────────────────────────────────
//
// 26 ส.ค. 69: เจอบั๊กบนเว็บจริง 3 ตัวรวดในวันเดียว ทั้งที่ชุดทดสอบ 394 ข้อเขียวหมด
//   • แดชบอร์ด HQ พังทั้งหน้าเมื่อเลือกช่วง "วันนี้"
//   • กราฟ "ยอดขายรายชั่วโมง" ของดีลเลอร์แสดงจุดเดียวแบบรายวัน
//   • ปุ่ม "เข้าระบบแทนดีลเลอร์" ใช้ไม่ได้เลย
// ต้นเหตุเดียวกันทั้งสามตัว: เครื่องพัฒนารันโหมด supabase แต่เว็บจริงรันโหมด api
// สองโหมดเดินคนละเส้นทางโค้ด ชุดทดสอบจึงไม่เคยแตะโค้ดที่พังจริง
//
// เทสต์นี้ไม่ได้ตรวจฟีเจอร์ — ตรวจว่า "แอปที่กำลังถูกทดสอบอยู่ในโหมดที่เราคิดจริงไหม"
// ถ้าตั้งโหมดแล้วไม่ติด (เช่น turbo กรอง env ทิ้ง) ต้องขึ้นแดงทันที ไม่ใช่เขียวแบบหลอก ๆ
test.skip(() => skipReason() !== "", skipReason() || "พร้อมรัน");

const โหมดที่สั่ง = appEnv("NEXT_PUBLIC_DATA_SOURCE");

test(`[parity] แอปต้องทำงานในโหมด "${โหมดที่สั่ง}" จริง ไม่ใช่แค่ตั้งค่าไว้`, async ({ page }) => {
  const ปลายทาง: string[] = [];
  page.on("request", r => ปลายทาง.push(r.url()));

  await open(page, "hq", "/hq/dashboard");
  await settle(page);

  const ผ่านแบ็กเอนด์เรา = ปลายทาง.filter(u => u.includes("/api/v1/"));
  const ยิงฐานตรง = SUPABASE_URL ? ปลายทาง.filter(u => u.startsWith(SUPABASE_URL)) : [];

  if (โหมดที่สั่ง === "api") {
    expect(ผ่านแบ็กเอนด์เรา.length,
      "โหมด api ต้องเห็นคำขอผ่าน /api/v1/ — ไม่เห็นเลย = แอปไม่ได้อยู่โหมด api จริง").toBeGreaterThan(0);
    expect(ยิงฐานตรง,
      "โหมด api ห้ามให้เบราว์เซอร์ยิงฐานข้อมูลตรง ๆ").toEqual([]);
  } else {
    expect(ยิงฐานตรง.length,
      "โหมด supabase ต้องเห็นคำขอตรงไปฐานข้อมูล").toBeGreaterThan(0);
  }
});
