// ตารางพอดีจอ (บอสสั่ง 6 พ.ย. 69) — ซ่อนคอลัมน์ที่ทั้งตารางเป็น "—" · ยังไม่มีแถว = แสดงครบ
//   ตกบนโค้ดก่อนแก้: ไม่มี lib/tableFit.ts
import { describe, it, expect } from "vitest";
import { ซ่อนคอลัมน์ว่าง, ว่าง } from "../../packages/shared/lib/tableFit";

describe("ซ่อนคอลัมน์ว่าง", () => {
  const คอล = ["ชื่อ", "ยอด", "ส่วนต่าง", "เสนอล่าสุด"] as const;
  const ค่า = (c: string, r: Record<string, unknown>) => r[c];
  it("ทั้งตารางเป็น — = ซ่อน · มีค่าแม้แถวเดียว = แสดง · 0 = มีค่า", () => {
    const แถว = [{ ชื่อ: "ก", ยอด: 0, ส่วนต่าง: null, เสนอล่าสุด: "—" }, { ชื่อ: "ข", ยอด: 10, ส่วนต่าง: undefined, เสนอล่าสุด: "2026-11-01" }];
    expect(ซ่อนคอลัมน์ว่าง(คอล, แถว, ค่า)).toEqual(["ชื่อ", "ยอด", "เสนอล่าสุด"]);
  });
  it("ยังไม่มีแถว (กำลังโหลด/ไม่พบ) = แสดงครบ ไม่เดาว่าว่าง · ห้ามซ่อนได้", () => {
    expect(ซ่อนคอลัมน์ว่าง(คอล, [], ค่า)).toEqual([...คอล]);
    expect(ซ่อนคอลัมน์ว่าง(คอล, [{ ชื่อ: "ก" }], ค่า, c => c === "ส่วนต่าง")).toEqual(["ชื่อ", "ส่วนต่าง"]);
  });
  it("ค่าว่าง = null · undefined · \"\" · — · NaN", () => {
    expect([null, undefined, "", "—", NaN].every(ว่าง)).toBe(true);
    expect([0, "0", "ก"].some(ว่าง)).toBe(false);
  });
});
