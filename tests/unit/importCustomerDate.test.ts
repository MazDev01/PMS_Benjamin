import { describe, it, expect } from "vitest";
import { แปลงวันที่นำเข้า } from "../../packages/shared/lib/importSheet";

// วันที่ในไฟล์ที่ดีลเลอร์ส่งออกจากระบบเก่ามาได้หลายรูปแบบ — แปลงผิดแล้วไม่มีข้อความเตือนให้เห็น
// (ลูกค้าจะไปโผล่ปีอื่นเงียบ ๆ แล้วหลุดตัวกรองช่วงเวลา)
describe("แปลงวันที่นำเข้า", () => {
  it("อ่านรูปแบบ วัน/เดือน/ปี ค.ศ.", () => {
    expect(แปลงวันที่นำเข้า("05/10/2025")).toBe("2025-10-05");
    expect(แปลงวันที่นำเข้า("5/1/2025")).toBe("2025-01-05");
  });
  it("ปี พ.ศ. ต้องลบ 543", () => {
    expect(แปลงวันที่นำเข้า("5/10/2568")).toBe("2025-10-05");
    expect(แปลงวันที่นำเข้า("2568-10-05")).toBe("2025-10-05");
  });
  it("รับรูปแบบมาตรฐานของระบบตรง ๆ", () => {
    expect(แปลงวันที่นำเข้า("2025-10-05")).toBe("2025-10-05");
  });
  it("อ่านไม่ออก/ว่าง = คืนค่าว่าง ไม่เดาวันที่ให้", () => {
    for (const v of ["", "  ", "เมื่อวาน", "13-13-2025", "05/13/2025", "2025/10", "0/10/2025"]) {
      expect(แปลงวันที่นำเข้า(v)).toBe("");
    }
  });
});
