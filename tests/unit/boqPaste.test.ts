import { describe, it, expect } from "vitest";
import { แยกแถววางจากExcel, เหลือหรือเกิน, แถวว่าง } from "../../packages/shared/lib/quoteRequests";

// ตาราง BOQ ของ HQ (บอสสั่ง 26 ต.ค. 69): วางจาก Excel แล้วแตกเป็นแถวเอง · แถวที่อ่านไม่ได้ต้องมีคำเตือน ไม่ทิ้งเงียบ ๆ
const TAB = String.fromCharCode(9);
const แถว = (...c: string[]) => c.join(TAB);

describe("วางจาก Excel", () => {
  it("3 แถว (รายการ/จำนวน/หน่วย/ต้นทุนต่อหน่วย) = 3 รายการ · ตัวเลขมีจุลภาคอ่านได้", () => {
    const ข้อความ = [แถว("โครงสร้างเหล็ก", "800", "ตร.ม.", "1,250"), แถว("หลังคาเมทัลชีท", "820", "ตร.ม.", "450.50"), แถว("ค่าขนส่ง", "1", "งาน", "15000")].join("\r\n") + "\r\n";
    const ผล = แยกแถววางจากExcel(ข้อความ)!;
    expect(ผล).toHaveLength(3);
    expect(ผล[0]).toEqual({ name: "โครงสร้างเหล็ก", qty: 800, unit: "ตร.ม.", unitCost: 1250 });
    expect(ผล[1].unitCost).toBe(450.5);
    expect(ผล.every(r => !r.เตือน)).toBe(true);
  });
  it("ข้ามแถวหัวตาราง", () => {
    const ผล = แยกแถววางจากExcel([แถว("รายการ", "จำนวน", "หน่วย", "ต้นทุนต่อหน่วย"), แถว("เสาเหล็ก", "12", "ชุด", "8000")].join("\n"))!;
    expect(ผล.map(r => r.name)).toEqual(["เสาเหล็ก"]);
  });
  it("แถวที่อ่านไม่ได้ยังอยู่ พร้อมคำเตือนที่แถวนั้น", () => {
    const ผล = แยกแถววางจากExcel([แถว("ประตูม้วน", "สี่", "บาน", "12000"), แถว("", "2", "ชุด", "abc")].join("\n"))!;
    expect(ผล).toHaveLength(2);
    expect(ผล[0].เตือน).toContain("อ่านจำนวนไม่ได้");
    expect(ผล[1].เตือน).toContain("ไม่มีชื่อรายการ");
    expect(ผล[1].เตือน).toContain("อ่านต้นทุนไม่ได้");
  });
  it("ข้อความบรรทัดเดียวไม่มี Tab = ไม่ใช่ตาราง (วางตามปกติ)", () => {
    expect(แยกแถววางจากExcel("โกดังเก็บสินค้า")).toBeNull();
  });
});

describe("เหลือ/เกินกี่วัน (ปฏิทินเวลาไทย)", () => {
  const ตอนนี้ = new Date("2026-10-26T10:00:00+07:00").getTime();
  it("เหลือ / เกิน / ครบวันนี้", () => {
    expect(เหลือหรือเกิน("2026-10-29T09:00:00+07:00", ตอนนี้)).toBe("เหลือ 3 วัน");
    expect(เหลือหรือเกิน("2026-10-24T09:00:00+07:00", ตอนนี้)).toBe("เกิน 2 วัน");
    expect(เหลือหรือเกิน("2026-10-26T18:00:00+07:00", ตอนนี้)).toBe("ครบกำหนดวันนี้");
    expect(เหลือหรือเกิน("2026-10-26T08:00:00+07:00", ตอนนี้)).toBe("เกินกำหนดวันนี้");
  });
  it("วันที่ล้วน (ยืนราคาถึง) = ถึงสิ้นวันนั้น · ไม่มีค่า = —", () => {
    expect(เหลือหรือเกิน("2026-10-26", ตอนนี้)).toBe("ครบกำหนดวันนี้");
    expect(เหลือหรือเกิน("2026-11-25", ตอนนี้)).toBe("เหลือ 30 วัน");
    expect(เหลือหรือเกิน(null, ตอนนี้)).toBe("—");
  });
});

describe("แถวว่าง", () => {
  it("ไม่มีชื่อและไม่มีต้นทุน = ว่าง · มีอย่างใดอย่างหนึ่ง = ไม่ว่าง", () => {
    expect(แถวว่าง({ name: " ", unitCost: 0 })).toBe(true);
    expect(แถวว่าง({ name: "เสา", unitCost: 0 })).toBe(false);
    expect(แถวว่าง({ name: "", unitCost: 5 })).toBe(false);
  });
});
