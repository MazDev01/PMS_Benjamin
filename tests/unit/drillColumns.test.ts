// คอลัมน์ที่ระดับเจาะลึกบอกอยู่แล้ว = ซ่อน (บอสสั่ง 9 พ.ย. 69 · ตัวกลาง drillColumns) — ตกบนโค้ดก่อนแก้: ไม่มี lib/drillColumns.ts
import { describe, it, expect } from "vitest";
import { ซ่อนตามระดับ, บรรทัดใต้ชื่อดีลเลอร์ } from "../../packages/shared/lib/drillColumns";

const แถว = [{ ภาค: "ภาคเหนือ", จ: "เชียงใหม่" }, { ภาค: "เหนือ", จ: "เชียงใหม่" }];
const อ่าน = { ภาค: (r: typeof แถว[number]) => r.ภาค, จังหวัด: (r: typeof แถว[number]) => r.จ };
describe("ซ่อนตามระดับ", () => {
  it("ทั้งเครือ = คงครบ · ระดับดีลเลอร์ = ไม่มีคอลัมน์ดีลเลอร์", () => {
    expect(ซ่อนตามระดับ({}, แถว, อ่าน)).toEqual({ ดีลเลอร์: false, ภาค: false, จังหวัด: false });
    expect(ซ่อนตามระดับ({ ดีลเลอร์: "CNX" }, แถว, อ่าน).ดีลเลอร์).toBe(true);
  });
  // ตรวจกลับด้าน (บอสตอบ 10 พ.ย. 69 · ล็อกความกว้างคอลัมน์ ทับ 9 พ.ย.): ภูมิภาค/จังหวัดแสดงเสมอ แม้ทุกแถวเท่ากับระดับที่เจาะ
  it("ทุกแถวเท่ากับระดับ = ยังแสดงภูมิภาค/จังหวัด (ไม่ซ่อนแล้ว) · มีแถวต่าง / ไม่มีแถว = แสดง", () => {
    expect(ซ่อนตามระดับ({ ภาค: "เหนือ", จังหวัด: "เชียงใหม่" }, แถว, อ่าน)).toEqual({ ดีลเลอร์: false, ภาค: false, จังหวัด: false });
    expect(ซ่อนตามระดับ({ ภาค: "เหนือ", จังหวัด: "เชียงใหม่", ดีลเลอร์: "CNX" }, แถว, อ่าน), "ระดับดีลเลอร์: ซ่อนเฉพาะดีลเลอร์").toEqual({ ดีลเลอร์: true, ภาค: false, จังหวัด: false });
    expect(ซ่อนตามระดับ({ จังหวัด: "เชียงใหม่" }, [...แถว, { ภาค: "เหนือ", จ: "ลำพูน" }], อ่าน).จังหวัด).toBe(false);
    expect(ซ่อนตามระดับ({ จังหวัด: "เชียงใหม่" }, [], อ่าน).จังหวัด).toBe(false);
  });
});
describe("บรรทัดใต้ชื่อดีลเลอร์", () => {
  it("ทั้งเครือ = ภูมิภาค · จังหวัด · เจาะภาค = จังหวัด · เจาะจังหวัด = ไม่มี", () => {
    const r = { region: "เหนือ", province: "เชียงใหม่" };
    expect(บรรทัดใต้ชื่อดีลเลอร์(r, {})).toBe("ภาคเหนือ · เชียงใหม่");
    expect(บรรทัดใต้ชื่อดีลเลอร์(r, { ภาค: "เหนือ" })).toBe("เชียงใหม่");
    expect(บรรทัดใต้ชื่อดีลเลอร์(r, { ภาค: "เหนือ", จังหวัด: "เชียงใหม่" })).toBe("");
  });
});
