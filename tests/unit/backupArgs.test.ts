import { describe, it, expect } from "vitest";
// @ts-expect-error — ไฟล์ .mjs ของเครื่องมือ (ไม่มีชนิดข้อมูล)
import { อ่านคำสั่งสำรอง } from "../../scripts/lib/backupArgs.mjs";

// ── ตัวอ่านคำสั่งของเครื่องมือสำรองฐาน (เหตุจริง 20 ต.ค. 69: โหมดฐานจริงทิ้งชื่อโฟลเดอร์ที่ db-push ตั้งให้) ──
const เวลา = new Date("2026-10-20T09:00:00Z");
describe("อ่านคำสั่งสำรอง", () => {
  it("โหมดฐานจริง (ไม่มี --target) + ชื่อโฟลเดอร์ → ใช้ชื่อนั้น", () => {
    expect(อ่านคำสั่งสำรอง(["2026-10-20-15-59-00-ก่อน-db-push"], เวลา)).toEqual({ target: "prod", ชื่อ: "2026-10-20-15-59-00-ก่อน-db-push" });
  });
  it("--target local + ชื่อโฟลเดอร์ (ทั้งก่อนและหลัง)", () => {
    expect(อ่านคำสั่งสำรอง(["--target", "local", "zz"], เวลา)).toEqual({ target: "local", ชื่อ: "zz" });
    expect(อ่านคำสั่งสำรอง(["zz", "--target", "local"], เวลา)).toEqual({ target: "local", ชื่อ: "zz" });
  });
  it("ไม่ระบุชื่อ → ชื่อตั้งต้นมีวินาที (สั่งซ้ำในนาทีเดียวกันไม่ชน)", () => {
    expect(อ่านคำสั่งสำรอง([], เวลา)).toEqual({ target: "prod", ชื่อ: "2026-10-20-16-00-00-prod" });
    expect(อ่านคำสั่งสำรอง(["--target", "local"], เวลา).ชื่อ).toBe("2026-10-20-16-00-00-local");
  });
});
