import { describe, it, expect } from "vitest";
import { สร้างไฟล์Xlsx, ชื่อคอลัมน์, ชื่อแผ่นที่ใช้ได้, ค่าสำหรับExcel } from "../../packages/shared/lib/exportWorkbook";
import { แยกสมุดงานจากXlsx } from "../../packages/shared/lib/importSheet";

// ไฟล์ที่ส่งออกต้องเปิดได้จริงและอ่านกลับได้ครบ — ไม่ใช่แค่ "ดาวน์โหลดแล้วมีไฟล์"
describe("ไฟล์ Excel ที่ส่งออก", () => {
  it("อ่านกลับได้ครบทุกแผ่น ทุกช่อง", async () => {
    const blob = สร้างไฟล์Xlsx([
      { ชื่อ: "ดีลเลอร์", หัวตาราง: ["รหัส", "ชื่อ", "เป้าทั้งปี (บาท)"], แถว: [["CNX", "เชียงใหม่", 12_000_000], ["RYG", "ระยอง", 8_500_000]] },
      { ชื่อ: "เหตุผลปิดการขาย", หัวตาราง: ["เหตุผล"], แถว: [["ราคาสูงกว่าคู่แข่ง"], ["ลูกค้าเลื่อนโครงการ"]] },
    ]);
    const เล่ม = await แยกสมุดงานจากXlsx(await blob.arrayBuffer());
    expect([...เล่ม.keys()]).toEqual(["ดีลเลอร์", "เหตุผลปิดการขาย"]);
    expect(เล่ม.get("ดีลเลอร์")).toEqual([
      ["รหัส", "ชื่อ", "เป้าทั้งปี (บาท)"],
      ["CNX", "เชียงใหม่", "12000000"],
      ["RYG", "ระยอง", "8500000"],
    ]);
    expect(เล่ม.get("เหตุผลปิดการขาย")?.length).toBe(3);
  });

  it("อักขระพิเศษกับช่องว่างไม่ทำให้ไฟล์เสีย", async () => {
    const blob = สร้างไฟล์Xlsx([{ ชื่อ: "ทดสอบ", หัวตาราง: ["ก", "ข", "ค"], แถว: [['บริษัท "เอ" & <บี>', "", "ปกติ"]] }]);
    const แผ่น = (await แยกสมุดงานจากXlsx(await blob.arrayBuffer())).get("ทดสอบ");
    expect(แผ่น?.[1]).toEqual(['บริษัท "เอ" & <บี>', "", "ปกติ"]);
  });

  it("ตั้งชื่อแผ่นตามกติกาของ Excel และไม่ให้ชื่อซ้ำกัน", async () => {
    expect(ชื่อแผ่นที่ใช้ได้("ราคา/หน่วย [2569]")).toBe("ราคา หน่วย  2569");
    expect(ชื่อแผ่นที่ใช้ได้("ก".repeat(40)).length).toBe(31);
    const เล่ม = await แยกสมุดงานจากXlsx(await สร้างไฟล์Xlsx([
      { ชื่อ: "ซ้ำ", หัวตาราง: ["ก"], แถว: [["1"]] },
      { ชื่อ: "ซ้ำ", หัวตาราง: ["ก"], แถว: [["2"]] },
    ]).arrayBuffer());
    expect([...เล่ม.keys()]).toEqual(["ซ้ำ", "ซ้ำ 2"]);
  });

  it("นับคอลัมน์เกิน Z ได้", () => {
    expect(ชื่อคอลัมน์(0)).toBe("A");
    expect(ชื่อคอลัมน์(25)).toBe("Z");
    expect(ชื่อคอลัมน์(26)).toBe("AA");
    expect(ชื่อคอลัมน์(27)).toBe("AB");
  });
});

describe("ยอดเงินที่หน้าจอจัดรูปแบบมาแล้ว", () => {
  it("กลายเป็นตัวเลขที่บวกลบใน Excel ได้", () => {
    expect(ค่าสำหรับExcel("฿2,160,000")).toBe(2_160_000);
    expect(ค่าสำหรับExcel("1,250.50")).toBe(1_250.5);
    expect(ค่าสำหรับExcel("900")).toBe(900);
    expect(ค่าสำหรับExcel(-42)).toBe(-42);
  });
  it("ค่าที่แปลงแล้วความหมายเพี้ยน ต้องคงเป็นข้อความ", () => {
    for (const v of ["45%", "—", "12 วัน", "081-234-5678", "0812345678", "V1", "Q-RYG-2026-2412", ""]) {
      expect(ค่าสำหรับExcel(v)).toBe(v);
    }
  });
});
