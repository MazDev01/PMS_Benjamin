import { describe, it, expect } from "vitest";
import { MODULE_LIST } from "@pms/shared/lib/hqPermissionMatrix";

// ตารางสิทธิ์ในหน้าผู้ใช้ต้องมี "เฉพาะเมนูที่มีอยู่จริง" — ห้ามมีหัวข้อผี
// (เดิมมีแถว "รายงาน" ซึ่งไม่มีหน้านั้นในระบบ · บอสทักท้วง 3 ก.ย. 69)
// เมนูจริง = เมนูข้างของ HQ (navConfig.tsx) — รอบ 2 ช่วง ง เติม 3 เมนูที่ตารางเคยขาด
const เมนูจริงของสำนักงานใหญ่ = [
  "แดชบอร์ด", "ลูกค้าเป้าหมาย (HQ)", "ใบค่าแฟรนไชส์", "ดีลเลอร์", "ภาพรวมยอดขาย", "คำขอใบเสนอราคา",
  "ลูกค้าเป้าหมายทั้งเครือ", "ใบเสนอราคาทั้งเครือ", "ลูกค้าทั้งเครือ", "บันทึกการใช้งาน", "ตั้งค่า",
];

describe("ตารางสิทธิ์ตามบทบาท", () => {
  it("หัวข้อในตารางตรงกับเมนูจริงทุกอัน ไม่ขาดไม่เกิน", () => {
    expect(MODULE_LIST).toEqual(เมนูจริงของสำนักงานใหญ่);
  });
  it("ไม่มีหัวข้อผีที่ไม่มีหน้าอยู่จริง", () => {
    for (const ผี of ["รายงาน", "ความปลอดภัย", "สัญญา", "การส่งมอบ", "ก่อสร้าง"]) {
      expect(MODULE_LIST).not.toContain(ผี);
    }
  });
});
