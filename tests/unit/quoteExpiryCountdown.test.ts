import { describe, it, expect } from "vitest";
import { ป้ายนับวันหมดอายุ } from "../../packages/shared/lib/quoteExpiry";

// แถบสรุปของหน้าต่างใบเสนอราคา/ใบค่าแฟรนไชส์ (บอสสั่ง 9 พ.ย. 69): "เหลือ x วัน" / "เลยมา x วัน" (แดง)
describe("ป้ายนับวันหมดอายุ", () => {
  it("ยังไม่ถึงวัน = เหลือ x วัน ไม่แดง", () => {
    expect(ป้ายนับวันหมดอายุ("2026-11-19", "2026-11-09")).toEqual({ ข้อความ: "เหลือ 10 วัน", เลย: false });
    expect(ป้ายนับวันหมดอายุ("2026-11-10", "2026-11-09")).toEqual({ ข้อความ: "เหลือ 1 วัน", เลย: false });
  });
  it("วันนี้ = หมดอายุวันนี้ ไม่แดง", () => {
    expect(ป้ายนับวันหมดอายุ("2026-11-09", "2026-11-09")).toEqual({ ข้อความ: "หมดอายุวันนี้", เลย: false });
  });
  it("เลยแล้ว = เลยมา x วัน แดง · ข้ามเดือน/ปีนับถูก", () => {
    expect(ป้ายนับวันหมดอายุ("2026-11-04", "2026-11-09")).toEqual({ ข้อความ: "เลยมา 5 วัน", เลย: true });
    expect(ป้ายนับวันหมดอายุ("2026-12-31", "2027-01-02")).toEqual({ ข้อความ: "เลยมา 2 วัน", เลย: true });
  });
  it("ไม่มีวัน/อ่านวันไม่ได้ = null (ไม่เดา)", () => {
    expect(ป้ายนับวันหมดอายุ("", "2026-11-09")).toBeNull();
    expect(ป้ายนับวันหมดอายุ(null, "2026-11-09")).toBeNull();
    expect(ป้ายนับวันหมดอายุ("ไม่ใช่วัน", "2026-11-09")).toBeNull();
  });
});
