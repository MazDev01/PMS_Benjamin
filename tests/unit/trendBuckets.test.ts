// กราฟแนวโน้มต้องแบ่งจุดตามช่วงที่เลือกบนแถบกรอง (บอสสั่ง 25 ส.ค. 69)
import { describe, it, expect } from "vitest";
import { ความละเอียดของช่วง, ยอดรายชั่วโมง, ช่องเวลาในช่วง, คีย์ช่อง } from "../../packages/shared/lib/trendBuckets";
void คีย์ช่อง;

const วัน = (s: string) => new Date(s + "T00:00:00");

describe("ความละเอียดของช่วง", () => {
  it("วันนี้ (วันเดียว) → รายชั่วโมง", () => {
    expect(ความละเอียดของช่วง(วัน("2026-08-25"), วัน("2026-08-25"))).toBe("hour");
  });
  it("7 วันล่าสุด และ เดือนนี้ → รายวัน", () => {
    expect(ความละเอียดของช่วง(วัน("2026-08-19"), วัน("2026-08-25"))).toBe("day");
    expect(ความละเอียดของช่วง(วัน("2026-08-01"), วัน("2026-08-31"))).toBe("day");
  });
  it("ปีนี้ → รายเดือน", () => {
    expect(ความละเอียดของช่วง(วัน("2026-01-01"), วัน("2026-08-25"))).toBe("month");
  });
  it("รอยต่อ 62/63 วัน", () => {
    expect(ความละเอียดของช่วง(วัน("2026-01-01"), วัน("2026-03-03"))).toBe("day");    // 62 วัน
    expect(ความละเอียดของช่วง(วัน("2026-01-01"), วัน("2026-03-04"))).toBe("month");  // 63 วัน
  });
});

describe("ยอดรายชั่วโมง", () => {
  it("รวมยอดเข้าช่องชั่วโมงที่บันทึก และคืนครบ 24 ช่อง", () => {
    const pts = ยอดรายชั่วโมง([
      { savedAt: "2026-08-25T09:38:00", valueNum: 2_000_000 },
      { savedAt: "2026-08-25T09:55:00", valueNum: 1_000_000 },
      { savedAt: "2026-08-25T14:10:00", valueNum: 500_000 },
    ])!;
    expect(pts).toHaveLength(24);
    expect(pts[9]).toEqual({ month: "09:00", value: 3 });     // 2M + 1M = 3 ล้าน
    expect(pts[14]).toEqual({ month: "14:00", value: 0.5 });
    expect(pts[0].value).toBe(0);
  });

  it("ไม่มีใบไหนมีเวลาบันทึก → คืน null (ห้ามเดาเวลาให้)", () => {
    expect(ยอดรายชั่วโมง([{ valueNum: 1_000_000 }])).toBeNull();
    expect(ยอดรายชั่วโมง([])).toBeNull();
  });

  it("เวลาที่อ่านไม่ออก ต้องไม่ทำให้ยอดเพี้ยน", () => {
    const pts = ยอดรายชั่วโมง([
      { savedAt: "ไม่ใช่เวลา", valueNum: 9_000_000 },
      { savedAt: "2026-08-25T08:00:00", valueNum: 1_000_000 },
    ])!;
    expect(pts.reduce((s, p) => s + p.value, 0)).toBe(1);
  });
});

describe("ช่องเวลาในช่วง", () => {
  it("วันเดียว → 24 ช่องชั่วโมง", () => {
    const ช่อง = ช่องเวลาในช่วง(new Date("2026-08-25T00:00:00"), new Date("2026-08-25T23:59:00"));
    expect(ช่อง).toHaveLength(24);
    expect(ช่อง[0].label).toBe("00:00");
    expect(ช่อง[23].label).toBe("23:00");
  });

  it("7 วัน → 7 ช่องวัน เรียงเก่าไปใหม่ และมีครบแม้วันที่ไม่มียอด", () => {
    const ช่อง = ช่องเวลาในช่วง(new Date("2026-08-19T00:00:00"), new Date("2026-08-25T00:00:00"));
    expect(ช่อง.map(b => b.label)).toEqual(["19 ส.ค.","20 ส.ค.","21 ส.ค.","22 ส.ค.","23 ส.ค.","24 ส.ค.","25 ส.ค."]);
  });

  // ข้ามปี = ป้ายติดปี พ.ศ. 2 หลัก (คนรวมงานแจ้ง 4 พ.ย. 69 · เดิมคาด "พ.ย.","ธ.ค.","ม.ค.","ก.พ." ไม่มีปี)
  it("ข้ามปี → นับเป็นคนละช่อง ไม่ทับกัน + ป้ายติดปี", () => {
    const ช่อง = ช่องเวลาในช่วง(new Date("2025-11-01T00:00:00"), new Date("2026-02-01T00:00:00"));
    expect(ช่อง.map(b => b.label)).toEqual(["พ.ย. 68","ธ.ค. 68","ม.ค. 69","ก.พ. 69"]);
    expect(new Set(ช่อง.map(b => b.key)).size).toBe(4);
  });

  it("ปีเดียวกัน → ป้ายชื่อเดือนอย่างเดียว", () => {
    const ช่อง = ช่องเวลาในช่วง(new Date("2026-03-15T00:00:00"), new Date("2026-06-20T00:00:00"));
    expect(ช่อง.map(b => b.label)).toEqual(["มี.ค.","เม.ย.","พ.ค.","มิ.ย."]);
  });

  // ค่าเริ่มต้น "1 ปี" = ย้อน 12 เดือนถึงวันนี้ → เดือนนี้มี 2 จุด (พ.ย. 68 กับ พ.ย. 69) ต้องแยกป้าย/คีย์ได้ และยอดไม่รวมกัน
  it("ช่วง 1 ปี (4 พ.ย. 68 – 4 พ.ย. 69) → 13 จุดเดือน ไม่มีป้ายซ้ำ ยอดสองเดือน พ.ย. ไม่ทับกัน", () => {
    const เริ่ม = new Date("2025-11-04T00:00:00"), จบ = new Date("2026-11-04T00:00:00");
    const ช่อง = ช่องเวลาในช่วง(เริ่ม, จบ);
    expect(ช่อง).toHaveLength(13);
    expect(new Set(ช่อง.map(b => b.label)).size).toBe(13);
    expect(new Set(ช่อง.map(b => b.key)).size).toBe(13);
    expect(ช่อง[0].label).toBe("พ.ย. 68");
    expect(ช่อง[12].label).toBe("พ.ย. 69");
    const ยอด = new Map<string, number>();
    for (const [d, v] of [["2025-11-10", 100], ["2026-11-02", 7]] as const) {
      const k = คีย์ช่อง(new Date(`${d}T00:00:00`), "month"); ยอด.set(k, (ยอด.get(k) ?? 0) + v);
    }
    expect(ยอด.get(ช่อง[0].key)).toBe(100);
    expect(ยอด.get(ช่อง[12].key)).toBe(7);
  });
});
