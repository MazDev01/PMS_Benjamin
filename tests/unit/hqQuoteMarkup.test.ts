import { describe, it, expect } from "vitest";
import { ราคาขายจากต้นทุน, รายการใบลูกค้าจากใบHQ, ยอดรวมใบ } from "../../packages/shared/lib/quoteRequests";

// สูตรหน้าจอของใบลูกค้าที่ทำจากใบ HQ (ด่าน 3) — ต้องตรงกับฐานข้อมูล (quotations_hq_apply_markup) ทุกตัวเลข
//   ฐานเป็นตัวตัดสินจริง แต่ถ้าหน้าจอคิดต่างไป ดีลเลอร์จะเห็นราคาหนึ่งแล้วใบออกมาอีกราคา
describe("ราคาใบลูกค้าจากใบ HQ", () => {
  it("ตัวอย่างของบอส: ต้นทุน 10 บวก 50% = 15", () => {
    expect(ราคาขายจากต้นทุน(10, 50)).toBe(15);
  });
  it("ปัด 2 ตำแหน่งแบบเดียวกับฐาน: 12,345.67 × 1.37 = 16,913.57", () => {
    expect(ราคาขายจากต้นทุน(12345.67, 37)).toBe(16913.57);
    expect(ราคาขายจากต้นทุน(450.5, 10)).toBe(495.55);
  });
  it("% ว่าง = 0 (ขายเท่าทุน)", () => {
    expect(ราคาขายจากต้นทุน(2500, Number.NaN)).toBe(2500);
  });
  it("รายการ/จำนวน/หน่วยมาจากใบ HQ · % ติดลบถูกปัดเป็น 0", () => {
    const li = รายการใบลูกค้าจากใบHQ(
      [{ name: "โครงเหล็ก", qty: 100, unit: "ตร.ม.", unitCost: 2500 }, { name: "หลังคา", qty: 100, unit: "ตร.ม.", unitCost: 450.5 }],
      (_l, i) => (i === 0 ? 20 : -5),
    );
    expect(li).toEqual([
      { name: "โครงเหล็ก", qty: 100, unit: "ตร.ม.", unitPrice: 3000, markupPct: 20 },
      { name: "หลังคา", qty: 100, unit: "ตร.ม.", unitPrice: 450.5, markupPct: 0 },
    ]);
    expect(ยอดรวมใบ(li.map(l => ({ qty: l.qty, unitCost: l.unitPrice })))).toBe(345050);
  });
});
