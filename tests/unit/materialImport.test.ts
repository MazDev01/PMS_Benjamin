// นำเข้ารายการวัสดุ (บอสสั่ง 5 พ.ย. 69 · ใบ 0279) — หาแถวหัวตาราง · อ่านราคา/เปิดใช้ · แบ่ง 4 กลุ่ม · ตรวจตารางเพิ่มหลายแถว
//   ตกบนโค้ดก่อนแก้: ไม่มี lib/materialImport.ts
import { describe, it, expect } from "vitest";
import { หาหัวตารางวัสดุ, อ่านราคา, อ่านเปิดใช้, เตรียมแถววัสดุ, จัดกลุ่มวัสดุ, แถวส่งฐานวัสดุ, หัวแบบฟอร์มวัสดุ, ลำดับช่องวัสดุ, ตรวจแถวเพิ่มวัสดุ } from "../../packages/shared/lib/materialImport";

const ที่มี = [{ id: 7, category: "ผนัง", name: "แผ่นตัวอย่าง ก", unit: "ตร.ม.", unitPrice: 100 }];
const หน่วย = ["ตร.ม.", "ตัน", "เมตร", "ชุด", "งาน", "แผ่น"];

describe("นำเข้ารายการวัสดุ", () => {
  it("หัวแบบฟอร์มตรงกับที่ระบบอ่าน · หาแถวหัวตารางได้แม้มีแถวชื่อไฟล์ข้างบน", () => {
    const ตาราง = [["ราคาวัสดุ ปี 2569"], ลำดับช่องวัสดุ.map(k => หัวแบบฟอร์มวัสดุ[k]), ["ผนัง", "ก", "ตร.ม.", "1", ""]];
    expect(หาหัวตารางวัสดุ(ตาราง)).toEqual({ แถวหัว: 1, คู่: { category: 0, name: 1, unit: 2, unitPrice: 3, active: 4 } });
    expect(หาหัวตารางวัสดุ([["ชื่อ", "ราคา"]]), "ไม่มีคอลัมน์หน่วย = หาไม่เจอ").toBeNull();
  });
  it("อ่านราคา: ตัด , ฿ บาท · ไม่ใช่ตัวเลข/ว่าง/ติดลบ = null (ไม่เดาเป็น 0)", () => {
    expect([อ่านราคา("1,250.50"), อ่านราคา("฿ 99"), อ่านราคา("120 บาท"), อ่านราคา(0)]).toEqual([1250.5, 99, 120, 0]);
    expect([อ่านราคา(""), อ่านราคา("abc"), อ่านราคา("-5"), อ่านราคา("1.2.3")]).toEqual([null, null, null, null]);
  });
  it("อ่านเปิดใช้: ว่าง = เปิด · อ่านไม่ออก = null", () => {
    expect([อ่านเปิดใช้(""), อ่านเปิดใช้("เปิด"), อ่านเปิดใช้("ปิด"), อ่านเปิดใช้("FALSE"), อ่านเปิดใช้("อาจจะ")]).toEqual([true, true, false, false, null]);
  });
  it("แบ่ง 4 กลุ่ม: พร้อม · อัปเดตราคา · ต้องตรวจ · ข้าม", () => {
    const ตาราง = [["หมวด", "ชื่อวัสดุ*", "หน่วย*", "ราคาต่อหน่วย (ก่อน VAT)", "เปิดใช้"],
      ["หลังคา", "ใหม่ ก", "แผ่น", "250", ""],                // 2 พร้อม
      [" ผนัง ", "แผ่นตัวอย่าง ก", "ตร.ม.", "125", "ปิด"],     // 3 อัปเดตราคา (หมวด+ชื่อตรงของเดิม)
      ["ผนัง", "แผ่นตัวอย่าง ก", "ตร.ม.", "130", ""],          // 4 ข้าม ซ้ำในไฟล์
      ["", "ใหม่ ข", "กล่อง", "10", ""],                      // 5 ต้องตรวจ หน่วยนอกรายการ
      ["", "ใหม่ ค", "ชุด", "สิบบาท", ""],                     // 6 ต้องตรวจ ราคาไม่ใช่ตัวเลข
      ["", "ไม่มีหน่วย", "", "1", ""],                        // 7 ข้าม
      ["ผนัง", "แผ่นตัวอย่าง ข", "ชุด", "1", "อาจจะ"],          // 8 ต้องตรวจ เปิดใช้อ่านไม่ออก
      ["", "", "", "", ""]];                                // แถวว่าง ไม่นับ
    const g = จัดกลุ่มวัสดุ(เตรียมแถววัสดุ(ตาราง, 0, หาหัวตารางวัสดุ(ตาราง)!.คู่), ที่มี, หน่วย);
    expect(g.map(r => [r.row, r.กลุ่ม])).toEqual([[2, "ready"], [3, "update"], [4, "skip"], [5, "review"], [6, "review"], [7, "skip"], [8, "review"]]);
    expect(g[1].เดิม).toEqual({ id: 7, unit: "ตร.ม.", unitPrice: 100 });
    expect(g[2].เหตุ).toEqual(["ซ้ำกันในไฟล์ (แถว 3)"]);
    expect(g[3].เหตุ[0]).toMatch(/ไม่อยู่ในรายการ/);
    expect(แถวส่งฐานวัสดุ(g[1]), "อัปเดตราคาส่งหน่วยเดิม · เปิดใช้ในไฟล์ไม่ใช้กับของเดิม (ฐานไม่เปลี่ยน)").toMatchObject({ name: "แผ่นตัวอย่าง ก", unit: "ตร.ม.", unitPrice: 125 });
    expect(แถวส่งฐานวัสดุ(g[0])).toEqual({ category: "หลังคา", name: "ใหม่ ก", unit: "แผ่น", unitPrice: 250, active: true });
  });
  it("หน้าตรวจ: ใช้หน่วยนี้ / ใช้หน่วยเดิม / ราคาเท่าเดิม", () => {
    const แถว = (p: object) => ({ row: 2, category: "ผนัง", name: "แผ่นตัวอย่าง ก", unit: "แผ่น", ราคาดิบ: "120", เปิดใช้ดิบ: "", กลุ่ม: "ready" as const, เหตุ: [], unitPrice: null, active: null, ...p });
    expect(จัดกลุ่มวัสดุ([แถว({})], ที่มี, หน่วย)[0].เหตุ, "หน่วยต่างจากของเดิม = ต้องตรวจ").toEqual(['หน่วยต่างจากของเดิม ("ตร.ม.")']);
    expect(จัดกลุ่มวัสดุ([แถว({ unit: "ตร.ม." })], ที่มี, หน่วย)[0].กลุ่ม, "ใช้หน่วยเดิม → อัปเดตราคา").toBe("update");
    expect(จัดกลุ่มวัสดุ([แถว({ unit: "ตร.ม.", ราคาดิบ: "100.00" })], ที่มี, หน่วย)[0].เหตุ, "ราคาเท่าเดิม = ข้าม").toEqual(["ราคาเท่าเดิม"]);
    const ใหม่ = แถว({ name: "ใหม่ ง", unit: "กล่อง" });
    expect(จัดกลุ่มวัสดุ([ใหม่], ที่มี, หน่วย)[0].กลุ่ม).toBe("review");
    expect(จัดกลุ่มวัสดุ([{ ...ใหม่, ยืนยันหน่วย: true }], ที่มี, หน่วย)[0].กลุ่ม, "กด ใช้หน่วยนี้ → พร้อม").toBe("ready");
  });
});

describe("ตารางเพิ่มวัสดุหลายแถว", () => {
  const r = (key: number, p: object) => ({ key, category: "", name: "", unit: "", price: "", active: true, ...p });
  it("แถวว่างทั้งแถวไม่นับ · ขาดชื่อ/หน่วย · ราคาไม่ใช่ตัวเลข · ซ้ำกันเอง/ซ้ำของเดิม = แถวผิด", () => {
    const ผล = ตรวจแถวเพิ่มวัสดุ([
      r(1, { name: "ใหม่ ก", unit: "ชุด", price: "10" }), r(2, {}), r(3, { name: "ใหม่ ข" }), r(4, { unit: "ชุด", price: "x" }),
      r(5, { category: "ผนัง", name: "แผ่นตัวอย่าง ก", unit: "ตร.ม." }), r(6, { name: " ใหม่ ก ", unit: "ชุด" }),
    ], ที่มี);
    expect([...ผล.keys()]).toEqual([3, 4, 5, 6]);
    expect(ผล.get(3)).toEqual({ unit: "ต้องเลือกหน่วย" });
    expect(ผล.get(4)).toEqual({ name: "ต้องระบุชื่อวัสดุ", price: "ราคาไม่ใช่ตัวเลข" });
    expect(ผล.get(5)?.name).toMatch(/อยู่แล้ว/);
    expect(ผล.get(6)?.name).toMatch(/ซ้ำ/);
  });
});
