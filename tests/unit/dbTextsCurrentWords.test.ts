describe("ข้อความจากฐาน → คำปัจจุบัน (ไม่เหลือคำเก่า)", () => {
  it.each(จากฐาน)("%s", เดิม => {
    const ใหม่ = แปลข้อความฐาน(เดิม);
    for (const re of คำเก่า) expect(ใหม่, `ยังมี ${re} ใน: ${ใหม่}`).not.toMatch(re);
    const รหัส = /^([a-z_]+):/.exec(เดิม)?.[1];
    if (รหัส) expect(ใหม่.startsWith(`${รหัส}: `), "คงรหัสนำหน้า (โค้ดแยกเคสด้วยรหัส)").toBe(true);
  });
  it("คำใหม่ตรงตามคำตัดสิน", () => {
    expect(คำปัจจุบันจากฐาน("เคลียร์จังหวัดทับซ้อน")).toBe("ล้างจังหวัดที่ซ้อนกัน");
    expect(คำปัจจุบันจากฐาน("เข้าสู่ระบบ")).toBe("เข้าระบบ");
    expect(คำปัจจุบันจากฐาน("ถูกแทนด้วยเวอร์ชันใหม่")).toBe("ฉบับเก่า");
    expect(คำปัจจุบันจากฐาน("profiles.dealer_code \"ABC\" ไม่มีสาขานี้อยู่จริงในตาราง dealers")).toBe("รหัสดีลเลอร์ \"ABC\" ไม่มีอยู่ในทะเบียนดีลเลอร์");
    expect(คำปัจจุบันจากฐาน("ส่งได้เฉพาะคำขอที่กำลังทำราคา (สถานะ sent)")).toBe("ส่งได้เฉพาะคำขอที่กำลังตีราคา (สถานะ ส่งแล้ว)");
    expect(คำปัจจุบันจากฐาน("เปลี่ยนสถานะใบค่าแฟรนไชส์จาก sent เป็น draft ไม่ได้")).toBe("เปลี่ยนสถานะใบค่าแฟรนไชส์จาก ส่งแล้ว เป็น ร่าง ไม่ได้");
    expect(คำปัจจุบันจากฐาน("ยกเลิกคำขอราคา QR-1")).toBe("ยกเลิกคำขอใบเสนอราคา QR-1");
  });
  it("ไม่แตะคำที่ถูกอยู่แล้ว/ชื่องานตาม FLOW · ข้อความผู้ใช้ทั่วไป", () => {
    for (const s of ["ส่งคำขอราคา", "คำขอราคา HQ", "ยังไม่ระบุ", "ออกแบบเฉพาะโครงการ", "โครงการบ้านพักคุณ ก", "ดีลเลอร์ RYG", "เข้าระบบแทนดีลเลอร์", "ปิดใช้งานดีลเลอร์"])
      expect(คำปัจจุบันจากฐาน(s)).toBe(s);
  });
  it("ประวัติผู้สนใจ: เพิ่มลูกค้าเป้าหมาย → เพิ่มผู้สนใจ · ถูกปฏิเสธ → ปฏิเสธแล้ว", () => {
    expect(คำปัจจุบันประวัติผู้สนใจ("เพิ่มลูกค้าเป้าหมาย · ขั้น นัดคุยแล้ว")).toBe("เพิ่มผู้สนใจ · ขั้น นัดคุยแล้ว");
    expect(คำปัจจุบันประวัติผู้สนใจ("ปิดว่าไม่สำเร็จ · เหตุผล: ไม่มีทุน")).toBe("ปิดไม่สำเร็จ · เหตุผล: ไม่มีทุน");
    expect(คำปัจจุบันประวัติผู้สนใจ("ถูกปฏิเสธ")).toBe("ปฏิเสธแล้ว");
  });
});

