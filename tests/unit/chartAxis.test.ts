import { describe, it, expect } from "vitest";
import { ขั้นกลม, axisTicks, niceCeil, แบบป้ายแกน, ขนาดป้ายแกน, ขอบล่างตามป้าย } from "@pms/shared/lib/chartAxis";
import { ป้ายเดือนปี } from "@pms/shared/lib/monthRange";

// กราฟรายเดือน (บอสสั่ง 11 พ.ย. 69): ปุ่ม 3 เดือน · 6 เดือน · 9 เดือน · 1 ปี (ค่าเริ่มต้น 1 ปี) · ป้ายเดือนครบ · แกนตั้งเลขกลม
//   ตกบนโค้ดเดิม: ขีดแกนแบ่ง 4 ส่วน (13 · 25 · 38) · ไม่มีตัวเลือกแบบป้าย · (ปุ่ม 3/6/9 เดือน/1 ปี ลบแล้ว 25 พ.ย. 69)
const กลม = (ขีด: number[]) => {
  if (ขีด[0] !== 0 || ขีด.length < 2) return false;
  const ห่าง = ขีด[1] - ขีด[0];
  if (!ขีด.every((v, i) => i === 0 || Math.abs(v - ขีด[i - 1] - ห่าง) < 1e-9)) return false;
  const ฐาน = Math.pow(10, Math.floor(Math.log10(ห่าง) + 1e-9));
  return [1, 2, 5].includes(Math.round((ห่าง / ฐาน) * 1e6) / 1e6);
};

describe("แกนตั้งเลขกลม", () => {
  it("ขั้นกลม = 1 · 2 · 5 × 10ⁿ ที่เล็กที่สุดที่ ≥ ค่า", () => {
    expect([0.3, 1, 1.2, 2, 3.3, 5, 7, 12, 37].map(ขั้นกลม)).toEqual([0.5, 1, 2, 2, 5, 5, 10, 20, 50]);
  });
  it("เพดาน + ขีด กลมทุกขนาด และขีดบนสุด = เพดาน (ไม่ล้นกรอบ)", () => {
    for (const v of [9, 13, 14.95, 17.9, 37, 46, 52.9, 120, 999, 12_345]) {
      const เพดาน = niceCeil(v), ขีด = axisTicks(เพดาน);
      expect(เพดาน, `เพดานของ ${v}`).toBeGreaterThanOrEqual(v);
      expect(กลม(ขีด), `ขีดของ ${v} → ${JSON.stringify(ขีด)}`).toBe(true);
      expect(ขีด[ขีด.length - 1], `ขีดบนสุดของ ${v}`).toBe(เพดาน);
      expect(ขีด.length, `จำนวนขีดของ ${v}`).toBeLessThanOrEqual(6);
    }
  });
  it("ตัวอย่างที่บอสยก: 13 → 0 · 5 · 10 · 15 ไม่ใช่ 13 · 25 · 38", () => {
    expect(axisTicks(niceCeil(13))).toEqual([0, 5, 10, 15]);
    expect(axisTicks(niceCeil(37))).toEqual([0, 10, 20, 30, 40]);
  });
});

describe("ป้ายแกนนอน: แบบเดียวทั้งกราฟ", () => {
  const ป้าย = ["ก.พ. 69", "มี.ค. 69", "เม.ย. 69", "พ.ค. 69"];
  it("ช่องกว้างพอ = บรรทัดเดียว · แคบ = แยก 2 บรรทัด · แคบมาก = เอียง", () => {
    expect(แบบป้ายแกน(ป้าย, 80, 13)).toBe("เดียว");
    expect(แบบป้ายแกน(ป้าย, 52, 13)).toBe("สอง");
    expect(แบบป้ายแกน(ป้าย, 20, 13)).toBe("เอียง");
  });
  it("แคบเกิน 2 บรรทัด = ย่อตัวอักษร (ไม่ต่ำกว่า 10) ก่อนเอียง — ป้ายเอียงกรอบซ้อนกันเสมอ (chart-label-overlap 11 พ.ย. 69)", () => {
    const ผล = ขนาดป้ายแกน(ป้าย, 44, 13);
    expect(ผล.แบบ).toBe("สอง");
    expect(ผล.fs).toBeLessThan(13);
    expect(ผล.fs).toBeGreaterThanOrEqual(10);
    expect(ขนาดป้ายแกน(ป้าย, 20, 13).แบบ).toBe("เอียง");
  });
  it("สระบน/ล่างไม่นับเป็นความกว้าง — \"มี.ค.\" กับ \"ก.พ.\" ได้แบบเดียวกัน (เดิมตัดสินทีละป้าย แล้วทับกัน)", () => {
    for (const ช่อง of [30, 36, 40, 44, 60]) expect(แบบป้ายแกน(["มี.ค. 69"], ช่อง, 13), `ช่อง ${ช่อง}`).toBe(แบบป้ายแกน(["ก.พ. 69"], ช่อง, 13));
  });
});

