// 12 พ.ย. 69: ป้ายเอียงยื่นลงใต้แกน — ขอบล่างของกราฟต้องพอ ไม่ให้ป้ายล้นไปชนขอบการ์ด (layout-spacing จอมือถือ /hq/dashboard ตก)
//   ตกบนโค้ดเดิม: ไม่มี ขอบล่างตามป้าย (ขอบล่างคงที่ 34–42)
describe("ขอบล่างตามป้าย", () => {
  const ป้าย = ["ธ.ค. 68", "ม.ค. 69", "ก.พ. 69", "มี.ค. 69", "เม.ย. 69", "พ.ค. 69", "มิ.ย. 69", "ก.ค. 69", "ส.ค. 69", "ก.ย. 69", "ต.ค. 69", "พ.ย. 69"];
  it("ช่องกว้าง (บรรทัดเดียว) = ขอบล่างเดิม", () => {
    expect(แบบป้ายแกน(ป้าย, 120, 13.5)).toBe("เดียว");
    expect(ขอบล่างตามป้าย(ป้าย, 120, 13.5, 26, 40)).toBe(40);
  });
  it("ป้ายเอียง: ขอบล่าง ≥ ระยะวาง + ความยาวป้ายยาวสุด × sin40° (ป้ายไม่ยื่นพ้นกราฟ)", () => {
    expect(แบบป้ายแกน(ป้าย, 22, 13.5)).toBe("เอียง");
    const ขอบ = ขอบล่างตามป้าย(ป้าย, 22, 13.5, 26, 40);
    const ยาวสุด = Math.max(...ป้าย.map(p => p.replace(/[ัิ-ฺ็-๎]/g, "").length * 13.5 * 0.68));
    expect(ขอบ).toBeGreaterThanOrEqual(26 + ยาวสุด * Math.sin((40 * Math.PI) / 180));
    expect(ขอบ).toBeGreaterThan(40);
  });
  it("ไม่ต่ำกว่าขั้นต่ำที่ส่งมา", () => {
    expect(ขอบล่างตามป้าย(["ม.ค."], 200, 13, 22, 34)).toBe(34);
  });
});
