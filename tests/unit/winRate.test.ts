import { describe, it, expect } from "vitest";
import { อัตราปิดการขาย } from "../../packages/shared/lib/winRate";

// อัตราปิดการขาย สูตรเดียว (รอบ 4 · บอสตัดสิน 21 ต.ค. 69): ลีดปิดสำเร็จ ÷ (สำเร็จ + ไม่สำเร็จ)
//   อัตราปิดการขายจากลีด() ลบแล้ว 25 พ.ย. 69 (ไม่มีคนเรียก — ทุกหน้านับที่ฐานแล้วส่งตัวเลขเข้าสูตรนี้)
describe("อัตราปิดการขาย", () => {
  it("3 สำเร็จ · 3 ไม่สำเร็จ = 50% (ลีดที่ยังเปิดไม่ส่งเข้าสูตร)", () => {
    expect(อัตราปิดการขาย(3, 3)).toBe(50);
  });
  it("ยังไม่มีลีดที่ปิด = null (ไม่ใช่ 0)", () => {
    expect(อัตราปิดการขาย(0, 0)).toBeNull();
  });
  it("ปัดเป็นจำนวนเต็ม", () => {
    expect(อัตราปิดการขาย(1, 2)).toBe(33);
    expect(อัตราปิดการขาย(2, 1)).toBe(67);
  });
});
