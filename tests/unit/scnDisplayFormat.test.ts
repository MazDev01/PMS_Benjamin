import { describe, it, expect } from "vitest";
import { แสดงเบอร์, ยอดใบเสนอราคา } from "@pms/shared/lib/format";

// ── ข้อผิดจากผู้ตรวจ 23 พ.ย. 69 (คนรวมงาน · ขับเบราว์เซอร์บน e2b941e1) — ตัวแสดงผลบนจอ ──
describe("แสดงเบอร์ — เบอร์ไม่ครบแสดงตามที่เก็บ (ข้อ 11)", () => {
  it("เบอร์ครบ 10 หลัก = จัดรูป", () => { expect(แสดงเบอร์("0000001234")).toBe("000-000-1234"); });
  it("เบอร์ที่เก็บแบบมีขีดอยู่แล้ว = จัดรูปเหมือนเดิม", () => { expect(แสดงเบอร์("000-000-1234")).toBe("000-000-1234"); });
  it("เบอร์ไม่ครบ 6 หลัก = ตามที่เก็บ (เดิมขึ้น 000-000 เหมือนเบอร์ถูกรูปแบบ)", () => { expect(แสดงเบอร์("000000")).toBe("000000"); });
  it("เบอร์เกิน 10 หลัก = ตามที่เก็บ ไม่ตัดทิ้ง", () => { expect(แสดงเบอร์("000000123456")).toBe("000000123456"); });
  it("ว่าง = ว่าง", () => { expect(แสดงเบอร์(null)).toBe(""); expect(แสดงเบอร์("")).toBe(""); });
});

describe("ยอดใบเสนอราคา — อ่านจาก total_value ไม่ใช่ข้อความ total (ข้อ 2)", () => {
  it("ข้อความ '0' แต่ total_value > 0 = ยอดจาก total_value (เดิมขึ้น 0)", () => {
    expect(ยอดใบเสนอราคา({ total: "0", totalValue: 1_900_000 })).toBe("฿" + (1_900_000).toLocaleString("th-TH"));
  });
  it("ข้อความไม่ตรงตัวเลข = เชื่อตัวเลข (ฐานคิดจากรายการ)", () => {
    expect(ยอดใบเสนอราคา({ total: "฿100", totalValue: 250.5 })).toBe("฿" + (250.5).toLocaleString("th-TH"));
  });
  it("ไม่มีตัวเลข = ข้อความเดิม · ไม่มีทั้งคู่ = —", () => {
    expect(ยอดใบเสนอราคา({ total: "฿5,000", totalValue: null })).toBe("฿5,000");
    expect(ยอดใบเสนอราคา({})).toBe("—");
  });
});
