// นำเข้าผู้สนใจจากไฟล์ทำงานจริงของทีม — ตรรกะล้วน (ข้อมูลปลอมทั้งหมด · ชื่อ/เบอร์ไม่ใช่ของจริง)
import { describe, it, expect } from "vitest";
import { จับคู่จังหวัด, จัดเบอร์, แยกเบอร์, แปลงช่องทาง, เดาขั้น, วันจากวันเดือน, จังหวัดทั้งหมด } from "../../packages/shared/lib/prospectImport";

describe("จับคู่จังหวัด (77 จังหวัด)", () => {
  it("มีรายการกลาง 77 จังหวัด", () => expect(จังหวัดทั้งหมด).toHaveLength(77));
  it("ตรงเป๊ะ = ไม่ต้องยืนยัน", () => expect(จับคู่จังหวัด("บุรีรัมย์")).toMatchObject({ จังหวัด: "บุรีรัมย์", อื่น: [], ต้องยืนยัน: false }));
  for (const [ย่อ, เต็ม] of [["อุบล", "อุบลราชธานี"], ["กทม", "กรุงเทพมหานคร"], ["ปทุม", "ปทุมธานี"], ["ปุทม", "ปทุมธานี"], ["สุราษฏ์", "สุราษฎร์ธานี"],
    ["สุราษฐ์", "สุราษฎร์ธานี"], ["นครศรี", "นครศรีธรรมราช"], ["นครศรีฯ", "นครศรีธรรมราช"], ["สงชลา", "สงขลา"], ["สรุบุรี", "สระบุรี"],
    ["สิงบุรี", "สิงห์บุรี"], ["กำแพงเพ็ช", "กำแพงเพชร"], ["ปราจีน", "ปราจีนบุรี"], ["อุดร", "อุดรธานี"]] as const) {
    it(`${ย่อ} → ${เต็ม} (ต้องยืนยัน)`, () => expect(จับคู่จังหวัด(ย่อ)).toMatchObject({ จังหวัด: เต็ม, ต้องยืนยัน: true }));
  }
  it("หลายจังหวัด = จังหวัดแรก + ที่เหลือ", () => {
    expect(จับคู่จังหวัด("นราธิวาส ปัตตานี ยะลา")).toMatchObject({ จังหวัด: "นราธิวาส", อื่น: ["ปัตตานี", "ยะลา"], ต้องยืนยัน: true });
  });
  it("มีวันที่/คำอื่นติดมา", () => {
    expect(จับคู่จังหวัด("ขอนแก่น และ มหาสารคาม27.8")).toMatchObject({ จังหวัด: "ขอนแก่น", อื่น: ["มหาสารคาม"] });
    expect(จับคู่จังหวัด("อยู่อุบล เลือก จังหวัดใกล้เคียง")).toMatchObject({ จังหวัด: "อุบลราชธานี", ต้องยืนยัน: true });
  });
  it("หาไม่ได้ = null ต้องยืนยัน · ว่าง = ไม่ต้อง", () => {
    expect(จับคู่จังหวัด("ไม่ระบุ")).toMatchObject({ จังหวัด: null, ต้องยืนยัน: true });
    expect(จับคู่จังหวัด("")).toMatchObject({ จังหวัด: null, ต้องยืนยัน: false });
  });
});

describe("เบอร์", () => {
  it("เว้นวรรค/ขีด/ช่องว่างหน้าหลัง → รูปแบบเดียว", () => {
    expect(จัดเบอร์(" 000 000 0001 ")).toBe("000-000-0001");
    expect(จัดเบอร์("000-000-0002")).toBe("000-000-0002");
    expect(จัดเบอร์("+66 00 000 0003")).toBe("000-000-0003");
    expect(จัดเบอร์("12345")).toBe("");
  });
  it("แถวรวมช่องเดียว: แยกเบอร์ ที่เหลือเป็นชื่อ/จังหวัด", () => {
    const r = แยกเบอร์("ทดสอบ ปลอมสกุล 000 000 0004 นครสวรรค์ (เล่น)");
    expect(r.เบอร์).toEqual(["000-000-0004"]);
    expect(r.เหลือ).toBe("ทดสอบ ปลอมสกุล นครสวรรค์ (เล่น)");
  });
});

describe("ช่องทาง", () => {
  for (const [เดิม, ได้] of [["FB", "Facebook"], ["Line OA", "LINE OA"], ["line OA", "LINE OA"], ["Line", "LINE ส่วนตัว"], ["Line Pu", "LINE ส่วนตัว"],
    ["Line PU", "LINE ส่วนตัว"], ["Direct", "โทรเข้ามาเอง"]] as const) {
    it(`${เดิม} → ${ได้}`, () => expect(แปลงช่องทาง(เดิม)).toEqual({ ช่องทาง: ได้, หมายเหตุ: "" }));
  }
  it("ไม่รู้จัก (ชื่อคน) = แนะนำต่อ + เก็บข้อความเดิม", () => expect(แปลงช่องทาง("คุณปลอม")).toEqual({ ช่องทาง: "แนะนำต่อ", หมายเหตุ: "ช่องทางในไฟล์: คุณปลอม" }));
  it("ตารางแปลงแก้ได้", () => expect(แปลงช่องทาง("Tiktok", { tiktok: "TikTok" }).ช่องทาง).toBe("TikTok"));
});

describe("เดาขั้นจากหมายเหตุ", () => {
  const เหตุผล = ["เงินทุนไม่พอ", "ยังไม่พร้อม", "เลือกแบรนด์อื่น", "ทำเลไม่เหมาะ"];
  it("ส่ง Company Profile → ส่งข้อมูลบริษัทแล้ว", () => {
    expect(เดาขั้น("ส่ง Company Profiles ad line แล้ว ให้ Follow").สถานะ).toBe("profile_sent");
    expect(เดาขั้น("ส่ง Company Profiles แล้ว").สถานะ).toBe("profile_sent");
  });
  it("ไม่มีคนรับ/รอโทรกลับ → ติดต่อแล้ว", () => {
    for (const s of ["ไม่มีคนรับ", "รอโทรกลับ", "รอโทรกลับ ติดต่อแล้ว ยังไม่ได้คุย", "โทรแล้ว ถ้าสนใจจะโทรกลับ"]) expect(เดาขั้น(s).สถานะ, s).toBe("contacted");
  });
  it("ไม่สนใจ/ไม่เอา/ไม่มีทุน → ไม่สำเร็จ + เหตุผลจากรายการ", () => {
    expect(เดาขั้น("ไม่มีทุน", เหตุผล)).toEqual({ สถานะ: "lost", เหตุผลไม่สำเร็จ: "เงินทุนไม่พอ", มั่นใจ: true });
    expect(เดาขั้น("ไม่เอา", เหตุผล)).toMatchObject({ สถานะ: "lost", เหตุผลไม่สำเร็จ: "ยังไม่พร้อม" });
    expect(เดาขั้น("น่าจะไม่สน", เหตุผล)).toMatchObject({ สถานะ: "lost", มั่นใจ: false });
  });
  it("ว่าง → รอติดต่อ · ไม่เข้าแบบ = ติดต่อแล้ว (ไม่มั่นใจ)", () => {
    expect(เดาขั้น("").สถานะ).toBe("new");
    expect(เดาขั้น("ข้อความอื่น")).toMatchObject({ สถานะ: "contacted", มั่นใจ: false });
  });
});

describe("วันที่ วัน.เดือน + ปีที่ถาม", () => {
  it("24.8 + 2569 → 2026-08-24", () => expect(วันจากวันเดือน(24.8, 2569)).toEqual({ วันที่: "2026-08-24", กำกวม: false }));
  it("ข้อความ 18.4 + ค.ศ.", () => expect(วันจากวันเดือน("18.4", 2026).วันที่).toBe("2026-04-18"));
  it("ทศนิยม 24.1 = กำกวม ม.ค./ต.ค. (Excel ตัดศูนย์)", () => expect(วันจากวันเดือน(24.1, 2026)).toEqual({ วันที่: "2026-01-24", กำกวม: true, ทางเลือก: "2026-10-24" }));
  it("วันไม่มีจริง = null", () => expect(วันจากวันเดือน("31.2", 2026)).toEqual({ วันที่: null, กำกวม: true }));
});
