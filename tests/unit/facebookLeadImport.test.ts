    // +66 9 หลักบ้าน → 0 + 8 หลัก = 9 หลักขึ้นต้น 02 = ครบ
    expect(เบอร์เฟซบุ๊ก("p:+66" + เลข("2", 8))).toMatchObject({ ตัวเลข: เลข("02", 9), ครบ: true, แสดง: ["02", "000", "0000"].join("-") });
