    expect(เบอร์เฟซบุ๊ก("p:+6600000107")).toEqual({ ตัวเลข: "000000107", ครบ: false, แสดง: "000000107" });
    expect(เบอร์เฟซบุ๊ก("").ตัวเลข).toBe("");
    // 10 หลัก = ครบ
    for (const d of ["00", "02", "08", "09"].map(x => เลข(x, 10))) expect(เบอร์ครบ(d), d).toBe(true);
    // 9 หลักขึ้นต้น 02 03 04 05 07 = เบอร์บ้าน/ออฟฟิศ ครบ (จัดรูป 0X-XXX-XXXX)
    for (const p of ["02", "03", "04", "05", "07"]) {
      const d = `${p}0000000`;
      expect(เบอร์ครบ(d), d).toBe(true);
      expect(เบอร์เฟซบุ๊ก(d).แสดง, d).toBe(`${p}-000-0000`);
    }
    // 9 หลักขึ้นต้น 06 08 09 = มือถือขาดตัว ไม่ครบ (ไม่จัดรูปให้ดูเหมือนเบอร์บ้าน) · 9 หลักขึ้นต้น 00/01 = ไม่ครบ
    for (const p of ["06", "08", "09", "00", "01"]) {
      const d = `${p}0000000`;
      expect(เบอร์ครบ(d), d).toBe(false);
      expect(เบอร์เฟซบุ๊ก(d).แสดง, d).toBe(d);
    }
    // ต่ำกว่า 9 หลัก = ไม่ครบ · เกิน 10 = ไม่ครบ
