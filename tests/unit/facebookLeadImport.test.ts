// ไฟล์ลีดจาก Facebook Lead Ads (บอสสั่ง 20 พ.ย. 69 · ใบ 0292) — ไฟล์ปลอม 2 ชีต หัวตารางเดียวกับของจริง (เบอร์ p:+66000000xxx · @example.test)
//   ตกบนโค้ดก่อนแก้: ไม่มี lib/facebookLeadImport (ไฟล์ Facebook ต้องจับคู่คอลัมน์เอง · อ่านแค่ชีตแรก · เบอร์ p:+66 อ่านไม่ออก)
import { describe, it, expect } from "vitest";
import { สร้างไฟล์Xlsx } from "../../packages/shared/lib/exportWorkbook";
import { แยกสมุดงานจากXlsx } from "../../packages/shared/lib/importSheet";
import {
  หัวไฟล์เฟซบุ๊ก, เป็นไฟล์เฟซบุ๊ก, เบอร์เฟซบุ๊ก, จังหวัดเฟซบุ๊ก, วันเฟซบุ๊ก, เตรียมแถวเฟซบุ๊ก, สรุปเฟซบุ๊ก, แถวเฟซบุ๊กส่งฐาน,
} from "../../packages/shared/lib/facebookLeadImport";

const หัว = [...หัวไฟล์เฟซบุ๊ก, "", ""];   // คอลัมน์หลังจากนั้นว่าง (ไฟล์จริงมี)
const แถว = (วัน: string, จังหวัด: string, ชื่อ: string, เบอร์: string, อีเมล = "") => [วัน, "ZZ แคมเปญตัวแทน", จังหวัด, อีเมล, ชื่อ, เบอร์, "", ""];
async function ไฟล์ปลอม() {
  const blob = สร้างไฟล์Xlsx([
    { ชื่อ: "10.26", หัวตาราง: หัว, แถว: [
      แถว("2026-10-05T14:22:10+07:00", "Khon Kaen", "ZZ หนึ่ง", "p:+66000000101", "zz1@example.test"),
      แถว("2026-10-06T23:30:00+0000", "ขอนแก่นครับ", "ZZ สอง", "p:+66000000102"),
      แถว("2026-10-07T09:00:00+07:00", "กทม", "ZZ สาม", "p:+66000000103"),
      แถว("2026-10-08T09:00:00+07:00", "​เชียงใหม่​", "ZZ สี่", "p:+66000000104"),
      แถว("2026-10-09T09:00:00+07:00", "ระยอง, ชลบุรี", "ZZ ห้า", "p:+66000000105"),
      แถว("2026-10-10T09:00:00+07:00", "อยากเป็นตัวแทนครับ", "ZZ หก", "p:+66000000106"),
      แถว("2026-10-11T09:00:00+07:00", "ตราด", "ZZ เบอร์ไม่ครบ", "p:+6600000107"),
      แถว("2026-10-12T09:00:00+07:00", "ตราด", "", "p:+66000000108"),
    ] },
    { ชื่อ: "11.26", หัวตาราง: หัว, แถว: [
      แถว("2026-11-01T09:00:00+07:00", "Bangkok", "ZZ ซ้ำในไฟล์", "p:+66000000101"),
      แถว("2026-11-02T09:00:00+07:00", "โคราช", "ZZ ซ้ำของเดิม", "p:+66000000199"),
      แถว("2026-11-03T09:00:00+07:00", "nakhon si thammarat", "ZZ เจ็ด", "p:+66000000110", "ไม่ใช่อีเมล"),
    ] },
  ]);
  return แยกสมุดงานจากXlsx(await blob.arrayBuffer());
}

describe("ไฟล์ลีด Facebook", () => {
  it("รู้จักไฟล์จากหัว full_name + phone_number · ไฟล์ทีมแบบเดิมไม่ใช่", async () => {
    expect(เป็นไฟล์เฟซบุ๊ก(await ไฟล์ปลอม())).toBe(true);
    expect(เป็นไฟล์เฟซบุ๊ก(new Map([["ผู้สนใจ", [["ชื่อ", "เบอร์โทร", "จังหวัด"]]]]))).toBe(false);
  });
  it("เบอร์ p:+66 → 0 · ไม่ครบ 10 หลัก = ไม่ครบ", () => {
    expect(เบอร์เฟซบุ๊ก("p:+66000000101")).toEqual({ ตัวเลข: "0000000101", ครบ: true, แสดง: "000-000-0101" });
    expect(เบอร์เฟซบุ๊ก("p:+6600000107")).toMatchObject({ ตัวเลข: "000000107", ครบ: false });
    expect(เบอร์เฟซบุ๊ก("").ตัวเลข).toBe("");
  });
  it("จังหวัดสะกดหลายแบบ → 77 จังหวัด · หลายจังหวัดใช้จังหวัดแรก · ไม่ใช่จังหวัด = ว่าง", () => {
    expect(จังหวัดเฟซบุ๊ก("Khon Kaen")).toBe("ขอนแก่น");
    expect(จังหวัดเฟซบุ๊ก("ขอนแก่นครับ")).toBe("ขอนแก่น");
    expect(จังหวัดเฟซบุ๊ก("กทม")).toBe("กรุงเทพมหานคร");
    expect(จังหวัดเฟซบุ๊ก("​เชียงใหม่​")).toBe("เชียงใหม่");
    expect(จังหวัดเฟซบุ๊ก("ระยอง, ชลบุรี")).toBe("ระยอง");
    expect(จังหวัดเฟซบุ๊ก("ขอนแก่น และ มหาสารคาม")).toBe("ขอนแก่น");
    expect(จังหวัดเฟซบุ๊ก("nakhon si thammarat")).toBe("นครศรีธรรมราช");
    expect(จังหวัดเฟซบุ๊ก("อยากเป็นตัวแทนครับ")).toBeNull();
    expect(จังหวัดเฟซบุ๊ก("")).toBeNull();
  });
  it("created_time → วันตามเวลาไทย", () => {
    expect(วันเฟซบุ๊ก("2026-10-05T14:22:10+07:00")).toBe("2026-10-05");
    expect(วันเฟซบุ๊ก("2026-10-06T23:30:00+0000")).toBe("2026-10-07");
    expect(วันเฟซบุ๊ก("2026-10-05")).toBe("2026-10-05");
    expect(วันเฟซบุ๊ก("46300"), "เลขวันของ Excel (46023 = 1 ม.ค. 69 · +277 วัน)").toBe("2026-10-05");
    expect(วันเฟซบุ๊ก("เมื่อวาน")).toBeNull();
  });
  it("อ่านทุกชีต · ซ้ำในไฟล์/ของเดิมข้าม · เบอร์ไม่ครบยังนำเข้า · ไม่มีชื่อข้าม · สรุป 4 ตัวเลข", async () => {
    const แถว = เตรียมแถวเฟซบุ๊ก(await ไฟล์ปลอม(), ["000-000-0199"], "2026-11-20");
    expect(แถว.map(r => r.row)).toContain("11.26:4");
    expect(แถว.find(r => r.name === "ZZ ซ้ำในไฟล์")?.ข้าม).toBe("เบอร์ซ้ำกับแถว 10.26:2");
    expect(แถว.find(r => r.name === "ZZ ซ้ำของเดิม")?.ข้าม).toBe("เบอร์นี้มีผู้สนใจอยู่แล้ว");
    expect(แถว.find(r => r.name === "ZZ เบอร์ไม่ครบ")).toMatchObject({ ข้าม: null, เบอร์ไม่ครบ: true });
    expect(แถว.find(r => r.phone === "000-000-0108")?.ข้าม).toBe("ไม่มีชื่อ (full_name)");
    expect(สรุปเฟซบุ๊ก(แถว)).toEqual({ นำเข้า: 8, ซ้ำ: 2, เบอร์ไม่ครบ: 1, จังหวัดไม่ได้: 1, ข้ามอื่น: 1 });
  });
  it("แถวส่งฐาน: รอติดต่อ · นัดวันนี้ · Facebook · หมายเหตุเก็บข้อความเดิม · entered_at · เบอร์ไม่ครบบอกฐาน", async () => {
    const แถว = เตรียมแถวเฟซบุ๊ก(await ไฟล์ปลอม(), [], "2026-11-20");
    expect(แถวเฟซบุ๊กส่งฐาน(แถว.find(r => r.name === "ZZ หนึ่ง")!)).toEqual({
      row: "10.26:2", name: "ZZ หนึ่ง", phone: "0000000101", email: "zz1@example.test", province: "ขอนแก่น", channel: "Facebook", status: "new",
      note: "จังหวัดที่ลูกค้าพิมพ์: Khon Kaen · โฆษณา: ZZ แคมเปญตัวแทน · ทิ้งเบอร์เมื่อ: 2026-10-05T14:22:10+07:00",
      follow_up_today: true, entered_at: "2026-10-05",
    });
    const ไม่ครบ = แถวเฟซบุ๊กส่งฐาน(แถว.find(r => r.name === "ZZ เบอร์ไม่ครบ")!);
    expect(ไม่ครบ).toMatchObject({ phone: "000000107", phone_incomplete: true });
    expect(ไม่ครบ.note).toContain("เบอร์ไม่ครบ");
    const อีเมลผิด = แถวเฟซบุ๊กส่งฐาน(แถว.find(r => r.name === "ZZ เจ็ด")!);
    expect(อีเมลผิด.email).toBe("");
    expect(อีเมลผิด.note).toContain("อีเมลที่กรอก: ไม่ใช่อีเมล");
  });
  it("created_time เกินวันนี้ = ไม่ส่ง entered_at (ฐานไม่รับ)", async () => {
    const แถว = เตรียมแถวเฟซบุ๊ก(await ไฟล์ปลอม(), [], "2026-10-31");
    expect(แถวเฟซบุ๊กส่งฐาน(แถว.find(r => r.name === "ZZ เจ็ด")!)).not.toHaveProperty("entered_at");
  });
});
