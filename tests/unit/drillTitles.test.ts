// หัวข้อกราฟ/ตารางของหน้าเจาะลึก HQ (บอสสั่ง 3 พ.ย. 69) — ชื่อเปลี่ยนตามแท็บมิติ + ระดับที่เลือก · คำอธิบายมีช่วงเวลา
import { describe, it, expect } from "vitest";
import { ชื่อหัวข้อ, คำอธิบายหัวข้อ, คำแนะนำกดแถว, ป้ายระดับ, ป้ายช่วง, วันที่ไทย } from "@pms/shared/lib/drillTitles";

const ทั้งเครือ = { ภาค: null, จังหวัด: null, ดีลเลอร์: null };

describe("ชื่อหัวข้อ (เป็นอะไร · แยกตามอะไร · ระดับไหน)", () => {
  it("ตามแท็บมิติ ระดับทั้งเครือ", () => {
    expect(ชื่อหัวข้อ("ใบเสนอราคา", "dealer", ทั้งเครือ)).toBe("ใบเสนอราคาแยกตามดีลเลอร์ · ทั้งเครือ");
    expect(ชื่อหัวข้อ("ใบเสนอราคา", "region", ทั้งเครือ)).toBe("ใบเสนอราคาแยกตามภูมิภาค · ทั้งเครือ");
    expect(ชื่อหัวข้อ("ใบเสนอราคา", "prov", ทั้งเครือ)).toBe("ใบเสนอราคาแยกตามจังหวัด · ทั้งเครือ");
    expect(ชื่อหัวข้อ("ใบเสนอราคา", "month", ทั้งเครือ)).toBe("ใบเสนอราคารายเดือน · ทั้งเครือ");
  });
  it("ตามระดับที่เลือก: ภาค · จังหวัด · ดีลเลอร์ (ระดับดีลเลอร์ = รายเดือนเสมอ)", () => {
    expect(ชื่อหัวข้อ("ลูกค้าเป้าหมาย", "prov", { ภาค: "เหนือ", จังหวัด: null, ดีลเลอร์: null })).toBe("ลูกค้าเป้าหมายแยกตามจังหวัด · ภาคเหนือ");
    expect(ชื่อหัวข้อ("ลูกค้าเป้าหมาย", "dealer", { ภาค: "เหนือ", จังหวัด: "เชียงใหม่", ดีลเลอร์: null })).toBe("ลูกค้าเป้าหมายแยกตามดีลเลอร์ · จังหวัดเชียงใหม่");
    expect(ชื่อหัวข้อ("ลูกค้า", "dealer", { ภาค: "เหนือ", จังหวัด: "เชียงใหม่", ดีลเลอร์: "CNX", ชื่อดีลเลอร์: "เชียงใหม่สตีล" })).toBe("ลูกค้ารายเดือน · ดีลเลอร์ CNX เชียงใหม่สตีล");
  });
  it("ภาคที่สะกดต่างในฐาน แสดงชื่อเต็มมาตรฐาน", () => {
    expect(ป้ายระดับ({ ภาค: "ตะวันออกเฉียงเหนือ", จังหวัด: null, ดีลเลอร์: null })).toBe("ภาคตะวันออกเฉียงเหนือ");
  });
});

describe("คำอธิบาย (ช่วงไหน · อ่าน/กดอย่างไร)", () => {
  it("ช่วงเป็นวันที่ไทย พ.ศ.", () => {
    expect(วันที่ไทย("2026-10-01")).toBe("1 ต.ค. 2569");
    expect(ป้ายช่วง({ start: "2026-10-01", end: "2026-10-31" })).toBe("ช่วง 1 ต.ค. 2569 – 31 ต.ค. 2569");
    expect(วันที่ไทย("")).toBe("—");
  });
  it("รวมส่วน · ข้ามส่วนว่าง · ไม่มีช่วง = ณ ตอนนี้", () => {
    expect(คำอธิบายหัวข้อ({ start: "2026-10-01", end: "2026-10-31" }, "แถวรวม = การ์ดด้านบน", null, "กดแถวเพื่อเจาะลึก"))
      .toBe("ช่วง 1 ต.ค. 2569 – 31 ต.ค. 2569 · แถวรวม = การ์ดด้านบน · กดแถวเพื่อเจาะลึก");
    expect(คำอธิบายหัวข้อ(null, "ลีดที่เปิดอยู่")).toBe("ณ ตอนนี้ (ไม่ขึ้นกับช่วงเวลา) · ลีดที่เปิดอยู่");
  });
  it("คำแนะนำกดแถวตามแท็บ · ระดับดีลเลอร์ไม่มีที่ให้เจาะต่อ", () => {
    expect(คำแนะนำกดแถว("dealer", ทั้งเครือ)).toBe("กดแถวเพื่อเจาะลึก");
    expect(คำแนะนำกดแถว("month", ทั้งเครือ)).toBe("กดแถวเพื่อดูรายดีลเลอร์ของเดือนนั้น");
    expect(คำแนะนำกดแถว("month", { ภาค: null, จังหวัด: null, ดีลเลอร์: "CNX" })).toBeNull();
  });
});
