import { describe, it, expect } from "vitest";
import { ขั้นของลีด, สภาพแถบขั้น, ชื่อขั้นการขาย, ชื่อขั้น, เลขขั้นทั้งหมด, ตัวเลือกขั้น, ป้ายย่อยขั้น, แปลงชื่อขั้นเดิม, เลขขั้นของลีด, จำนวนขั้น } from "../../packages/shared/lib/leadStage";
import { ความคืบหน้าลีด } from "../../packages/shared/lib/leadProgress";
import { LEAD_STATUS_ORDER } from "../../packages/shared/lib/mock";

// ── สถานะลีด → ขั้นการขาย (รอบ 4 · บอสสั่ง 21 ต.ค. 69 · ยุบเหลือ 4 ขั้น 9 พ.ย. 69 ใบ 0284) — ตารางเดียวกับ docs/FLOW.html "สถานะ ↔ ขั้น" ──
//   ต้องตกบนโค้ดก่อนยุบ: ชื่อขั้น 5 ชื่อ (มี "ทำใบให้ลูกค้า" · "รอลูกค้าตอบ") · เสนอราคา = ขั้น 5 · แถบ 5 ช่อง · ความคืบหน้าขั้นละ 20%
const ว่าง = { คำขอ: [], ใบลูกค้า: [] };

describe("ขั้นของลีด", () => {
  it("ชื่อขั้นชุดเดียว 4 ขั้น (ทำใบให้ลูกค้า + รอลูกค้าตอบ ยุบเป็น เสนอราคาลูกค้า)", () => {
    expect([...ชื่อขั้นการขาย]).toEqual(["ข้อมูลลูกค้า", "ขอราคา HQ", "ได้ใบ HQ", "เสนอราคาลูกค้า"]);
    expect(จำนวนขั้น).toBe(4);
  });
  it("ป้ายขั้นไม่มีเลขลำดับนำหน้า ทุกขั้น (บอสสั่ง 28 ต.ค. 69) · ไม่มีชื่อขั้นเดิม", () => {
    expect(เลขขั้นทั้งหมด.map(ชื่อขั้น)).toEqual(["ข้อมูลลูกค้า", "ขอราคา HQ", "ได้ใบ HQ", "เสนอราคาลูกค้า", "ปิดสำเร็จ", "ปิดไม่สำเร็จ"]);
    expect(ตัวเลือกขั้น.map(o => o.l).filter(l => /^\d/.test(l))).toEqual([]);
    expect(ตัวเลือกขั้น.map(o => o.l).filter(l => /ทำใบให้ลูกค้า|รอลูกค้าตอบ/.test(l)), "ตัวกรองขั้นไม่มีชื่อขั้นเดิม").toEqual([]);
    expect(ตัวเลือกขั้น.map(o => o.v), "ปิดสำเร็จ/ไม่สำเร็จคงเลข 6/7 (ลิงก์ ?stage= เดิมไม่เปลี่ยนความหมาย)").toEqual(["1", "2", "3", "4", "6", "7"]);
  });
  it("ตารางสถานะ ↔ ขั้น ตามที่บอสตัดสิน", () => {
    expect(ขั้นของลีด("WAITING", false)).toEqual({ kind: "open", step: 1 });
    expect(ขั้นของลีด("BULLET", false)).toEqual({ kind: "open", step: 1 });
    expect(ขั้นของลีด("HQ_PRICING", false)).toEqual({ kind: "open", step: 2 });
    expect(ขั้นของลีด("HQ_QUOTED", false)).toEqual({ kind: "open", step: 3 });
    expect(ขั้นของลีด("HQ_QUOTED", true), "ทำใบแล้วยังไม่ส่ง = เสนอราคาลูกค้า").toEqual({ kind: "open", step: 4 });
    expect(ขั้นของลีด("QUOTED", false), "ส่งให้ลูกค้าแล้ว = เสนอราคาลูกค้า (เดิมขั้น 5)").toEqual({ kind: "open", step: 4 });
    expect(ขั้นของลีด("PAID", false)).toEqual({ kind: "won" });
    expect(ขั้นของลีด("CANCELLED", false)).toEqual({ kind: "lost" });
    expect(เลขขั้นของลีด("PAID", false)).toBe(6);
    expect(เลขขั้นของลีด("CANCELLED", false)).toBe(7);
  });
  it("ใบร่างแยกขั้นเฉพาะตอนได้ราคา HQ — ขั้นอื่นไม่เปลี่ยนตามใบร่าง", () => {
    for (const s of LEAD_STATUS_ORDER) if (s !== "HQ_QUOTED") expect(ขั้นของลีด(s, true)).toEqual(ขั้นของลีด(s, false));
  });
  it("ไม่มีสถานะไหนได้ขั้น 5 อีก", () => {
    for (const s of LEAD_STATUS_ORDER) for (const ร่าง of [false, true]) expect(เลขขั้นของลีด(s, ร่าง), s).not.toBe(5);
  });
});

describe("ป้ายย่อยขั้นเสนอราคาลูกค้า (บอสสั่ง 9 พ.ย. 69)", () => {
  it("ทำใบแล้ว (ยังไม่ส่ง) / ส่งให้ลูกค้าแล้ว · ขั้นอื่นไม่มีป้ายย่อย", () => {
    expect(ป้ายย่อยขั้น("HQ_QUOTED", true)).toBe("ทำใบแล้ว (ยังไม่ส่ง)");
    expect(ป้ายย่อยขั้น("QUOTED", false)).toBe("ส่งให้ลูกค้าแล้ว");
    expect(ป้ายย่อยขั้น("QUOTED", true), "มีใบร่างฉบับใหม่แต่ส่งใบแล้ว = ส่งแล้ว (ตามสถานะ)").toBe("ส่งให้ลูกค้าแล้ว");
    for (const s of ["WAITING", "BULLET", "HQ_PRICING", "PAID", "CANCELLED"] as const) expect(ป้ายย่อยขั้น(s, true), s).toBeNull();
    expect(ป้ายย่อยขั้น("HQ_QUOTED", false), "ได้ใบ HQ ยังไม่ทำใบ").toBeNull();
  });
});

describe("บันทึกเก่าแปลงชื่อขั้นตอนแสดง (ไม่แก้ข้อมูล)", () => {
  it("ทำใบให้ลูกค้า / รอลูกค้าตอบ → เสนอราคาลูกค้า", () => {
    expect(แปลงชื่อขั้นเดิม("ย้ายขั้น ได้ใบ HQ → ทำใบให้ลูกค้า")).toBe("ย้ายขั้น ได้ใบ HQ → เสนอราคาลูกค้า");
    expect(แปลงชื่อขั้นเดิม("ขั้น รอลูกค้าตอบ: เพิ่มงาน")).toBe("ขั้น เสนอราคาลูกค้า: เพิ่มงาน");
    expect(แปลงชื่อขั้นเดิม("ข้อความอื่น ไม่เปลี่ยน")).toBe("ข้อความอื่น ไม่เปลี่ยน");
  });
});

describe("แถบขั้น — ไฮไลต์ขั้นที่อยู่ตอนนี้", () => {
  it("ลีดเปิดอยู่: ขั้นก่อนหน้า = ผ่าน · ขั้นนี้ = ตอนนี้ · ขั้นหลัง = ยังไม่ถึง", () => {
    expect(สภาพแถบขั้น("HQ_PRICING", false, ว่าง)).toEqual(["ผ่าน", "ตอนนี้", "ยังไม่ถึง", "ยังไม่ถึง"]);
    expect(สภาพแถบขั้น("WAITING", false, ว่าง)).toEqual(["ตอนนี้", "ยังไม่ถึง", "ยังไม่ถึง", "ยังไม่ถึง"]);
    expect(สภาพแถบขั้น("HQ_QUOTED", true, ว่าง), "ทำใบแล้วยังไม่ส่ง").toEqual(["ผ่าน", "ผ่าน", "ผ่าน", "ตอนนี้"]);
    expect(สภาพแถบขั้น("QUOTED", false, ว่าง), "ส่งแล้ว อยู่ขั้นเดียวกัน").toEqual(["ผ่าน", "ผ่าน", "ผ่าน", "ตอนนี้"]);
  });
  it("ปิดสำเร็จ = ผ่านครบ 4 ขั้น", () => {
    expect(สภาพแถบขั้น("PAID", false, ว่าง)).toEqual(["ผ่าน", "ผ่าน", "ผ่าน", "ผ่าน"]);
  });
  it("ปิดไม่สำเร็จก่อนขอราคา → ติ๊กแค่ขั้น 1 (เดิมติ๊ก 1–4 หมด)", () => {
    expect(สภาพแถบขั้น("CANCELLED", false, ว่าง)).toEqual(["ผ่าน", "ไม่ได้ทำ", "ไม่ได้ทำ", "ไม่ได้ทำ"]);
  });
  it("ยกเลิกคำขอก่อน HQ ส่งใบ → ขั้น 2 ผ่าน ขั้น 3 ไม่ได้ทำ", () => {
    expect(สภาพแถบขั้น("CANCELLED", false, { คำขอ: ["cancelled"], ใบลูกค้า: [] }))
      .toEqual(["ผ่าน", "ผ่าน", "ไม่ได้ทำ", "ไม่ได้ทำ"]);
  });
  it("ได้ใบ HQ แล้วปิดไม่สำเร็จโดยไม่ทำใบ → ผ่าน 1–3", () => {
    expect(สภาพแถบขั้น("CANCELLED", false, { คำขอ: ["lost"], ใบลูกค้า: [] }))
      .toEqual(["ผ่าน", "ผ่าน", "ผ่าน", "ไม่ได้ทำ"]);
  });
  it("ทำใบร่างแต่ไม่ได้ส่ง / ใบหมดอายุ → ผ่านครบ 4 (เคยทำใบเสนอราคาลูกค้าแล้ว)", () => {
    expect(สภาพแถบขั้น("CANCELLED", false, { คำขอ: ["lost"], ใบลูกค้า: ["draft"] })).toEqual(["ผ่าน", "ผ่าน", "ผ่าน", "ผ่าน"]);
    expect(สภาพแถบขั้น("CANCELLED", false, { คำขอ: ["lost"], ใบลูกค้า: ["expired"] })[3]).toBe("ผ่าน");
  });
  it("ลูกค้าปฏิเสธใบที่ส่งแล้ว → ผ่านครบ 4 ขั้น", () => {
    expect(สภาพแถบขั้น("CANCELLED", false, { คำขอ: ["lost"], ใบลูกค้า: ["lost"] })).toEqual(["ผ่าน", "ผ่าน", "ผ่าน", "ผ่าน"]);
  });
  it("ทุกสถานะได้แถบ 4 ช่อง", () => {
    for (const s of LEAD_STATUS_ORDER) expect(สภาพแถบขั้น(s, false, ว่าง)).toHaveLength(4);
  });
});

describe("ความคืบหน้าในตาราง (แถบ 4 ช่อง · ขั้นละ 25%)", () => {
  const ค = (status: Parameters<typeof ความคืบหน้าลีด>[0]["status"], ร่าง = false, reachedStep?: number) => ความคืบหน้าลีด({ status, reachedStep }, ร่าง);
  it("เปิดอยู่: ขั้น × 25% · ปิดสำเร็จ 100%", () => {
    expect([ค("WAITING"), ค("HQ_PRICING"), ค("HQ_QUOTED"), ค("HQ_QUOTED", true), ค("QUOTED"), ค("PAID")].map(x => x.เปอร์เซ็นต์))
      .toEqual([25, 50, 75, 100, 100, 100]);
  });
  it("ปิดไม่สำเร็จ = แดงตามขั้นที่ไปถึง (reached_step) · ค่าเก่า 5 = ขั้น 4", () => {
    expect(ค("CANCELLED", false, 2)).toEqual({ ขั้น: 2, เปอร์เซ็นต์: 50, ปิดไม่สำเร็จ: true });
    expect(ค("CANCELLED", false, 4).เปอร์เซ็นต์).toBe(100);
    expect(ค("CANCELLED", false, 5), "ค่าค้างก่อนใบ 0284").toEqual({ ขั้น: 4, เปอร์เซ็นต์: 100, ปิดไม่สำเร็จ: true });
  });
});
