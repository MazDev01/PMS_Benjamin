// ชื่อแสดงของดีลเลอร์ ตัวกลาง (บอสสั่ง 6 พ.ย. 69) — ชื่อซ้ำ = "ชื่อ (รหัส)" เฉพาะคู่ที่ซ้ำ · กติกาเดียวกับฐาน _dealer_display_name (ใบ 0281)
//   ตกบนโค้ดก่อนแก้: ไม่มี lib/dealerDisplayName.ts
import { describe, it, expect } from "vitest";
import { สร้างชื่อแสดง } from "../../packages/shared/lib/dealerDisplayName";

describe("ชื่อแสดงของดีลเลอร์", () => {
  const ชื่อ = สร้างชื่อแสดง([
    { code: "AAA", name: "เหล็กดี" }, { code: "BBB", name: " เหล็กดี " }, { code: "CCC", name: "ไทยสตีล" }, { code: "DDD", name: "" },
  ]);
  it("ชื่อไม่ซ้ำ = ชื่ออย่างเดียว · ชื่อซ้ำ = ชื่อ (รหัส) ทั้งคู่ (ไม่สนช่องว่างหน้าหลัง)", () => {
    expect([ชื่อ("CCC"), ชื่อ("AAA"), ชื่อ("BBB")]).toEqual(["ไทยสตีล", "เหล็กดี (AAA)", "เหล็กดี (BBB)"]);
  });
  it("ไม่มีชื่อในทะเบียน = ชื่อสำรองที่ส่งมา หรือรหัส · ไม่มีรหัส = —", () => {
    expect([ชื่อ("DDD"), ชื่อ("ZZZ", "ชื่อจากแถว"), ชื่อ("ZZZ"), ชื่อ(null)]).toEqual(["DDD", "ชื่อจากแถว", "ZZZ", "—"]);
  });
});
