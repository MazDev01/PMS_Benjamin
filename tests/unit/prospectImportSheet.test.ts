// นำเข้าผู้สนใจ: อ่านตารางโครงเดียวกับไฟล์ทำงานจริงของทีม (ข้อมูลปลอมทั้งหมด · 000-000-NNNN)
//   หัวตารางแถว 2 · แถวหัวข้อแทรก ("BJM PEB" · "BJM PEB โทรแล้ว") ถูกข้าม · แถวรวมช่องเดียว → ต้องตรวจ
//   จังหวัดย่อจับคู่ถูก · 24.8 + ปี → วันที่ถูก · เบอร์ซ้ำในไฟล์/ของเดิม → ข้าม · คอลัมน์ไม่รู้จักถูกข้าม
import { describe, it, expect } from "vitest";
import { หาแถวหัวตาราง, เดาคอลัมน์, เตรียมแถว, จัดกลุ่ม, แถวส่งฐาน, ลายเซ็นหัว, เลือกวันที่ } from "../../packages/shared/lib/prospectImport";

const หัว = ["", "social", "เบอร์", "จังหวัด", "ชื่อ", "เริ่มติดต่อ", "ติดตาม", "Type", "หมายหตุ", "Channel", "Total", "DM", "Ad Run", "BD", "Website", "SEO",
  "Branding", "Production", "AI", "DEV", "Other", "note"];
// ตัวอ่าน xlsx ทิ้งแถวว่าง (แถว 3 ของไฟล์จริง) — ตารางที่ได้จึงต่อกันเลย
const ตาราง: string[][] = [
  ["", "", "รอนัดหมาย"],
  หัว,
  ["", "", "BJM PEB"],
  ["31", "เพจปลอมหนึ่ง", "000 000 0101", "บุรีรัมย์", "", "24.8", "", "", "ไม่มีคนรับ", "FB"],
  ["34", "เพจปลอมสอง", "000 000 0102", "นราธิวาส ปัตตานี ยะลา", "เล่นปลอม", "25.8", "", "ทำอสังหาฯ", "โทรแล้ว ถ้าสนใจจะโทรกลับ", "Line Pu"],
  ["37", "ปลอม สกุลปลอม", "000-000-0103", "อยู่อุบล เลือก จังหวัดใกล้เคียง", "ปลอม", "25.8", "18.4", "", "ไม่มีทุน", "Line OA", "", "ข้อความ DM ปลอม"],
  ["", "", "BJM PEB โทรแล้ว"],
  ["40", "", "ปลอมรวม สกุลรวม 000 000 0104 นครสวรรค์ (เล่น)"],
  ["41", "เพจปลอมซ้ำ", " 000 000 0101 ", "กทม", "ซ้ำ", "26.8", "", "", "ส่ง Company Profiles แล้ว", "Direct"],
  ["42", "เพจปลอมเดิม", "000 000 0199", "ปทุม", "เดิม", "26.8", "", "", "", "คุณแนะนำปลอม"],
  ["43", "เพจไม่มีเบอร์", "", "สงชลา", "ไม่มีเบอร์", "24.1", "", "", "ไม่สนใจ", "line OA"],
];

describe("หัวตาราง + จับคู่คอลัมน์", () => {
  it("หัวตารางอยู่แถว 2 (ไม่ใช่แถวแรก)", () => expect(หาแถวหัวตาราง(ตาราง)).toBe(1));
  it("เดาคอลัมน์ที่รู้จัก · ข้ามคอลัมน์ไม่รู้จัก (DM · Ad Run · Website …)", () => {
    expect(เดาคอลัมน์(หัว)).toEqual({ social: 1, phone: 2, province: 3, name: 4, firstContact: 5, followUp: 6, type: 7, note: 8, channel: 9, note2: 21 });
  });
  it("ลายเซ็นหัวเหมือนกันทุกครั้ง (จำการจับคู่ครั้งหน้า)", () => expect(ลายเซ็นหัว(หัว)).toBe(ลายเซ็นหัว([...หัว])));
});

describe("เตรียมแถว", () => {
  const { แถว, หัวข้อที่ข้าม } = เตรียมแถว(ตาราง, 1, เดาคอลัมน์(หัว), { ปี: 2569, เหตุผลไม่สำเร็จ: ["เงินทุนไม่พอ", "ยังไม่พร้อม"], เบอร์ที่มีอยู่: ["000-000-0199"] });
  const ของ = (เบอร์หรือชื่อ: string) => แถว.find(r => r.phone === เบอร์หรือชื่อ || r.name === เบอร์หรือชื่อ)!;
  it("แถวหัวข้อแทรกถูกข้าม (2 แถว) ไม่เป็นข้อมูล", () => {
    expect(หัวข้อที่ข้าม).toBe(2);
    expect(แถว.some(r => /BJM PEB/.test(r.name))).toBe(false);
    expect(แถว).toHaveLength(7);
  });
  it("แถวปกติ: ชื่อว่างใช้ชื่อโซเชียล · 24.8 + 2569 = 2026-08-24 · FB = Facebook · ไม่มีคนรับ = ติดต่อแล้ว · พร้อม", () => {
    expect(ของ("000-000-0101")).toMatchObject({ name: "เพจปลอมหนึ่ง", province: "บุรีรัมย์", firstContact: "2026-08-24", channel: "Facebook",
      status: "contacted", contactNote: "ไม่มีคนรับ", กลุ่ม: "ready" });
  });
  it("หลายจังหวัด = จังหวัดแรก + ที่เหลือลงหมายเหตุ · ประเภทลงหมายเหตุ · Line Pu = LINE ส่วนตัว", () => {
    const r = ของ("000-000-0102");
    expect(r).toMatchObject({ province: "นราธิวาส", channel: "LINE ส่วนตัว", status: "contacted", กลุ่ม: "review" });
    expect(r.note).toContain("ประเภท: ทำอสังหาฯ");
    expect(r.note).toContain("จังหวัดอื่นในไฟล์: ปัตตานี ยะลา");
  });
  // วันติดตามไม่ก่อนวันเริ่มติดต่อ (บอสแก้ 4 พ.ย. 69 · เดิมคาด 2026-04-18 = ปีที่เลือก ก่อนวันเริ่ม 25 ส.ค.)
  it("จังหวัดย่อ (อุบล) จับคู่ถูก → ต้องตรวจ · ไม่มีทุน = ไม่สำเร็จ + เงินทุนไม่พอ · วันติดตาม 18.4 หลังเริ่ม 25.8 = เม.ย. ปีถัดไป", () => {
    expect(ของ("000-000-0103")).toMatchObject({ province: "อุบลราชธานี", status: "lost", lostReason: "เงินทุนไม่พอ", firstContact: "2026-08-25", followUp: "2027-04-18", กลุ่ม: "review" });
    expect(ของ("000-000-0103").note, "หมายเหตุเพิ่มเติมจากคอลัมน์ note เท่านั้น — DM ข้าม").not.toContain("DM");
  });
  // กฎปี (บอสตัดสิน 4 พ.ย. 69 · วันนี้ 4 พ.ย. 69 · เลือก 2569): เริ่ม 24.12 → ธ.ค. 68 · ติดตาม 5.1 หลังเริ่ม → ม.ค. 69 · ติดตาม "304"/"??" = ต้องตรวจ
  it("กฎปีระดับแถว: เริ่มไม่เกินวันนี้ · ติดตามไม่ก่อนวันเริ่ม · ติดตามไม่ใช่วันที่ = ข้ามแถว (บอสสั่ง 4 พ.ย. 69 · เดิมต้องตรวจ)", () => {
    const ตาราง2: string[][] = [หัว,
      ["1", "เพจกฎปีหนึ่ง", "000 000 0301", "บุรีรัมย์", "กฎปีหนึ่ง", "24.12", "5.1", "", "ไม่มีคนรับ", "FB"],
      ["2", "เพจกฎปีสอง", "000 000 0302", "บุรีรัมย์", "กฎปีสอง", "24.8", "304", "", "ไม่มีคนรับ", "FB"],
      ["3", "เพจกฎปีสาม", "000 000 0303", "บุรีรัมย์", "กฎปีสาม", "", "24.12", "", "ไม่มีคนรับ", "FB"],
      ["4", "เพจกฎปีสี่", "000 000 0304", "บุรีรัมย์", "กฎปีสี่", "24.8", "??", "", "ไม่มีคนรับ", "FB"],
    ];
    const { แถว: ได้ } = เตรียมแถว(ตาราง2, 0, เดาคอลัมน์(หัว), { ปี: 2569, วันนี้: "2026-11-04" });
    const ที่ = (n: string) => ได้.find(r => r.phone === n)!;
    expect(ที่("000-000-0301")).toMatchObject({ firstContact: "2025-12-24", followUp: null, กลุ่ม: "review" });   // 5.1 = กำกวม ม.ค./ต.ค. (คงเดิม)
    expect(ที่("000-000-0301").เหตุ.join(" ")).toMatch(/วันติดตาม "5\.1" อาจเป็น ม\.ค\. หรือ ต\.ค\./);
    expect(ที่("000-000-0302")).toMatchObject({ firstContact: "2026-08-24", followUp: null, กลุ่ม: "skip" });
    expect(ที่("000-000-0302").เหตุ.join(" ")).toMatch(/ข้าม: วันติดตาม "304" อ่านไม่ออก/);
    expect(ที่("000-000-0303"), "ไม่มีวันเริ่ม → ติดตามใช้กฎไม่เกินวันนี้").toMatchObject({ firstContact: null, followUp: "2025-12-24" });
    expect(ที่("000-000-0304")).toMatchObject({ followUp: null, กลุ่ม: "skip" });
    expect(ที่("000-000-0304").เหตุ.join(" ")).toMatch(/ข้าม: วันติดตาม "\?\?" อ่านไม่ออก/);
  });
  // ── วันที่กำกวม/อ่านไม่ออกต้องไม่หายเงียบ (บอสสั่ง 4 พ.ย. 69 · เดิมกด "ยืนยัน" แล้วแถวขึ้นพร้อม วันที่เป็นว่าง) ──
  const ตารางกำกวม: string[][] = [หัว,
    ["1", "เพจกำกวมหนึ่ง", "000 000 0311", "บุรีรัมย์", "กำกวมหนึ่ง", "5.1", "", "", "ไม่มีคนรับ", "FB"],
    ["2", "เพจกำกวมสอง", "000 000 0312", "บุรีรัมย์", "กำกวมสอง", "20.1", "25.1", "", "ไม่มีคนรับ", "FB"],
    ["3", "เพจอ่านไม่ออก", "000 000 0313", "บุรีรัมย์", "อ่านไม่ออก", "??", "", "", "ไม่มีคนรับ", "FB"],
    ["4", "เพจวันไม่มีจริง", "000 000 0314", "บุรีรัมย์", "วันไม่มีจริง", "31.2", "", "", "ไม่มีคนรับ", "FB"],
  ];
  const ตั้งกำกวม = { ปี: 2569, วันนี้: "2026-11-04" };
  const ก = () => เตรียมแถว(ตารางกำกวม, 0, เดาคอลัมน์(หัว), ตั้งกำกวม).แถว;
  const ของก = (xs: ReturnType<typeof ก>, n: string) => xs.find(r => r.phone === n)!;
  it("วันที่กำกวม: ต้องตรวจ + ตัวเลือก ม.ค./ต.ค. · กด ยืนยัน (ล้างเหตุ) แล้วก็ยังไม่พร้อม", () => {
    const xs = ก(), r = ของก(xs, "000-000-0311");
    expect(r).toMatchObject({ กลุ่ม: "review", firstContact: null });
    expect(r.วันต้องเลือก).toEqual([{ ช่อง: "firstContact", ดิบ: "5.1", ตัวเลือก: ["2026-01-05", "2026-10-05"] }]);
    const หลังยืนยัน = ของก(จัดกลุ่ม(xs.map(x => x.row === r.row ? { ...x, เหตุ: [] } : x)), "000-000-0311");
    expect(หลังยืนยัน.กลุ่ม, "ยืนยันโดยยังไม่เลือกเดือน = ยังต้องตรวจ").toBe("review");
    expect(หลังยืนยัน.เหตุ.join(" ")).toMatch(/เลือกเดือนของวันเริ่มติดต่อ "5\.1" ก่อน/);
    expect(() => แถวส่งฐาน(หลังยืนยัน), "แถวที่ยังไม่เลือกเดือนส่งฐานไม่ได้").toThrow(/วันที่ยังไม่ครบ/);
  });
  it("เลือกเดือนแล้ว + ยืนยัน = พร้อม และส่งวันที่ที่เลือกไปฐาน", () => {
    const xs = ก(), r = ของก(xs, "000-000-0311");
    const เลือก = เลือกวันที่(r, "firstContact", "2026-10-05");
    const พร้อม = ของก(จัดกลุ่ม(xs.map(x => x.row === r.row ? { ...เลือก, เหตุ: [] } : x)), "000-000-0311");
    expect(พร้อม.กลุ่ม).toBe("ready");
    expect(แถวส่งฐาน(พร้อม).first_contact).toBe("2026-10-05");
  });
  it("เลือกเดือนวันเริ่ม → วันติดตามคิดใหม่ (ไม่ก่อนวันเริ่ม)", () => {
    const r = ของก(ก(), "000-000-0312");
    expect(r.วันต้องเลือก?.map(x => x.ช่อง)).toEqual(["firstContact", "followUp"]);
    const ตุลา = เลือกวันที่(r, "firstContact", "2026-10-20");
    // เริ่ม 20 ต.ค. 69 → ติดตาม 25.1 = 25 ม.ค. 70 หรือ 25 ต.ค. 69 (ยังกำกวม · ตัวเลือกคิดจากวันเริ่มใหม่)
    expect(ตุลา.วันต้องเลือก).toEqual([{ ช่อง: "followUp", ดิบ: "25.1", ตัวเลือก: ["2027-01-25", "2026-10-25"] }]);
    const ครบ = เลือกวันที่(ตุลา, "followUp", "2026-10-25");
    expect(ครบ).toMatchObject({ firstContact: "2026-10-20", followUp: "2026-10-25", วันต้องเลือก: [] });
  });
  it("มีค่าวันที่ในไฟล์แต่อ่านไม่ได้ (\"??\" · 31.2) = ข้ามแถว พร้อมเหตุ (ไปไฟล์แถวที่ข้าม) · ยืนยันไม่ได้ ส่งฐานไม่ได้", () => {
    const xs = ก();
    for (const [n, ดิบ] of [["000-000-0313", "\\?\\?"], ["000-000-0314", "31\\.2"]] as const) {
      const r = ของก(xs, n);
      expect(r.กลุ่ม, n).toBe("skip");
      expect(r.เหตุ.join(" "), n).toMatch(new RegExp(`ข้าม: วันเริ่มติดต่อ "${ดิบ}" อ่านไม่ออก`));
      expect(ของก(จัดกลุ่ม(xs.map(x => x.row === r.row ? { ...x, เหตุ: [] } : x)), n).กลุ่ม, "ล้างเหตุแล้วก็ยังข้าม").toBe("skip");
      expect(() => แถวส่งฐาน(r)).toThrow(/วันที่ยังไม่ครบ/);
    }
  });
  it("แถวรวมช่องเดียว → แยกเบอร์ ชื่อ จังหวัด → กลุ่มต้องตรวจ เก็บข้อความเดิม", () => {
    expect(ของ("000-000-0104")).toMatchObject({ name: "ปลอมรวม สกุลรวม (เล่น)", province: "นครสวรรค์", กลุ่ม: "review",
      เดิม: "ปลอมรวม สกุลรวม 000 000 0104 นครสวรรค์ (เล่น)" });
    expect(ของ("000-000-0104").เหตุ.join(" ")).toContain("แถวรวมช่องเดียว");
  });
  it("เบอร์ซ้ำในไฟล์ (เว้นวรรคต่างกัน) = ข้าม · เบอร์มีอยู่แล้ว = ข้าม · ไม่มีเบอร์ = ข้าม", () => {
    expect(แถว.find(r => r.name === "ซ้ำ")).toMatchObject({ กลุ่ม: "skip" });
    expect(แถว.find(r => r.name === "ซ้ำ")!.เหตุ[0]).toMatch(/เบอร์ซ้ำกับแถว/);
    expect(ของ("000-000-0199")).toMatchObject({ กลุ่ม: "skip" });
    expect(ของ("000-000-0199").เหตุ[0]).toBe("ข้าม: เบอร์นี้มีผู้สนใจอยู่แล้ว");
    expect(แถว.find(r => r.name === "ไม่มีเบอร์")).toMatchObject({ กลุ่ม: "skip" });
  });
  it("ช่องทางไม่รู้จัก (ชื่อคน) = แนะนำต่อ + ข้อความเดิมในหมายเหตุ", () => {
    expect(ของ("000-000-0199")).toMatchObject({ channel: "แนะนำต่อ" });
    expect(ของ("000-000-0199").note).toContain("ช่องทางในไฟล์: คุณแนะนำปลอม");
  });
  it("วันที่ 24.1 กำกวม (ม.ค./ต.ค.) = ไม่เดา (ว่าง) + เหตุผลให้ตรวจ", () => {
    const r = แถว.find(x => x.name === "ไม่มีเบอร์")!;
    expect(r.firstContact).toBeNull();
    expect(r.เหตุ.join(" ")).toContain("อาจเป็น ม.ค. หรือ ต.ค.");
  });
  it("HQ แก้ในหน้าตรวจ → จัดกลุ่มใหม่: ใส่ชื่อ/ยืนยัน = พร้อม · ส่งฐานเฉพาะช่องที่ฐานรับ", () => {
    const แก้ = จัดกลุ่ม(แถว.map(r => r.phone === "000-000-0104" ? { ...r, เหตุ: [] } : r), ["000-000-0199"]);
    expect(แก้.find(r => r.phone === "000-000-0104")!.กลุ่ม).toBe("ready");
    expect(Object.keys(แถวส่งฐาน(แก้[0])).sort()).toEqual(["channel", "contact_note", "first_contact", "follow_up", "lost_reason", "name", "note", "phone", "province", "row", "social", "status"]);
  });
});
