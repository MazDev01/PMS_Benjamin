// นำเข้าผู้สนใจ: อ่านตารางโครงเดียวกับไฟล์ทำงานจริงของทีม (ข้อมูลปลอมทั้งหมด · 000-000-NNNN)
//   หัวตารางแถว 2 · แถวหัวข้อแทรก ("BJM PEB" · "BJM PEB โทรแล้ว") ถูกข้าม · แถวรวมช่องเดียว → ต้องตรวจ
//   จังหวัดย่อจับคู่ถูก · 24.8 + ปี → วันที่ถูก · เบอร์ซ้ำในไฟล์/ของเดิม → ข้าม · คอลัมน์ไม่รู้จักถูกข้าม
import { describe, it, expect } from "vitest";
import { หาแถวหัวตาราง, เดาคอลัมน์, เตรียมแถว, จัดกลุ่ม, แถวส่งฐาน, ลายเซ็นหัว } from "../../packages/shared/lib/prospectImport";

const หัว = ["", "social", "เบอร์", "จังหวัด", "ชื่อ", "เริ่มติดต่อ", "ติดตาม", "Type", "หมายหตุ", "Channel", "Total", "DM", "Ad Run", "BD", "Website", "SEO",
  "Branding", "Production", "AI", "DEV", "Other", "note"];
// ตัวอ่าน xlsx ทิ้งแถวว่าง (แถว 3 ของไฟล์จริง) — ตารางที่ได้จึงต่อกันเลย
const ตาราง: string[][] = [
  ["", "", "รอนัดหมาย"],
  หัว,
  ["", "", "BJM PEB"],
  ["31", "เพจปลอมหนึ่ง", "000 000 0101", "บุรีรัมย์", "", "24.8", "", "", "ไม่มีคนรับ", "FB"],
  ["34", "เพจปลอมสอง", "000 000 0102", "นราธิวาส ปัตตานี ยะลา", "เล่นปลอม", "25.8", "", "ทำอสังหาฯ", "โทรแล้ว ถ้าสนใจจะโทรกลับ", "Line Pu"],
  ["37", "ปลอม สกุลปลอม", "000-000-0103", "อยู่อุบล เลือก จังหวัดใกล้เคียง", "ปลอม", "25.8", "18.4", "", "ไม่มีทุน", "Line OA", "", "ข้อความ DM ปลอม"],
  ["", "", "BJM PEB โทรแล้ว"],
  ["40", "", "ปลอมรวม สกุลรวม 000 000 0104 นครสวรรค์ (เล่น)"],
  ["41", "เพจปลอมซ้ำ", " 000 000 0101 ", "กทม", "ซ้ำ", "26.8", "", "", "ส่ง Company Profiles แล้ว", "Direct"],
  ["42", "เพจปลอมเดิม", "000 000 0199", "ปทุม", "เดิม", "26.8", "", "", "", "คุณแนะนำปลอม"],
  ["43", "เพจไม่มีเบอร์", "", "สงชลา", "ไม่มีเบอร์", "24.1", "", "", "ไม่สนใจ", "line OA"],
];

describe("หัวตาราง + จับคู่คอลัมน์", () => {
  it("หัวตารางอยู่แถว 2 (ไม่ใช่แถวแรก)", () => expect(หาแถวหัวตาราง(ตาราง)).toBe(1));
  it("เดาคอลัมน์ที่รู้จัก · ข้ามคอลัมน์ไม่รู้จัก (DM · Ad Run · Website …)", () => {
    expect(เดาคอลัมน์(หัว)).toEqual({ social: 1, phone: 2, province: 3, name: 4, firstContact: 5, followUp: 6, type: 7, note: 8, channel: 9, note2: 21 });
  });
  it("ลายเซ็นหัวเหมือนกันทุกครั้ง (จำการจับคู่ครั้งหน้า)", () => expect(ลายเซ็นหัว(หัว)).toBe(ลายเซ็นหัว([...หัว])));
});

describe("เตรียมแถว", () => {
  const { แถว, หัวข้อที่ข้าม } = เตรียมแถว(ตาราง, 1, เดาคอลัมน์(หัว), { ปี: 2569, เหตุผลไม่สำเร็จ: ["เงินทุนไม่พอ", "ยังไม่พร้อม"], เบอร์ที่มีอยู่: ["000-000-0199"] });
  const ของ = (เบอร์หรือชื่อ: string) => แถว.find(r => r.phone === เบอร์หรือชื่อ || r.name === เบอร์หรือชื่อ)!;
  it("แถวหัวข้อแทรกถูกข้าม (2 แถว) ไม่เป็นข้อมูล", () => {
    expect(หัวข้อที่ข้าม).toBe(2);
    expect(แถว.some(r => /BJM PEB/.test(r.name))).toBe(false);
    expect(แถว).toHaveLength(7);
  });
  it("แถวปกติ: ชื่อว่างใช้ชื่อโซเชียล · 24.8 + 2569 = 2026-08-24 · FB = Facebook · ไม่มีคนรับ = ติดต่อแล้ว · พร้อม", () => {
    expect(ของ("000-000-0101")).toMatchObject({ name: "เพจปลอมหนึ่ง", province: "บุรีรัมย์", firstContact: "2026-08-24", channel: "Facebook",
      status: "contacted", contactNote: "ไม่มีคนรับ", กลุ่ม: "ready" });
  });
  it("หลายจังหวัด = จังหวัดแรก + ที่เหลือลงหมายเหตุ · ประเภทลงหมายเหตุ · Line Pu = LINE ส่วนตัว", () => {
    const r = ของ("000-000-0102");
    expect(r).toMatchObject({ province: "นราธิวาส", channel: "LINE ส่วนตัว", status: "contacted", กลุ่ม: "review" });
    expect(r.note).toContain("ประเภท: ทำอสังหาฯ");
    expect(r.note).toContain("จังหวัดอื่นในไฟล์: ปัตตานี ยะลา");
  });
  it("จังหวัดย่อ (อุบล) จับคู่ถูก → ต้องตรวจ · ไม่มีทุน = ไม่สำเร็จ + เงินทุนไม่พอ · วันติดตาม 18.4", () => {
    expect(ของ("000-000-0103")).toMatchObject({ province: "อุบลราชธานี", status: "lost", lostReason: "เงินทุนไม่พอ", followUp: "2026-04-18", กลุ่ม: "review" });
    expect(ของ("000-000-0103").note, "หมายเหตุเพิ่มเติมจากคอลัมน์ note เท่านั้น — DM ข้าม").not.toContain("DM");
  });
  it("แถวรวมช่องเดียว → แยกเบอร์ ชื่อ จังหวัด → กลุ่มต้องตรวจ เก็บข้อความเดิม", () => {
    expect(ของ("000-000-0104")).toMatchObject({ name: "ปลอมรวม สกุลรวม (เล่น)", province: "นครสวรรค์", กลุ่ม: "review",
      เดิม: "ปลอมรวม สกุลรวม 000 000 0104 นครสวรรค์ (เล่น)" });
    expect(ของ("000-000-0104").เหตุ.join(" ")).toContain("แถวรวมช่องเดียว");
  });
  it("เบอร์ซ้ำในไฟล์ (เว้นวรรคต่างกัน) = ข้าม · เบอร์มีอยู่แล้ว = ข้าม · ไม่มีเบอร์ = ข้าม", () => {
    expect(แถว.find(r => r.name === "ซ้ำ")).toMatchObject({ กลุ่ม: "skip" });
    expect(แถว.find(r => r.name === "ซ้ำ")!.เหตุ[0]).toMatch(/เบอร์ซ้ำกับแถว/);
    expect(ของ("000-000-0199")).toMatchObject({ กลุ่ม: "skip" });
    expect(ของ("000-000-0199").เหตุ[0]).toBe("ข้าม: เบอร์นี้มีผู้สนใจอยู่แล้ว");
    expect(แถว.find(r => r.name === "ไม่มีเบอร์")).toMatchObject({ กลุ่ม: "skip" });
  });
  it("ช่องทางไม่รู้จัก (ชื่อคน) = แนะนำต่อ + ข้อความเดิมในหมายเหตุ", () => {
    expect(ของ("000-000-0199")).toMatchObject({ channel: "แนะนำต่อ" });
    expect(ของ("000-000-0199").note).toContain("ช่องทางในไฟล์: คุณแนะนำปลอม");
  });
  it("วันที่ 24.1 กำกวม (ม.ค./ต.ค.) = ไม่เดา (ว่าง) + เหตุผลให้ตรวจ", () => {
    const r = แถว.find(x => x.name === "ไม่มีเบอร์")!;
    expect(r.firstContact).toBeNull();
    expect(r.เหตุ.join(" ")).toContain("อาจเป็น ม.ค. หรือ ต.ค.");
  });
  it("HQ แก้ในหน้าตรวจ → จัดกลุ่มใหม่: ใส่ชื่อ/ยืนยัน = พร้อม · ส่งฐานเฉพาะช่องที่ฐานรับ", () => {
    const แก้ = จัดกลุ่ม(แถว.map(r => r.phone === "000-000-0104" ? { ...r, เหตุ: [] } : r), ["000-000-0199"]);
    expect(แก้.find(r => r.phone === "000-000-0104")!.กลุ่ม).toBe("ready");
    expect(Object.keys(แถวส่งฐาน(แก้[0])).sort()).toEqual(["channel", "contact_note", "first_contact", "follow_up", "lost_reason", "name", "note", "phone", "province", "row", "social", "status"]);
  });
});
