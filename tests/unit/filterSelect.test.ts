import { describe, it, expect } from "vitest";
import { กรองตัวเลือก, ขยับไฮไลต์, ต้องมีช่องค้น, ต้องเลื่อนก่อนกาง, ตำแหน่งรายการ } from "@pms/shared/lib/filterSelect";

// ช่องเลือกในแถบตัวกรอง (บอสสั่ง 11 พ.ย. 69): กางลงข้างล่างเสมอ · สูงไม่เกินที่ว่างใต้ช่อง · ค้นหาเมื่อเกิน 8 · คีย์บอร์ด
//   ตกบนโค้ดเดิม: ไม่มีตัวคำนวณ (ใช้ <select> ของเบราว์เซอร์)
const จังหวัด = [{ v: "ALL", l: "ทุกจังหวัด" }, { v: "กรุงเทพมหานคร", l: "กรุงเทพมหานคร" }, { v: "เชียงใหม่", l: "เชียงใหม่" }, { v: "เชียงราย", l: "เชียงราย" }, { v: "ตราด", l: "ตราด" }];

describe("ช่องค้นหา", () => {
  it("มีเมื่อเกิน 8 ตัวเลือก (รวม \"ทั้งหมด\")", () => {
    expect(ต้องมีช่องค้น(8)).toBe(false);
    expect(ต้องมีช่องค้น(9)).toBe(true);
  });
  it("กรองตามข้อความที่เห็น · ตัวเลือกทั้งหมดอยู่เสมอ · คำค้นว่าง = ทั้งหมด", () => {
    expect(กรองตัวเลือก(จังหวัด, "เชียง", "ALL").map(o => o.v)).toEqual(["ALL", "เชียงใหม่", "เชียงราย"]);
    expect(กรองตัวเลือก(จังหวัด, " ", "ALL")).toHaveLength(5);
    expect(กรองตัวเลือก(จังหวัด, "ไม่มีจังหวัดนี้", "ALL").map(o => o.v)).toEqual(["ALL"]);
  });
});

describe("คีย์บอร์ด", () => {
  it("ลูกศรลง/ขึ้น ไม่วนรอบ · Home/End", () => {
    expect(ขยับไฮไลต์(-1, "ArrowDown", 5)).toBe(0);
    expect(ขยับไฮไลต์(4, "ArrowDown", 5)).toBe(4);
    expect(ขยับไฮไลต์(0, "ArrowUp", 5)).toBe(0);
    expect(ขยับไฮไลต์(3, "ArrowUp", 5)).toBe(2);
    expect(ขยับไฮไลต์(2, "Home", 5)).toBe(0);
    expect(ขยับไฮไลต์(2, "End", 5)).toBe(4);
    expect(ขยับไฮไลต์(2, "ArrowDown", 0)).toBe(-1);
  });
});

describe("ตำแหน่งรายการ: กางลงใต้ช่องเสมอ", () => {
  const จอ = { w: 1366, h: 768 };
  it("ช่องบนจอ: ใต้ช่อง สูงถึงเพดาน", () => {
    const p = ตำแหน่งรายการ({ left: 100, bottom: 200, width: 140 }, จอ);
    expect(p.top).toBeGreaterThan(200);
    expect(p.maxHeight).toBe(320);
  });
  it("ช่องล่างจอ: ยังอยู่ใต้ช่อง (ไม่พลิกขึ้น) · สูงเท่าที่ว่างใต้ช่อง", () => {
    const p = ตำแหน่งรายการ({ left: 100, bottom: 560, width: 140 }, จอ);
    expect(p.top).toBeGreaterThan(560);
    expect(p.maxHeight).toBe(768 - 560 - 8);
  });
  it("ไม่ล้นขอบขวาของจอ · กว้างอย่างน้อยเท่าช่อง", () => {
    const p = ตำแหน่งรายการ({ left: 1300, bottom: 200, width: 140 }, จอ);
    expect(p.left + p.minWidth).toBeLessThanOrEqual(1366 - 8);
    expect(p.minWidth).toBeGreaterThanOrEqual(140);
  });
});

describe("ต้องเลื่อนก่อนกาง: ช่องติดขอบล่าง = เลื่อนขึ้นก่อน (13 พ.ย. 69 · ลูกค้าเป้าหมายทั้งเครือ ช่องขั้นตอนท้ายจอ)", () => {
  it("ช่องล่างสุดของจอ (เหลือ 20px) 4 ตัวเลือก = ต้องเลื่อน", () => { expect(ต้องเลื่อนก่อนกาง(700, 720, 4, false)).toBe(true); });
  it("ที่ว่างพอ (4 ตัวเลือก ต้องใช้ 152px) = ไม่เลื่อน", () => { expect(ต้องเลื่อนก่อนกาง(300, 720, 4, false)).toBe(false); });
  it("รายการยาวมีช่องค้นหา ใช้ไม่เกินเพดาน 320", () => {
    expect(ต้องเลื่อนก่อนกาง(720 - 8 - 320, 720, 50, true)).toBe(false);
    expect(ต้องเลื่อนก่อนกาง(720 - 8 - 319, 720, 50, true)).toBe(true);
  });
});
