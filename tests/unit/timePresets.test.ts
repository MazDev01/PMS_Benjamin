// ตัวเลือกช่วงเวลาเหลือ 4 ตัว (บอสสั่ง 3 พ.ย. 69): 1 เดือน · 3 เดือน · 1 ปี (ค่าเริ่มต้น) · กำหนดเอง
//   ย้อนเดือนแล้ววันไม่มีในเดือนปลายทาง = วันสุดท้ายของเดือนนั้น (ไม่ล้นไปเดือนถัดไป)
//   ตกบนโค้ดก่อน 3 พ.ย. 69: มี 6 ตัวเลือก (ทุกช่วงเวลา · วันนี้ · 7 วันล่าสุด · เดือนนี้ · ปีนี้ · กำหนดเอง) · ไม่มี ย้อนเดือน
import { describe, it, expect } from "vitest";
import { TIME_PRESETS, ย้อนเดือน } from "../../packages/shared/lib/timePresets";

const iso = (d: Date) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
const วัน = (s: string) => new Date(`${s}T00:00:00`);

describe("ตัวเลือกช่วงเวลา", () => {
  it("มี 4 ตัวเลือกพอดี ตามลำดับ", () => {
    expect(TIME_PRESETS.map(p => p.label)).toEqual(["1 เดือน", "3 เดือน", "1 ปี", "กำหนดเอง"]);
  });
  it("ตัวเลือกที่เอาออกไม่มีแล้ว", () => {
    for (const เก่า of ["ทุกช่วงเวลา", "วันนี้", "7 วันล่าสุด", "เดือนนี้", "ปีนี้"]) expect(TIME_PRESETS.map(p => p.label)).not.toContain(เก่า);
  });
});

describe("ย้อนเดือน", () => {
  it("ย้อนปกติ", () => {
    expect(iso(ย้อนเดือน(วัน("2026-11-03"), 1))).toBe("2026-10-03");
    expect(iso(ย้อนเดือน(วัน("2026-11-03"), 3))).toBe("2026-08-03");
    expect(iso(ย้อนเดือน(วัน("2026-11-03"), 12))).toBe("2025-11-03");
  });
  it("สิ้นเดือน: 31 มี.ค. ย้อน 1 เดือน = วันสุดท้ายของ ก.พ. (ไม่ล้นไป มี.ค.)", () => {
    expect(iso(ย้อนเดือน(วัน("2027-03-31"), 1))).toBe("2027-02-28");
    expect(iso(ย้อนเดือน(วัน("2028-03-31"), 1))).toBe("2028-02-29");   // ปีอธิกสุรทิน
    expect(iso(ย้อนเดือน(วัน("2026-05-31"), 3))).toBe("2026-02-28");
    expect(iso(ย้อนเดือน(วัน("2026-12-31"), 1))).toBe("2026-11-30");
  });
  it("ข้ามปี", () => {
    expect(iso(ย้อนเดือน(วัน("2027-01-15"), 1))).toBe("2026-12-15");
    expect(iso(ย้อนเดือน(วัน("2028-02-29"), 12))).toBe("2027-02-28");
  });
});
