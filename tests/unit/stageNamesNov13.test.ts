// ── ชื่อขั้นการขายชุดใหม่ (บอสสั่ง 13 พ.ย. 69) — ของเก่าที่ฐานเก็บไว้แปลงตอนแสดง ไม่มีใบปรับฐาน ─────────────────────────
//   ข้อความผิดพลาดจากฐาน (friendlyError) · ชื่องานของระบบในฐาน (_lead_system_tasks: "ได้ใบ" + " HQ") · ไฟล์ส่งออก/ตัวกรองใช้ ชื่อขั้น()
//   ชื่อเดิมต่อเป็นชิ้น (ข้อความเต็มห้ามอยู่ในโค้ด — ตัวตรวจคำเก่า)
import { describe, it, expect } from "vitest";
import { friendlyError, DbError } from "@pms/shared/lib/friendlyError";
import { แปลงชื่อขั้นเดิม, ชื่อขั้น, ตัวเลือกขั้น, เลขขั้นทั้งหมด } from "@pms/shared/lib/leadStage";

const เดิม = { ขอ: "ขอราคา" + " HQ", ได้: "ได้ใบ" + " HQ", เสนอ: "เสนอราคา" + "ลูกค้า" };
const ห้าม = new RegExp(`${เดิม.ขอ}|${เดิม.ได้}|(?<!ใบ)${เดิม.เสนอ}`);

describe("ข้อความผิดพลาดจากฐานที่มีชื่อขั้นเดิม → คำปัจจุบันบนจอ", () => {
  it("request_stage: คำขอที่ได้ใบ HQ แล้ว", () => {
    const ข้อความ = friendlyError(new DbError(`request_stage: ขอแก้ราคาได้เฉพาะคำขอที่${เดิม.ได้} แล้วและยังไม่ปิด`));
    expect(ข้อความ).toBe("ขอแก้ราคาได้เฉพาะคำขอที่ได้ราคาจาก HQ แล้วและยังไม่ปิด");
    expect(ข้อความ).not.toMatch(ห้าม);
  });
  it("lead_tasks_invalid: รายการชื่อขั้นเต็มชุด → ชื่อขั้นปัจจุบันครบชุด", () => {
    const ข้อความ = friendlyError(new DbError(`lead_tasks_invalid: ทุกรายการต้องมีรหัส ชื่อ และขั้น 1–4 (ข้อมูลลูกค้า · ${เดิม.ขอ} · ${เดิม.ได้} · ${เดิม.เสนอ})`));
    expect(ข้อความ).toBe("ทุกรายการต้องมีรหัส ชื่อ และขั้น 1–4 (1. เก็บข้อมูลลูกค้า · 2. รอราคาจาก HQ · 3. ได้ราคาจาก HQ แล้ว · 4. ทำใบเสนอราคาให้ลูกค้า)");
  });
  it("lead_status_retired: อยู่ขั้น \"เสนอราคาลูกค้า\" → ขั้นปัจจุบัน", () => {
    expect(friendlyError(new DbError(`lead_status_retired: อยู่ขั้น "${เดิม.เสนอ}" จนลูกค้าตอบรับ`))).toBe(`อยู่ขั้น "ทำใบเสนอราคาให้ลูกค้า" จนลูกค้าตอบรับ`);
  });
});

describe("ชื่องานของระบบในฐาน + ตำแหน่งชื่อขั้น", () => {
  it("ชื่องาน \"ได้ใบ HQ\" (ฐาน) แสดงเป็น \"ได้ราคาจาก HQ\"", () => {
    expect(แปลงชื่อขั้นเดิม(เดิม.ได้)).toBe("ได้ราคาจาก HQ");
  });
  it("ตำแหน่งชื่อขั้น (ชื่อขั้น · ตัวกรอง) ไม่มี \"ข้อมูลลูกค้า\" ลอย ๆ และไม่มีชื่อเดิม", () => {
    const ทุกชื่อ = [...เลขขั้นทั้งหมด.map(ชื่อขั้น), ...ตัวเลือกขั้น.map(o => o.l)];
    expect(ทุกชื่อ.filter(x => x === "ข้อมูลลูกค้า" || ห้าม.test(x))).toEqual([]);
  });
});
