// เหตุผลปิดการขายไม่สำเร็จ = รายการกลาง lead_lost_reason (บอสตัดสิน 23 พ.ย. 69 ข้อ 14 · ใบ 0301)
//   ตัวจัดค่าหน้าเว็บ (จัดค่าเหตุผล) ต้องได้ผลเดียวกับ _lead_lost_value ในฐาน — ข้อมูลตัวอย่างในเครื่องที่ยังเป็นข้อความแสดงเหมือนฐานจริง
//   กราฟ HQ: ชื่อในรายการ · "อื่น ๆ (ระบุ)" ทุกข้อความรวมกลุ่มเดียว
import { describe, it, expect } from "vitest";
import { รายการตั้งต้นของ, จัดค่าเหตุผล, ป้ายเหตุผล, กลุ่มเหตุผล, รายการกลางทั้งหมด, ชื่อรายการกลาง } from "../../packages/shared/lib/optionLists";

const เหตุผล = รายการตั้งต้นของ("lead_lost_reason");

describe("รายการตั้งต้น lead_lost_reason (ตรงกับใบ 0301)", () => {
  it("4 ชื่อเดิมของระบบ + อื่น ๆ (ระบุ) ท้าย", () => {
    expect(เหตุผล.map(x => `${x.code}:${x.label}`)).toEqual([
      "price_high:ราคาสูงเกินงบประมาณ", "competitor:คู่แข่งให้ข้อเสนอดีกว่า", "budget:งบประมาณไม่พร้อม", "no_response:ลูกค้าไม่ตอบสนอง", "other:อื่น ๆ (ระบุ)"]);
    expect(เหตุผล.find(x => x.code === "other")?.freeText).toBe(true);
  });
  it("อยู่ในรายการกลางทั้งหมด (หน้าตั้งค่า/สำรองข้อมูล/ปลายทาง API ใช้ชุดนี้)", () => {
    expect(รายการกลางทั้งหมด).toContain("lead_lost_reason");
    expect(ชื่อรายการกลาง.lead_lost_reason).toBe("เหตุผลปิดการขายไม่สำเร็จ");
  });
});

describe("จัดค่าเหตุผล = กติกาเดียวกับ _lead_lost_value", () => {
  it.each([
    ["price_high", "price_high"],
    ["other:ไปซื้อที่อื่น", "other:ไปซื้อที่อื่น"],
    ["ราคาสูงเกินงบประมาณ", "price_high"],
    ["งบประมาณ  ไม่พร้อม", "budget"],
    ["อื่นๆ (ระบุเอง): ไปซื้อที่อื่น", "other:ไปซื้อที่อื่น"],
    ["อื่น ๆ: ย้ายไปจังหวัดอื่น", "other:ย้ายไปจังหวัดอื่น"],
    ["ราคาสูงกว่าคู่แข่ง", "other:ราคาสูงกว่าคู่แข่ง"],
    ["", ""],
  ])("%s → %s", (เดิม, ได้) => {
    expect(จัดค่าเหตุผล(เหตุผล, เดิม)).toBe(ได้);
  });
});

describe("ป้าย/กลุ่มของเหตุผล", () => {
  it("รหัส = ชื่อ · ระบุเอง = อื่น ๆ: ข้อความ · ข้อความเก่า = อื่น ๆ: ข้อความ · ว่าง = ค่าว่างที่ส่ง", () => {
    expect(ป้ายเหตุผล(เหตุผล, "budget")).toBe("งบประมาณไม่พร้อม");
    expect(ป้ายเหตุผล(เหตุผล, "other:ไปซื้อที่อื่น")).toBe("อื่น ๆ: ไปซื้อที่อื่น");
    expect(ป้ายเหตุผล(เหตุผล, "ราคาสูงกว่าคู่แข่ง")).toBe("อื่น ๆ: ราคาสูงกว่าคู่แข่ง");
    expect(ป้ายเหตุผล(เหตุผล, null, "ไม่ได้ระบุเหตุผล")).toBe("ไม่ได้ระบุเหตุผล");
  });
  it("กราฟ: ระบุเองทุกข้อความรวมกลุ่ม other (ชื่อ อื่น ๆ) · ชื่อเดิมที่ตรงรายการเข้ากลุ่มของตัวนั้น", () => {
    expect(กลุ่มเหตุผล(เหตุผล, "other:ก")).toEqual({ key: "other", label: "อื่น ๆ", ข้อความ: "ก" });
    expect(กลุ่มเหตุผล(เหตุผล, "ลูกค้าเลื่อนโครงการ")?.key).toBe("other");
    expect(กลุ่มเหตุผล(เหตุผล, "ราคาสูงเกินงบประมาณ")).toEqual({ key: "price_high", label: "ราคาสูงเกินงบประมาณ" });
    expect(กลุ่มเหตุผล(เหตุผล, "")).toBeNull();
  });
});
