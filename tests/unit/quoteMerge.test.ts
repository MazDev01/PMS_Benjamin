import { describe, it, expect } from "vitest";
import { รับแถวใบ, ใหม่กว่า } from "../../packages/shared/lib/quoteMerge";
import type { QuotationMock } from "../../packages/shared/lib/mock";

// ── ข่าวอัปเดตสดที่เก่ากว่าหรือเท่ากับของบนจอต้องถูกทิ้ง (ใบ 0238 · บอสสั่ง 22 ต.ค. 69) ─────────────────────────────
const ใบ = (id: string, totalValue: number, updatedAt?: string): QuotationMock =>
  ({ id, totalValue, updatedAt, customer: "", project: "", total: "", materialCost: 0, province: "", buildingType: "", area: 0,
     status: "draft", date: "2026-10-22", items: 1, customerId: 0, projectId: 0 }) as QuotationMock;
const T = "2026-10-22T06:56:44.798000+00:00";
const ก่อน = "2026-10-22T06:56:43.709000+00:00", หลัง = "2026-10-22T06:56:44.798001+00:00";

describe("รับแถวใบเข้ารายการบนจอ", () => {
  it("ข่าวที่เก่ากว่าของบนจอ → ทิ้ง (รายการเดิมอ้างอิงเดิม)", () => {
    const รายการ = [ใบ("Q-1-V2", 2950, T)];
    const ผล = รับแถวใบ(รายการ, ใบ("Q-1-V2", 2750, ก่อน));
    expect(ผล).toBe(รายการ);
    expect(ผล[0].totalValue).toBe(2950);
  });
  it("ข่าวที่เวลาเท่ากับของบนจอ → ทิ้ง (เท่ากัน = ไม่ใช่ของใหม่)", () => {
    const รายการ = [ใบ("Q-1-V2", 2950, T)];
    expect(รับแถวใบ(รายการ, ใบ("Q-1-V2", 2750, T))).toBe(รายการ);
  });
  it("เวลาเท่ากันแต่เขียนคนละรูปแบบ (Z กับ +00:00) → ยังนับว่าเท่ากัน ทิ้ง", () => {
    const รายการ = [ใบ("Q-1-V2", 2950, "2026-10-22T06:56:44.798Z")];
    expect(รับแถวใบ(รายการ, ใบ("Q-1-V2", 2750, "2026-10-22T06:56:44.798+00:00"))).toBe(รายการ);
  });
  it("ข่าวที่ใหม่กว่า → แทนที่ (ใบอื่นไม่ถูกแตะ)", () => {
    const อื่น = ใบ("Q-2", 100, T);
    const ผล = รับแถวใบ([ใบ("Q-1-V2", 2750, T), อื่น], ใบ("Q-1-V2", 2950, หลัง));
    expect(ผล[0].totalValue).toBe(2950);
    expect(ผล[1]).toBe(อื่น);
  });
  it("ใหม่กว่าแค่ 1 ไมโครวินาที (ฐานขยับเวลาทีละ µs) → ยังนับว่าใหม่กว่า แทนที่", () => {
    const ผล = รับแถวใบ([ใบ("Q-1-V2", 2750, "2026-10-22T06:56:44.798000+00:00")], ใบ("Q-1-V2", 2950, "2026-10-22T06:56:44.798001+00:00"));
    expect(ผล[0].totalValue).toBe(2950);
    expect(รับแถวใบ([ใบ("Q-1-V2", 2950, "2026-10-22T06:56:44.798001+00:00")], ใบ("Q-1-V2", 2750, "2026-10-22T06:56:44.798+00:00"))[0].totalValue,
      "เก่ากว่า 1 µs → ทิ้ง").toBe(2950);
    expect(ใหม่กว่า({ updatedAt: "2026-10-22T13:56:44.798+07:00" }, { updatedAt: "2026-10-22T06:56:44.798001Z" }), "คนละเขตเวลา เทียบถูก").toBe(true);
  });
  it("ใบที่ยังไม่มีบนจอ → เพิ่มบนสุด", () => {
    const ผล = รับแถวใบ([ใบ("Q-2", 100, T)], ใบ("Q-3", 300, ก่อน));
    expect(ผล.map(q => q.id)).toEqual(["Q-3", "Q-2"]);
  });
  it("เทียบเวลาไม่ได้ (ไม่มีเวลา/อ่านไม่ออก) → รับตามเดิม", () => {
    expect(รับแถวใบ([ใบ("Q-1", 1)], ใบ("Q-1", 2, T))[0].totalValue).toBe(2);
    expect(รับแถวใบ([ใบ("Q-1", 1, T)], ใบ("Q-1", 2))[0].totalValue).toBe(2);
    expect(รับแถวใบ([ใบ("Q-1", 1, "ไม่ใช่เวลา")], ใบ("Q-1", 2, T))[0].totalValue).toBe(2);
    expect(ใหม่กว่า(undefined, ใบ("Q-1", 1, T))).toBe(true);
  });
});
