// ช่องบังคับกรอก — ตัวกลาง (บอสสั่ง 4 พ.ย. 69): ว่าง/เว้นวรรคล้วน = ไม่ผ่าน · "-" = ผ่าน (ตั้งใจไม่มี) · ตัวเลข 0 = กรอกแล้ว
import { describe, it, expect } from "vitest";
import { ว่างอยู่, เป็นขีดตั้งใจไม่มี, ตรวจช่องบังคับ, สรุปช่องที่ขาด, ข้อความช่องขีด } from "../../packages/shared/lib/requiredFields";

describe("ว่างอยู่", () => {
  it("ว่าง / เว้นวรรคล้วน / null / NaN / รายการว่าง = ว่าง", () => {
    for (const v of [null, undefined, "", "   ", "\n\t", Number.NaN, []]) expect(ว่างอยู่(v), JSON.stringify(v)).toBe(true);
  });
  it('"-" · ตัวเลข 0 · ข้อความ = กรอกแล้ว', () => {
    for (const v of ["-", " - ", 0, "ก", ["x"], false]) expect(ว่างอยู่(v), JSON.stringify(v)).toBe(false);
    expect(เป็นขีดตั้งใจไม่มี(" - ")).toBe(true);
    expect(เป็นขีดตั้งใจไม่มี("--")).toBe(false);
  });
});

describe("ตรวจช่องบังคับ", () => {
  const ช่อง = [
    { key: "a", label: "ค่าแรกเข้า", value: "" },
    { key: "b", label: "ภาค", value: "ตะวันออก" },
    { key: "c", label: "เงื่อนไข", value: "  ", ข้อความ: ข้อความช่องขีด("เงื่อนไข") },
    { key: "d", label: "เงื่อนไขอื่น", value: "-" },
  ];
  it("คืนเฉพาะช่องที่ขาด ตามลำดับฟอร์ม พร้อมข้อความใต้ช่อง", () => {
    const ผล = ตรวจช่องบังคับ(ช่อง);
    expect(Object.keys(ผล)).toEqual(["a", "c"]);
    expect(ผล.a).toBe("ต้องกรอกค่าแรกเข้า");
    expect(ผล.c).toBe('ต้องกรอกเงื่อนไข — ไม่มีให้ใส่ "-"');
    expect(สรุปช่องที่ขาด(ช่อง, ผล)).toBe("กรอกให้ครบก่อนบันทึก: ค่าแรกเข้า · เงื่อนไข");
  });
  it("ครบทุกช่อง = ผ่าน (ว่าง)", () => expect(ตรวจช่องบังคับ(ช่อง.map(c => ({ ...c, value: "x" })))).toEqual({}));
});
