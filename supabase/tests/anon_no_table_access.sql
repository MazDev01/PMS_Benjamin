-- ── ข้อทดสอบใบ 0297: คนนอก (anon) แตะตาราง/มุมมองในสคีมา public ไม่ได้เลย · ผู้ใช้ที่เข้าระบบใช้งานได้เหมือนเดิม (คนรวมงานสั่ง 23 พ.ย. 69) ──
--   1) ทุกตาราง/มุมมอง: anon ไม่มีสิทธิ์ใดเหลือ (ไล่จากฐาน ไม่เขียนรายชื่อเอง) · อ่านจริงด้วยบทบาท anon = permission denied ทุกตัว
--   2) ตารางที่สร้างใหม่หลังใบนี้ (บัญชี postgres) ไม่ได้สิทธิ์ anon ตามค่าตั้งต้น · ตัวนับเลขก็เช่นกัน
--   3) ไม่เหลือกฎ RLS "to public" ในสคีมา public
--   4) health_ping(): anon เรียกได้ คืน true · ผู้ใช้ HQ อ่าน dealers ได้เหมือนเดิม (กฎย้ายเป็น authenticated ไม่กระทบ)
--   ตกบนฐานก่อนใบ 0297: anon มีสิทธิ์ตาราง 23 ตัว · กฎ to public 60+ ตัว · ไม่มี health_ping
-- รัน: docker exec -i <คอนเทนเนอร์ฐานทดสอบ> psql -U postgres -d postgres -X -q -v ON_ERROR_STOP=1 < supabase/tests/anon_no_table_access.sql
begin;
create schema antest;
create function antest.ok(p_cond boolean, p_what text) returns void language plpgsql as $$
begin if p_cond is not true then raise exception 'FAIL: %', p_what; end if; raise notice 'ok  %', p_what; end $$;
grant usage on schema antest to anon, authenticated;
grant execute on all functions in schema antest to anon, authenticated;

-- ── 1) สิทธิ์ในแคตาล็อก ──
select antest.ok(not exists (
  select 1 from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p', 'v', 'm', 'f')
     and (has_table_privilege('anon', c.oid, 'SELECT') or has_table_privilege('anon', c.oid, 'INSERT') or has_table_privilege('anon', c.oid, 'UPDATE')
       or has_table_privilege('anon', c.oid, 'DELETE') or has_table_privilege('anon', c.oid, 'TRUNCATE') or has_table_privilege('anon', c.oid, 'REFERENCES')
       or has_table_privilege('anon', c.oid, 'TRIGGER'))),
  '1) anon ไม่มีสิทธิ์ตาราง/มุมมองใดในสคีมา public');
select antest.ok((select count(*) from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'v')) > 50, '1) ตรวจจริง (ตาราง/มุมมองเกิน 50 ตัว)');

-- ── 1) อ่านจริงด้วยบทบาท anon ทุกตัว ──
do $$
declare t record; ผ่าน int := 0; หลุด text[] := '{}';
begin
  set local role anon;
  for t in select c.relname from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p', 'v', 'm') order by 1 loop
    begin
      execute format('select 1 from public.%I limit 1', t.relname);
      หลุด := หลุด || t.relname;
    exception when insufficient_privilege then ผ่าน := ผ่าน + 1;
    end;
  end loop;
  reset role;
  perform antest.ok(cardinality(หลุด) = 0, '1) anon อ่านทุกตาราง/มุมมอง = ปฏิเสธ (' || ผ่าน || ' ตัว)' || case when cardinality(หลุด) > 0 then ' หลุด: ' || array_to_string(หลุด, ', ') else '' end);
end $$;

-- ── 2) ตาราง/ตัวนับเลขที่สร้างใหม่ ──
create table public.zz_anon_probe (id bigint generated by default as identity primary key, x text);
create sequence public.zz_anon_probe_seq;
select antest.ok(not has_table_privilege('anon', 'public.zz_anon_probe', 'SELECT') and not has_table_privilege('anon', 'public.zz_anon_probe', 'INSERT'),
  '2) ตารางที่สร้างใหม่ไม่ให้สิทธิ์ anon ตามค่าตั้งต้น');
select antest.ok(not has_sequence_privilege('anon', 'public.zz_anon_probe_seq', 'USAGE'), '2) ตัวนับเลขที่สร้างใหม่ไม่ให้สิทธิ์ anon');
select antest.ok(has_table_privilege('authenticated', 'public.zz_anon_probe', 'SELECT'), '2) ผู้ใช้ที่เข้าระบบยังได้ค่าตั้งต้นเดิม (ไม่แตะ authenticated)');

-- ── 3) กฎ RLS ──
select antest.ok(not exists (select 1 from pg_policy pol join pg_class c on c.oid = pol.polrelid
                              where c.relnamespace = 'public'::regnamespace and pol.polroles = array[0::oid]),
  '3) ไม่เหลือกฎ RLS "to public"');

-- ── 4) health_ping + ผู้ใช้อ่านได้ ──
do $$
begin
  set local role anon;
  perform antest.ok(public.health_ping(), '4) anon เรียก health_ping ได้ = true');
  reset role;
  perform set_config('request.jwt.claims', json_build_object('sub', '00000000-0000-4000-8000-0000000a7297', 'role', 'authenticated',
    'user_role', 'SUPER_ADMIN', 'dealer_code', '')::text, true);
end $$;
set local session_replication_role = replica;
insert into auth.users (id, email, aud, role) values ('00000000-0000-4000-8000-0000000a7297', 'zzan-hq@example.test', 'authenticated', 'authenticated');
insert into profiles (id, role, dealer_code, name, status) values ('00000000-0000-4000-8000-0000000a7297', 'SUPER_ADMIN', '', 'ZZAN ผู้ดูแล', 'active');
insert into dealers (code, name, province, region, status) values ('ZAN', 'ZZTEST anon', 'ตราด', 'ตะวันออก', 'active');
set local session_replication_role = origin;
do $$
begin
  set local role authenticated;
  perform antest.ok(exists (select 1 from public.dealers where code = 'ZAN'), '4) ผู้ใช้ HQ อ่าน dealers ได้เหมือนเดิม (กฎ to authenticated)');
  perform antest.ok((select count(*) from public.profiles where id = '00000000-0000-4000-8000-0000000a7297') = 1, '4) ผู้ใช้อ่านโปรไฟล์ตัวเองได้');
  reset role;
end $$;

select 'ALL PASS' as result;
rollback;
