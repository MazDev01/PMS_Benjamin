-- ── ลบดีลเลอร์ / ย้ายข้อมูลดีลเลอร์: ให้ฝั่งเซิร์ฟเวอร์เรียกได้ และให้เรียกได้ทางเดียว ──────────────
--
-- บั๊ก (พบ 13 ต.ค. 69 ตอนรันชุดทดสอบบนฐานที่สร้างจากใบแก้ฐานข้อมูลล้วน ๆ):
--   เส้นทางของสำนักงานใหญ่ (apps/hq/app/api/admin/dealers · …/dealers/move) เรียกสองคำสั่งนี้ด้วยกุญแจฝั่งเซิร์ฟเวอร์
--   แต่ใบ 0119–0121 และ 0138–0139 เขียนว่า
--       revoke all … from public, anon;   grant execute … to authenticated;
--   สิทธิ์ของฝั่งเซิร์ฟเวอร์ (service_role) มาจาก public ทางเดียว — ถอน public แล้วไม่ได้ให้คืน = เรียกไม่ได้
--   → กด "ลบดีลเลอร์" หรือ "ย้ายข้อมูลดีลเลอร์" ได้ 503 "ไม่สำเร็จชั่วคราว" ทุกครั้ง
--
--   ทำไมไม่มีใครเห็น: ฐานทดสอบในเครื่องเคยถูกให้สิทธิ์ฟังก์ชันแบบเหมานอกใบ (ทุกคนเรียกได้หมด)
--   ข้อทดสอบของสองเรื่องนี้จึงผ่านมาตลอด ทั้งที่ฐานที่สร้างจากใบจริงเรียกไม่ได้
--   (ใบ 0121 แก้ "การตรวจสิทธิ์ข้างในคำสั่ง" ให้ฝั่งเซิร์ฟเวอร์ผ่านแล้ว แต่ไม่ได้แก้ "สิทธิ์เรียกคำสั่ง")
--
-- แก้:
--   1) ให้สิทธิ์เรียกกับฝั่งเซิร์ฟเวอร์
--   2) ถอนสิทธิ์จากผู้ใช้ที่เข้าระบบ — ไม่มีโค้ดฝั่งหน้าเว็บเรียกสองคำสั่งนี้ตรง ๆ (ตรวจแล้ว: มีแค่ 2 เส้นทางของ HQ ข้างบน)
--      เส้นทางของ HQ ตรวจบทบาทผู้เรียก จำกัดจำนวนคำขอ และลงบันทึกการใช้งานก่อนเรียก — เรียกตรงคือข้ามทั้งหมดนั้น
--   ตัวตรวจ scripts/check-server-rpc-grants.mjs กันเรื่องนี้ซ้ำ: คำสั่งที่โค้ดฝั่งเซิร์ฟเวอร์เรียก ต้องมีสิทธิ์ service_role
revoke all on function public.delete_dealer_atomic(text) from public, anon, authenticated;
grant execute on function public.delete_dealer_atomic(text) to service_role;

revoke all on function public.move_dealer_data_atomic(text, text) from public, anon, authenticated;
grant execute on function public.move_dealer_data_atomic(text, text) to service_role;
