-- ── คำขอใบเสนอราคา + ใบ HQ (โครงของ Flow ใหม่ · ระยะ 1) ─────────────────────────────────
--
-- Flow ใหม่ (บอสสั่ง 12 ต.ค. 69): คนตีราคาเปลี่ยนจากดีลเลอร์เป็นสำนักงานใหญ่
--   ดีลเลอร์ส่งคำขอ → HQ รับเรื่อง ทำ BOQ → ส่ง "ใบ HQ" (ต้นทุนของดีลเลอร์) ภายใน 14 วัน
--   → ดีลเลอร์บวก % ทำใบให้ลูกค้า → ลูกค้าตอบรับ → ใบ HQ กลายเป็นคำสั่งผลิต
--
-- หลักของใบนี้: "สองฝั่งขยับตามกันที่ฐานข้อมูล" — ไม่มีใครต้องไปกดเปลี่ยนสถานะฝั่งตรงข้ามเอง
--   ตารางสองตัวนี้จึง **ไม่มีสิทธิ์เขียนตรง** ทุกการเปลี่ยนสถานะเดินผ่านคำสั่ง (RPC) ที่ตรวจสิทธิ์เอง
--   และสถานะ "รอราคา HQ" ของลูกค้าเป้าหมายเข้า/ออกได้ทางคำสั่งชุดนี้ทางเดียว
--
-- ยังไม่อยู่ในใบนี้ (ระยะ 2): ซ่อนราคาแม่แบบจากดีลเลอร์ · ใบลูกค้าต้องตรงกับใบ HQ (รายการ/จำนวน/%)
--   · อายุใบลูกค้าไม่เกินใบ HQ · กันลูกค้าเป้าหมายซ้ำ   (ระยะ 5): นับ 14 วันแล้วส่งอีเมล

-- ═══ 1. คำขอใบเสนอราคา ═══════════════════════════════════════════════════════════════
create table public.quote_requests (
  id            bigint generated by default as identity primary key,
  request_no    text not null unique,
  dealer_code   text not null references public.dealers(code) on update cascade on delete restrict,
  lead_num_id   integer not null,
  -- สายของคำขอ: ขอแก้ราคา = คำขอใหม่ที่ชี้กลับคำขอเดิม · root_id = คำขอแรกของงานนี้ (ใช้นับเวอร์ชันใบ HQ)
  root_id       bigint references public.quote_requests(id) on delete restrict,
  supersedes_id bigint references public.quote_requests(id) on delete restrict,
  product       text not null default '',          -- แม่แบบ
  subtype       text not null default '',          -- แม่แบบย่อย
  area          numeric check (area is null or area >= 0),
  province      text not null default '',          -- จังหวัดหน้างาน
  spec          text not null default '',          -- สเปก/รายละเอียดที่ดีลเลอร์แจ้ง
  status        text not null default 'new'
                check (status in ('new','pricing','quoted','won','lost','cancelled','superseded')),
  assignee      uuid references auth.users(id) on delete set null,   -- ผู้รับผิดชอบฝั่ง HQ
  assignee_name text not null default '',
  submitted_at  timestamptz not null default now(),
  due_at        timestamptz not null,              -- ครบกำหนดส่งใบ (submitted_at + 14 วัน)
  accepted_at   timestamptz,
  quoted_at     timestamptz,                       -- HQ ส่งใบ = หยุดนับ
  closed_at     timestamptz,
  cancel_reason text not null default '',
  lost_reason   text not null default '',
  overdue_notified_at timestamptz,                 -- ระยะ 5: ส่งอีเมลเตือนเกินกำหนดแล้วเมื่อไร
  created_by    uuid references auth.users(id) on delete set null,
  updated_at    timestamptz not null default now(),
  constraint quote_requests_lead_fk foreign key (dealer_code, lead_num_id)
    references public.leads(dealer_code, num_id) on update cascade on delete restrict,
  constraint quote_requests_cancel_needs_reason check (status <> 'cancelled' or btrim(cancel_reason) <> '')
);

comment on table public.quote_requests is
  'คำขอใบเสนอราคาที่ดีลเลอร์ส่งให้สำนักงานใหญ่ตีราคา — เขียนผ่านคำสั่ง quote_request_* เท่านั้น';

-- ลูกค้าเป้าหมายหนึ่งรายมีคำขอที่ยังเปิดอยู่ได้ใบเดียว
create unique index quote_requests_one_open_per_lead
  on public.quote_requests (dealer_code, lead_num_id)
  where status in ('new','pricing','quoted');
create index quote_requests_queue_idx on public.quote_requests (status, due_at);
create index quote_requests_dealer_idx on public.quote_requests (dealer_code, submitted_at desc);

/** กำหนดส่งใบ HQ นับจากวันที่ดีลเลอร์ส่งคำขอ (วัน) — ที่เดียว เปลี่ยนเกณฑ์แก้ตรงนี้ */
create or replace function public.quote_request_sla_days() returns integer
  language sql immutable as $$ select 14 $$;

/** เกินกำหนดหรือยัง — นับเฉพาะช่วงที่ลูกบอลอยู่ที่ HQ (ยังไม่ส่งใบ) */
create or replace function public.quote_request_overdue(r public.quote_requests) returns boolean
  language sql stable as $$ select r.status in ('new','pricing') and now() > r.due_at $$;

-- ═══ 2. ใบ HQ (ต้นทุนของดีลเลอร์ · มีเวอร์ชัน · ส่งแล้วแก้ไม่ได้) ═══════════════════════════════
create table public.hq_quotes (
  id          bigint generated by default as identity primary key,
  request_id  bigint not null references public.quote_requests(id) on delete restrict,
  version     integer not null check (version >= 1),
  quote_no    text not null unique,
  status      text not null default 'draft'
              check (status in ('draft','sent','ordered','superseded')),
  -- รายการ BOQ: [{ name, qty, unit, unitCost }] — unitCost = ต้นทุนต่อหน่วยที่ดีลเลอร์จ่าย HQ
  line_items  jsonb not null default '[]'::jsonb,
  total_cost  numeric not null default 0 check (total_cost >= 0),
  valid_until date,
  note        text not null default '',
  sent_at     timestamptz,
  ordered_at  timestamptz,                         -- ลูกค้าตอบรับ = สั่งผลิต ล็อกราคา นับเป็นยอดขาย HQ
  created_by  uuid references auth.users(id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (request_id)                              -- คำขอหนึ่งใบได้ใบ HQ หนึ่งใบ · แก้ราคา = คำขอใหม่ เวอร์ชันใหม่
);

comment on table public.hq_quotes is
  'ใบ HQ = ราคาต้นทุนที่สำนักงานใหญ่ส่งให้ดีลเลอร์ — ร่างเห็นเฉพาะ HQ · ส่งแล้วแก้ไม่ได้ ต้องออกเวอร์ชันใหม่';

-- ═══ 3. ประวัติของคำขอ (ไทม์ไลน์ · ระยะ 5 ใช้เป็นต้นทางอีเมล) ═══════════════════════════════
create table public.quote_request_events (
  id          bigint generated by default as identity primary key,
  request_id  bigint not null references public.quote_requests(id) on delete cascade,
  from_status text,
  to_status   text not null,
  note        text not null default '',
  actor       text not null default '',
  actor_role  text not null default '',
  at          timestamptz not null default now()
);
create index quote_request_events_req_idx on public.quote_request_events (request_id, at);

-- ═══ 4. ใบเสนอราคาของดีลเลอร์ผูกกับใบ HQ ═══════════════════════════════════════════════════
-- ใบเดิมก่อน Flow ใหม่ไม่มีใบ HQ (hq_quote_id ว่าง) = เก็บไว้อ่านอย่างเดียว ตัวดักข้างล่างไม่แตะ
alter table public.quotations
  add column if not exists hq_quote_id    bigint references public.hq_quotes(id) on delete restrict,
  add column if not exists markup_percent numeric;   -- % ที่ดีลเลอร์บวกทั้งใบ (รายบรรทัดอยู่ใน line_items)
create index if not exists quotations_hq_quote_idx on public.quotations (hq_quote_id) where hq_quote_id is not null;

-- ═══ 5. สิทธิ์การมองเห็น ══════════════════════════════════════════════════════════════════
alter table public.quote_requests       enable row level security;
alter table public.hq_quotes            enable row level security;
alter table public.quote_request_events enable row level security;

revoke all on public.quote_requests, public.hq_quotes, public.quote_request_events from anon;
revoke insert, update, delete, truncate on public.quote_requests, public.hq_quotes, public.quote_request_events from authenticated;
grant select on public.quote_requests, public.hq_quotes, public.quote_request_events to authenticated;

create policy quote_requests_select on public.quote_requests for select to authenticated
  using (is_hq() or dealer_code = auth_dealer());

-- ร่างของ HQ ดีลเลอร์ไม่เห็น — เห็นเมื่อส่งแล้วเท่านั้น และเฉพาะใบของคำขอตัวเอง
create policy hq_quotes_select on public.hq_quotes for select to authenticated
  using (
    is_hq() or (
      status <> 'draft' and exists (
        select 1 from public.quote_requests r
         where r.id = hq_quotes.request_id and r.dealer_code = auth_dealer()
      )
    )
  );

create policy quote_request_events_select on public.quote_request_events for select to authenticated
  using (exists (
    select 1 from public.quote_requests r
     where r.id = quote_request_events.request_id and (is_hq() or r.dealer_code = auth_dealer())
  ));

/** ใครฝั่ง HQ ตีราคาได้ — ที่เดียว อยากจำกัดเฉพาะบางบทบาทแก้ตรงนี้ */
create or replace function public.can_price_quotes() returns boolean
  language sql stable set search_path to 'public'
  as $$ select is_hq() and public.is_account_active() $$;

-- ═══ 6. ลูกค้าเป้าหมาย: สถานะ "รอราคา HQ" เข้า/ออกได้ทางคำสั่งของระบบเท่านั้น ═══════════════
create or replace function public.leads_hq_pricing_guard() returns trigger
  language plpgsql set search_path to 'public' as $$
begin
  if coalesce(current_setting('pms.flow_sync', true), '') = '1' then return new; end if;
  if tg_op = 'INSERT' then
    if new.status = 'HQ_PRICING' then
      raise exception 'hq_pricing_locked: สถานะ "รอราคา HQ" ตั้งเองไม่ได้ — ต้องส่งคำขอใบเสนอราคา';
    end if;
  elsif new.status is distinct from old.status then
    if new.status = 'HQ_PRICING' then
      raise exception 'hq_pricing_locked: สถานะ "รอราคา HQ" ตั้งเองไม่ได้ — ต้องส่งคำขอใบเสนอราคา';
    elsif old.status = 'HQ_PRICING' then
      raise exception 'hq_pricing_locked: ลูกค้าเป้าหมายนี้รอราคาจากสำนักงานใหญ่อยู่ — เปลี่ยนสถานะเองไม่ได้ (ยกเลิกคำขอ หรือส่งใบเสนอราคาให้ลูกค้าก่อน)';
    end if;
  end if;
  return new;
end $$;

create trigger leads_hq_pricing_guard before insert or update of status on public.leads
  for each row execute function public.leads_hq_pricing_guard();

/** ขยับสถานะลูกค้าเป้าหมายในนามของระบบ (ผ่านตัวดักข้างบน) — ใช้ภายในเท่านั้น */
create or replace function public._lead_flow_set_status(
  p_dealer text, p_num_id integer, p_status public.lead_status, p_lost_reason text default null
) returns void language plpgsql security definer set search_path to 'public' as $$
begin
  perform set_config('pms.flow_sync', '1', true);
  update leads
     set status = p_status,
         lost_reason = case when p_lost_reason is not null then p_lost_reason else lost_reason end
   where dealer_code = p_dealer and num_id = p_num_id and status is distinct from p_status;
  perform set_config('pms.flow_sync', '', true);
end $$;
revoke all on function public._lead_flow_set_status(text, integer, public.lead_status, text) from public, anon, authenticated;

-- ═══ 7. ประวัติ + เวลาแก้ล่าสุด ═══════════════════════════════════════════════════════════
create or replace function public.quote_requests_log() returns trigger
  language plpgsql security definer set search_path to 'public' as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into quote_request_events (request_id, from_status, to_status, note, actor, actor_role)
    values (new.id, case when tg_op = 'UPDATE' then old.status end, new.status,
            case new.status when 'cancelled' then new.cancel_reason when 'lost' then new.lost_reason else '' end,
            audit_actor(), auth_role());
    insert into audit_log("user", role, action, target)
    values (audit_actor(), auth_role(),
            case when tg_op = 'INSERT' then 'ส่งคำขอใบเสนอราคา'
                 else 'คำขอใบเสนอราคา ' || old.status || ' → ' || new.status end,
            new.dealer_code || ' · ' || new.request_no);
  end if;
  return new;
end $$;

create or replace function public.touch_updated_at() returns trigger
  language plpgsql as $$ begin new.updated_at := now(); return new; end $$;

create trigger quote_requests_touch before update on public.quote_requests
  for each row execute function public.touch_updated_at();
create trigger quote_requests_log after insert or update of status on public.quote_requests
  for each row execute function public.quote_requests_log();
create trigger hq_quotes_touch before update on public.hq_quotes
  for each row execute function public.touch_updated_at();

-- ═══ 8. คำสั่งฝั่งดีลเลอร์ ══════════════════════════════════════════════════════════════════

/** ดีลเลอร์ส่งคำขอใบเสนอราคา — ลูกค้าเป้าหมาย → รอราคา HQ · เริ่มนับ 14 วัน */
create or replace function public.quote_request_submit(
  p_lead_num_id integer, p_product text, p_subtype text default '',
  p_area numeric default null, p_spec text default '', p_province text default ''
) returns public.quote_requests language plpgsql security definer set search_path to 'public' as $$
declare
  v_dealer text := auth_dealer();
  v_lead   leads;
  v_id     bigint;
  r        quote_requests;
begin
  if not can_write_sales() or v_dealer = '' then
    raise exception 'forbidden: ไม่มีสิทธิ์ส่งคำขอใบเสนอราคา';
  end if;
  if btrim(coalesce(p_product, '')) = '' then
    raise exception 'product_required: ต้องเลือกแม่แบบก่อนส่งคำขอ';
  end if;

  select * into v_lead from leads where dealer_code = v_dealer and num_id = p_lead_num_id for update;
  if not found then raise exception 'lead_not_found: ไม่พบลูกค้าเป้าหมายนี้'; end if;
  if v_lead.status not in ('WAITING', 'BULLET') then
    raise exception 'lead_stage: ส่งคำขอได้เฉพาะลูกค้าเป้าหมายที่ยังไม่ได้ขอราคา (ขั้นปัจจุบัน %)', v_lead.status;
  end if;
  if exists (select 1 from quote_requests where dealer_code = v_dealer and lead_num_id = p_lead_num_id
                and status in ('new','pricing','quoted')) then
    raise exception 'request_open: ลูกค้าเป้าหมายนี้มีคำขอที่ยังเปิดอยู่แล้ว';
  end if;

  v_id := nextval(pg_get_serial_sequence('public.quote_requests', 'id'));
  insert into quote_requests (id, request_no, dealer_code, lead_num_id, root_id, product, subtype, area,
                              province, spec, due_at, created_by)
  values (v_id,
          'RQ-' || to_char(now() at time zone 'Asia/Bangkok', 'YYYY') || '-' || lpad(v_id::text, 5, '0'),
          v_dealer, p_lead_num_id, v_id, btrim(p_product), btrim(coalesce(p_subtype, '')), p_area,
          btrim(coalesce(nullif(btrim(coalesce(p_province, '')), ''), v_lead.province, '')),
          btrim(coalesce(p_spec, '')),
          now() + make_interval(days => quote_request_sla_days()), auth.uid())
  returning * into r;

  perform _lead_flow_set_status(v_dealer, p_lead_num_id, 'HQ_PRICING');
  return r;
end $$;

/** ดีลเลอร์ยกเลิกคำขอ — ได้จนกว่า HQ จะส่งใบ · ต้องมีเหตุผล · ลูกค้าเป้าหมายกลับ BULLET หรือปิดไม่สำเร็จ */
create or replace function public.quote_request_cancel(
  p_id bigint, p_reason text, p_close_lead boolean default false
) returns public.quote_requests language plpgsql security definer set search_path to 'public' as $$
declare r quote_requests;
begin
  if not can_write_sales() then raise exception 'forbidden: ไม่มีสิทธิ์ยกเลิกคำขอ'; end if;
  if btrim(coalesce(p_reason, '')) = '' then raise exception 'reason_required: ต้องระบุเหตุผลที่ยกเลิกคำขอ'; end if;

  select * into r from quote_requests where id = p_id and dealer_code = auth_dealer() for update;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if r.status not in ('new', 'pricing') then
    raise exception 'request_locked: ยกเลิกได้เฉพาะคำขอที่สำนักงานใหญ่ยังไม่ได้ส่งใบ (สถานะ %)', r.status;
  end if;

  update quote_requests set status = 'cancelled', cancel_reason = btrim(p_reason), closed_at = now()
   where id = p_id returning * into r;
  delete from hq_quotes where request_id = p_id and status = 'draft';   -- ร่างที่ยังไม่เคยส่ง ไม่มีใครอ้างถึง

  if p_close_lead then
    perform _lead_flow_set_status(r.dealer_code, r.lead_num_id, 'CANCELLED', btrim(p_reason));
  else
    perform _lead_flow_set_status(r.dealer_code, r.lead_num_id, 'BULLET');
  end if;
  return r;
end $$;

/** ดีลเลอร์ขอแก้ราคา — คำขอและใบ HQ เดิมปิด · คำขอใหม่เริ่มนับ 14 วันใหม่ · ลูกค้าเป้าหมายกลับไปรอราคา HQ */
create or replace function public.quote_request_reprice(
  p_id bigint, p_reason text, p_spec text default null
) returns public.quote_requests language plpgsql security definer set search_path to 'public' as $$
declare
  old_r quote_requests;
  r     quote_requests;
  v_id  bigint;
begin
  if not can_write_sales() then raise exception 'forbidden: ไม่มีสิทธิ์ขอแก้ราคา'; end if;
  if btrim(coalesce(p_reason, '')) = '' then raise exception 'reason_required: ต้องระบุว่าขอแก้ราคาเพราะอะไร'; end if;

  select * into old_r from quote_requests where id = p_id and dealer_code = auth_dealer() for update;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if old_r.status <> 'quoted' then
    raise exception 'request_stage: ขอแก้ราคาได้เฉพาะคำขอที่ได้ใบ HQ แล้วและยังไม่ปิด (สถานะ %)', old_r.status;
  end if;

  update quote_requests set status = 'superseded', closed_at = now() where id = p_id;
  update hq_quotes set status = 'superseded' where request_id = p_id and status = 'sent';

  v_id := nextval(pg_get_serial_sequence('public.quote_requests', 'id'));
  insert into quote_requests (id, request_no, dealer_code, lead_num_id, root_id, supersedes_id, product, subtype,
                              area, province, spec, due_at, created_by)
  values (v_id,
          'RQ-' || to_char(now() at time zone 'Asia/Bangkok', 'YYYY') || '-' || lpad(v_id::text, 5, '0'),
          old_r.dealer_code, old_r.lead_num_id, coalesce(old_r.root_id, old_r.id), old_r.id,
          old_r.product, old_r.subtype, old_r.area, old_r.province,
          btrim(coalesce(nullif(btrim(coalesce(p_spec, '')), ''), old_r.spec) || E'\n[ขอแก้ราคา] ' || btrim(p_reason)),
          now() + make_interval(days => quote_request_sla_days()), auth.uid())
  returning * into r;

  perform _lead_flow_set_status(r.dealer_code, r.lead_num_id, 'HQ_PRICING');
  return r;
end $$;

-- ═══ 9. คำสั่งฝั่งสำนักงานใหญ่ ═════════════════════════════════════════════════════════════

/** HQ กดรับเรื่อง — ใหม่ → กำลังทำราคา · ผู้กดเป็นผู้รับผิดชอบ (หรือมอบให้คนอื่นด้วย p_assignee) */
create or replace function public.quote_request_accept(p_id bigint, p_assignee uuid default null)
returns public.quote_requests language plpgsql security definer set search_path to 'public' as $$
declare
  r      quote_requests;
  v_who  uuid := coalesce(p_assignee, auth.uid());
  v_name text;
begin
  if not can_price_quotes() then raise exception 'forbidden: เฉพาะสำนักงานใหญ่เท่านั้นที่รับคำขอได้'; end if;
  select coalesce(name, '') into v_name from profiles
   where id = v_who and role in ('SUPER_ADMIN', 'HQ_MANAGEMENT', 'HQ_STAFF');
  if not found then raise exception 'assignee_invalid: ผู้รับผิดชอบต้องเป็นผู้ใช้ของสำนักงานใหญ่'; end if;

  select * into r from quote_requests where id = p_id for update;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if r.status not in ('new', 'pricing') then
    raise exception 'request_stage: รับเรื่องได้เฉพาะคำขอที่ยังไม่ได้ส่งใบ (สถานะ %)', r.status;
  end if;

  update quote_requests
     set status = 'pricing', assignee = v_who, assignee_name = v_name,
         accepted_at = coalesce(accepted_at, now())
   where id = p_id returning * into r;
  return r;
end $$;

/** HQ บันทึกร่างใบ HQ (BOQ + ต้นทุน) — ยอดรวมคิดจากรายการเสมอ ไม่รับยอดที่ส่งมา */
create or replace function public.hq_quote_save(
  p_request_id bigint, p_lines jsonb, p_valid_until date default null, p_note text default ''
) returns public.hq_quotes language plpgsql security definer set search_path to 'public' as $$
declare
  r       quote_requests;
  h       hq_quotes;
  v_total numeric := 0;
  v_line  jsonb;
  v_ver   integer;
  v_id    bigint;
begin
  if not can_price_quotes() then raise exception 'forbidden: เฉพาะสำนักงานใหญ่เท่านั้นที่ทำใบ HQ ได้'; end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' then raise exception 'lines_invalid: รายการต้องเป็นรายการสินค้า'; end if;

  for v_line in select * from jsonb_array_elements(p_lines) loop
    if btrim(coalesce(v_line ->> 'name', '')) = '' then raise exception 'lines_invalid: ทุกรายการต้องมีชื่อ'; end if;
    if coalesce((v_line ->> 'qty')::numeric, 0) <= 0 then raise exception 'lines_invalid: จำนวนต้องมากกว่า 0 (%)', v_line ->> 'name'; end if;
    if coalesce((v_line ->> 'unitCost')::numeric, -1) < 0 then raise exception 'lines_invalid: ต้องใส่ต้นทุนต่อหน่วย (%)', v_line ->> 'name'; end if;
    v_total := v_total + round((v_line ->> 'qty')::numeric * (v_line ->> 'unitCost')::numeric, 2);
  end loop;

  select * into r from quote_requests where id = p_request_id for update;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if r.status not in ('new', 'pricing') then
    raise exception 'request_stage: แก้ใบ HQ ได้เฉพาะคำขอที่ยังไม่ได้ส่งใบ (สถานะ %) — ส่งแล้วต้องออกเวอร์ชันใหม่', r.status;
  end if;

  -- เริ่มทำราคาโดยยังไม่กดรับเรื่อง = รับเรื่องให้เลย
  if r.status = 'new' then perform quote_request_accept(p_request_id); end if;

  select * into h from hq_quotes where request_id = p_request_id;
  if found then
    update hq_quotes set line_items = p_lines, total_cost = v_total, valid_until = p_valid_until,
                         note = btrim(coalesce(p_note, ''))
     where id = h.id returning * into h;
  else
    -- เวอร์ชัน = ลำดับของคำขอในสายเดียวกัน (ขอแก้ราคาครั้งที่ n = V{n+1})
    select count(*) into v_ver from quote_requests q
     where coalesce(q.root_id, q.id) = coalesce(r.root_id, r.id) and q.id <= r.id;
    v_id := nextval(pg_get_serial_sequence('public.hq_quotes', 'id'));
    insert into hq_quotes (id, request_id, version, quote_no, line_items, total_cost, valid_until, note, created_by)
    values (v_id, p_request_id, v_ver,
            'HQ-' || to_char(now() at time zone 'Asia/Bangkok', 'YYYY') || '-' ||
              lpad(coalesce(r.root_id, r.id)::text, 5, '0') || '-V' || v_ver,
            p_lines, v_total, p_valid_until, btrim(coalesce(p_note, '')), auth.uid())
    returning * into h;
  end if;
  return h;
end $$;

/** HQ ส่งใบ HQ ให้ดีลเลอร์ — ล็อกเนื้อหา · คำขอ → ส่งใบแล้ว (หยุดนับ 14 วัน) · ลูกค้าเป้าหมายคงเดิม */
create or replace function public.hq_quote_send(p_request_id bigint)
returns public.hq_quotes language plpgsql security definer set search_path to 'public' as $$
declare
  r quote_requests;
  h hq_quotes;
begin
  if not can_price_quotes() then raise exception 'forbidden: เฉพาะสำนักงานใหญ่เท่านั้นที่ส่งใบ HQ ได้'; end if;
  select * into r from quote_requests where id = p_request_id for update;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if r.status <> 'pricing' then raise exception 'request_stage: ส่งใบได้เฉพาะคำขอที่กำลังทำราคา (สถานะ %)', r.status; end if;

  select * into h from hq_quotes where request_id = p_request_id and status = 'draft' for update;
  if not found then raise exception 'quote_missing: ยังไม่มีร่างใบ HQ ของคำขอนี้'; end if;
  if jsonb_array_length(h.line_items) = 0 or h.total_cost <= 0 then
    raise exception 'quote_empty: ใบ HQ ต้องมีรายการและยอดรวมมากกว่า 0';
  end if;
  if h.valid_until is null or h.valid_until < (now() at time zone 'Asia/Bangkok')::date then
    raise exception 'quote_validity: ต้องกำหนดวันยืนราคา และต้องไม่ย้อนหลัง';
  end if;

  update hq_quotes set status = 'sent', sent_at = now() where id = h.id returning * into h;
  update quote_requests set status = 'quoted', quoted_at = now() where id = p_request_id;
  return h;
end $$;

-- ═══ 10. ใบ HQ ที่ส่งแล้วแก้ไม่ได้ (ด่านสุดท้าย — ต่อให้มีคนเขียนตรงด้วยสิทธิ์ผู้ดูแล) ═════════════
create or replace function public.hq_quotes_lock_sent() returns trigger
  language plpgsql set search_path to 'public' as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'draft' then raise exception 'hq_quote_locked: ใบ HQ ที่ส่งแล้วลบไม่ได้'; end if;
    return old;
  end if;
  if old.status <> 'draft' and (
       new.line_items is distinct from old.line_items or new.total_cost is distinct from old.total_cost
    or new.valid_until is distinct from old.valid_until or new.version is distinct from old.version
    or new.request_id is distinct from old.request_id or new.quote_no is distinct from old.quote_no) then
    raise exception 'hq_quote_locked: ใบ HQ ที่ส่งแล้วแก้ไม่ได้ — ต้องออกเวอร์ชันใหม่ผ่านการขอแก้ราคา';
  end if;
  if new.status is distinct from old.status and not (
       (old.status = 'draft'   and new.status = 'sent')
    or (old.status = 'sent'    and new.status in ('ordered', 'superseded'))
    or (old.status = 'ordered' and new.status = 'sent')) then        -- ย้อนการตอบรับของลูกค้า
    raise exception 'hq_quote_locked: เปลี่ยนสถานะใบ HQ จาก % เป็น % ไม่ได้', old.status, new.status;
  end if;
  return new;
end $$;

create trigger hq_quotes_lock_sent before update or delete on public.hq_quotes
  for each row execute function public.hq_quotes_lock_sent();

-- ═══ 11. ใบเสนอราคาของดีลเลอร์ → ขยับคำขอ ใบ HQ และลูกค้าเป้าหมายตาม ═══════════════════════════

/** ผูกใบ HQ ได้เฉพาะใบของคำขอตัวเองที่ส่งแล้ว · ผูกแล้วเปลี่ยนไปใบอื่นไม่ได้ */
create or replace function public.quotations_hq_link_guard() returns trigger
  language plpgsql security definer set search_path to 'public' as $$
declare
  h hq_quotes;
  r quote_requests;
begin
  if tg_op = 'UPDATE' and old.hq_quote_id is not null and new.hq_quote_id is distinct from old.hq_quote_id then
    raise exception 'hq_link_locked: ใบเสนอราคานี้ผูกกับใบ HQ แล้ว เปลี่ยนไม่ได้ — ออกใบใหม่จากใบ HQ เวอร์ชันใหม่';
  end if;
  if new.hq_quote_id is null or (tg_op = 'UPDATE' and new.hq_quote_id is not distinct from old.hq_quote_id) then
    return new;
  end if;

  select * into h from hq_quotes where id = new.hq_quote_id;
  if found then select * into r from quote_requests where id = h.request_id; end if;
  if h.id is null or r.dealer_code is distinct from new.dealer_code or h.status = 'draft' then
    raise exception 'hq_link_invalid: ไม่พบใบ HQ นี้ในคำขอของสาขา';
  end if;
  if h.status <> 'sent' then
    raise exception 'hq_link_invalid: ใบ HQ % ใช้ออกใบใหม่ไม่ได้แล้ว (สถานะ %)', h.quote_no, h.status;
  end if;
  if new.deal_id is null then new.deal_id := r.lead_num_id;
  elsif new.deal_id <> r.lead_num_id then
    raise exception 'hq_link_invalid: ใบ HQ นี้เป็นของลูกค้าเป้าหมายรายอื่น';
  end if;
  return new;
end $$;

create trigger quotations_hq_link_guard before insert or update of hq_quote_id on public.quotations
  for each row execute function public.quotations_hq_link_guard();

/** สถานะใบของดีลเลอร์เปลี่ยน → ฝั่ง HQ และลูกค้าเป้าหมายขยับตามเอง (เฉพาะใบที่ผูกใบ HQ) */
create or replace function public.quotations_flow_sync() returns trigger
  language plpgsql security definer set search_path to 'public' as $$
declare
  h hq_quotes;
  r quote_requests;
  was text := case when tg_op = 'UPDATE' then old.status::text else '' end;
begin
  if new.hq_quote_id is null or new.status::text = was then return new; end if;
  select * into h from hq_quotes where id = new.hq_quote_id for update;
  select * into r from quote_requests where id = h.request_id for update;

  if new.status = 'sent_to_client' then
    -- ดีลเลอร์ส่งใบให้ลูกค้า: คำขอคงเดิม · ลูกค้าเป้าหมาย รอราคา HQ → เสนอราคา
    if exists (select 1 from leads where dealer_code = r.dealer_code and num_id = r.lead_num_id and status = 'HQ_PRICING') then
      perform _lead_flow_set_status(r.dealer_code, r.lead_num_id, 'QUOTED');
    end if;

  elsif new.status = 'won' then
    -- ลูกค้าตอบรับ: ใบ HQ = สั่งผลิต · คำขอปิด (won) · ลูกค้าเป้าหมาย → ปิดการขายสำเร็จ
    if h.status <> 'sent' then
      raise exception 'hq_quote_unusable: ปิดการขายไม่ได้ — ใบ HQ % ใช้ไม่ได้แล้ว (สถานะ %)', h.quote_no, h.status;
    end if;
    update hq_quotes set status = 'ordered', ordered_at = now() where id = h.id;
    update quote_requests set status = 'won', closed_at = now() where id = r.id;
    perform _lead_flow_set_status(r.dealer_code, r.lead_num_id, 'PAID');

  elsif new.status = 'lost' then
    -- ลูกค้าปฏิเสธ: คำขอปิด (lost) · ลูกค้าเป้าหมาย → ปิดไม่สำเร็จ + เหตุผล
    --   ยังมีใบอื่นของใบ HQ เดียวกันค้างอยู่ = งานยังไม่จบ ไม่ปิด
    if r.status = 'quoted' and not exists (
         select 1 from quotations q
          where q.hq_quote_id = new.hq_quote_id and (q.dealer_code, q.id) <> (new.dealer_code, new.id)
            and q.status in ('draft', 'sent_to_client', 'won')) then
      update quote_requests set status = 'lost', lost_reason = coalesce(new.lost_reason, ''), closed_at = now()
       where id = r.id;
      if exists (select 1 from leads where dealer_code = r.dealer_code and num_id = r.lead_num_id
                    and status not in ('PAID', 'CANCELLED')) then
        perform _lead_flow_set_status(r.dealer_code, r.lead_num_id, 'CANCELLED', coalesce(new.lost_reason, ''));
      end if;
    end if;
  end if;

  -- ย้อนการตอบรับ (won → อย่างอื่น): ใบ HQ กลับเป็นส่งแล้ว · คำขอกลับมาเปิด — ยอดขาย HQ ต้องลดตาม
  if was = 'won' and new.status <> 'won' and h.status = 'ordered' then
    update hq_quotes set status = 'sent', ordered_at = null where id = h.id;
    update quote_requests set status = 'quoted', closed_at = null where id = r.id and status = 'won';
  end if;
  return new;
end $$;

create trigger quotations_flow_sync after insert or update of status on public.quotations
  for each row execute function public.quotations_flow_sync();

