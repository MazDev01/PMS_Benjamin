-- ═══ 6. กฎของถัง (ทางที่ผู้ใช้ยิงตรงเข้าถัง) ════════════════════════════════════════════════════════════════
create or replace function public.quote_file_object_visible(p_name text) returns boolean
  language sql stable security definer set search_path = public as $$
  select exists (select 1 from quote_files f where f.object_name = p_name and _quote_file_visible(f));
$$;
create or replace function public.quote_file_object_reserved(p_name text) returns boolean
  language sql stable security definer set search_path = public as $$
  select exists (select 1 from quote_files f where f.object_name = p_name and f.status = 'pending' and f.uploaded_by = auth.uid()
                   and _quote_file_actor_ok(f.dealer_code, f.side) and _quote_file_open(f.request_id, f.side, f.hq_quote_id));
$$;
/** ลบได้: ฝั่งของผู้เรียกเอง · ยังไม่ล็อก (ดีลเลอร์ลบไฟล์ HQ ไม่ได้ · HQ ลบไฟล์ดีลเลอร์ไม่ได้) */
create or replace function public.quote_file_object_deletable(p_name text) returns boolean
  language sql stable security definer set search_path = public as $$
  select exists (select 1 from quote_files f where f.object_name = p_name
                   and _quote_file_actor_ok(f.dealer_code, f.side) and _quote_file_open(f.request_id, f.side, f.hq_quote_id));
$$;

