-- ═══ 7. อ่าน ════════════════════════════════════════════════════════════════════════════════════════════
/** ไฟล์ทั้งสายของคำขอ (คำขอแรก + ขอแก้ราคาทุกครั้ง) ที่ผู้เรียกเห็น — ใหม่สุดก่อน · ขนาดจริงจากถัง */
create or replace function public.quote_files_list(p_request_id bigint) returns jsonb
  language plpgsql stable security definer set search_path = public as $$
declare r quote_requests; v_root bigint;
begin
  select * into r from quote_requests where id = p_request_id;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if not (is_hq() or (auth_dealer() <> '' and auth_dealer() = r.dealer_code)) then raise exception 'forbidden: ไม่ใช่คำขอของสาขานี้'; end if;
  v_root := coalesce(r.root_id, r.id);
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', f.id, 'requestId', f.request_id, 'requestNo', q.request_no, 'side', f.side,
             'hqQuoteId', f.hq_quote_id, 'quoteNo', h.quote_no, 'version', h.version,
             'name', f.display_name, 'path', f.object_name,
             'size', coalesce((o.metadata ->> 'size')::bigint, f.declared_size),
             'uploadedByName', f.uploaded_by_name, 'createdAt', f.created_at,
             'canDelete', _quote_file_actor_ok(f.dealer_code, f.side) and _quote_file_open(f.request_id, f.side, f.hq_quote_id))
           order by f.created_at desc, f.id desc)
      from quote_files f
      join quote_requests q on q.id = f.request_id
      left join hq_quotes h on h.id = f.hq_quote_id
      left join storage.objects o on o.bucket_id = 'quote-files' and o.name = f.object_name
     where f.status = 'ready' and coalesce(q.root_id, q.id) = v_root and _quote_file_visible(f)), '[]'::jsonb);
end $$;

/** ป้ายจำนวนไฟล์ในรายการคำขอ — [{request, dealer, hq}] นับเฉพาะที่ผู้เรียกเห็น · ฝั่ง HQ นับใบ HQ ของคำขอนั้น */
create or replace function public.quote_file_counts(p_request_ids bigint[]) returns jsonb
  language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('request', x.request_id, 'dealer', x.d, 'hq', x.h) order by x.request_id), '[]'::jsonb)
    from (select f.request_id, count(*) filter (where f.side = 'dealer') as d, count(*) filter (where f.side = 'hq') as h
            from quote_files f
           where f.request_id = any(coalesce(p_request_ids, '{}')) and f.status = 'ready' and _quote_file_visible(f)
           group by f.request_id) x;
$$;

-- ═══ 8. พื้นที่เก็บไฟล์ (หน้าตั้งค่า) ══════════════════════════════════════════════════════════════════════
alter table public.hq_policy add column if not exists storage_quota_gb numeric check (storage_quota_gb is null or storage_quota_gb > 0);
comment on column public.hq_policy.storage_quota_gb is 'โควตาพื้นที่เก็บไฟล์ (GB) ที่ HQ ตั้งเอง — ว่าง = ยังไม่ตั้ง (หน้าจอแสดงพื้นที่ที่ใช้อย่างเดียว ไม่เดาโควตา)';

/** พื้นที่ที่ใช้ไปทุกถัง (ขนาดจริงจากถัง) + โควตาที่ตั้งไว้ — HQ เท่านั้น */
create or replace function public.storage_usage() returns jsonb
  language plpgsql stable security definer set search_path = public as $$
begin
  if not is_hq() then raise exception 'forbidden: เฉพาะสำนักงานใหญ่'; end if;
  return jsonb_build_object(
    'buckets', coalesce((select jsonb_agg(jsonb_build_object('bucket', b.id, 'files', coalesce(s.n, 0), 'bytes', coalesce(s.bytes, 0)) order by b.id)
                           from storage.buckets b
                           left join (select bucket_id, count(*) as n, sum(coalesce((metadata ->> 'size')::bigint, 0)) as bytes
                                        from storage.objects group by bucket_id) s on s.bucket_id = b.id), '[]'::jsonb),
    'quotaGb', (select storage_quota_gb from hq_policy where id = 1));
end $$;

/** HQ ตั้งโควตา (GB · null = ยังไม่ตั้ง) — ผู้ดูแล/ผู้บริหาร HQ · ตัวดักของ hq_policy ลงบันทึกการใช้งานเอง */
create or replace function public.storage_quota_set(p_gb numeric) returns void
  language plpgsql security definer set search_path = public as $$
begin
  if not can_write_master() then raise exception 'forbidden: เฉพาะผู้ดูแล/ผู้บริหาร HQ'; end if;
  if p_gb is not null and (p_gb <= 0 or p_gb > 100000) then raise exception 'bad_quota: โควตาต้องมากกว่า 0 GB'; end if;
  update hq_policy set storage_quota_gb = p_gb where id = 1;
end $$;

