-- ═══ 2. ตารางไฟล์แนบ ═════════════════════════════════════════════════════════════════════════════════════
create table public.quote_files (
  id               bigint generated by default as identity primary key,
  request_id       bigint not null references public.quote_requests(id) on delete restrict,
  dealer_code      text not null,
  side             text not null check (side in ('dealer', 'hq')),
  hq_quote_id      bigint references public.hq_quotes(id) on delete restrict,
  object_name      text not null unique,                    -- ชื่อในถัง (ASCII ล้วน · ฐานตั้งให้)
  display_name     text not null check (btrim(display_name) <> '' and length(display_name) <= 200),
  declared_size    bigint not null check (declared_size > 0),
  status           text not null default 'pending' check (status in ('pending', 'ready')),
  uploaded_by      uuid references auth.users(id) on delete set null,
  uploaded_by_name text not null default '',
  created_at       timestamptz not null default now(),
  check ((side = 'hq') = (hq_quote_id is not null))
);
create index quote_files_request_idx on public.quote_files (request_id, side);
create index quote_files_hq_quote_idx on public.quote_files (hq_quote_id) where hq_quote_id is not null;
comment on table public.quote_files is
  'ไฟล์แนบของคำขอราคา (ใบ 0273) — side=dealer ผูกคำขอ · side=hq ผูกใบ HQ ฉบับนั้น · เขียนผ่านคำสั่งของฐาน/ตัวดักของถังเท่านั้น';

alter table public.quote_files enable row level security;
revoke all on table public.quote_files from public, anon, authenticated, service_role;
grant all on table public.quote_files to service_role;
revoke all on sequence public.quote_files_id_seq from public, anon, authenticated, service_role;
grant usage, select on sequence public.quote_files_id_seq to service_role;

-- ═══ 3. กติกากลาง ════════════════════════════════════════════════════════════════════════════════════════
create or replace function public._quote_file_ext(p_name text) returns text
  language sql immutable set search_path = public as $$
  select lower(substring(coalesce(p_name, '') from '\.([A-Za-z0-9]+)$'));
$$;
create or replace function public._quote_file_ext_ok(p_ext text) returns boolean
  language sql immutable set search_path = public as $$
  select coalesce(p_ext in ('pdf', 'jpg', 'jpeg', 'png', 'xlsx', 'xls', 'csv', 'dwg', 'dxf'), false);
$$;

/** ยังแนบ/ลบได้ไหม (ไม่สนว่าใครทำ): ฝั่งดีลเลอร์ = คำขอยังอยู่กับ HQ (new/pricing) · ฝั่ง HQ = ใบ HQ ฉบับนั้นยังเป็นร่าง */
create or replace function public._quote_file_open(p_request bigint, p_side text, p_hq bigint) returns boolean
  language sql stable security definer set search_path = public as $$
  select case p_side
    when 'dealer' then exists (select 1 from quote_requests where id = p_request and status in ('new', 'pricing'))
    when 'hq' then exists (select 1 from hq_quotes h join quote_requests r on r.id = h.request_id
                            where h.id = p_hq and h.request_id = p_request and h.status = 'draft' and r.status in ('new', 'pricing'))
    else false end;
$$;

/** ผู้เรียกทำฝั่งนี้ของคำขอนี้ได้ไหม (ตามใบผ่าน) — ดีลเลอร์ = สาขาเจ้าของคำขอ · HQ = บทบาทที่ทำราคาได้ */
create or replace function public._quote_file_actor_ok(p_dealer text, p_side text) returns boolean
  language sql stable security definer set search_path = public as $$
  select case p_side
    when 'dealer' then not is_hq() and auth_dealer() <> '' and auth_dealer() = p_dealer and is_account_active()
    when 'hq' then can_price_quotes()
    else false end;
$$;

/** ผู้เรียกเห็นไฟล์นี้ไหม — HQ ทุกไฟล์ · ดีลเลอร์เฉพาะคำขอของสาขาตัวเอง และไฟล์ HQ เฉพาะใบที่ส่งแล้ว · ผู้อัปโหลดเห็นแถวจองของตัวเอง */
create or replace function public._quote_file_visible(f public.quote_files) returns boolean
  language sql stable security definer set search_path = public as $$
  select (f.status = 'ready' or f.uploaded_by = auth.uid())
     and (is_hq()
          or (auth_dealer() <> '' and f.dealer_code = auth_dealer()
              and (f.side = 'dealer' or exists (select 1 from hq_quotes h where h.id = f.hq_quote_id and h.status <> 'draft'))));
$$;

-- ═══ 4. จองที่ก่อนอัปโหลด ═══════════════════════════════════════════════════════════════════════════════
/** คืน {id, path} — path = ชื่อในถังที่ต้องอัปโหลดไป · ตรวจทุกอย่างที่ตรวจได้ก่อนไฟล์ออกจากเครื่อง */
create or replace function public.quote_file_reserve(p_request_id bigint, p_side text, p_name text, p_size bigint)
  returns jsonb language plpgsql security definer set search_path = public as $$
declare
  r quote_requests; h hq_quotes; v_ext text; v_name text := btrim(coalesce(p_name, '')); v_n integer; v_path text; v_id bigint;
begin
  if p_side is null or p_side not in ('dealer', 'hq') then raise exception 'bad_side: ระบุฝั่งไม่ถูกต้อง'; end if;
  select * into r from quote_requests where id = p_request_id for update;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if not _quote_file_actor_ok(r.dealer_code, p_side) then raise exception 'forbidden: ไม่มีสิทธิ์แนบไฟล์ฝั่งนี้ของคำขอนี้'; end if;
  if p_side = 'hq' then
    select * into h from hq_quotes where request_id = r.id for update;
    if not found then raise exception 'quote_missing: บันทึกร่างใบ HQ ก่อนแนบไฟล์'; end if;
  end if;
  if not _quote_file_open(r.id, p_side, h.id) then
    raise exception 'file_locked: %', case when p_side = 'dealer' then 'HQ ส่งใบแล้ว (หรือคำขอปิดแล้ว) — แนบ/ลบไฟล์ไม่ได้'
                                           else 'ส่งใบ HQ ให้ดีลเลอร์แล้ว — แนบ/ลบไฟล์ของใบนี้ไม่ได้' end;
  end if;
  if v_name = '' or length(v_name) > 200 or v_name ~ '[/\\]' then raise exception 'file_name: ชื่อไฟล์ไม่ถูกต้อง'; end if;
  v_ext := _quote_file_ext(v_name);
  if not _quote_file_ext_ok(v_ext) then
    raise exception 'file_type: ไม่รองรับไฟล์ชนิด "%" — รับเฉพาะ PDF, JPG/PNG, Excel/CSV, DWG/DXF', coalesce(v_ext, 'ไม่ทราบ');
  end if;
  if p_size is null or p_size <= 0 then raise exception 'file_size: ไม่ทราบขนาดไฟล์'; end if;
  if p_size > 20971520 then raise exception 'file_size: ไฟล์ใหญ่เกิน 20 MB'; end if;
  -- นับไฟล์ที่ลงถังแล้ว + ที่จองไว้ไม่เกิน 30 นาที (กำลังอัปโหลด) — ฝั่งดีลเลอร์ต่อคำขอ · ฝั่ง HQ ต่อฉบับ
  select count(*) into v_n from quote_files f
   where f.request_id = r.id and f.side = p_side and f.hq_quote_id is not distinct from h.id
     and (f.status = 'ready' or f.created_at > now() - interval '30 minutes');
  if v_n >= 10 then raise exception 'file_count: แนบได้ไม่เกิน 10 ไฟล์%', case when p_side = 'hq' then 'ต่อใบ HQ' else 'ต่อคำขอ' end; end if;

  v_path := r.dealer_code || '/' || r.id || '/' || case when p_side = 'dealer' then 'd' else 'h' || h.id end
            || '/' || replace(gen_random_uuid()::text, '-', '') || '.' || v_ext;
  insert into quote_files (request_id, dealer_code, side, hq_quote_id, object_name, display_name, declared_size, uploaded_by, uploaded_by_name)
  values (r.id, r.dealer_code, p_side, h.id, v_path, v_name, p_size, auth.uid(), audit_actor_name())
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'path', v_path);
end $$;

-- ═══ 5. ตัวดักของถัง — ตรวจซ้ำตอนไฟล์ลงถังจริง (ลิงก์อัปโหลดที่เซ็นแล้วอาจทำงานด้วยสิทธิ์ระบบ → ใช้เจ้าของไฟล์แทนใบผ่าน) ═══
create or replace function public.quote_files_object_guard() returns trigger
  language plpgsql security definer set search_path = public as $$
declare f quote_files;
begin
  if new.bucket_id <> 'quote-files' then return new; end if;
  if tg_op = 'UPDATE' then
    if new.name is distinct from old.name then raise exception 'file_locked: ย้าย/เปลี่ยนชื่อไฟล์แนบไม่ได้'; end if;
    return new;
  end if;
  select * into f from quote_files where object_name = new.name and status = 'pending' for update;
  if not found then raise exception 'file_unreserved: ต้องขอสิทธิ์อัปโหลดจากระบบก่อน' using errcode = 'check_violation'; end if;
  if f.uploaded_by is distinct from coalesce(auth.uid(), new.owner) then
    raise exception 'forbidden: ไฟล์นี้จองไว้ให้ผู้ใช้อื่น' using errcode = 'check_violation';
  end if;
  if not _quote_file_ext_ok(_quote_file_ext(new.name)) then
    raise exception 'file_type: ไม่รองรับไฟล์ชนิดนี้' using errcode = 'check_violation';
  end if;
  if not _quote_file_open(f.request_id, f.side, f.hq_quote_id) then
    raise exception 'file_locked: ส่งใบ HQ แล้ว — แนบไฟล์ไม่ได้' using errcode = 'check_violation';
  end if;
  if coalesce((new.metadata ->> 'size')::bigint, 0) > 20971520 then
    raise exception 'file_size: ไฟล์ใหญ่เกิน 20 MB' using errcode = 'check_violation';
  end if;
  return new;
end $$;

create or replace function public.quote_files_object_added() returns trigger
  language plpgsql security definer set search_path = public as $$
declare f quote_files; v_role text;
begin
  if new.bucket_id <> 'quote-files' then return new; end if;
  update quote_files set status = 'ready' where object_name = new.name and status = 'pending' returning * into f;
  if not found then return new; end if;
  select role::text into v_role from profiles where id = f.uploaded_by;
  insert into audit_log("user", role, action, target)
  values (coalesce(nullif(f.uploaded_by_name, ''), 'system'), coalesce(v_role, ''), 'แนบไฟล์คำขอราคา',
          (select request_no from quote_requests where id = f.request_id) || ' · '
          || case when f.side = 'dealer' then 'ไฟล์จากดีลเลอร์' else 'ไฟล์จาก HQ ' || coalesce((select quote_no from hq_quotes where id = f.hq_quote_id), '—') end
          || ' · ' || f.display_name);
  return new;
end $$;

create or replace function public.quote_files_object_removed() returns trigger
  language plpgsql security definer set search_path = public as $$
declare f quote_files;
begin
  if old.bucket_id <> 'quote-files' then return old; end if;
  delete from quote_files where object_name = old.name returning * into f;
  -- ลบโดยผู้ใช้ = ลงบันทึก · สคริปต์ล้างข้อมูลทดสอบ (สิทธิ์ระบบ ไม่มีผู้ใช้) = ไม่ลง
  if found and f.status = 'ready' and auth.uid() is not null then
    perform _audit_hq('ลบไฟล์คำขอราคา',
      (select request_no from quote_requests where id = f.request_id) || ' · '
      || case when f.side = 'dealer' then 'ไฟล์จากดีลเลอร์' else 'ไฟล์จาก HQ ' || coalesce((select quote_no from hq_quotes where id = f.hq_quote_id), '—') end
      || ' · ' || f.display_name);
  end if;
  return old;
end $$;

