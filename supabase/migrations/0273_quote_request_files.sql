-- ── ใบ 0273: แนบไฟล์ 2 ทาง ดีลเลอร์ ↔ HQ ในคำขอราคา (บอสสั่ง 2 พ.ย. 69 · จองโดยเซสชัน ef) ──────────────────────────────
-- ดีลเลอร์ → HQ (D3): แนบที่คำขอ · แนบ/ลบได้จนกว่า HQ ส่งใบ (คำขอสถานะ new/pricing) แล้วล็อก
-- HQ → ดีลเลอร์ (H8/H9): แนบที่ใบ HQ ฉบับร่าง · กดส่งใบแล้วไฟล์ล็อกพร้อมใบ · ไฟล์ผูกกับใบ HQ แต่ละฉบับ
--   ออกฉบับใหม่ (ขอแก้ราคา = คำขอใหม่ + ใบ HQ ใหม่) = แนบใหม่ได้ · ไฟล์ฉบับเก่าอยู่ที่ใบเก่า ดูย้อนได้ (รายการไฟล์คืนทั้งสาย)
--   ดีลเลอร์เห็นไฟล์ HQ เฉพาะของใบที่ส่งแล้ว (ร่างไม่หลุด) · HQ เห็นทุกคำขอ
-- ร่วมกัน: PDF · JPG/PNG · XLSX/XLS/CSV · DWG/DXF · ≤ 20 MB/ไฟล์ · ≤ 10 ไฟล์ต่อฝั่งต่อคำขอ (ฝั่ง HQ = ต่อฉบับ)
--
-- ทางเดินของไฟล์ (ไม่ผ่าน API ของเรา — Vercel รับ body ≤ 4.5 MB):
--   1) quote_file_reserve() — ฐานตรวจสิทธิ์/ล็อก/ชนิด/ขนาดที่แจ้ง/จำนวน แล้วจองแถว (pending) + ตั้งชื่อในถังให้เอง
--   2) เซิร์ฟเวอร์ออกลิงก์อัปโหลดที่เซ็นแล้ว (ในนามผู้ใช้) → หน้าเว็บส่งไฟล์ตรงเข้าถัง quote-files (private)
--   3) ตัวดักบน storage.objects ตรวจซ้ำตอนไฟล์ลงถังจริง: ต้องมีแถวจองของผู้อัปโหลดคนนั้น · ยังไม่ล็อก · ชนิดถูก
--      ขนาดจริงถังบังคับ (file_size_limit 20 MB) — ไม่เชื่อค่าที่หน้าเว็บส่ง · ลงถังแล้ว = แถว ready + บันทึกการใช้งาน
--   ลบ: ลบจากถังในนามผู้ใช้ — กฎของถังตรวจฝั่ง/ล็อก (ส่งใบแล้ว = ลบไม่ได้) · ตัวดักลบแถว + บันทึกการใช้งาน
--   ดาวน์โหลด: ลิงก์มีอายุที่เซิร์ฟเวอร์ออกในนามผู้ใช้ — กฎอ่านของถังตรวจว่าเห็นไฟล์นั้นได้ไหม
-- แจ้งเตือน: กระดิ่ง/อีเมลตอนส่งใบ HQ บอกจำนวนไฟล์แนบจาก HQ ({files})
-- หน้าตั้งค่า: storage_usage() พื้นที่ที่ใช้ไปทุกถัง + โควตาที่ HQ ตั้งเอง (hq_policy.storage_quota_gb · ว่าง = ยังไม่ตั้ง)
-- ข้อทดสอบ: supabase/tests/quote_request_files.sql · tests/scenario/quote-request-files.spec.ts
-- รวมใบเดียวกัน (บอสสั่ง 2 พ.ย. 69): ส่งคำขอราคาได้เมื่อข้อมูลลูกค้า + ข้อมูลงานของลีดครบ (ข้อ 11 ท้ายใบ)
