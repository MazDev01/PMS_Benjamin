-- ราคาเปลี่ยน = ประทับวันที่อัปเดตราคา (ฐานทำเอง หน้าเว็บส่งมาไม่ได้)
create or replace function public.material_templates_touch() returns trigger
language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  if tg_op = 'INSERT' then new.price_updated_at := now();
  elsif new.unit_price is distinct from old.unit_price then new.price_updated_at := now();
  else new.price_updated_at := old.price_updated_at;
  end if;
  return new;
end $$;
create trigger material_templates_touch before insert or update on public.material_templates
  for each row execute function public.material_templates_touch();
revoke all on function public.material_templates_touch() from public, anon, authenticated, service_role;

/** HQ บันทึกแม่แบบวัสดุ (ปุ่มบันทึกกลางของหน้าตั้งค่า) — เพิ่ม/แก้ (p_rows ไม่มี id = เพิ่ม) + ลบ (p_delete_ids) ในคำสั่งเดียว
 *  ลงบันทึกการใช้งาน 1 แถวที่ฐาน (ใบ 0240) · คืนรายการทั้งหมดหลังบันทึก */
create or replace function public.material_templates_save(p_rows jsonb, p_delete_ids bigint[] default '{}')
returns setof public.material_templates language plpgsql security definer set search_path = public as $$
declare
  v jsonb; เพิ่ม int := 0; แก้ int := 0; ลบ int := 0; n int;
  v_price numeric;
begin
  if not can_write_master() then raise exception 'forbidden: เฉพาะสำนักงานใหญ่ (ผู้ดูแล/ผู้บริหาร) แก้แม่แบบวัสดุได้'; end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then raise exception 'rows_invalid: รายการต้องเป็นรายการ'; end if;

  if coalesce(array_length(p_delete_ids, 1), 0) > 0 then
    delete from material_templates where id = any(p_delete_ids);
    get diagnostics ลบ = row_count;
  end if;

  for v in select * from jsonb_array_elements(p_rows) loop
    if btrim(coalesce(v ->> 'name', '')) = '' then raise exception 'rows_invalid: ทุกรายการต้องมีชื่อวัสดุ'; end if;
    begin v_price := (v ->> 'unitPrice')::numeric;
    exception when others then raise exception 'rows_invalid: ราคาต่อหน่วยของ "%" ไม่ใช่ตัวเลข', v ->> 'name'; end;
    if v_price is null or v_price < 0 then raise exception 'rows_invalid: ต้องใส่ราคาต่อหน่วย (0 ขึ้นไป) ของ "%"', v ->> 'name'; end if;
    if nullif(v ->> 'id', '') is null then
      insert into material_templates (category, name, unit, unit_price, active)
      values (btrim(coalesce(v ->> 'category', '')), btrim(v ->> 'name'), btrim(coalesce(v ->> 'unit', '')), round(v_price, 2),
              coalesce((v ->> 'active')::boolean, true));
      เพิ่ม := เพิ่ม + 1;
    else
      update material_templates
         set category = btrim(coalesce(v ->> 'category', '')), name = btrim(v ->> 'name'), unit = btrim(coalesce(v ->> 'unit', '')),
             unit_price = round(v_price, 2), active = coalesce((v ->> 'active')::boolean, true)
       where id = (v ->> 'id')::bigint
         and (category, name, unit, unit_price, active) is distinct from
             (btrim(coalesce(v ->> 'category', '')), btrim(v ->> 'name'), btrim(coalesce(v ->> 'unit', '')), round(v_price, 2), coalesce((v ->> 'active')::boolean, true));
      get diagnostics n = row_count;
      แก้ := แก้ + n;
    end if;
  end loop;

  if เพิ่ม + แก้ + ลบ > 0 then
    perform _audit_hq('บันทึกแม่แบบวัสดุ', concat_ws(' · ',
      case when เพิ่ม > 0 then 'เพิ่ม ' || เพิ่ม || ' รายการ' end,
      case when แก้ > 0 then 'แก้ ' || แก้ || ' รายการ' end,
      case when ลบ > 0 then 'ลบ ' || ลบ || ' รายการ' end));
  end if;
  return query select * from material_templates order by lower(category), lower(name), id;
end $$;
revoke all on function public.material_templates_save(jsonb, bigint[]) from public, anon, authenticated, service_role;
grant execute on function public.material_templates_save(jsonb, bigint[]) to authenticated;

-- ═══ 2. คำขอราคาเก็บสำเนารายการประเมิน ═══════════════════════════════════════════════════════════════════
alter table public.quote_requests
  add column estimate_items jsonb not null default '[]'::jsonb check (jsonb_typeof(estimate_items) = 'array'),
  add column estimate_total numeric(14,2) check (estimate_total is null or estimate_total >= 0),
  add column estimate_deviation_pct numeric(8,1);

/** แปลงรายการที่ดีลเลอร์เลือก [{templateId, qty}] → สำเนา ณ ตอนนี้ [{templateId, category, name, unit, qty, unitPrice}]
 *  ราคา/ชื่อ/หน่วยมาจากแม่แบบที่เปิดใช้เท่านั้น (ไม่รับจากหน้าเว็บ) */
create or replace function public._estimate_snapshot(p_items jsonb) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v jsonb; m material_templates; ผล jsonb := '[]'::jsonb; v_qty numeric;
begin
  if p_items is null or p_items = 'null'::jsonb then return ผล; end if;
  if jsonb_typeof(p_items) <> 'array' then raise exception 'estimate_invalid: รายการวัสดุต้องเป็นรายการ'; end if;
  if jsonb_array_length(p_items) > 200 then raise exception 'estimate_invalid: เลือกวัสดุได้ไม่เกิน 200 รายการ'; end if;
  for v in select * from jsonb_array_elements(p_items) loop
    select * into m from material_templates where id = nullif(v ->> 'templateId', '')::bigint and active;
    if not found then raise exception 'estimate_invalid: ไม่พบวัสดุที่เลือก หรือ HQ ปิดใช้แล้ว'; end if;
    begin v_qty := (v ->> 'qty')::numeric;
    exception when others then raise exception 'estimate_invalid: จำนวนของ "%" ไม่ใช่ตัวเลข', m.name; end;
    if v_qty is null or v_qty <= 0 then raise exception 'estimate_invalid: จำนวนของ "%" ต้องมากกว่า 0', m.name; end if;
    ผล := ผล || jsonb_build_object('templateId', m.id, 'category', m.category, 'name', m.name, 'unit', m.unit,
                                   'qty', v_qty, 'unitPrice', m.unit_price);
  end loop;
  return ผล;
end $$;
revoke all on function public._estimate_snapshot(jsonb) from public, anon, authenticated, service_role;

create or replace function public._estimate_total(p_items jsonb) returns numeric
language sql immutable set search_path = public as $$
  select case when jsonb_array_length(coalesce(p_items, '[]'::jsonb)) = 0 then null
              else (select sum(round((e ->> 'qty')::numeric * (e ->> 'unitPrice')::numeric, 2)) from jsonb_array_elements(p_items) e) end;
$$;
revoke all on function public._estimate_total(jsonb) from public, anon, authenticated, service_role;

-- ส่งคำขอ: เพิ่ม p_estimate (ไม่บังคับ) — นิยามเดิม (0183) ทุกบรรทัด + สำเนารายการประเมิน
drop function public.quote_request_submit(integer, text, text, numeric, text, text);
create function public.quote_request_submit(
  p_lead_num_id integer, p_product text, p_subtype text default '',
  p_area numeric default null, p_spec text default '', p_province text default '',
  p_estimate jsonb default '[]'::jsonb
) returns public.quote_requests language plpgsql security definer set search_path to 'public' as $$
declare
  v_dealer text := auth_dealer();
  v_lead   leads;
  v_id     bigint;
  v_est    jsonb;
  r        quote_requests;
begin
  if not can_write_sales() or v_dealer = '' then
    raise exception 'forbidden: ไม่มีสิทธิ์ส่งคำขอใบเสนอราคา';
  end if;
  if btrim(coalesce(p_product, '')) = '' then
    raise exception 'product_required: ต้องเลือกแม่แบบก่อนส่งคำขอ';
  end if;

  select * into v_lead from leads where dealer_code = v_dealer and num_id = p_lead_num_id for update;
  if not found then raise exception 'lead_not_found: ไม่พบลูกค้าเป้าหมายนี้'; end if;
  if v_lead.status not in ('WAITING', 'BULLET') then
    raise exception 'lead_stage: ส่งคำขอได้เฉพาะลูกค้าเป้าหมายที่ยังไม่ได้ขอราคา (ขั้นปัจจุบัน %)', v_lead.status;
  end if;
  if exists (select 1 from quote_requests where dealer_code = v_dealer and lead_num_id = p_lead_num_id
                and status in ('new','pricing','quoted')) then
    raise exception 'request_open: ลูกค้าเป้าหมายนี้มีคำขอที่ยังเปิดอยู่แล้ว';
  end if;
  v_est := _estimate_snapshot(p_estimate);

  v_id := nextval(pg_get_serial_sequence('public.quote_requests', 'id'));
  insert into quote_requests (id, request_no, dealer_code, lead_num_id, root_id, product, subtype, area,
                              province, spec, due_at, created_by, estimate_items, estimate_total)
  values (v_id,
          'RQ-' || to_char(now() at time zone 'Asia/Bangkok', 'YYYY') || '-' || lpad(v_id::text, 5, '0'),
          v_dealer, p_lead_num_id, v_id, btrim(p_product), btrim(coalesce(p_subtype, '')), p_area,
          btrim(coalesce(nullif(btrim(coalesce(p_province, '')), ''), v_lead.province, '')),
          btrim(coalesce(p_spec, '')),
          now() + make_interval(days => quote_request_sla_days()), auth.uid(),
          v_est, _estimate_total(v_est))
  returning * into r;

  perform _lead_flow_set_status(v_dealer, p_lead_num_id, 'HQ_PRICING');
  return r;
end $$;
revoke all on function public.quote_request_submit(integer, text, text, numeric, text, text, jsonb) from public, anon, authenticated, service_role;
grant execute on function public.quote_request_submit(integer, text, text, numeric, text, text, jsonb) to authenticated;

-- ขอแก้ราคา: นิยามเดิม (0183) ทุกบรรทัด + คำขอใหม่ถือรายการประเมินชุดเดิม
create or replace function public.quote_request_reprice(
  p_id bigint, p_reason text, p_spec text default null
) returns public.quote_requests language plpgsql security definer set search_path to 'public' as $$
declare
  old_r quote_requests;
  r     quote_requests;
  v_id  bigint;
begin
  if not can_write_sales() then raise exception 'forbidden: ไม่มีสิทธิ์ขอแก้ราคา'; end if;
  if btrim(coalesce(p_reason, '')) = '' then raise exception 'reason_required: ต้องระบุว่าขอแก้ราคาเพราะอะไร'; end if;

  select * into old_r from quote_requests where id = p_id and dealer_code = auth_dealer() for update;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if old_r.status <> 'quoted' then
    raise exception 'request_stage: ขอแก้ราคาได้เฉพาะคำขอที่ได้ใบ HQ แล้วและยังไม่ปิด (สถานะ %)', old_r.status;
  end if;

  update quote_requests set status = 'superseded', closed_at = now() where id = p_id;
  update hq_quotes set status = 'superseded' where request_id = p_id and status = 'sent';

  v_id := nextval(pg_get_serial_sequence('public.quote_requests', 'id'));
  insert into quote_requests (id, request_no, dealer_code, lead_num_id, root_id, supersedes_id, product, subtype,
                              area, province, spec, due_at, created_by, estimate_items, estimate_total)
  values (v_id,
          'RQ-' || to_char(now() at time zone 'Asia/Bangkok', 'YYYY') || '-' || lpad(v_id::text, 5, '0'),
          old_r.dealer_code, old_r.lead_num_id, coalesce(old_r.root_id, old_r.id), old_r.id,
          old_r.product, old_r.subtype, old_r.area, old_r.province,
          btrim(coalesce(nullif(btrim(coalesce(p_spec, '')), ''), old_r.spec) || E'\n[ขอแก้ราคา] ' || btrim(p_reason)),
          now() + make_interval(days => quote_request_sla_days()), auth.uid(),
          old_r.estimate_items, old_r.estimate_total)
  returning * into r;

  perform _lead_flow_set_status(r.dealer_code, r.lead_num_id, 'HQ_PRICING');
  return r;
end $$;

-- ═══ 3. ส่งใบ HQ: เก็บ % ราคาประเมินคลาดจากยอดใบ HQ — นิยามเดิม (0185) ทุกบรรทัด + 1 คำสั่ง ═══════════════════════════
create or replace function public.hq_quote_send(p_request_id bigint)
returns public.hq_quotes language plpgsql security definer set search_path to 'public' as $$
declare
  r      quote_requests;
  h      hq_quotes;
  v_name text;
begin
  if not can_price_quotes() then raise exception 'forbidden: บทบาทนี้ส่งใบ HQ ไม่ได้'; end if;
  select * into r from quote_requests where id = p_request_id for update;
  if not found then raise exception 'request_not_found: ไม่พบคำขอนี้'; end if;
  if r.status <> 'pricing' then raise exception 'request_stage: ส่งใบได้เฉพาะคำขอที่กำลังทำราคา (สถานะ %)', r.status; end if;

  select * into h from hq_quotes where request_id = p_request_id and status = 'draft' for update;
  if not found then raise exception 'quote_missing: ยังไม่มีร่างใบ HQ ของคำขอนี้'; end if;
  if jsonb_array_length(h.line_items) = 0 or h.total_cost <= 0 then
    raise exception 'quote_empty: ใบ HQ ต้องมีรายการและยอดรวมมากกว่า 0';
  end if;
  if h.valid_until is null or h.valid_until < (now() at time zone 'Asia/Bangkok')::date then
    raise exception 'quote_validity: ต้องกำหนดวันยืนราคา และต้องไม่ย้อนหลัง';
  end if;

  select coalesce(nullif(btrim(name), ''), audit_actor()) into v_name from profiles where id = auth.uid();
  update hq_quotes set status = 'sent', sent_at = now(), sent_by = auth.uid(), sent_by_name = coalesce(v_name, audit_actor())
   where id = h.id returning * into h;
  -- % คลาด = (ราคาประเมิน − ยอดใบ HQ) ÷ ยอดใบ HQ × 100 · ไม่มีราคาประเมิน = null (ไม่นับในค่าเฉลี่ย)
  update quote_requests set status = 'quoted', quoted_at = now(),
         estimate_deviation_pct = case when r.estimate_total is null then null
                                       else round((r.estimate_total - h.total_cost) / h.total_cost * 100, 1) end
   where id = p_request_id;

  -- เวอร์ชันใหม่ถึงมือดีลเลอร์แล้ว → ใบของดีลเลอร์ที่ยังค้างอยู่กับเวอร์ชันก่อนหน้าในงานเดียวกัน หมดอายุ
  update quotations q
     set status = 'expired', expired_reason = hq_version_expired_reason()
    from hq_quotes oh
    join quote_requests orq on orq.id = oh.request_id
   where q.hq_quote_id = oh.id
     and oh.id <> h.id
     and coalesce(orq.root_id, orq.id) = coalesce(r.root_id, r.id)
     and q.status in ('draft', 'sent_to_client');
  return h;
end $$;

/** ความแม่นของราคาประเมิน (หน้าแม่แบบวัสดุ · HQ เท่านั้น) — นับเฉพาะคำขอที่มีราคาประเมินและ HQ ส่งใบแล้ว
 *  avg_abs_pct = คลาดเฉลี่ย (ไม่สนทิศ) · avg_pct = เฉลี่ยตามทิศ (ลบ = ประเมินต่ำกว่าใบ HQ) · n = 0 → ค่าเฉลี่ย null ("—") */
create or replace function public.material_estimate_accuracy() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare ผล jsonb;
begin
  if not is_hq() then raise exception 'forbidden: เฉพาะสำนักงานใหญ่'; end if;
  select jsonb_build_object('n', count(*), 'avg_abs_pct', round(avg(abs(estimate_deviation_pct)), 1), 'avg_pct', round(avg(estimate_deviation_pct), 1))
    into ผล from quote_requests where estimate_deviation_pct is not null;
  return ผล;
end $$;
revoke all on function public.material_estimate_accuracy() from public, anon, authenticated, service_role;
grant execute on function public.material_estimate_accuracy() to authenticated;

-- ═══ 4. กล่องงาน HQ คืนรายการประเมิน (ใบ HQ เปิดมามีรายการจากคำขอ · H8) — นิยามล่าสุด (0242) ทุกตัวอักษร + 3 ช่อง ═══════════
CREATE OR REPLACE FUNCTION public.hq_quote_board(p_group text DEFAULT 'todo'::text, p_q text DEFAULT ''::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  q text := lower(btrim(coalesce(p_q, '')));
  นับ jsonb; แถว jsonb;
begin
  if not is_hq() then raise exception 'forbidden: เฉพาะสำนักงานใหญ่'; end if;
  if p_group not in ('todo', 'quoted', 'won', 'closed') then raise exception 'invalid_group: %', p_group; end if;

  with ค as (
    select r.*, coalesce(d.name, '') as dealer_name, coalesce(l.company, '') as lead_company,
           coalesce(l.contact, '') as lead_contact, coalesce(l.phone, '') as lead_phone,
           coalesce(l.email, '') as lead_email, coalesce(l.address, '') as lead_address,
           h.status as hq_status, h.valid_until, h.quote_no,
           case when r.status in ('new', 'pricing') then 'todo' when r.status = 'quoted' then 'quoted'
                when r.status = 'won' then 'won' else 'closed' end as กลุ่ม
      from quote_requests r
      left join dealers d on d.code = r.dealer_code
      left join leads l on l.dealer_code = r.dealer_code and l.num_id = r.lead_num_id
      left join hq_quotes h on h.request_id = r.id
     where q = '' or lower(concat_ws(' ', r.request_no, r.dealer_code, d.name, l.company, r.product, r.subtype, r.province)) like '%' || q || '%'
  )
  select jsonb_build_object(
           'todo',    count(*) filter (where กลุ่ม = 'todo'),
           'overdue', count(*) filter (where กลุ่ม = 'todo' and due_at < now()),
           'quoted',  count(*) filter (where กลุ่ม = 'quoted'),
           'won',     count(*) filter (where กลุ่ม = 'won'),
           'closed',  count(*) filter (where กลุ่ม = 'closed')),
         coalesce(jsonb_agg(jsonb_build_object(
           'id', id, 'request_no', request_no, 'dealer_code', dealer_code, 'dealer_name', dealer_name,
           'lead_num_id', lead_num_id, 'lead_company', lead_company, 'product', product, 'subtype', subtype,
           'lead_contact', lead_contact, 'lead_phone', lead_phone, 'lead_email', lead_email, 'lead_address', lead_address,
           'estimate_items', estimate_items, 'estimate_total', estimate_total, 'estimate_deviation_pct', estimate_deviation_pct,
           'area', area, 'province', province, 'spec', spec, 'status', status, 'hq_status', hq_status, 'quote_no', quote_no,
           'valid_until', valid_until, 'submitted_at', submitted_at, 'due_at', due_at, 'quoted_at', quoted_at,
           'closed_at', closed_at, 'assignee_name', assignee_name, 'supersedes_id', supersedes_id,
           'waiting_days', greatest(0, floor(extract(epoch from (now() - submitted_at)) / 86400))::int,
           'tag', case
             when status in ('new', 'pricing') and due_at < now() then 'overdue'
             when status in ('new', 'pricing') and supersedes_id is not null then 'reprice'
             when status = 'pricing' and hq_status = 'draft' then 'draft'
             when status = 'new' then 'new'
             else status end)
           order by
             case when p_group = 'todo' then due_at end asc,
             case when p_group = 'quoted' then valid_until end asc nulls last,
             case when p_group in ('won', 'closed') then coalesce(closed_at, updated_at) end desc,
             id asc)
           filter (where กลุ่ม = p_group), '[]'::jsonb)
    into นับ, แถว
    from ค;

  return jsonb_build_object('counts', นับ, 'rows', แถว);
end $function$;
