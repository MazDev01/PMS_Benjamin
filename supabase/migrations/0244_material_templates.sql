-- ── ใบ 0244: แม่แบบวัสดุ + ราคาประเมินเบื้องต้นตอนขอราคา (บอสสั่ง 26 ต.ค. 69) ─────────────────────────────────────────────
--
-- บอสคืน "แม่แบบวัสดุ" = รายการวัสดุ/ส่วนประกอบ (ผนัง ประตู หลังคา ฯลฯ) พร้อมราคาต่อหน่วย (ราคาส่งดีลเลอร์ ก่อน VAT)
--   ไม่ใช่แม่แบบอาคารแบบเดิม — ตารางแม่แบบเดิม (master_catalog) คงไว้ทุกอย่าง ห้ามลบ/drop (ไม่แตะในใบนี้)
--   ทำไมไม่ใช้ master_catalog ต่อ: ไม่มีหมวด/เปิดปิดใช้/วันที่อัปเดตราคา · มีคอลัมน์ของแม่แบบอาคาร (แบบแปลน ฯลฯ) และข้อมูลเก่า 45 แถว
--   ที่บอสสั่งห้ามไหลกลับมา · กฎอ่านของตารางนั้นซ่อนราคาจากดีลเลอร์ (แม่แบบวัสดุต้องให้ดีลเลอร์เห็นราคา) → ตารางใหม่ material_templates
--
-- 1. material_templates: หมวด (HQ พิมพ์เอง) · ชื่อ · หน่วย · ราคาต่อหน่วย · เปิด/ปิดใช้ · วันที่อัปเดตราคา (ฐานประทับเองเมื่อราคาเปลี่ยน)
--    อ่าน: HQ เห็นทุกแถว · ดีลเลอร์เห็นเฉพาะที่เปิดใช้ (เห็นราคา) · เขียน: ผ่าน material_templates_save เท่านั้น (can_write_master)
--    ไม่มีสิทธิ์เขียนตารางตรงสำหรับบทบาทหน้าเว็บ — ดีลเลอร์แก้ราคาไม่ได้แม้ยิงคำสั่งเอง
-- 2. คำขอราคาเก็บสำเนารายการประเมิน ณ ตอนส่ง (estimate_items: ชื่อ · หน่วย · จำนวน · ราคาต่อหน่วย) + ยอดประเมิน (estimate_total)
--    ราคาคิดที่ฐานจากแม่แบบตอนส่ง ไม่รับราคาจากหน้าเว็บ · HQ เปลี่ยนราคาทีหลัง คำขอเก่าไม่เปลี่ยน
--    ไม่บังคับ (ไม่เลือก = [] · ยอด null) · ไม่ใช่ใบเสนอราคา · ไม่นับในมูลค่าโอกาสการขาย (มูลค่าลีด = ใบเสนอราคาล่าสุดเท่านั้น)
-- 3. HQ ส่งใบ (hq_quote_send) → เก็บ % ราคาประเมินคลาดจากยอดใบ HQ (estimate_deviation_pct) · หน้าแม่แบบแสดงค่าเฉลี่ย
-- 4. ขอแก้ราคา: คำขอใหม่ถือรายการประเมินชุดเดิมต่อ (ดีลเลอร์ไม่ได้เลือกใหม่)
-- 5. กล่องงาน HQ (hq_quote_board) คืนรายการประเมิน → ใบ HQ (H8) เปิดมามีรายการจากคำขอ
-- ข้อทดสอบ: supabase/tests/material_templates.sql

